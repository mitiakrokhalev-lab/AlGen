import test from 'node:test';
import assert from 'node:assert/strict';

import { category, каталогГрупп } from '../src/load.js';
import {
  подгруппы, нормальна, фактор, центр, коммутант, свойстваГруппы, гомоморфизмы,
  изоморфны, порядки, прямоеПроизведение, подгруппаКакГруппа, проста, разрешима,
  нильпотентна, группаАвтоморфизмов,
} from '../src/model/group.js';
import { генерировать } from '../src/generate.js';
import { таблицаПримеров } from '../src/witness.js';

const cat = category('grp');
// Модель конечных групп проверяется БЕЗ бесконечных: у них свой файл тестов.
const каталог = каталогГрупп({ бесконечные: false });
const по = (id) => каталог.find((G) => G.id === id);

test('библиотека загружается и мелкие группы идут первыми', () => {
  assert.ok(каталог.length >= 30, `групп всего ${каталог.length}`);
  assert.equal(каталог[0].n, 1);
  for (let i = 1; i < каталог.length; i++) {
    assert.ok(каталог[i - 1].n <= каталог[i].n, 'каталог должен идти по возрастанию порядка');
  }
});

test('известные группы посчитаны верно', () => {
  const S3 = по('S3');
  const A5 = по('A5');
  const Q8 = по('Q8');
  const D4 = по('D4');
  assert.equal(S3.n, 6);
  assert.equal(A5.n, 60);
  assert.equal(подгруппы(S3).length, 6, 'у S₃ шесть подгрупп');
  assert.equal(подгруппы(A5).length, 59, 'у A₅ пятьдесят девять подгрупп');
  assert.ok(проста(A5), 'A₅ проста');
  assert.ok(!разрешима(A5), 'A₅ неразрешима');
  assert.ok(разрешима(S3) && !нильпотентна(S3), 'S₃ разрешима, но не нильпотентна');
  assert.ok(нильпотентна(Q8) && !свойстваГруппы(Q8).abelian, 'Q₈ нильпотентна и неабелева');
  assert.equal(центр(Q8).length, 2, 'центр Q₈ — порядка 2');
  assert.equal(коммутант(S3).length, 3, 'коммутант S₃ — это A₃');
  assert.ok(!изоморфны(Q8, D4), 'Q₈ и D₄ не изоморфны, хотя порядок один');
});

test('фактор считается и даёт ожидаемое', () => {
  const S3 = по('S3');
  const A3 = подгруппы(S3).find((H) => H.length === 3);
  assert.ok(нормальна(S3, A3));
  const Q = фактор(S3, A3).группа;
  assert.equal(Q.n, 2);
  assert.ok(изоморфны(Q, по('C2')));
  // Фактор по всей группе тривиален, по единичной — сама группа.
  assert.equal(фактор(S3, [0, 1, 2, 3, 4, 5]).группа.n, 1);
  assert.ok(изоморфны(фактор(S3, [0]).группа, S3));
});

test('группа автоморфизмов считается', () => {
  assert.equal(группаАвтоморфизмов(по('C3')).n, 2, '|Aut(C₃)| = 2');
  assert.equal(группаАвтоморфизмов(по('V4')).n, 6, '|Aut(V₄)| = 6');
  assert.equal(группаАвтоморфизмов(по('S3')).n, 6, '|Aut(S₃)| = 6');
  assert.equal(группаАвтоморфизмов(по('Q8')).n, 24, '|Aut(Q₈)| = 24');
});

test('гомоморфизмы перечисляются целиком', () => {
  // Hom(C₄, C₂) — ровно два, Hom(C₂, C₃) — только тривиальный.
  assert.equal(гомоморфизмы(по('C4'), по('C2')).length, 2);
  assert.equal(гомоморфизмы(по('C2'), по('C3')).length, 1);
  assert.equal(гомоморфизмы(по('C6'), по('C6')).length, 6);
  for (const φ of гомоморфизмы(по('S3'), по('C2'))) {
    for (let a = 0; a < 6; a++) {
      for (let b = 0; b < 6; b++) {
        const S3 = по('S3');
        assert.equal(φ[S3.mul[a * 6 + b]], по('C2').mul[φ[a] * 2 + φ[b]]);
      }
    }
  }
});

test('таблица примеров строится по схеме и помечает слепые столбцы', async () => {
  const схема = {
    узлы: [
      { имя: 'G', op: 'given', sort: 'Grp.obj' },
      { имя: 'N', op: 'choose-sub', args: ['G'], props: { normal: true } },
      { имя: 'Q', op: 'quotient', args: ['G', 'N'] },
    ],
  };
  const т = await таблицаПримеров({ cat, схема, каталог, предел: 500 });
  // Строки таблицы — это РАЗЛИЧНЫЕ ПРОФИЛИ с кратностью, а не по одной на
  // привязку: иначе таблица схемы гомоморфизмов модулей в память не влезала
  // вовсе. Поэтому проверяется и то, и другое: профилей много И сумма
  // кратностей равна числу привязок, то есть счёт склейкой не поехал.
  assert.ok(т.строки.length > 50, `различных профилей ${т.строки.length}`);
  const привязок = т.строки.reduce((s, r) => s + (r.сколько ?? 1), 0);
  assert.ok(привязок > 100, `привязок всего ${привязок}`);
  assert.ok(привязок > т.строки.length,
    'склейка обязана что-то склеивать: иначе кратности не нужны');
  // Фактор строится только по нормальным подгруппам — иначе строки бы не было.
  assert.ok(т.постоянные.has('finite@G'), 'у одних лишь конечных групп конечность — слепое пятно');
  assert.ok(!т.постоянные.has('abelian@Q'), 'абелевость фактора обязана меняться');
});

