test('база и модель не противоречат друг другу ни на одной схеме', async () => {
  const схемы = [
    { узлы: [{ имя: 'G', op: 'given', sort: 'Grp.obj' }] },
    {
      узлы: [
        { имя: 'G', op: 'given', sort: 'Grp.obj' },
        { имя: 'Z', op: 'center', args: ['G'] },
      ],
    },
    {
      узлы: [
        { имя: 'A', op: 'given', sort: 'Grp.obj' },
        { имя: 'B', op: 'given', sort: 'Grp.obj' },
        { имя: 'P', op: 'prod', args: ['A', 'B'] },
      ],
    },
  ];
  for (const схема of схемы) {
    const итог = await генерировать({
      cat, схема, границы: { объект: 1, подобъект: 1 }, каталог, примеров: 600,
      // Два предела, и оба нужны по разным причинам.
      //
      // `хватит` — потому что база растёт: то, что при 120 правилах считалось
      // секунды, при 171 не заканчивается. Спор базы с моделью ловится на
      // первых же тысячах пар.
      //
      // `предельныйПорядок` — потому что каталог тут БЕЗ бесконечных групп, и
      // произведения считаются по-настоящему: при пороге по умолчанию (200)
      // перебираются все подгруппы групп порядка под две сотни. С бесконечными
      // такие пары просто невычислимы и стоят даром, а здесь — минуты.
      хватит: 20000,
      предельныйПорядок: 24,
    });
    assert.deepEqual(
      итог.противоречия.slice(0, 3), [],
      `на схеме из ${схема.узлы.length} вершин база спорит с моделью`,
    );
    assert.ok(итог.баланс);
  }
});

test('произведение подгрупп считается в тех же координатах, что и произведение', async () => {
  const схема = {
    узлы: [
      { имя: 'G', op: 'given', sort: 'Grp.obj' },
      { имя: 'H', op: 'given', sort: 'Grp.obj' },
      { имя: 'P', op: 'prod', args: ['G', 'H'] },
      { имя: 'D', op: 'commutator', args: ['P'] },
      { имя: 'DG', op: 'commutator', args: ['G'] },
      { имя: 'DH', op: 'commutator', args: ['H'] },
      { имя: 'S', op: 'prod-sub', args: ['G', 'H', 'DG', 'DH'] },
    ],
  };
  const т = await таблицаПримеров({ cat, схема, каталог, предел: 200, предельныйПорядок: 24 });
  assert.ok(т.строки.length > 50, `строк ${т.строки.length}`);
  // Задача 7.10 — теорема, и на всех примерах она обязана подтверждаться.
  // Если координаты разъедутся, это сломается первым.
  const i = т.индекс.get('eq-sub#D#S');
  assert.ok(i !== undefined, 'равенство подгрупп обязано быть среди атомов');
  assert.ok(т.строки.every((r) => r.биты[i] === 1),
    '[G × H, G × H] = [G,G] × [H,H] — теорема, а модель её не подтверждает');
});

// Подгруппа — ЭТО подмножество (Grp.sub ≤ Grp.subset), и свойства подмножества
// у неё обязаны считаться. Пока не считались, `set-whole` у подгруппы был
// неизвестен НИКОГДА: на схеме «подгруппа» это давало 195 немых пробелов из
// 534 — больше трети всей её бедности, и ни одного кандидата в научные.
test('у подгруппы считаются и свойства подмножества', async () => {
  const { category: кат, каталогГрупп: кг } = await import('../src/load.js');
  const { построитьСхему } = await import('../src/scene.js');
  const { вычислитьУзел, свойства } = await import('../src/model/instance.js');
  const c = кат('grp');
  const каталог = кг();
  const схема = {
    узлы: [
      { имя: 'G', op: 'given', sort: 'Grp.obj' },
      { имя: 'N', op: 'trivial-sub', args: ['G'] },
      { имя: 'W', op: 'whole-sub', args: ['G'] },
    ],
  };
  const { g, имена } = построитьСхему(c, схема);
  const S3 = каталог.find((x) => x.имя === 'S₃');
  assert.ok(S3, 'S₃ в каталоге');
  const знач = new Map([[имена.get('G'), { вид: 'группа', G: S3 }]]);
  const N = вычислитьУзел(g, имена.get('N'), знач);
  знач.set(имена.get('N'), N);
  const W = вычислитьУзел(g, имена.get('W'), знач);
  for (const [имя, v, ожидание] of [['1', N, false], ['S₃', W, true]]) {
    const p = свойства(v);
    assert.equal(p.subgroup, true, `${имя}: подгруппа по сорту`);
    assert.equal(p['set-whole'], ожидание, `${имя}: set-whole должно совпадать с whole`);
    assert.equal(p['set-whole'], p.whole, `${имя}: set-whole и whole обязаны совпасть`);
  }
  // То же у ОБЪЯВЛЕННОЙ подгруппы бесконечной группы.
  const Z = каталог.find((x) => x.бесконечная && x.id === 'Z');
  const знач2 = new Map([[имена.get('G'), Z._сам]]);
  const N2 = вычислитьУзел(g, имена.get('N'), знач2);
  знач2.set(имена.get('N'), N2);
  const W2 = вычислитьУзел(g, имена.get('W'), знач2);
  assert.equal(свойства(N2)['set-whole'], false, '0 ⊂ ℤ — не всё');
  assert.equal(свойства(W2)['set-whole'], true, 'ℤ в ℤ — всё');
  assert.equal(свойства(W2).subgroup, true);
});
