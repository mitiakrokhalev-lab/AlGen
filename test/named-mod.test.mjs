import test from 'node:test';
import assert from 'node:assert/strict';

import { category, каталогМодулей } from '../src/load.js';
import { таблицаПримеров } from '../src/witness.js';
import { генерировать } from '../src/generate.js';
import { свойства } from '../src/model/instance.js';
import { модуль } from '../src/model/modules.js';

const cat = category('mod');
const каталог = каталогМодулей();
const найтиМодуль = (id) => каталог.модули.find((m) => m.вид === 'имя' && m.зап.id === id);
const кольцо = (id) => каталог.кольца.find((r) => r.id === id);

const МОРФИЗМ = {
  узлы: [
    { имя: 'R', op: 'choose-ring', args: [] },
    { имя: 'M', op: 'choose-mod', args: ['R'] },
    { имя: 'N', op: 'choose-mod', args: ['R'] },
    { имя: 'f', op: 'choose-mod-mor', args: ['M', 'N'] },
    { имя: 'K', op: 'ker-mod', args: ['f'] },
    { имя: 'I', op: 'im-mod', args: ['f'] },
  ],
};

test('объявленный модуль знает свойства объекта, а не только вложения', () => {
  const ℤ = кольцо('Z');
  const Q = найтиМодуль('Q');
  assert.ok(Q, 'ℚ⁺ обязана быть модулем над ℤ');
  const p = свойства(модуль(ℤ, Q));
  assert.equal(p['fin-gen'], false);
  assert.equal(p.divisible, true);
  assert.equal(p['torsion-free'], true);
});

test('⊕C₂ — векторное пространство над 𝔽₂ и не свободна над ℤ', () => {
  const S = найтиМодуль('SumC2');
  assert.ok(S);
  assert.equal(свойства(модуль(кольцо('Z'), S)).free, false, 'над ℤ кручение мешает');
  assert.equal(свойства(модуль(кольцо('Z2'), S)).free, true, 'над полем базис есть всегда');
  assert.equal(свойства(модуль(кольцо('Z3'), S)).free, undefined,
    'экспонента 2 не делит 3 — такого модуля просто нет');
});

test('морфизмы существуют и для объявленных модулей', async () => {
  const т = await таблицаПримеров({ cat, схема: МОРФИЗМ, каталог, предел: 20000, предельныйПорядок: 8 });
  const именованные = т.строки.filter((r) => /M = /u.test(r.описание));
  assert.ok(именованные.length > 100, `строк с объявленным модулем: ${именованные.length}`);
  // Сюръективность обязана быть ИЗВЕСТНА: она и есть полнота образа, а образ
  // нулевого морфизма — нулевой подмодуль, посчитанный или объявленный.
  const i = т.индекс.get('surjective@f');
  assert.equal(именованные.filter((r) => r.биты[i] === 2).length, 0,
    'неизвестная сюръективность выбрасывает строку из любого условия про f');
});

test('ядро объявленного морфизма знает, что оно не конечно порождено', async () => {
  const т = await таблицаПримеров({ cat, схема: МОРФИЗМ, каталог, предел: 20000, предельныйПорядок: 8 });
  const i = т.индекс.get('fin-gen@K');
  const нет = т.строки.filter((r) => r.биты[i] === 0);
  assert.ok(нет.length > 0, 'бесконечное ядро обязано находиться');
  assert.equal(т.строки.filter((r) => r.биты[i] === 2).length, 0, 'неизвестных быть не должно');
});

test('«артинов модуль ⇒ ядро конечно порождено» опровергается модулем Прюфера', async () => {
  // Порог порядка намеренно низкий: опровержение даёт БЕСКОНЕЧНЫЙ модуль, и
  // конечные тут только замедляют перебор.
  const итог = await генерировать({
    cat, схема: МОРФИЗМ, границы: { объект: 1, кольцо: 0, морфизм: 0 },
    каталог, примеров: 4000, предельныйПорядок: 3, цели: ['K'],
  });
  const про = итог.найдено.find((z) => z.цель.p === 'fin-gen'
    && z.корзина === 'опровергается примером'
    && z.свойства.some(([имя, p]) => имя === 'M' && p.artinian === true));
  assert.ok(про, 'такая задача обязана порождаться и опровергаться');
  // Контрпример обязан быть ОБЪЯВЛЕННЫМ модулем: конечное ядро всегда конечно
  // порождено, и до этой работы опровергать было нечем.
  assert.match(про.свидетель, /K = /u, `свидетель: ${про.свидетель}`);
  assert.ok(итог.баланс);
});

// --- три конструкции на ОБЪЯВЛЕННЫХ модулях -----------------------------------
//
// Объявленный модуль — это абелева группа библиотеки, и у неё уже есть таблицы
// произведений, факторов и записанное кручение. Пока модель в них не ходила,
// `sum-mod`, `tors` и `quotient-mod` на бесконечных модулях не вычислялись
// никогда: вся бедность схем «сумма» и «кручение» была немотой.

const СУММА = {
  узлы: [
    { имя: 'R', op: 'choose-ring', args: [] },
    { имя: 'M', op: 'choose-mod', args: ['R'] },
    { имя: 'N', op: 'choose-mod', args: ['R'] },
    { имя: 'S', op: 'sum-mod', args: ['M', 'N'] },
  ],
};

test('сумма объявленных модулей берётся из таблицы произведений групп', async () => {
  const { построитьСхему } = await import('../src/scene.js');
  const { вычислитьУзел } = await import('../src/model/instance.js');
  const { НЕ_СЧИТАЕМ } = await import('../src/model/значение.js');
  const { g, имена } = построитьСхему(cat, СУММА);
  const Z = кольцо('Z');
  assert.ok(Z, 'кольцо ℤ в каталоге');
  const пары = [['Z', 'Z', 'ZxZ'], ['Z', 'C2', 'ZxC2']];
  for (const [a, b, ожидание] of пары) {
    const M = найтиМодуль(a) ?? каталог.модули.find((m) => m.вид === 'группа' && m.G.имя === a);
    const N = найтиМодуль(b) ?? каталог.модули.find((m) => m.вид === 'группа' && m.G.имя === b);
    assert.ok(M && N, `нет модулей ${a}, ${b}`);
    const знач = new Map([
      [имена.get('R'), Z],
      [имена.get('M'), модуль(Z, M)],
      [имена.get('N'), модуль(Z, N)],
    ]);
    const S = вычислитьУзел(g, имена.get('S'), знач);
    assert.notEqual(S, НЕ_СЧИТАЕМ, `${a} ⊕ ${b} не посчиталось`);
    assert.equal(S.A?.зап?.id ?? S.A?.G?.id, ожидание, `${a} ⊕ ${b} должно быть ${ожидание}`);
  }
});

test('M ⊕ 0 = M — тождество, а не запись таблицы', async () => {
  const { построитьСхему } = await import('../src/scene.js');
  const { вычислитьУзел } = await import('../src/model/instance.js');
  const { g, имена } = построитьСхему(cat, СУММА);
  const Z = кольцо('Z');
  const Q = найтиМодуль('Q');
  const ноль = каталог.модули.find((m) => m.вид === 'группа' && m.G.n === 1);
  assert.ok(Q && ноль, 'ℚ⁺ и нулевой модуль в каталоге');
  const знач = new Map([
    [имена.get('R'), Z],
    [имена.get('M'), модуль(Z, Q)],
    [имена.get('N'), модуль(Z, ноль)],
  ]);
  const S = вычислитьУзел(g, имена.get('S'), знач);
  assert.equal(S.A?.зап?.id, 'Q', 'ℚ⁺ ⊕ 0 — это сам ℚ⁺');
});

test('кручение и фактор по нему считаются у объявленных модулей', async () => {
  const схема = {
    узлы: [
      { имя: 'R', op: 'choose-ring', args: [] },
      { имя: 'M', op: 'choose-mod', args: ['R'] },
      { имя: 'T', op: 'tors', args: ['R', 'M'] },
      { имя: 'Q', op: 'quotient-mod', args: ['M', 'T'] },
    ],
  };
  const { построитьСхему } = await import('../src/scene.js');
  const { вычислитьУзел } = await import('../src/model/instance.js');
  const { НЕ_СЧИТАЕМ } = await import('../src/model/значение.js');
  const { g, имена } = построитьСхему(cat, схема);
  const Z = кольцо('Z');
  // ℚ/ℤ периодична: кручение — вся группа, фактор по нему нулевой.
  // ℤ без кручения: кручение тривиально, фактор — сама ℤ.
  for (const [ид, ожиданиеФактора] of [['QmodZ', 1], ['Z', null]]) {
    const M = найтиМодуль(ид);
    assert.ok(M, `нет модуля ${ид}`);
    const знач = new Map([[имена.get('R'), Z], [имена.get('M'), модуль(Z, M)]]);
    const T = вычислитьУзел(g, имена.get('T'), знач);
    assert.notEqual(T, НЕ_СЧИТАЕМ, `кручение ${ид} не посчиталось`);
    знач.set(имена.get('T'), T);
    const Q = вычислитьУзел(g, имена.get('Q'), знач);
    assert.notEqual(Q, НЕ_СЧИТАЕМ, `фактор ${ид}/T не посчитался`);
    if (ожиданиеФактора === 1) {
      assert.equal(свойства(Q).trivial, true, `${ид} периодичен — фактор по кручению нулевой`);
    } else {
      assert.equal(Q.A?.зап?.id, ид, `${ид} без кручения — фактор равен ему самому`);
    }
  }
});
