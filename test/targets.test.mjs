import test from 'node:test';
import assert from 'node:assert/strict';

import { нарушенияДоговора, задачи, собрать, проверить } from '../tools/targets.mjs';
import { задачаТекст } from '../src/statement.js';

// Главный тест проекта на сегодня. Он не про код, а про ДОГОВОР: всё, что в
// реестре объявлено выразимым, обязано собираться движком. Если кто-то
// переименует конструкцию или уберёт свойство — падает здесь, а не тихо
// исчезает из выдачи.
test('все выразимые мишени собираются', () => {
  const беды = нарушенияДоговора();
  assert.deepEqual(беды, [], `договор нарушен:\n  ${беды.join('\n  ')}`);
});

test('у каждой мишени объявлен осмысленный статус', () => {
  const годные = new Set(['выразима', 'нужно', 'позже', 'встроена', 'не наша']);
  for (const z of задачи) {
    assert.ok(годные.has(z.статус), `${z.id}: непонятный статус ${z.статус}`);
    assert.ok(z.текст && z.текст.length > 10, `${z.id}: нет формулировки`);
    if (z.статус === 'выразима') assert.ok(z.узлы, `${z.id}: нет графа`);
    else if (!z.узлы) {
      assert.ok((z.нужно ?? []).length || z.почему, `${z.id}: не сказано, чего не хватает`);
    }
  }
});

test('мишени печатаются словами, и в тексте нет дыр', () => {
  for (const z of задачи.filter((x) => x.узлы)) {
    const { g, участники, посылки, цель } = собрать(z);
    const { текст } = задачаТекст(g, { участники, посылки, цель });
    assert.ok(текст.startsWith('Пусть '), `${z.id}: условие не начинается с «Пусть»`);
    assert.ok(текст.includes('Верно ли'), `${z.id}: нет вопроса`);
    assert.ok(!текст.includes('?—'), `${z.id}: неподставленная связь`);
    assert.ok(!/%[sadc]/u.test(текст), `${z.id}: в тексте остался шаблон: ${текст}`);
  }
});

test('подгруппа подгруппы не выдаётся за подгруппу объемлющей группы', () => {
  // 5.9 и char-в-normal отличаются от своих тривиальных двойников ровно тем,
  // что as-sub меняет объемлющий объект. Если печать перестанет называть его,
  // две разные задачи станут неразличимы на бумаге.
  for (const id of ['5.9', 'char-в-normal']) {
    const z = задачи.find((x) => x.id === id);
    const { текст } = задачаТекст(собрать(z).g, {
      участники: собрать(z).участники,
      посылки: собрать(z).посылки,
      цель: собрать(z).цель,
    });
    assert.ok(/нормальна в G\?/u.test(текст), `${id}: в цели не назван объемлющий объект: ${текст}`);
  }
});

test('мишени со статусом «нужно» называют недостающее поимённо', () => {
  // Пустой список дел — законное состояние: все мишени, которым чего-то не
  // хватало, разобраны. Требовать непустоты значило бы требовать, чтобы работа
  // никогда не кончалась. А вот «позже» пусто быть не должно, пока есть
  // отложенное, и каждая такая мишень обязана объяснять, ЧЕГО ждёт.
  for (const z of задачи.filter((x) => x.статус === 'нужно')) {
    assert.ok((z.нужно ?? []).length, `${z.id}: не сказано, чего не хватает`);
  }
  for (const z of задачи.filter((x) => x.статус === 'позже')) {
    assert.ok(z.почему, `${z.id}: отложена без объяснения`);
  }
});

test('3.31б собирается: нормальность пересечения база выводит сама', () => {
  // Эта мишень долго числилась в «нужно» по моей ошибке: правило есть, оно
  // записано как «сохраняет» у пересечения. Договор поймал ошибку, когда
  // определённость стали судить по ВЫВЕДЕННЫМ фактам, а не по одним gives.
  const z = задачи.find((x) => x.id === '3.31б');
  assert.equal(z.статус, 'выразима');
  const итог = проверить(z);
  assert.deepEqual(итог.беды, []);
  assert.deepEqual(итог.неопределено, [], 'фактор по пересечению обязан быть определён');
});
