import test from 'node:test';
import assert from 'node:assert/strict';

import { СЕМЕЙСТВА, членыСемейства } from '../src/model/семейства.js';
import { свойстваГруппы, группаАвтоморфизмов, центр } from '../src/model/group.js';

// Семейства живут ОТДЕЛЬНЫМ каталогом, а не в общей библиотеке: C₁₇ и C₁₉ не
// различаются ни одним нашим свойством, и сотня таких членов раздула бы таблицу
// примеров каждого раздела, не добавив ни одного нового набора свойств. Ценны
// они другим — вопросом «при каких n», которого в языке свойств нет.

test('все четыре семейства строятся с верными порядками', () => {
  const ждём = { C: (n) => n, D: (n) => 2 * n, S: (n) => [1, 1, 2, 6, 24, 120][n], A: (n) => [1, 1, 1, 3, 12, 60][n] };
  for (const [ключ, сем] of Object.entries(СЕМЕЙСТВА)) {
    const члены = членыСемейства(ключ, { от: 1, до: 5, предельныйПорядок: 200 });
    assert.ok(члены.length > 0, `семейство ${ключ} пусто`);
    for (const G of члены) {
      assert.equal(G.n, ждём[ключ](G.параметр),
        `${G.имя}: порядок ${G.n}, а ждали ${ждём[ключ](G.параметр)}`);
      assert.equal(сем.порядок(G.параметр), G.n, 'объявленный порядок обязан совпасть с посчитанным');
    }
  }
});

test('диэдральная группа неабелева, а её центр тривиален ровно при нечётном n', () => {
  for (const G of членыСемейства('D', { от: 3, до: 10, предельныйПорядок: 40 })) {
    assert.equal(свойстваГруппы(G).abelian, false, `${G.имя} обязана быть неабелевой`);
    const Z = центр(G);
    const тривиален = Z.length === 1;
    assert.equal(тривиален, G.параметр % 2 === 1,
      `${G.имя}: центр ${тривиален ? 'тривиален' : 'нет'}, а n ${G.параметр % 2 === 1 ? 'нечётно' : 'чётно'}`);
  }
});

test('знакопеременная группа проста при n = 3 и n ⩾ 5, но не при n = 4', () => {
  const члены = членыСемейства('A', { от: 3, до: 5, предельныйПорядок: 60 });
  const по = new Map(члены.map((G) => [G.параметр, свойстваГруппы(G).simple]));
  assert.equal(по.get(3), true, 'A₃ ≅ C₃ проста');
  assert.equal(по.get(4), false, 'у A₄ есть нормальная подгруппа V₄');
  assert.equal(по.get(5), true, 'A₅ — наименьшая неразрешимая простая');
});

test('Aut(Cₙ) циклична ровно при n = 1, 2, 4, pᵏ, 2pᵏ', () => {
  // Это и есть вопрос, который инструмент находит сам, и ответ на него —
  // существование первообразного корня по модулю n.
  const первообразный = (n) => {
    if (n === 1 || n === 2 || n === 4) return true;
    let m = n;
    if (m % 2 === 0) m /= 2;
    if (m % 2 === 0) return false;
    if (m <= 1) return false;
    for (let p = 2; p <= m; p++) {
      if (m % p !== 0) continue;
      let k = m;
      while (k % p === 0) k /= p;
      return k === 1;
    }
    return false;
  };
  for (const G of членыСемейства('C', { от: 1, до: 24, предельныйПорядок: 24 })) {
    const A = группаАвтоморфизмов(G);
    assert.equal(свойстваГруппы(A).cyclic, первообразный(G.параметр),
      `n = ${G.параметр}: Aut(Cₙ) ${свойстваГруппы(A).cyclic ? 'циклична' : 'нет'}`);
  }
});

test('порог порядка — видимая настройка, а не потолок из кода', () => {
  // S₇ это 5040 элементов, и перечислять его подгруппы минуты. Решение «докуда
  // считать» принимает человек, и оно обязано быть параметром.
  const мало = членыСемейства('S', { от: 1, до: 7, предельныйПорядок: 30 });
  const больше = членыСемейства('S', { от: 1, до: 7, предельныйПорядок: 130 });
  assert.ok(больше.length > мало.length, 'подняли порог — стало больше членов');
  assert.ok(мало.every((G) => G.n <= 30));
});
