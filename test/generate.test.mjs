test('вывод пользуется наследственностью для любого подобъекта, а не только для выбранного', () => {
  const g = new TermGraph(cat);
  const G = g.given('Grp.obj', { abelian: true });
  const Z = g.apply('center', [G]);
  const K = g.apply('commutator', [G]);
  const мир = вывести(g, []);
  assert.equal(мир.знает({ p: 'abelian', t: Z }), true);
  assert.equal(мир.знает({ p: 'abelian', t: K }), true);
});

test('достройка даёт доказательство, для которого в условии нет терма', () => {
  // «Эпиморфный образ абелевой группы абелев» требует терма im φ, которого в
  // условии нет. Без достройки это пробел, с достройкой — вывод.
  const собрать = () => {
    const g = new TermGraph(cat);
    const G = g.given('Grp.obj', { abelian: true });
    const H = g.given('Grp.obj');
    g.apply('choose-mor', [G, H], { props: { surjective: true } });
    return { g, H };
  };
  const без = собрать();
  assert.equal(вывести(без.g, []).знает({ p: 'abelian', t: без.H }), undefined);
  const с = собрать();
  assert.equal(рассуждать(с.g, [], { достройка: 1 }).знает({ p: 'abelian', t: с.H }), true);
});

test('достройка не строит неопределённое', () => {
  // Фактор по подгруппе, нормальность которой неизвестна, достраивать нельзя.
  const g = new TermGraph(cat);
  const G = g.given('Grp.obj');
  g.apply('choose-sub', [G]);
  рассуждать(g, [], { достройка: 1 });
  const факторы = g.nodes.filter((n) => n.op === 'quotient');
  for (const f of факторы) {
    const N = g.get(f.args[1]);
    const нормальна = N.props?.normal === true || cat.cons.get(N.op)?.gives?.normal === true;
    assert.ok(нормальна, `достроен фактор по ненормальной ${N.key}`);
  }
});

// Разнообразие считается по ПОДТВЕРЖДЕНИЯМ, а не по строкам, подходящим под
// посылки. Разница не косметическая: строка годится под посылки и при этом
// ничего не говорит о цели, если цель на ней невычислима. Пока счёт шёл по
// посылкам, в научные кандидаты проходил пробел «подходит примеров 0,
// различных профилей 230» — то есть цель не посчиталась НИ НА ОДНОМ примере.
test('разнообразие не превышает числа подтверждений', async () => {
  const { category: кат, каталогГрупп: кг } = await import('../src/load.js');
  const c = кат('grp');
  const схема = {
    узлы: [
      { имя: 'G', op: 'given', sort: 'Grp.obj' },
      { имя: 'N', op: 'choose-sub', args: ['G'] },
      { имя: 'Q', op: 'quotient', args: ['G', 'N'] },
    ],
  };
  const итог = await генерировать({
    cat: c, схема, границы: { объект: 1, подобъект: 1 },
    каталог: кг(), примеров: 3000, предельныйПорядок: 12, хватит: 3000,
  });
  let проверено = 0;
  for (const z of итог.найдено) {
    if (z.разнообразие === null) continue;
    проверено++;
    assert.ok(z.разнообразие <= (z.верных ?? 0),
      `разнообразие ${z.разнообразие} больше числа подтверждений ${z.верных}`);
    if ((z.примеров ?? 0) === 0) {
      assert.equal(z.разнообразие, 0,
        'цель не посчиталась ни на одном примере — подтверждений нуль');
    }
  }
  assert.ok(проверено > 100, `проверено всего ${проверено} задач`);
});

// Схема «фактор»: на ней ни библиотека, ни модель не являются ограничением.
// Ни одного пробела, где под условие не подошёл НИ ОДИН объект («пусто») или
// где цель не вычислилась ни разу («немо»). Остаётся только «однолико» —
// объекты есть и цель считается, но нашим языком свойств они неразличимы, и
// лечится это новыми свойствами, а не объектами или вычислимостью.
//
// Сперва тест требовал полного отсутствия БЕДНЫХ пробелов, и это держалось,
// пока отсев условий с выводимой посылкой не освободил бюджет: перебор стал
// доставать до условий, до которых прежде не доходил, и среди них нашлись
// «одноликие». Требование ослаблено до честного — до того, за что отвечают
// библиотека и модель.
//
// Второй раз требование ослабло, когда ВЫРОЖДЕННЫЕ СТРОКИ перестали идти в
// подтверждения (см. `разбор` в src/witness.js). Тогда пустых и немых пробелов
// стало 122, и это оказался не откат, а находка: шестьдесят из них указали на
// пропуск в данных — «set-whole» и «whole» значат одно и то же на двух сортах,
// а база их не связывала, и условие «N совпадает с G» не попадало в
// вырожденные. После двух правил осталось ПЯТЬ, и у всех пяти одна причина:
// все подтверждения были вырожденными. Причина названа предметно — при пределе
// порядка 12 в библиотеке нет ни одной нетривиальной делимой нормальной
// подгруппы и ни одной нетривиальной совершенной, поэтому единственная
// подходящая N — тривиальная, а G/1 = G.
//
// Поэтому тест теперь держит не нуль, а ВИД остатка: всякий бедный пробел этой
// схемы обязан объясняться вырожденностью подтверждений. Пробел с настоящими
// подтверждениями, которых мало, значил бы откат.
test('на схеме «фактор» ни библиотека, ни модель не ограничивают', async () => {
  const { category: кат, каталогГрупп: кг } = await import('../src/load.js');
  const { построитьСхему } = await import('../src/scene.js');
  const c = кат('grp');
  const схема = {
    узлы: [
      { имя: 'G', op: 'given', sort: 'Grp.obj' },
      { имя: 'N', op: 'choose-sub', args: ['G'], props: { normal: true } },
      { имя: 'Q', op: 'quotient', args: ['G', 'N'] },
    ],
  };
  const итог = await генерировать({
    cat: c, схема, границы: { объект: 2, подобъект: 1 },
    каталог: кг(), примеров: 8000, предельныйПорядок: 12, хватит: 8000,
  });
  const { g, имена } = построитьСхему(c, схема);
  const вершиныЦели = (ц) => (Array.isArray(ц?.или)
    ? ц.или.flatMap(вершиныЦели)
    : (ц?.rel ? ц.узлы : [ц?.узел]));
  const этаж = (ц) => Math.max(...вершиныЦели(ц).map((имя) => {
    const id = имена.get(имя);
    if (id === undefined) return 0;
    const глубина = (t) => {
      const n = g.get(t);
      if (!n.args.length || c.cons.get(n.op)?.choice) return 0;
      return 1 + Math.max(...n.args.map(глубина));
    };
    return глубина(id);
  }));
  const плохие = итог.найдено.filter((z) => z.корзина === 'пробел'
    && !z.усечено
    && (z.свойства ?? []).some(([, p]) => Object.keys(p).length)
    && этаж(z.цель) >= 1
    && (z.разнообразие ?? 0) < 7
    // Ровно две причины, за которые отвечают библиотека и модель.
    && (!(z.строк ?? 0) || !(z.примеров ?? 0)));
  // Остаток объясним ровно одним: подтверждения были и все оказались
  // вырожденными. Непонятый остаток — откат, и его видно по пустому списку
  // причин.
  const непонятые = плохие.filter((z) => !(z.вырожденных && !z.верных));
  assert.deepEqual(непонятые.map((z) => JSON.stringify(z.цель)).slice(0, 5), [],
    `пробелов без объяснения ${непонятые.length} из ${плохие.length} — схема откатилась`);
  assert.ok(плохие.length <= 12,
    `бедных пробелов ${плохие.length} — было пять, стало больше: библиотека или вырождения поехали`);
});

// РОСТ УСЛОВИЯ ничего не добавляет, кроме украшений.
//
// Замер (`tools/рост-условия.mjs`) на двух схемах разного устройства: при
// подъёме границы с 2 до 4 кандидатов становится в 20–30 раз больше, а
// РАЗЛИЧНЫХ вопросов — ровно столько же. То есть граница 2 — не произвольная
// настройка, а точка насыщения: при границе 1 вопросов меньше (10 против 21 на
// схеме «центр», 4 против 7 на «автоморфизмах»), при границе 3 и выше — те же.
//
// Тест держит именно это: если правка начнёт выдавать при большем условии
// НОВЫЕ вопросы, значит насыщение сдвинулось и границу надо пересматривать;
// если перестанет выдавать старые — значит что-то потерялось.
test('при росте условия новых вопросов не появляется', async () => {
  const { category: кат, каталогГрупп: кг } = await import('../src/load.js');
  const { построитьСхему, ключВопроса } = await import('../src/scene.js');
  const c = кат('grp');
  const каталог = кг();
  const схема = {
    узлы: [
      { имя: 'G', op: 'given', sort: 'Grp.obj' },
      { имя: 'A', op: 'aut', args: ['G'] },
    ],
  };
  const сцена = построитьСхему(c, схема);
  const вопросы = async (граница) => {
    const итог = await генерировать({
      cat: c, схема, границы: { объект: граница }, каталог,
      примеров: 3000, предельныйПорядок: 200, хватит: 80000,
    });
    assert.ok(итог.баланс, `граница ${граница}: договор о корзинах нарушен`);
    assert.deepEqual(итог.противоречия, [], `граница ${граница}: база спорит с моделью`);
    const out = new Set();
    for (const z of итог.найдено) {
      if (z.корзина !== 'пробел' || z.усечено) continue;
      if (!(z.свойства ?? []).some(([, p]) => Object.keys(p).length)) continue;
      if ((z.разнообразие ?? 0) < 8) continue;
      // Кандидатами считаются только вопросы про ПОСТРОЕННОЕ: про исходную
      // вершину всё интересное либо в учебнике, либо в библиотеке. Без этого
      // фильтра сравнение не то: при границе 3 появляется «G конечно
      // порождена» — вопрос про саму G, а не про Aut(G).
      const вершины = z.цель.rel ? z.цель.узлы : [z.цель.узел];
      const этаж = Math.max(...вершины.map((имя) => {
        const id = сцена.имена.get(имя);
        return id === undefined ? 0 : сцена.g.get(id).args.length;
      }));
      if (!этаж) continue;
      out.add(ключВопроса(сцена.g, сцена.имена, z.цель));
    }
    return out;
  };
  const два = await вопросы(2);
  const три = await вопросы(3);
  assert.ok(два.size > 0, 'при границе 2 вопросы вообще находятся');
  for (const в of три) {
    assert.ok(два.has(в), `граница 3 дала НОВЫЙ вопрос ${в} — насыщение сдвинулось`);
  }
  for (const в of два) {
    assert.ok(три.has(в), `граница 3 потеряла вопрос ${в}`);
  }
});
