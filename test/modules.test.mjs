test('«над областью целостности всякое кольцо — поле» опровергается', async () => {
  const итог = await генерировать({
    cat, схема: ФАКТОР, границы: { объект: 1, подобъект: 0, кольцо: 1 },
    каталог, примеров: 400, предельныйПорядок: 12, цели: ['R'],
  });
  const про = итог.найдено.find((z) => z.цель.p === 'field'
    && z.свойства.some(([, props]) => props.domain === true));
  assert.ok(про, 'такая задача обязана порождаться');
  assert.equal(про.корзина, 'опровергается примером');
  assert.match(про.свидетель, /ℤ/u);
  assert.ok(итог.баланс);
});

