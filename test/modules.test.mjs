import test from 'node:test';
import assert from 'node:assert/strict';

import { category, каталогМодулей } from '../src/load.js';
import { построитьСхему } from '../src/scene.js';
import { рассуждать } from '../src/deduce.js';
import { генерировать, текстЗадачи } from '../src/generate.js';
import { таблицаПримеров, ключЗначения } from '../src/witness.js';
import { свойства } from '../src/model/instance.js';
import { модуль } from '../src/model/modules.js';

const cat = category('mod');
const каталог = каталогМодулей();

const ФАКТОР = {
  узлы: [
    { имя: 'R', op: 'choose-ring', args: [] },
    { имя: 'M', op: 'choose-mod', args: ['R'] },
    { имя: 'P', op: 'choose-submod', args: ['M'] },
    { имя: 'Q', op: 'quotient-mod', args: ['M', 'P'] },
  ],
};

test('кольцо подмодуля берётся ссылкой в два шага', () => {
  const { g, имена } = построитьСхему(cat, ФАКТОР);
  assert.equal(g.rel(имена.get('P'), 'base'), имена.get('R'),
    '«base ambient» обязана разрешиться в то же кольцо, что у объемлющего модуля');
  assert.equal(g.rel(имена.get('Q'), 'base'), имена.get('R'));
});

test('гомоморфизма между модулями над разными кольцами не существует', () => {
  const схема = {
    узлы: [
      { имя: 'R', op: 'choose-ring', args: [] },
      { имя: 'S', op: 'choose-ring', args: [] },
      { имя: 'M', op: 'choose-mod', args: ['R'] },
      { имя: 'N', op: 'choose-mod', args: ['S'] },
      { имя: 'f', op: 'choose-mod-mor', args: ['M', 'N'] },
    ],
  };
  // Два choose-ring — это две РАЗНЫЕ вершины (конструкция выбора не склеивается),
  // и согласование по «base M» обязано не дать построить между ними морфизм.
  assert.throws(() => построитьСхему(cat, схема), /base/u);
});

test('двусортное правило выводит свойство модуля из свойства кольца', () => {
  const { g, имена } = построитьСхему(cat, ФАКТОР, new Map([['R', { field: true }]]));
  const мир = рассуждать(g, [...имена.values()]);
  assert.equal(мир.знает({ p: 'free', t: имена.get('M') }), true, 'над полем всякий модуль свободен');
  assert.equal(мир.знает({ p: 'free', t: имена.get('P') }), true);
  assert.equal(мир.знает({ p: 'comm', t: имена.get('R') }), true, 'поле коммутативно');
});

test('подмодуль свободного свободен только над кольцом главных идеалов', () => {
  const надПИД = построитьСхему(cat, ФАКТОР, new Map([['R', { pid: true }], ['M', { free: true }]]));
  assert.equal(
    рассуждать(надПИД.g, [...надПИД.имена.values()]).знает({ p: 'free', t: надПИД.имена.get('P') }),
    true,
  );
  const простоКольцо = построитьСхему(cat, ФАКТОР, new Map([['M', { free: true }]]));
  assert.equal(
    рассуждать(простоКольцо.g, [...простоКольцо.имена.values()]).знает({ p: 'free', t: простоКольцо.имена.get('P') }),
    undefined,
    'без условия на кольцо это неверно, и база обязана молчать',
  );
});

test('свободность модуля — не свободность группы', () => {
  const Z = каталог.модули.find((m) => m.вид === 'имя' && m.зап.id === 'ZxZ');
  const ℤ = каталог.кольца.find((r) => r.id === 'Z');
  assert.ok(Z, 'ℤ² обязана быть в библиотеке модулей');
  assert.equal(свойства(модуль(ℤ, Z)).free, true, 'ℤ² свободен как ℤ-модуль ранга 2');
  assert.equal(Z.зап.props.free, false, 'и при этом НЕ свободная группа');
});

test('кручение считается по кольцу, а не по целым числам', () => {
  const поле = каталог.кольца.find((r) => r.id === 'Z2');
  const C2 = каталог.модули.find((m) => m.вид === 'группа' && m.G.n === 2);
  // Над ℤ/2ℤ ненулевой скаляр обратим, поэтому кручения нет, хотя как абелева
  // группа модуль целиком периодический.
  assert.equal(свойства(модуль(поле, C2))['torsion-free'], true);
});

test('значения модулей различимы по ключу', () => {
  const ℤ = каталог.кольца.find((r) => r.id === 'Z');
  const поле = каталог.кольца.find((r) => r.id === 'Z2');
  const C2 = каталог.модули.find((m) => m.вид === 'группа' && m.G.n === 2);
  const C3 = каталог.модули.find((m) => m.вид === 'группа' && m.G.n === 3);
  const ключи = new Set([модуль(ℤ, C2), модуль(ℤ, C3), модуль(поле, C2)].map(ключЗначения));
  assert.equal(ключи.size, 3,
    'иначе все строки таблицы сливаются в одну группу и опровержения теряются');
});

