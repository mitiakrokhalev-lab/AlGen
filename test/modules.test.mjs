// --- неразложимость и полупростота ---------------------------------------------
//
// Два свойства, заведённые против «одноликости»: прежними десятью ℤ/4 и
// ℤ/2 × ℤ/2 не различались НИ ОДНИМ свойством языка, хотя это разные модули.
// Свойства независимы друг от друга, и это проверяется на трёх примерах.

test('неразложимость и полупростота считаются и независимы', async () => {
  const { каталогМодулей: км, category: кат } = await import('../src/load.js');
  const { модуль, конечная } = await import('../src/model/modules.js');
  const { свойства } = await import('../src/model/instance.js');
  const каталог = км();
  const Z = каталог.кольца.find((R) => R.id === 'Z');
  assert.ok(Z, 'кольцо ℤ');
  const поИмени = (имя) => каталог.модули.find((m) => m.вид === 'группа' && m.G.имя === имя);
  const случаи = [
    // имя, неразложим, полупрост
    ['C4', true, false],   // циклический примарного порядка, экспонента 4
    ['V₄', false, true],   // ℤ/2 × ℤ/2: разложим, экспонента 2
    ['C6', false, true],   // ℤ/6 ≅ ℤ/2 × ℤ/3: разложим, экспонента 6 без квадратов
    ['C2', true, true],    // простой: и то, и другое
  ];
  for (const [имя, нераз, полу] of случаи) {
    const м = поИмени(имя);
    assert.ok(м, `нет модуля ${имя}`);
    const p = свойства(модуль(Z, м));
    assert.equal(p.indecomposable, нераз, `${имя}: неразложимость`);
    assert.equal(p.semisimple, полу, `${имя}: полупростота`);
  }
  // Независимость: все четыре комбинации встречаются среди наших же модулей,
  // кроме «разложим и не полупрост» — его даёт ℤ/4 × ℤ/2.
  const пары = new Set();
  for (const м of каталог.модули) {
    const p = свойства(модуль(Z, м));
    if (p.indecomposable === undefined || p.semisimple === undefined) continue;
    пары.add(`${p.indecomposable}|${p.semisimple}`);
  }
  assert.ok(пары.size >= 3, `различных комбинаций всего ${пары.size}: ${[...пары].join(' ')}`);
  void конечная;
});

test('нулевой модуль полупрост, но разложимым не считается', async () => {
  const { каталогМодулей: км } = await import('../src/load.js');
  const { модуль } = await import('../src/model/modules.js');
  const { свойства } = await import('../src/model/instance.js');
  const каталог = км();
  const Z = каталог.кольца.find((R) => R.id === 'Z');
  const ноль = каталог.модули.find((m) => m.вид === 'группа' && m.G.n === 1);
  assert.ok(ноль, 'нулевой модуль в каталоге');
  const p = свойства(модуль(Z, ноль));
  assert.equal(p.semisimple, true, 'пустая сумма простых — это нуль');
  assert.equal(p.indecomposable, false, 'соглашение: неразложимость спрашивают у НЕНУЛЕВОГО');
});
