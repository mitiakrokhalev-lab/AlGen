// --- канонические морфизмы и перенос по изоморфизму ------------------------------
//
// Объявленных гомоморфизмов было 24, и это была главная причина бедности схем
// «алгебра» и «гомоморфизм»: условия на морфизм не находили ни одного примера
// (пустота 2618 и 1992 пробела). Канонические морфизмы объявлять рукой незачем —
// они определяются самим кольцом, а свойства у них вынужденные.

test('канонические морфизмы синтезированы, и свойства у них вынужденные', () => {
  const по = (id) => каталог.морфизмы.find((f) => f.id === id);
  const по2 = (id) => каталог.кольца.find((R) => R.id === id);
  assert.ok(каталог.морфизмы.length > 100, `морфизмов всего ${каталог.морфизмы.length}`);
  // Тождественный ищется по виду id, а не по конкретному кольцу: у ℤ морфизм
  // ℤ → ℤ ОБЪЯВЛЕН рукой, и синтез его не перезаписывает — рука главнее, а
  // расхождение между ними поймала бы сверка.
  const тождественные = каталог.морфизмы.filter((f) => f.id.startsWith('id:'));
  assert.ok(тождественные.length > 10, `тождественных всего ${тождественные.length}`);
  for (const тожд of тождественные) {
    assert.equal(тожд.props['iso-ring'], true, `${тожд.имя}: тождественный — изоморфизм`);
    assert.equal(тожд.props['finite-dim'], true, 'R над собой порождено единицей');
    assert.equal(тожд.дом, тожд.код, 'у тождественного источник и цель совпадают');
  }
  const коммТожд = тождественные.find((f) => по2(f.дом)?.props?.comm === true);
  assert.ok(коммТожд, 'есть тождественный над коммутативным кольцом');
  assert.equal(коммТожд.props['central-mor'], true,
    'в коммутативном кольце центр — всё кольцо, значит образ в центре');
  // Вложение в многочлены — единственный источник БЕСКОНЕЧНОМЕРНЫХ алгебр.
  const вПоли = по('in-poly:Z');
  assert.ok(вПоли, 'вложение ℤ ↪ ℤ[x]');
  assert.equal(вПоли.props['injective-ring'], true);
  assert.equal(вПоли.props['surjective-ring'], false, 'x в образе не лежит');
  assert.equal(вПоли.props['finite-dim'], false, 'свободный модуль бесконечного ранга');
  // Вложение скалярными матрицами — конечномерно и центрально.
  const вМат = по('in-mat:Z');
  assert.ok(вМат, 'вложение ℤ ↪ M₂(ℤ)');
  assert.equal(вМат.props['finite-dim'], true, 'ранг 4');
  assert.equal(вМат.props['central-mor'], true, 'скалярные матрицы и есть центр');
  const бескон = каталог.морфизмы.filter((f) => f.props?.['finite-dim'] === false);
  assert.ok(бескон.length >= 5, `бесконечномерных алгебр всего ${бескон.length}`);
});

test('у сюръективного морфизма образ наследует ВСЁ от цели', () => {
  // Это проверка переноса свойств по изоморфизму: правило даёт лишь
  // `S ≅ im f`, а дальше замыкание мира переносит каждое свойство само.
  const схема = ПОРАЗДЕЛАМ.ring.гомоморфизм;
  const { g, имена } = построитьСхему(cat, схема,
    new Map([['S', { field: true }], ['f', { 'surjective-ring': true }]]));
  const мир = рассуждать(g, [...имена.values()]);
  const образ = g.find('im-ring', [имена.get('f')]);
  assert.ok(образ !== null, 'терм образа в схеме есть');
  assert.equal(мир.знает({ rel: 'iso', args: [имена.get('S'), образ] }), true,
    'сюръективность и значит, что образ — всё S');
  for (const p of ['field', 'comm', 'domain']) {
    assert.equal(мир.знает({ p, t: образ }), true,
      `свойство ${p} обязано перенестись с S на im f по изоморфизму`);
  }
});

