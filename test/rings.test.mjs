test('канонический идеал R × 0 факторизуется во ВТОРОЙ сомножитель', () => {
  // Перепутать здесь «что внутри» и «что снаружи» проще всего, а ошибка тихая:
  // R × 0 объявлялся простым по свойствам R, хотя фактор по нему — это S.
  // Квадраты ℚ × ℚ и ℤ/4ℤ × ℤ/4ℤ синтезируются тоже, и брать надо именно
  // СМЕШАННОЕ произведение: у квадрата оба сомножителя одинаковы, и путаницу
  // «что внутри — что снаружи» на нём не видно.
  const { все } = синтезироватьПроизведенияКолец([по('Q'), по('Z4')]);
  const T = все.find((x) => x.id === 'prod:Q|Z4');
  assert.ok(T, 'смешанное произведение обязано быть среди синтезированных');
  const слева = T.идеалы.find((i) => i.id.endsWith('.L'));
  const справа = T.идеалы.find((i) => i.id.endsWith('.R'));
  const первый = 'Q';
  const второй = 'Z4';
  assert.equal(слева.фактор, второй, 'фактор по «первый × 0» — это второй сомножитель');
  assert.equal(справа.фактор, первый);
  // ℚ — поле, ℤ/4ℤ — нет. Значит идеал с фактором ℚ максимален, а второй нет.
  const кФ = T.идеалы.find((i) => i.фактор === 'Q');
  const кZ4 = T.идеалы.find((i) => i.фактор === 'Z4');
  assert.equal(кФ.props['maximal-ideal'], true);
  assert.equal(кZ4.props['maximal-ideal'], false);
  assert.equal(кZ4.props['radical-ideal'], false, '√(ℚ × 0) = ℚ × (2) шире самого идеала: ℤ/4ℤ не приведено');
});

