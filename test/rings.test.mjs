test('R[1] ≅ R считается моделью, а не объявляется записью', () => {
  const схема = {
    узлы: [
      { имя: 'R', op: 'choose-ring' },
      { имя: 'G', op: 'choose-group', sort: 'Grp.obj' },
      { имя: 'A', op: 'group-ring', args: ['R', 'G'] },
    ],
  };
  const { g, имена } = построитьСхему(cat, схема);
  const C1 = каталог.группы.find((x) => x.имя === 'C1');
  assert.ok(C1, 'тривиальная группа в каталоге');
  for (const id of ['M2Q', 'ZZ']) {
    const R = каталог.кольца.find((r) => r.id === id);
    assert.ok(R, `нет кольца ${id}`);
    const знач = new Map();
    знач.set(имена.get('R'), { вид: 'ркольцо', зап: R });
    знач.set(имена.get('G'), { вид: 'группа', G: C1 });
    const A = вычислитьУзел(g, имена.get('A'), знач);
    assert.notEqual(A, НЕ_СЧИТАЕМ, `R[1] для ${id} не посчиталось`);
    assert.equal(A.зап, R, 'R[1] обязано быть самим R');
  }
});

