test('слепое пятно КОЛЬЦА считается и называется вслух', async () => {
  const { каталогМодулей, category: кат } = await import('../src/load.js');
  const { слепыеСвойства } = await import('../src/witness.js');
  const модКат = кат('mod');
  const полный = каталогМодулей();
  // Свойства КОЛЬЦА обязаны попадать в счёт слепых пятен. Проверяется это на
  // библиотеке без объявленных колец: там все кольца коммутативны и нётеровы,
  // и обе посылки не могли бы выполниться ни на одном примере. Пока кольца не
  // считались отдельными примерами, счёт их не видел вовсе и возвращал пусто.
  const толькоВычислимые = {
    ...полный,
    кольца: полный.кольца.filter((R) => !R.объявлено),
  };
  const урезанные = слепыеСвойства(модКат, толькоВычислимые);
  assert.ok(урезанные.has('comm'), 'без объявленных колец коммутативность слепа');
  assert.ok(урезанные.has('noeth-ring'), 'и нётеровость тоже');
  assert.ok(!урезанные.has('field'), 'а поле — нет: ℤ не поле, ℤ/2ℤ поле');

  // А в полной библиотеке этих пятен быть не должно: ради того объявленные
  // кольца (ℤ[x], ℤ[x₁,x₂,…], M₂(ℚ)) и заведены.
  const все = слепыеСвойства(модКат, полный);
  assert.ok(!все.has('comm'), 'M₂(ℚ) некоммутативно — пятна нет');
  assert.ok(!все.has('noeth-ring'), 'ℤ[x₁,x₂,…] не нётерово — пятна нет');
});

