import test from 'node:test';
import assert from 'node:assert/strict';

import { category, каталогГрупп } from '../src/load.js';
import { генерировать, текстЗадачи, пометкиЗадачи } from '../src/generate.js';
import { построитьСхему } from '../src/scene.js';
import { TermGraph } from '../src/term.js';

const cat = category('grp');
const каталог = каталогГрупп();

const схемаС = (quant) => ({
  узлы: [
    { имя: 'G', op: 'given', sort: 'Grp.obj', props: { finite: true } },
    { имя: 'N', op: 'choose-sub', args: ['G'], quant },
  ],
});

test('по умолчанию выбирающий узел стоит под ВСЕОБЩНОСТЬЮ', () => {
  const g = new TermGraph(cat);
  const G = g.given('Grp.obj');
  const N = g.apply('choose-sub', [G]);
  assert.equal(g.get(N).quant, 'forall',
    '«пусть N ⩽ G» в математической речи значит «для всякой»');
});

test('два квантора дают разные задачи из одной схемы', async () => {
  const прогон = (quant) => генерировать({
    cat, схема: схемаС(quant), границы: { объект: 0, подобъект: 1 },
    каталог, примеров: 400, цели: ['N'],
  });
  const в = await прогон('forall');
  const е = await прогон('exists');
  const текстВ = текстЗадачи(cat, схемаС('forall'), в.найдено[0]);
  const текстЕ = текстЗадачи(cat, схемаС('exists'), е.найдено[0]);
  assert.match(текстВ, /^Пусть G — группа, N ⩽ G\./u, 'всеобщность вводит N как данность');
  assert.match(текстЕ, /существует N ⩽ G, для которой/u, 'существование уезжает в вопрос');
  assert.ok(!/^Пусть G — группа, N ⩽ G/u.test(текстЕ), 'под ∃ вершина не вводится как данность');
  assert.ok(в.баланс && е.баланс);
});

test('под ∃ контрпримером служит объект, для которого свидетеля нет', async () => {
  // «Существует ли у конечной G нетривиальная подгруппа?» — неверно ровно для
  // единичной группы, и именно она обязана оказаться контрпримером.
  const схема = {
    узлы: [
      { имя: 'G', op: 'given', sort: 'Grp.obj', props: { finite: true } },
      { имя: 'N', op: 'choose-sub', args: ['G'], quant: 'exists', props: { trivial: false } },
    ],
  };
  const итог = await генерировать({
    cat, схема, границы: { объект: 0, подобъект: 0 }, каталог, примеров: 400, цели: ['N'],
  });
  const про = итог.найдено.find((z) => z.цель.p === 'abelian');
  assert.ok(про, 'задача про абелевость искомой подгруппы обязана найтись');
  assert.equal(про.корзина, 'опровергается примером');
  assert.match(про.свидетель, /C1/u, 'контрпример — единичная группа');
});

test('под ∀ та же цель опровергается другим примером', async () => {
  const схема = {
    узлы: [
      { имя: 'G', op: 'given', sort: 'Grp.obj', props: { finite: true } },
      { имя: 'N', op: 'choose-sub', args: ['G'], quant: 'forall', props: { trivial: false } },
    ],
  };
  const итог = await генерировать({
    cat, схема, границы: { объект: 0, подобъект: 0 }, каталог, примеров: 400, цели: ['N'],
  });
  const про = итог.найдено.find((z) => z.цель.p === 'abelian');
  assert.ok(про);
  // «всякая нетривиальная подгруппа абелева» ложно, например, в S₃ ⩽ S₃.
  assert.equal(про.корзина, 'опровергается примером');
  assert.ok(!/C1/u.test(про.свидетель ?? ''), 'под ∀ единичная группа не контрпример');
});

test('существование, подтверждённое примерами, не выдаётся за доказанное', async () => {
  // Там, где свидетеля у базы нет, примеры могут подтверждать сколько угодно —
  // это подтверждение, а не доказательство, и разница обязана быть названа.
  const схема = {
    узлы: [
      { имя: 'G', op: 'given', sort: 'Grp.obj' },
      { имя: 'N', op: 'choose-sub', args: ['G'], quant: 'exists' },
    ],
  };
  const итог = await генерировать({
    cat, схема, границы: { объект: 0, подобъект: 1 }, каталог, примеров: 300, цели: ['N'],
  });
  const подтверждённые = итог.найдено.filter(
    (z) => z.корзина === 'пробел' && z.примеров > 0 && z.верных === z.примеров,
  );
  assert.ok(подтверждённые.length > 0, 'такие случаи обязаны быть — база не всесильна');
  for (const z of подтверждённые.slice(0, 5)) {
    assert.ok(
      пометкиЗадачи(z).some((s) => /существование подтверждено/u.test(s)),
      `не сказано, что это лишь подтверждение: ${z.цельID}`,
    );
  }
});

test('на «существует» база отвечает свидетелем, а не выводом', async () => {
  const схема = {
    узлы: [
      { имя: 'G', op: 'given', sort: 'Grp.obj' },
      { имя: 'N', op: 'choose-sub', args: ['G'], quant: 'exists', props: { normal: true } },
    ],
  };
  const итог = await генерировать({
    cat, схема, границы: { объект: 0, подобъект: 0 }, цели: ['N'],
  });
  const про = итог.найдено.find((z) => z.цель.p === 'abelian');
  assert.equal(про.корзина, 'выводится');
  assert.equal(про.свидетельБазы, '1', 'единичная подгруппа и нормальна, и абелева');
  assert.ok(пометкиЗадачи(про).some((s) => /свидетель: 1/u.test(s)));
});

test('свидетелем бывает не только единица', async () => {
  // «Существует ли нормальная подгруппа, совпадающая со всей группой?» —
  // свидетель здесь сама G, и назвать надо именно её.
  const схема = {
    узлы: [
      { имя: 'G', op: 'given', sort: 'Grp.obj' },
      { имя: 'N', op: 'choose-sub', args: ['G'], quant: 'exists', props: { whole: true } },
    ],
  };
  const итог = await генерировать({
    cat, схема, границы: { объект: 0, подобъект: 0 }, цели: ['N'],
  });
  const про = итог.найдено.find((z) => z.цель.p === 'normal' && z.корзина === 'выводится');
  assert.ok(про, 'нормальность искомой подгруппы обязана выводиться');
  assert.equal(про.свидетельБазы, 'G');
});

test('свидетель не подменяет ЧУЖОЙ выбор', async () => {
  // В схеме две выбирающие вершины; подставлять вместо искомой другую
  // выбранную нельзя — это была бы другая подгруппа, а не свидетель.
  const схема = {
    узлы: [
      { имя: 'G', op: 'given', sort: 'Grp.obj' },
      { имя: 'M', op: 'choose-sub', args: ['G'], props: { normal: true } },
      { имя: 'N', op: 'choose-sub', args: ['G'], quant: 'exists', props: { normal: true } },
    ],
  };
  const итог = await генерировать({
    cat, схема, границы: { объект: 0, подобъект: 0 }, цели: ['N'],
  });
  for (const z of итог.найдено) {
    assert.notEqual(z.свидетельБазы, 'M', 'чужой выбор выдан за свидетеля');
  }
});

test('выбор итогового объекта сужает перебор', async () => {
  const схема = {
    узлы: [
      { имя: 'G', op: 'given', sort: 'Grp.obj' },
      { имя: 'Z', op: 'center', args: ['G'] },
      { имя: 'Q', op: 'quotient', args: ['G', 'Z'] },
    ],
  };
  const всё = await генерировать({ cat, схема, границы: { объект: 1 } });
  const толькоQ = await генерировать({ cat, схема, границы: { объект: 1 }, цели: ['Q'] });
  assert.ok(толькоQ.пар > 0 && толькоQ.пар < всё.пар, 'сужение обязано уменьшать число пар');
  assert.ok(всё.баланс && толькоQ.баланс, 'баланс обязан сходиться и при сужении');
  for (const z of толькоQ.найдено) {
    assert.equal(z.цель.узел ?? z.цель.узлы?.[0], 'Q', 'спрошено не про то, что просили');
  }
});

test('отношение под отрицанием печатается человеческими словами', () => {
  const схема = {
    узлы: [
      { имя: 'G', op: 'given', sort: 'Grp.obj' },
      { имя: 'N', op: 'choose-sub', args: ['G'] },
      { имя: 'M', op: 'choose-sub', args: ['G'] },
    ],
  };
  const { g, имена } = построитьСхему(cat, схема);
  void g;
  void имена;
  const запись = {
    свойства: [],
    цель: { rel: 'le', узлы: ['N', 'M'], значение: false },
    корзина: 'пробел', посылок: 0,
  };
  const текст = текстЗадачи(cat, схема, запись);
  assert.match(текст, /N не содержится в M/u);
  assert.ok(!/неверно, что/u.test(текст), 'для отношения есть своё отрицание');
});
