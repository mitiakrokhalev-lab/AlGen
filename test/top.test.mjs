test('в одноточечном пространстве подпространство — всё, и оно ему гомеоморфно', async () => {
  const { построитьСхему, атомыСхемы } = await import('../src/scene.js');
  const { рассуждать } = await import('../src/deduce.js');
  const { g, имена } = построитьСхему(cat, {
    узлы: [
      { имя: 'X', op: 'choose-space', args: [], props: { point: true } },
      { имя: 'A', op: 'choose-sub', args: ['X'] },
    ],
  });
  const мир = рассуждать(g, [...имена.values()]);
  const атомы = атомыСхемы(g, имена);
  const найти = (p, узел) => атомы.find((a) => a.p === p && a.t === имена.get(узел));
  assert.equal(мир.знает(найти('whole', 'A')), true);
  assert.equal(мир.знает(найти('open', 'A')), true, 'из «всё» следует открытость');
  assert.equal(мир.знает(найти('dense', 'A')), true);
  const гомео = атомы.find((a) => a.rel === 'homeomorphic');
  assert.equal(мир.знает(гомео), true,
    'вопрос «верно ли, что Y ≈ im f» у сюръекции — это определение сюръекции');
});
