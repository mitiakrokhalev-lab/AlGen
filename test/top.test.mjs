const cat = category('top');
const каталог = каталогПространств();
const найти = (id) => каталог.find((x) => x.id === id);

test('конечные пространства — это предпорядки, и их ровно столько, сколько предпорядков', () => {
  // Последовательность классов топологий на n точках: 1, 3, 9, 33, 139.
  assert.deepEqual([1, 2, 3, 4].map((n) => всеПространства(n).length), [1, 3, 9, 33]);
});

test('у конечного пространства T₁ равносильно дискретности', () => {
  for (const X of всеПространства(3)) {
    const p = свойстваПространства(X);
    assert.equal(p.T1, p.discrete, 'это теорема о конечных пространствах, а не упрощение модели');
    assert.equal(p.T2, p.discrete);
    assert.equal(p.metrizable, p.discrete);
    assert.equal(p.compact, true, 'конечное компактно всегда');
  }
});

test('замыкание и внутренность считаются по специализации', () => {
  // Пространство Серпинского: точка 0 открыта, точка 1 нет. В нашей записи
  // открытые замкнуты ВНИЗ, значит 0 ≤ 1 и cl{0} = {0, 1}.
  const S = пространствоП(2, [Uint8Array.from([1, 1]), Uint8Array.from([0, 1])]);
  assert.deepEqual(замыканиеП(S, [0]), [0, 1], 'замыкание открытой точки — всё пространство');
  assert.deepEqual(замыканиеП(S, [1]), [1]);
  assert.deepEqual(внутренностьП(S, [1]), [], 'внутренность замкнутой точки пуста');
  assert.deepEqual(внутренностьП(S, [0]), [0]);
  assert.equal(свойстваПространства(S).connected, true, 'Серпинский связен');
  assert.equal(свойстваПространства(S).T0, true);
});

test('фактор конечного пространства считается транзитивным замыканием', () => {
  const S = пространствоП(2, [Uint8Array.from([1, 1]), Uint8Array.from([0, 1])]);
  const Q = стянутьП(S, [0, 1]);
  assert.equal(Q.n, 1, 'стянув всё, получаем точку');
});

test('непрерывные отображения конечных пространств — это монотонные', () => {
  const S = пространствоП(2, [Uint8Array.from([1, 1]), Uint8Array.from([0, 1])]);
  const D = пространствоП(2, [Uint8Array.from([1, 0]), Uint8Array.from([0, 1])]);
  // Из дискретного в Серпинского непрерывны все 4 отображения,
  // из Серпинского в дискретное — только 2 постоянных.
  assert.equal(отображенияП(D, S).length, 4);
  assert.equal(отображенияП(S, D).length, 2);
  assert.equal(гомеоморфны(S, D), false);
});

test('объявленные пространства связались и дают свойства', () => {
  const S = найти('S');
  assert.ok(S, 'прямая Зоргенфрея обязана быть в библиотеке');
  const p = свойства({ вид: 'имяпростр', зап: S });
  assert.equal(p.separable, true);
  assert.equal(p['second-countable'], false);
  assert.equal(p.metrizable, false, 'сепарабельность плюс первая аксиома метризуемости не дают');
  const плоскость = свойства({ вид: 'имяпростр', зап: найти('S2') });
  assert.equal(плоскость.T3, true);
  assert.equal(плоскость.T4, false, 'ради этого единственного факта плоскость и объявлена');
});

test('синтез произведения — конъюнкция, и нормальность в него не входит', () => {
  const a = { T2: true, T4: true, compact: true, separable: true, connected: true };
  const b = { T2: true, T4: true, compact: false, separable: true, connected: true };
  const p = свойстваПроизведенияТоп(a, b);
  assert.equal(p.T2, true);
  assert.equal(p.compact, false, 'некомпактный сомножитель делает произведение некомпактным');
  assert.equal(p.T4, undefined, 'плоскость Зоргенфрея: нормальность произведением не сохраняется');
  const s = свойстваСуммыТоп(a, b);
  assert.equal(s.connected, false, 'сумма двух непустых несвязна всегда');
  assert.equal(s.T4, true, 'а нормальность дизъюнктной суммой сохраняется');
  assert.equal(s.point, false);
});

