import test from 'node:test';
import assert from 'node:assert/strict';

import { category, каталогРаздела } from '../src/load.js';
import { генерировать, текстВычисления } from '../src/generate.js';
import { таблицаПримеров, отобратьСтроки } from '../src/witness.js';
import { ПОРАЗДЕЛАМ } from '../src/схемы.js';

// Цель «ВЫЧИСЛИТЕ» — другая форма вопроса, а не ещё одна корзина. Корзины
// раскладывают пары «посылки × утверждение», и договор о балансе держится на
// том, что каждая пара попала ровно в одну; вычисление спрашивает ВЕЛИЧИНУ,
// пары не образует и считается отдельным проходом по той же таблице примеров.

const cat = category('grp');
const схема = ПОРАЗДЕЛАМ.grp.индекс;

test('числовые величины доходят до таблицы примеров', async () => {
  const т = await таблицаПримеров({
    cat, схема, каталог: каталогРаздела('grp'), предел: 300, предельныйПорядок: 12,
  });
  assert.deepEqual(т.числовые, ['i'], 'индекс — единственная числовая вершина схемы');
  const есть = т.строки.filter((r) => Number.isFinite(r.числа?.[0]));
  assert.ok(есть.length > 50, 'у большинства строк индекс посчитан');
});

test('условие, определяющее величину, даёт её одним значением', async () => {
  // Прямая проверка самого мерила: если отобрать строки, где подгруппа — вся
  // группа, индекс на всех окажется единицей. Именно это и ищет проход
  // «вычислите»; здесь оно проверяется без перебора.
  const т = await таблицаПримеров({
    cat, схема, каталог: каталогРаздела('grp'), предел: 20000, предельныйПорядок: 12,
  });
  const строки = отобратьСтроки(т, [{ ключ: 'whole@N', значение: true }]);
  const значения = new Set(строки.map((r) => r.числа[0]).filter((v) => v !== undefined && v !== null));
  assert.ok(строки.length > 10, 'строк с целой подгруппой должно быть много');
  assert.deepEqual([...значения], [1], 'индекс целой подгруппы равен единице');
});

test('баланс корзин не ломается новым проходом', async () => {
  const итог = await генерировать({
    cat, схема, границы: { объект: 1, подобъект: 1, число: 0 },
    каталог: каталогРаздела('grp'), примеров: 4000, хватит: 3000,
  });
  assert.ok(итог.баланс, 'вычисления не считаются парой и баланса не трогают');
  assert.ok(Array.isArray(итог.вычисления), 'проход отдаёт свой список');
});

test('тавтология не спрашивается: величину, заданную посылкой, не вычисляют', async () => {
  // «Известно, что (G : N) равно 2. Вычислите (G : N)» — это не вопрос. Запрет
  // тот же, что «цель — посылка» у обычных задач, только для числового.
  const итог = await генерировать({
    cat, схема, границы: { объект: 0, подобъект: 0, число: 1 },
    каталог: каталогРаздела('grp'), примеров: 4000, хватит: 3000,
  });
  const тавтологии = (итог.вычисления ?? []).filter((z) =>
    (z.свойства ?? []).some(([имя, p]) => имя === z.узел && Object.keys(p).length));
  assert.deepEqual(тавтологии, [], 'вершина с условием на саму величину не спрашивается');
});

test('текст вопроса «вычислите» собирается без цели-утверждения', () => {
  const z = { свойства: [['N', { normal: true }]], узел: 'i', значение: 2, примеров: 7 };
  const текст = текстВычисления(cat, схема, z);
  assert.match(текст, /Вычислите \(G : N\)\.$/u);
  assert.ok(!текст.includes('Верно ли'), 'у вычисления нет цели-утверждения');
});
