import test from 'node:test';
import assert from 'node:assert/strict';

import { таблицаПоПрезентации, перечислитьКлассы } from '../src/model/презентация.js';
import {
  группа, свойстваГруппы, подгруппы, порождённая, нормальна, умножить,
} from '../src/model/group.js';
import { каталогГрупп } from '../src/load.js';

// Перечисление смежных классов проверяется на заданиях с ИЗВЕСТНЫМ ответом:
// иначе проверять нечем. Ассоциативность тоже проверяется — ошибка в
// перечислении даёт «таблицу», которая группой не является, и заметить это по
// одному порядку нельзя.
const собрать = (k, соотн, предел = 20000) => {
  const r = таблицаПоПрезентации(k, соотн, предел);
  assert.ok(!r.оборвано, `перечисление оборвано на ${r.оборвано}`);
  return { r, G: группа(r.n, r.mul, 'проба') };
};

const ассоциативна = (G, шаг = 1) => {
  for (let a = 0; a < G.n; a += шаг) {
    for (let b = 0; b < G.n; b++) {
      for (let c = 0; c < G.n; c++) {
        if (умножить(G, умножить(G, a, b), c) !== умножить(G, a, умножить(G, b, c))) return false;
      }
    }
  }
  return true;
};

test('циклическая по одному соотношению', () => {
  const { G } = собрать(1, [[[0, 5]]]);
  assert.equal(G.n, 5);
  const p = свойстваГруппы(G);
  assert.equal(p.cyclic, true);
  assert.equal(p.abelian, true);
});

test('S₃ по стандартному заданию', () => {
  const { G } = собрать(2, [[[0, 3]], [[1, 2]], [[0, 1], [1, 1], [0, 1], [1, 1]]]);
  assert.equal(G.n, 6);
  assert.equal(ассоциативна(G), true);
  const p = свойстваГруппы(G);
  assert.equal(p.abelian, false);
  assert.equal(p.solvable, true);
});

test('Q₈ по заданию a⁴ = e, a² = b², ab = ba⁻¹', () => {
  const { G } = собрать(2, [[[0, 4]], [[0, 2], [1, -2]], [[0, 1], [1, 1], [0, 1], [1, -1]]]);
  assert.equal(G.n, 8);
  assert.equal(ассоциативна(G), true);
  const p = свойстваГруппы(G);
  assert.equal(p.abelian, false);
  // У Q₈ ровно одна инволюция — это и отличает её от D₄ того же порядка.
  let инволюций = 0;
  for (let a = 1; a < G.n; a++) if (умножить(G, a, a) === 0) инволюций++;
  assert.equal(инволюций, 1);
});

test('свободная группа ранга 2: перечисление ОБРЫВАЕТСЯ, а не врёт', () => {
  // Соотношений нет, группа бесконечна. Правильный ответ — «оборвано», и
  // молчать об этом нельзя: «не влезло» и «бесконечна» — разные утверждения.
  const r = перечислитьКлассы(2, [], 200);
  assert.ok(r.оборвано, 'перечисление обязано оборваться');
  assert.equal(r.предел, 200);
  assert.equal(r.n, undefined);
});

test('мишень 8.8: H = ⟨a²⟩ нормальна и |G/H| = 30', () => {
  const { r, G } = собрать(2, [[[0, 22]], [[1, 15]], [[0, 1], [1, 1], [0, -3], [1, -1]]]);
  assert.equal(G.n, 330);
  // Шаг 7 вместо полного обхода: 330³ — тридцать шесть миллионов тройек, и
  // проверка стала бы самым долгим тестом набора. Ошибку перечисления ловит и
  // выборка.
  assert.equal(ассоциативна(G, 7), true);
  const a = r.образующие[0];
  const H = порождённая(G, [умножить(G, a, a)]);
  assert.equal(H.length, 11);
  assert.equal(нормальна(G, H), true);
  assert.equal(G.n / H.length, 30);
});

