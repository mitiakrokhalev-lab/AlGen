test('три расширения, закрывшие названные пустоты', () => {
  // Несовершенное поле с СЕПАРАБЕЛЬНЫМ расширением: Артин — Шрайер.
  const as = расшир('F2x<F2tAS');
  assert.ok(as, 'расширение Артина — Шрайера объявлено');
  assert.equal(as.props.separable, true, 'у x² + x + t производная 1 ≠ 0');
  assert.equal(as.props.galois, true);
  assert.equal(поле('F2x').props['perfect-field'], false, 'основное поле НЕсовершенно');
  // Ненормальное расширение в положительной характеристике.
  const cb = расшир('F2x<F2tcbrt');
  assert.equal(cb.степень, 3);
  assert.equal(cb.props['normal-ext'], false, 'ζ₃ ∉ 𝔽₂(t)');
  assert.equal(cb.props.separable, true, '3 взаимно просто с характеристикой 2');
  // Несепарабельное расширение НЕЧЁТНОЙ степени.
  const ins = расшир('F3x<F3t3');
  assert.equal(ins.степень, 3);
  assert.equal(ins.props.separable, false);
  assert.equal(ins.props['normal-ext'], true, 'чисто несепарабельное нормально');
});
