// --- синтез полей и правила невозможности --------------------------------------
//
// Библиотека полей была мала (30 полей), и главной причиной бедности раздела
// оказалась не немота, а ПУСТОТА: под условие не подходил ни один объект.
// Диагност `мера --пусто` показал, что часть таких условий ПРОТИВОРЕЧИВА, —
// значит виновата не библиотека, а база.

test('рациональные функции и замыкание синтезируются по теоремам', () => {
  const K = поле('F3');
  assert.ok(K._рациональные, 'у 𝔽₃ есть поле рациональных функций');
  const F3x = поле('F3x') ?? K._рациональные;
  assert.equal(F3x.props['perfect-field'], false,
    'в характеристике p поле рациональных функций НЕсовершенно: у t нет корня степени p');
  const зам = поле('F3')._замыкание;
  assert.ok(зам, 'у 𝔽₃ есть алгебраическое замыкание');
  assert.equal(зам.props['alg-closed'], true);
  assert.equal(зам.props['finite-field'], false, 'замкнутое поле бесконечно');
  assert.equal(зам.props['perfect-field'], true);
  // Несовершенных полей стало много больше четырёх — это и есть польза синтеза.
  const несовершенные = каталог.поля.filter((F) => F.props?.['perfect-field'] === false);
  assert.ok(несовершенные.length >= 12, `несовершенных всего ${несовершенные.length}`);
});

