test('несепарабельное расширение в библиотеке есть, и оно опровергает «алгебраическое ⇒ сепарабельное»', () => {
  const S = расшир('F2t2<F2x');
  assert.equal(S.props.algebraic, true);
  assert.equal(S.props.separable, false);
  assert.equal(S.props['normal-ext'], true, 'нормально: (x − t)² — единственный корень, и он в поле');
  assert.equal(S.props.galois, false);
  // И основное поле обязано быть несовершенным, иначе правило «над совершенным
  // алгебраическое сепарабельно» противоречило бы записи.
  assert.equal(поле('F2t2').props['perfect-field'], false);
});

