test('перебор по полям даёт опровержения, а не одни пробелы', async () => {
  const итог = await генерировать({
    cat, схема: ГАЛУА, границы: { объект: 1, морфизм: 1, число: 1 },
    каталог, примеров: 4000, хватит: 4000,
  });
  const по = {};
  for (const z of итог.найдено) по[z.корзина] = (по[z.корзина] ?? 0) + 1;
  assert.ok(итог.баланс, 'договор о корзинах: каждая задача ровно в одной');
  assert.ok((по['опровергается примером'] ?? 0) > 50,
    `опровержений примером должно быть много, а их ${по['опровергается примером'] ?? 0}`);
  // Текст обязан собираться: формулы [L : K] и Gal(L/K) берут поля ролями.
  const z = итог.найдено.find((x) => x.корзина === 'опровергается примером');
  assert.match(текстЗадачи(cat, ГАЛУА, z), /Докажите или опровергните/u);
});

