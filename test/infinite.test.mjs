// --- свободное произведение ---------------------------------------------------
//
// Пока A ∗ B было целиком невычислимо, условие «A абелева, B неразрешима»
// уходило в пробел: цель «центр A ∗ B тривиален» нечем было ни подтвердить, ни
// опровергнуть. А опровержение лежит на поверхности — A = 1.

const СХЕМА_СВОБОДНОЕ = {
  узлы: [
    { имя: 'A', op: 'given', sort: 'Grp.obj' },
    { имя: 'B', op: 'given', sort: 'Grp.obj' },
    { имя: 'F', op: 'freeprod', args: ['A', 'B'] },
    { имя: 'Z', op: 'center', args: ['F'] },
  ],
};

test('тождество 1 ∗ B = B делает свободное произведение вычислимым', () => {
  const { g, имена } = построитьСхему(cat, СХЕМА_СВОБОДНОЕ);
  const значения = new Map();
  значения.set(имена.get('A'), { вид: 'группа', G: каталог.find((x) => x.имя === 'C1') });
  значения.set(имена.get('B'), зап('A5xZ')._сам);
  const F = вычислитьУзел(g, имена.get('F'), значения);
  assert.equal(F?.вид, 'имя', 'A ∗ B при тривиальном A — это сам B');
  assert.equal(F.зап.id, 'A5xZ');
});

test('объявленная таблица даёт C₂ ∗ C₂ ≅ D∞', () => {
  const { g, имена } = построитьСхему(cat, СХЕМА_СВОБОДНОЕ);
  const значения = new Map();
  const C2 = каталог.find((x) => x.имя === 'C2');
  значения.set(имена.get('A'), { вид: 'группа', G: C2 });
  значения.set(имена.get('B'), { вид: 'группа', G: C2 });
  const F = вычислитьУзел(g, имена.get('F'), значения);
  assert.equal(F?.вид, 'имя');
  assert.equal(F.зап.id, 'Dinf', 'C₂ ∗ C₂ — бесконечная диэдральная');
  // И таблица обязана читаться в обе стороны.
  assert.equal(свойства(F).finite, false);
});

test('«A абелева, B неразрешима ⇒ центр A ∗ B тривиален» ОПРОВЕРГАЕТСЯ примером', async () => {
  const т = await таблицаПримеров({
    cat, схема: СХЕМА_СВОБОДНОЕ, каталог, предел: 20000, предельныйПорядок: 12,
  });
  const i = (к) => {
    const j = т.индекс.get(к);
    assert.ok(j !== undefined, `нет атома ${к}`);
    return j;
  };
  const [ab, sol, triv] = [i('abelian@A'), i('solvable@B'), i('trivial@Z')];
  const подходят = т.строки.filter((r) => r.биты[ab] === 1 && r.биты[sol] === 0);
  assert.ok(подходят.length > 100, `условию подходит всего ${подходят.length} примеров`);
  const контр = подходят.filter((r) => r.биты[triv] === 0);
  assert.ok(контр.length > 0, 'условие обязано опровергаться: при A = 1 центр равен Z(B)');
  assert.ok(
    контр.some((r) => /A = C1/.test(r.описание ?? '')),
    'контрпример должен быть именно с тривиальным A',
  );
});

