test('канонические морфизмы бесконечной группы строятся без объявления', () => {
  const схема = {
    узлы: [
      { имя: 'G', op: 'given', sort: 'Grp.obj' },
      { имя: 'N', op: 'choose-sub', args: ['G'], props: { normal: true } },
      { имя: 'p', op: 'proj', args: ['G', 'N'] },
      { имя: 'i', op: 'incl', args: ['G', 'N'] },
    ],
  };
  const { g, имена } = построитьСхему(cat, схема);
  const значения = new Map();
  значения.set(имена.get('G'), { вид: 'имя', зап: зап('Z') });
  значения.set(имена.get('N'), подзначение(зап('Z')._поПодгруппе.get('2Z')));
  const π = вычислитьУзел(g, имена.get('p'), значения);
  const ι = вычислитьУзел(g, имена.get('i'), значения);
  assert.ok(π && ι, 'проекция и вложение обязаны строиться из уже записанного');
  assert.equal(свойства(π).surjective, true);
  assert.equal(свойства(π).injective, false, 'ядро проекции — 2ℤ, она не инъективна');
  assert.equal(свойства(ι).injective, true);
  assert.equal(свойства(ι).surjective, false, 'образ вложения — 2ℤ, не вся ℤ');
});

