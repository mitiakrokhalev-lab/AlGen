const cat = category('grp');
const каталог = каталогГрупп();
const бесконечные = каталог.filter((x) => x.бесконечная);
const зап = (id) => бесконечные.find((x) => x.id === id);

const СХЕМА_ФАКТОР = {
  узлы: [
    { имя: 'G', op: 'given', sort: 'Grp.obj' },
    { имя: 'N', op: 'choose-sub', args: ['G'], props: { normal: true } },
    { имя: 'Q', op: 'quotient', args: ['G', 'N'] },
  ],
};

test('библиотека содержит и конечные, и бесконечные', () => {
  assert.ok(бесконечные.length >= 10, `бесконечных ${бесконечные.length}`);
  assert.ok(каталог.some((x) => x.mul), 'конечные никуда не делись');
  assert.ok(зап('Z') && зап('Q') && зап('F2') && зап('Dinf'));
});

test('ссылки в записях связаны, а не оставлены строками', () => {
  const Z = зап('Z');
  assert.ok(Z._поПодгруппе.get('2Z'), 'подгруппа 2ℤ не найдена');
  assert.equal(Z._конструкции.center.зап.id, 'все', 'центр ℤ — вся группа');
  assert.equal(Z._конструкции.commutator.зап.id, '0', 'коммутант ℤ тривиален');
  assert.equal(Z._факторы.get('2Z').G.имя, 'C2', 'ℤ/2ℤ ≅ C₂');
  assert.equal(Z._конструкции.aut.G.имя, 'C2', 'Aut(ℤ) ≅ C₂');
});

test('конструкции на бесконечной группе вычисляются по объявлению', () => {
  const { g, имена } = построитьСхему(cat, СХЕМА_ФАКТОР);
  const значения = new Map();
  значения.set(имена.get('G'), { вид: 'имя', зап: зап('Z') });
  значения.set(имена.get('N'), подзначение(зап('Z')._поПодгруппе.get('2Z')));
  const Q = вычислитьУзел(g, имена.get('Q'), значения);
  assert.ok(Q, 'фактор ℤ/2ℤ обязан вычислиться');
  assert.equal(свойства(Q).finite, true);
  assert.equal(свойства(Q).cyclic, true);
});

