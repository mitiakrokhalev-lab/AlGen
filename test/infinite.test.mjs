// --- группа Григорчука --------------------------------------------------------
//
// Во всей прежней библиотеке конечно порождённые периодические группы были
// только конечными, и четыре вопроса этого семейства подтверждались на всех
// примерах. Это общая проблема Бернсайда, и ответ на неё отрицательный.

test('группа Григорчука опровергает «конечно порождена и периодична ⇒ G/Z(G) конечна»', async () => {
  const схема = {
    узлы: [
      { имя: 'G', op: 'given', sort: 'Grp.obj' },
      { имя: 'Z', op: 'center', args: ['G'] },
      { имя: 'Q', op: 'quotient', args: ['G', 'Z'] },
    ],
  };
  const т = await таблицаПримеров({ cat, схема, каталог, предел: 4000, предельныйПорядок: 12 });
  const i = (к) => {
    const j = т.индекс.get(к);
    assert.ok(j !== undefined, `нет атома ${к}`);
    return j;
  };
  const под = т.строки.filter((r) => r.биты[i('fin-gen@G')] === 1 && r.биты[i('periodic@G')] === 1);
  assert.ok(под.length >= 10, `конечно порождённых периодических примеров всего ${под.length}`);
  for (const атом of ['finite@Q', 'finite-index@Z']) {
    const нет = под.filter((r) => r.биты[i(атом)] === 0);
    assert.ok(нет.length > 0, `«${атом}» не опровергается`);
    assert.ok(нет.some((r) => /Григорчука/.test(r.описание ?? '')),
      `контрпример к «${атом}» должен быть группой Григорчука`);
  }
});

