// Перебор задач из командной строки.
//
//   node bin/gen.mjs --схемы                     — какие схемы встроены
//   node bin/gen.mjs фактор                      — перебрать по схеме «фактор»
//   node bin/gen.mjs центр --подобъект 2 --корзина пробел
//   node bin/gen.mjs морфизм --хватит 5 --случайно     — «случайная задача»
//
// Флаги границ (--объект, --подобъект, --морфизм) — это СКОЛЬКО свойств
// разрешено навесить на узел соответствующего сорта. Потолков, кроме
// названных человеком, тут нет; обрыв объявляется вслух.

import { category, каталогРаздела } from '../src/load.js';
import { генерировать, текстЗадачи, пометкиЗадачи } from '../src/generate.js';
import { жетон } from '../src/stop.js';

// Таблица примеров берётся с диска, если данные и код модели не менялись.
// Флаг `--без-кэша` — для случая, когда надо замерить честную постройку.
const КЭШ = process.argv.includes('--без-кэша') ? null : кэшПримеров();

export { СХЕМЫ, СХЕМЫ_МОД, СХЕМЫ_ТОП, ПОРАЗДЕЛАМ } from '../src/схемы.js';
import { ПОРАЗДЕЛАМ } from '../src/схемы.js';
import { сводкаРазрядов, РАЗРЯДЫ, БЕДНОСТЬ } from '../src/мера-пробела.js';
import { кэшПримеров } from '../src/кэш-примеров.js';
function разобрать(argv) {
  const o = { границы: {}, корзины: null };
  const имена = [];
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (!a.startsWith('--')) {
      имена.push(a);
      continue;
    }
    const ключ = a.slice(2);
    const дальше = argv[i + 1];
    switch (ключ) {
      case 'объект': case 'подобъект': case 'морфизм': case 'элемент': case 'кольцо':
      case 'число': case 'система': case 'семейство':
        o.границы[ключ] = Number(argv[++i]); break;
      case 'достройка': o.достройка = Number(argv[++i]); break;
      case 'дизъюнкции': o.дизъюнктивные = true; break;
      case 'хватит': o.хватит = Number(argv[++i]); break;
      case 'зерно': o.зерно = Number(argv[++i]); break;
      case 'примеров': o.примеров = Number(argv[++i]); break;
      case 'раздел': o.раздел = argv[++i]; break;
      case 'безпримеров': o.безПримеров = true; break;
      case 'случайно': o.случайно = true; break;
      case 'схемы': o.перечислить = true; break;
      case 'корзина': o.корзины = (дальше ?? '').split(','); i++; break;
      // Фильтр по РАЗРЯДУ пробела: «--разряд кандидат» оставляет только
      // кандидатов в научные, «--разряд пусто,немо» — только бедность базы.
      case 'разряд': o.разряды = (дальше ?? '').split(','); i++; break;
      case 'всё': o.всё = true; break;
      default: throw new Error(`не знаю флаг --${ключ}`);
    }
  }
  o.схема = имена[0];
  o.раздел ??= 'grp';
  return o;
}

const o = разобрать(process.argv.slice(2));

if (o.перечислить || !o.схема) {
  console.log('Встроенные схемы:');
  for (const [id, s] of Object.entries(ПОРАЗДЕЛАМ[o.раздел])) {
    console.log(`  ${id.padEnd(22)} ${s.имя}  (узлов ${s.узлы.length})`);
  }
  process.exit(o.схема ? 0 : 1);
}

const схема = ПОРАЗДЕЛАМ[o.раздел][o.схема];
if (!схема) throw new Error(`нет схемы «${o.схема}» в разделе «${o.раздел}»; посмотреть: --схемы`);

const cat = category(o.раздел);
const знак = жетон();
const t0 = Date.now();

const итог = await генерировать({
        кэш: КЭШ,
  cat,
  схема,
  границы: o.границы,
  достройка: o.достройка ?? 1,
  // Дизъюнктивные цели умножают их число: на каждый предикат добавляется пара
  // на каждую пару вершин. Поэтому по умолчанию выключены и просятся явно.
  дизъюнктивные: Boolean(o.дизъюнктивные),
  хватит: o.хватит ?? null,
  случайно: o.случайно ?? false,
  зерно: o.зерно ?? 1,
  каталог: o.безПримеров ? null : каталогРаздела(o.раздел),
  примеров: o.примеров ?? 3000,
  знак,
  тик: (с) => {
    if (с.вид === 'примеры-готовы') console.log(`примеров построено: ${с.строк}${с.усечено ? ' (УСЕЧЕНО, см. --примеров)' : ''}`);
    else if (с.вид === 'начало') console.log(`наборов посылок: ${с.наборов}, свободных узлов: ${с.свободных}`);
    else if (process.stderr.isTTY) process.stderr.write(`\r  ${с.сделано}/${с.всего}, найдено ${с.найдено}   `);
  },
});
process.stderr.write('\r' + ' '.repeat(50) + '\r');

const показать = итог.найдено
  .filter((z) => !o.корзины || o.корзины.includes(z.корзина))
  .filter((z) => !o.разряды || (z.разряд && o.разряды.includes(z.разряд)));
const предел = o.всё ? показать.length : Math.min(показать.length, 40);
for (const z of показать.slice(0, предел)) {
  console.log(`\n[${z.корзина}] ${текстЗадачи(cat, схема, z)}`);
  for (const п of пометкиЗадачи(z)) console.log(`    ${п}`);
}
if (предел < показать.length) {
  console.log(`\n…показано ${предел} из ${показать.length}; весь список — флаг --всё`);
}

console.log('\n— корзины —');
for (const [k, v] of Object.entries(итог.счёт)) if (v) console.log(`  ${k.padEnd(16)} ${v}`);
// РАЗБОР ПРОБЕЛОВ. Без него «пробелов 2293» — число, по которому нельзя понять
// ничего: в нём и кандидаты в научные, и условия, под которые не подошёл ни
// один объект библиотеки. Это противоположные вещи, и показывать их одним
// числом было ошибкой.
const св = сводкаРазрядов(итог.найдено);
if (св.пробелов) {
  console.log('');
  console.log('— из чего состоят пробелы —');
  for (const р of РАЗРЯДЫ) {
    const v = св.счёт[р];
    if (!v) continue;
    const доля = `${(100 * v / св.пробелов).toFixed(1)}%`;
    const метка = р === 'кандидат' ? '  <- КАНДИДАТЫ В НАУЧНЫЕ' : (БЕДНОСТЬ.has(р) ? '  (бедность библиотеки)' : '');
    console.log(`  ${р.padEnd(14)} ${String(v).padStart(6)}  ${доля.padStart(6)}${метка}`);
  }
  const проц = (v) => `${(100 * v / св.пробелов).toFixed(1)}%`.padStart(6);
  console.log(`  ${'ВСЕГО бедности'.padEnd(14)} ${String(св.бедность).padStart(6)}  ${проц(св.бедность)}  — лечится библиотекой и моделью, не математикой`);
  console.log(`  ${'КАНДИДАТОВ'.padEnd(14)} ${String(св.кандидатов).padStart(6)}  ${проц(св.кандидатов)}  — показать их: --корзина пробел --разряд кандидат`);
}
console.log(`  ${'ИТОГО пар'.padEnd(16)} ${итог.пар}  баланс ${итог.баланс ? 'сошёлся' : 'НЕ СОШЁЛСЯ'}`);
if (итог.противоречия?.length) {
  console.log(`  ПРОТИВОРЕЧИЙ базы и модели: ${итог.противоречия.length}`);
  for (const p of итог.противоречия.slice(0, 5)) console.log(`    ${p.цель}: правило «${p.правило}» против примера «${p.пример}»`);
}
if (итог.оборвано) console.log(`  оборвано: ${итог.оборвано.причина}`);
console.log(`  время: ${((Date.now() - t0) / 1000).toFixed(1)} с`);
