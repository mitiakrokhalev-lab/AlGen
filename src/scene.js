// Схема условия: построение графа по описанию и перечень атомов.
//
// Вынесено отдельно, потому что этим пользуются и перебор, и таблица примеров.
// Список атомов обязан быть ОДИН: если цели генератора и столбцы таблицы
// разойдутся, опровержения начнут теряться молча.

import { TermGraph } from './term.js';
import { fits, свойствоПодходит } from './sorts.js';

export function построитьСхему(cat, схема, свойства = new Map()) {
  const g = new TermGraph(cat);
  const имена = new Map();
  const узел = (имя) => {
    if (!имена.has(имя)) throw new Error(`узел «${имя}» не объявлен раньше использования`);
    return имена.get(имя);
  };
  for (const n of схема.узлы) {
    const props = { ...(n.props ?? {}), ...(свойства.get(n.имя) ?? {}) };
    if (n.op === 'given' || n.op === 'named') {
      // У именованной вершины идентификатор («Z») и то, как её читают («ℤ»), —
      // разные вещи. Печатать идентификатор значит показывать человеку
      // внутреннее имя библиотеки вместо математического обозначения.
      const показ = n.показ ?? n.объект ?? null;
      имена.set(n.имя, g.given(n.sort, props, { имя: показ, объект: n.объект ?? null, named: n.op === 'named', схемИмя: n.имя }));
    } else {
      имена.set(n.имя, g.apply(n.op, (n.args ?? []).map(узел), { props, quant: n.quant, схемИмя: n.имя }));
    }
  }
  return { g, имена };
}

// Всё, про что может пойти речь: свойства на вершинах схемы и отношения между
// ними. Это же и множество целей перебора.
export function атомыСхемы(g, имена) {
  const свои = [...имена.values()];
  const out = [];
  for (const id of свои) {
    const n = g.get(id);
    for (const p of g.cat.props.values()) {
      if (свойствоПодходит(n.sort, p, g.cat.up)) out.push({ p: p.id, t: id });
    }
  }
  for (const r of g.cat.rels.values()) {
    for (const a of свои) {
      for (const b of свои) {
        if (a === b) continue;
        if (r.symmetric && b < a) continue;
        if (!fits(g.get(a).sort, r.in[0], g.cat.up)) continue;
        if (!fits(g.get(b).sort, r.in[1], g.cat.up)) continue;
        if (r.same && g.rel(a, r.same) !== g.rel(b, r.same)) continue;
        out.push({ rel: r.id, args: [a, b] });
      }
    }
  }
  return out;
}

// Атом в виде, не зависящем от конкретного графа: по именам вершин схемы.
export function ключПоИмени(атом, имяПоУзлу) {
  // Дизъюнктивная цель «A или B» — это тоже атом выдачи, и ключ у неё свой.
  // Части сортируются: «A или B» и «B или A» — одна и та же цель.
  if (Array.isArray(атом.или)) {
    return `или(${атом.или.map((a) => ключПоИмени(a, имяПоУзлу)).sort().join(",")})`;
  }
  return атом.rel
    ? `${атом.rel}#${имяПоУзлу.get(атом.args[0])}#${имяПоУзлу.get(атом.args[1])}`
    : `${атом.p}@${имяПоУзлу.get(атом.t)}`;
}

export function свободныеВершины(схема, cat) {
  return схема.узлы.filter((n) => n.op === 'given' || cat.cons.get(n.op)?.choice);
}

// --- чем задача опознаётся для читателя ---------------------------------------
//
// «Там, где должно быть от силы десять задач, их десятки тысяч» — это про то,
// что одно и то же утверждение выдаётся с десятками разных наборов посылок.
// Вопрос задан про КОНКРЕТНЫЙ ТЕРМ и состоит в КОНКРЕТНОМ свойстве, и ровно
// этой парой задача и опознаётся.
//
// Ключ терма из `src/term.js` для этого не годится прямо: у ВЫБИРАЮЩЕГО узла в
// ключ входят его свойства и личный номер («возьмём НОРМАЛЬНУЮ подгруппу» —
// другая личность, чем «возьмём подгруппу»), поэтому по нему «N нормальна ⇒
// G/N абелева» и «N нормальна и максимальна ⇒ G/N абелева» — разные вопросы.
// А для читателя это один вопрос с двумя условиями, и из двух надо брать то,
// где посылок меньше: оно сильнее.
//
// Поэтому из ключа вычёркиваются навешанные свойства, а структура терма
// сохраняется. Вырождений ключ НЕ знает: `построитьСхему` их не делает (это
// работа `src/normalize.js`), и «Z(G) циклична» при абелевой G остаётся
// отдельным вопросом от «G циклична». Отсеиваются такие условия раньше —
// вырожденное условие вообще не доходит до отбора.
//
// Отсюда же следствие, на которое стоит опираться: ключ НЕ ЗАВИСИТ от посылок,
// и сцену для него достаточно построить ОДИН РАЗ на схему.
// Из ключа вычёркиваются ровно фигурные скобки — навешанные на выбор свойства.
// Личный номер выбора (`#3`) ОСТАЁТСЯ: он говорит, какая это из двух подгрупп,
// и без него «N ∩ M тривиально» склеилось бы с «N ∩ N тривиально». Номер
// устойчив: он выдаётся по порядку создания узлов, а порядок задаёт схема, а не
// посылки. Имена свойств — латинские идентификаторы, фигурных скобок в них
// быть не может, поэтому вычёркивание однозначно.
export function канонТерма(g, id) {
  return g.get(id).key.replace(/\{[^{}]*\}/g, '');
}

export function ключВопроса(g, имена, цель) {
  const части = [];
  const вершины = (ц) => (ц?.rel ? ц.узлы : [ц?.узел]);
  const собрать = (ц) => {
    if (Array.isArray(ц?.или)) { ц.или.forEach(собрать); return; }
    const т = вершины(ц).map((имя) => {
      const id = имена.get(имя);
      return id === undefined ? '?' : канонТерма(g, id);
    });
    части.push(`${ц?.rel ?? ц?.p}${ц?.значение === false ? '!' : ''}(${т.join(',')})`);
  };
  собрать(цель);
  return части.sort().join(' | ');
}
