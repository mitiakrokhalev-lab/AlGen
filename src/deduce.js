// Вывод фактов о термах графа.
//
// Работает вперёд по клаузам Хорна над СЦЕНОЙ: у правила есть роли со своими
// сортами и согласованиями, роли привязываются к УЖЕ ПОСТРОЕННЫМ термам графа,
// после чего посылки проверяются, а заключение добавляется в мир.
//
// Почему роли привязываются к любым термам, а не только к вводящим узлам: это
// и даёт наследственность бесплатно. Правило «подгруппа абелевой группы
// абелева» написано один раз, а срабатывает на Z(G), ker φ, N ∩ M и на всём
// остальном, что имеет сорт Grp.sub и нужный объемлющий объект.
//
// Глубина вывода считается и хранится: она и есть мера учебности задачи.
// Длинное доказательство очевидного факта означает дыру в таблице сохранения,
// а не находку, — первые прогоны нового раздела читать именно на это.

import { fits, свойствоПодходит } from './sorts.js';
import { matchAny } from './normalize.js';
import { known } from './facts.js';

const СВЯЗИ = ['ambient', 'dom', 'cod', 'base'];

// --- компиляция правил ------------------------------------------------------

// Сокращённая запись сохранения разворачивается в обычное правило: «preserves»
// у конструкции значит «свойство всех входов ТОГО ЖЕ сорта, что и выход,
// переносится на выход». Для фактора это X (подгруппа объявлена другим
// сортом), для произведения — оба сомножителя, для пересечения — обе
// подгруппы. Правило выбора сорта, а не перечисление, — чтобы данные не врали
// молча при добавлении слота.
function однородныеРоли(c) {
  return (c.in ?? []).filter((s) => s.sort === c.out.sort).map((s) => s.role);
}

function сценаКонструкции(c) {
  return (c.in ?? []).map((s) => {
    const r = { name: s.role, sort: s.sort };
    for (const k of СВЯЗИ) if (s[k] !== undefined) r[k] = s[k];
    return r;
  });
}

function развернутьСокращения(cat) {
  const out = [];
  for (const c of cat.cons.values()) {
    const роли = однородныеРоли(c);
    const выход = { op: c.id, args: (c.in ?? []).map((s) => s.role) };
    for (const запись of c.preserves ?? []) {
      const { p, from } = typeof запись === 'string' ? { p: запись, from: null } : запись;
      const откуда = from ?? роли;
      if (!откуда.length) continue;
      out.push({
        id: `${c.id}:сохраняет:${p}`,
        ссылка: (typeof запись === 'object' && запись.ссылка) || null,
        scene: сценаКонструкции(c),
        if: откуда.map((r) => ({ p, t: r })),
        then: { p, t: выход },
      });
    }
    for (const запись of c.reflects ?? []) {
      const { p, from } = typeof запись === 'string' ? { p: запись, from: null } : запись;
      const откуда = from ?? роли;
      for (const r of откуда) {
        out.push({
          id: `${c.id}:отражает:${p}:${r}`,
          ссылка: (typeof запись === 'object' && запись.ссылка) || null,
          scene: сценаКонструкции(c),
          if: [{ p, t: выход }],
          then: { p, t: r },
        });
      }
    }
  }
  return out;
}

// ПЕРЕНОС СВОЙСТВ ПО ИЗОМОРФИЗМУ.
//
// Отношение `iso` было объявлено, но в выводе бесплодно: «теорема о
// гомоморфизме» давала изоморфизм im f ≅ R/ker f, и дальше с ним нельзя было
// сделать НИЧЕГО. Между тем перенос свойств по изоморфизму — не теорема
// предметной области, а смысл самого слова: свойства объекта у нас ровно те,
// что инвариантны относительно изоморфизма.
//
// Делается это НЕ правилом над сценой, и это принципиально. Правилом вышло бы
// по две клаузы на свойство, каждая со сценой из двух свободных объектов, то
// есть |термов|² привязок в плане — а планы кэшируются по строению графа, и у
// перебора таких строений тысячи. Память на этом кончалась: сверка колец
// падала с OOM. Перенос — это ЗАМЫКАНИЕ МИРА, и считать его надо по УЖЕ
// ИЗВЕСТНЫМ изоморфизмам, которых единицы, а не по всем парам термов.
//
// Ограничение существенно: переносятся только свойства, объявленные НА ТОМ ЖЕ
// сорте, что и входы отношения. Иначе перенос соврал бы — `iso` у групп
// объявлена на `Grp.obj`, а `Grp.sub ≤ Grp.obj`, и привязать её можно к двум
// ПОДГРУППАМ; тогда перенос `normal` (свойства ВЛОЖЕНИЯ, а не тела) был бы
// ошибкой. Свойства вложения объявлены на `Grp.sub` и в список не попадают.
function переносимые(cat) {
  if (cat._переносимые) return cat._переносимые;
  const out = new Map();
  for (const r of cat.rels.values()) {
    if (!r.перенос) continue;
    const [a, b] = r.in;
    if (a !== b) continue;
    const свойства = [];
    for (const p of cat.props.values()) {
      const сорта = String(p.sort).split(',').map((x) => x.trim());
      if (сорта.includes(a)) свойства.push(p.id);
    }
    if (свойства.length) out.set(r.id, { сорт: a, свойства });
  }
  cat._переносимые = out;
  return out;
}

// ВЫРОЖДЕНИЯ — В ФАКТЫ. Вырождения объявлены данными (`1 ∗ B ≅ B`,
// `G × 1 ≅ G`, «ядро изоморфизма тривиально»), и до этого ими пользовались
// только таблица примеров и отсев условий. Вывод их не видел вовсе, и это
// било ровно там, где больнее всего: разбор случаев по тривиальности в ветви
// «A тривиальна» не знал, что A ∗ B это и есть B, и потому не мог сказать
// про A ∗ B ничего. Четырнадцать различных вопросов схемы свободного
// произведения держались на этом одном незнании.
//
// Теперь: если условие вырождения ВЫПОЛНЕНО по известным фактам, объявляется
// факт «узел изоморфен тому, во что он вырождается». Дальше работает обычное
// замыкание по изоморфизму — оно и переносит свойства.
//
// Отношение берётся то же, что у переноса (`iso` у групп, `iso-ring` у колец),
// и только если его сорт совпадает с сортом узла: изоморфизм объектов и
// совпадение подгрупп — разные отношения, и путать их нельзя.
function вырожденияВФакты(graph, мир) {
  const перенос = переносимые(graph.cat);
  if (!перенос.size || !graph.cat.degen?.length) return false;
  const спросить = (g, id, prop) => {
    const v = мир.знает({ p: prop, t: id });
    return v === undefined ? known(g, id, prop) : v;
  };
  let новое = false;
  // ЦЕНА. Первая редакция звала `matchAny` для каждого узла на каждом круге
  // неподвижной точки, и вывод со достройкой стал неподъёмным: один вывод на
  // схеме «фактор» занимал больше пятнадцати секунд вместо восьмидесяти
  // миллисекунд. Поэтому: операции без правил вырождения не трогаем вовсе, а
  // сработавший узел запоминаем — второй раз тот же факт не добавит ничего.
  const сОперацией = new Set(graph.cat.degen.map((r) => r.op));
  мир._вырожденияСделаны ??= new Set();
  // Копия списка: `matchAny` вправе достроить терм-цель, и перебор по живому
  // массиву тогда пошёл бы по новым узлам.
  for (const n of [...graph.nodes]) {
    if (!сОперацией.has(n.op)) continue;
    if (мир._вырожденияСделаны.has(n.id)) continue;
    const c = graph.cat.cons.get(n.op);
    if (!c || !n.args.length || c.choice) continue;
    let хит = null;
    try {
      хит = matchAny(graph, n.id, спросить);
    } catch {
      хит = null;     // зацикленные вырождения — забота normalize, не вывода
    }
    if (!хит || хит.id === n.id) continue;
    мир._вырожденияСделаны.add(n.id);
    for (const [rel, п] of перенос) {
      if (п.сорт !== n.sort) continue;
      const atom = { rel, args: [n.id, хит.id] };
      if (мир.положить(atom, true, 1, `вырождение: ${хит.rule.почему ?? хит.rule.equals}`)) {
        новое = true;
      }
    }
  }
  return новое;
}

// Узлы, у которых данный узел стоит аргументом. Кэш живёт на графе и
// обновляется, когда число узлов изменилось: строение графа — единственное, от
// чего индекс зависит.
function кэшПотребителей(graph) {
  const кэш = graph._потребители;
  if (кэш && кэш.узлов === graph.nodes.length) return кэш.карта;
  const карта = new Map();
  for (const n of graph.nodes) {
    for (const a of n.args) {
      let список = карта.get(a);
      if (!список) карта.set(a, (список = []));
      if (!список.includes(n)) список.push(n);
    }
  }
  graph._потребители = { узлов: graph.nodes.length, карта };
  return карта;
}

// ИЗОМОРФИЗМ ЧЕРЕЗ КАНОНИЧЕСКИЕ КОНСТРУКЦИИ: при X ≅ Y верно Z(X) ≅ Z(Y),
// [X, X] ≅ [Y, Y], X^ab ≅ Y^ab, Aut X ≅ Aut Y. Это и есть то, без чего
// вырождение в факте бесполезно: знать «A ∗ B ≅ B» мало, если спрашивают про
// ЦЕНТР свободного произведения.
//
// Два ограничения, оба существенные:
//
//   * ВЫБИРАЮЩИЕ конструкции исключены. «Возьмите подгруппу H ≤ X» и
//     «возьмите подгруппу H ≤ Y» — разные выборы, и никакого изоморфизма
//     между ними нет;
//   * терм-близнец НЕ СТРОИТСЯ, а ищется среди уже имеющихся (`graph.find`).
//     Строить значило бы растить мир без края; достройка термов и так его
//     наращивает, и если Z(B) в графе есть, связь найдётся. Если нет —
//     вывод промолчит, и это честнее, чем бесконечный граф.
function изоЧерезКонструкции(graph, мир) {
  const перенос = переносимые(graph.cat);
  if (!перенос.size) return false;
  let новое = false;
  // Пары обрабатываются ПО ОДНОМУ РАЗУ. Без памяти каждый круг неподвижной
  // точки заново разворачивал все известные изоморфизмы по всем узлам, и
  // поскольку сам разворот рождает новые изоморфизмы, работа росла
  // квадратично: вывод со достройкой переставал заканчиваться.
  мир._изоСделаны ??= new Set();
  const пары = [];
  for (const { atom, значение } of [...мир.факты.values()]) {
    if (!atom.rel || значение !== true || !перенос.has(atom.rel)) continue;
    const ключ = `${atom.rel}#${atom.args[0]}#${atom.args[1]}`;
    if (мир._изоСделаны.has(ключ)) continue;
    мир._изоСделаны.add(ключ);
    пары.push([atom.rel, atom.args[0], atom.args[1]]);
  }
  if (!пары.length) return false;
  // ОБРАТНЫЙ ИНДЕКС «кто использует этот узел». Без него на каждую пару
  // просматривались ВСЕ узлы графа, а после достройки их триста: шестьдесят
  // пар на триста узлов на каждое условие — и перебор схемы автоморфизмов
  // перестал заканчиваться. Индекс строится один раз на строение графа, как
  // и план вывода, и по тому же признаку обновляется — числу узлов.
  const индекс = кэшПотребителей(graph);
  for (const [rel, a, b] of пары) {
    for (const [из, в] of [[a, b], [b, a]]) {
      for (const n of индекс.get(из) ?? []) {
        const c = graph.cat.cons.get(n.op);
        if (!c || c.choice) continue;
        const близнец = graph.find(n.op, n.args.map((x) => (x === из ? в : x)));
        if (близнец === null || близнец === n.id) continue;
        const п = перенос.get(rel);
        if (п.сорт !== graph.get(близнец).sort || п.сорт !== n.sort) continue;
        const глубина = (мир.глубина({ rel, args: [a, b] }) ?? 0) + 1;
        if (мир.положить({ rel, args: [n.id, близнец] }, true, глубина, `${rel}:через:${n.op}`)) {
          новое = true;
        }
      }
    }
  }
  return новое;
}

// Один проход замыкания: по каждому известному изоморфизму — перенос свойств в
// обе стороны. Возвращает true, если что-то добавилось.
function замкнутьПоИзоморфизму(graph, мир) {
  const перенос = переносимые(graph.cat);
  if (!перенос.size) return false;
  let новое = false;
  for (const { atom, значение } of [...мир.факты.values()]) {
    if (!atom.rel || значение !== true) continue;
    const п = перенос.get(atom.rel);
    if (!п) continue;
    const [a, b] = atom.args;
    // Сорт проверяется у самих термов: отношение могло привязаться к
    // ПОДобъектам, и тогда переносить свойства объекта всё равно можно, а вот
    // список свойств берётся по сорту ОТНОШЕНИЯ, и этого довольно.
    for (const p of п.свойства) {
      for (const [из, в] of [[a, b], [b, a]]) {
        const v = мир.знает({ p, t: из });
        if (v === undefined) continue;
        const глубина = (мир.глубина({ p, t: из }) ?? 0) + 1;
        if (мир.положить({ p, t: в }, v, глубина, `${atom.rel}:переносит:${p}`)) новое = true;
      }
    }
  }
  return новое;
}

// Контрапозиция правила с ОДНОЙ посылкой. «Над полем всякий модуль свободен»
// значит ровно и то, что несвободный модуль живёт не над полем, — а человек
// пользуется правилом в обе стороны не задумываясь. Без этого задача «R —
// поле, M циклический, M не свободен: верно ли, что R — поле?» уезжала в
// «опровергается примером», хотя опровергается она одной строчкой базы.
//
// Правило с НЕСКОЛЬКИМИ посылками даёт столько же контрапозиций, сколько
// посылок: из «A и B ⇒ C» вместе с ¬C и A следует ¬B. Дизъюнкции тут не
// возникает — выбрасывается ровно одна посылка, а остальные остаются в
// условии, и клауза по-прежнему хорновская.
//
// Это нашлось на задаче «G проста и не циклична: верно ли, что центр G/Z(G)
// тривиален». Она решается в две строки (простая нециклическая неабелева,
// значит без центра, значит G/Z(G) = G), но первый шаг — ровно контрапозиция
// двухпосылочного правила «простая абелева ⇒ циклическая», и без неё задача
// висела пробелом.
// НЕ ВСЯКОЕ правило контрапозируется в НАШЕМ представлении фактов, и это не
// придирка: пара «чётно ⇒ конечно» и «нечётно ⇒ конечно» даёт контрапозиции
// «бесконечно ⇒ НЕ чётно» и «бесконечно ⇒ НЕ нечётно», то есть на порядке
// бесконечной группы num-even получает сразу false и true. Причина — в том,
// что «значение false» у нас значит сразу две вещи: «нечётно» и «чётность не
// определена». У бесконечного числа чётности нет вовсе, и записать это
// двузначным хранилищем нельзя.
//
// Поэтому правило вправе объявить `"без_контрапозиции": true`. Это говорит не
// «мне так удобнее», а «моя посылка определена не на всех значениях сорта, и
// обратное направление в двузначной записи выразить нечем». Нашлось на
// условии «A нетривиальна, центр B тривиален, B не свободна» в схеме
// свободного произведения: вывод объявлял условие ПУСТЫМ, то есть терял его
// целиком, а с ним и все задачи этого условия.
function контрапозиции(r) {
  if (r.без_контрапозиции) return [];
  const посылки = r.if ?? [];
  if (!посылки.length) return [];
  const перевернуть = (a) => ({ ...a, значение: a.значение === false });
  return посылки.map((выброшенная, i) => ({
    ...r,
    id: посылки.length === 1 ? `${r.id} (наоборот)` : `${r.id} (наоборот, про ${имяАтома(выброшенная)})`,
    наоборот: true,
    if: [...посылки.slice(0, i), ...посылки.slice(i + 1), перевернуть(r.then)],
    then: перевернуть(выброшенная),
  }));
}

const имяАтома = (a) => (a.rel ? a.rel : a.p);

// Правило про ОДИН объект действует и ПОЧЛЕННО — на семействе, на подсемействе,
// на направленной системе. «Конечная группа периодична» верно и в форме «если
// конечна каждая группа системы, то каждая и периодична»: свойство на таком
// сорте по определению значит «у каждого члена».
//
// Сорта с почленной семантикой узнаются по шаблону `каждый` — тому самому, что
// печатает «каждая подгруппа из 𝒩». Выписывать эти копии руками значило бы
// держать одно и то же в трёх местах и однажды разойтись.
function поЧленам(cat, r) {
  if (r.scene.length !== 1) return [];
  const роль = r.scene[0];
  const атомы = [...r.if, r.then];
  if (атомы.some((a) => a.rel || typeof a.t !== 'string' || a.t !== роль.name)) return [];

  const out = [];
  for (const [sort, опис] of cat.sorts) {
    if (!опис?.каждый || sort === роль.sort) continue;
    // Копия имеет смысл, только если ВСЕ свойства правила живут и на этом сорте.
    const годится = атомы.every((a) => {
      const p = cat.props.get(a.p);
      return p && свойствоПодходит(sort, p, cat.up);
    });
    if (!годится) continue;
    out.push({
      ...r,
      id: `${r.id} (почленно, ${опис.имя ?? sort})`,
      почленно: true,
      scene: [{ name: роль.name, sort }],
    });
  }
  return out;
}

export function правила(cat) {
  if (!cat._правила) {
    const свои = [
      ...развернутьСокращения(cat),
      ...cat.rules.map((r, i) => ({
        id: r.id ?? `правило#${i}`,
        ссылка: r.ссылка ?? null,
        scene: Object.entries(r.scene).map(([name, v]) =>
          typeof v === 'string' ? { name, sort: v } : { name, ...v },
        ),
        if: r.if ?? [],
        then: r.then,
        // Запрет контрапозиции ПЕРЕНОСИТСЯ в разобранное правило. Поля,
        // которых здесь нет, до вывода не доходят вовсе — на этом запрет и
        // не сработал с первого раза: в данных он стоял, а в правиле его не
        // было.
        без_контрапозиции: r.без_контрапозиции === true,
      })),
    ];
    const прямые = [...свои, ...свои.flatMap((r) => поЧленам(cat, r))];
    cat._правила = [...прямые, ...прямые.flatMap(контрапозиции)];
  }
  return cat._правила;
}

// --- мир фактов -------------------------------------------------------------

const ключСвойства = (t, p) => `${p}@${t}`;
const ключОтношения = (rel, a, b) => `${rel}#${a}#${b}`;

export class Мир {
  constructor(graph) {
    this.graph = graph;
    this.факты = new Map();
    this.противоречие = null;
  }

  ключ(atom) {
    if (atom.rel) {
      const r = this.graph.cat.rels.get(atom.rel);
      const [a, b] = atom.args;
      if (r?.symmetric && b < a) return ключОтношения(atom.rel, b, a);
      return ключОтношения(atom.rel, a, b);
    }
    return ключСвойства(atom.t, atom.p);
  }

  знает(atom) {
    const f = this.факты.get(this.ключ(atom));
    return f ? f.значение : undefined;
  }

  // Возвращает true, если факт новый.
  положить(atom, значение, глубина, правило) {
    const k = this.ключ(atom);
    const было = this.факты.get(k);
    if (было) {
      if (было.значение !== значение && !this.противоречие) {
        this.противоречие = { atom, было: было.значение, стало: значение, правило };
      }
      if (было.значение === значение && было.глубина <= глубина) return false;
      if (было.значение !== значение) return false;
    }
    this.факты.set(k, { atom, значение, глубина, правило });
    return true;
  }

  глубина(atom) {
    return this.факты.get(this.ключ(atom))?.глубина ?? null;
  }

  вывод(atom) {
    return this.факты.get(this.ключ(atom))?.правило ?? null;
  }
}

// --- сопоставление сцены с графом -------------------------------------------

// Указатель по сортам и по согласующим связям. Без него привязка ролей
// перебирает все узлы на каждую роль, и вывод упирается в это раньше, чем в
// сами правила.
function указатель(graph) {
  if (graph._указатель && graph._указатель.узлов === graph.nodes.length) return graph._указатель;
  const поСорту = new Map();
  const поСвязи = new Map();
  const добавить = (карта, ключ, id) => {
    let список = карта.get(ключ);
    if (!список) карта.set(ключ, (список = []));
    список.push(id);
  };
  // Снимок: rel у inn достраивает Aut(G), а менять список по ходу обхода нельзя.
  const снимок = graph.nodes.map((n) => n.id);
  for (const id of снимок) {
    const n = graph.get(id);
    for (const s of graph.cat.up.get(n.sort) ?? [n.sort]) добавить(поСорту, s, id);
    if (!(graph.cat.up.get(n.sort) ?? new Set()).size) добавить(поСорту, n.sort, id);
    for (const k of СВЯЗИ) {
      const t = graph.rel(id, k);
      if (t !== null && t !== undefined) добавить(поСвязи, `${k}|${t}`, id);
    }
  }
  const у = { узлов: graph.nodes.length, поСорту, поСвязи };
  graph._указатель = у;
  return у;
}

function кандидаты(graph, роль, привязка) {
  const у = указатель(graph);
  let списки = [у.поСорту.get(роль.sort) ?? []];
  for (const k of СВЯЗИ) {
    if (роль[k] === undefined) continue;
    let надо;
    try {
      надо = graph.resolve(роль[k], привязка);
    } catch {
      return [];
    }
    if (надо === null || надо === undefined) return [];
    списки.push(у.поСвязи.get(`${k}|${надо}`) ?? []);
  }
  списки.sort((a, b) => a.length - b.length);
  if (списки.length === 1) return списки[0];
  const прочие = списки.slice(1).map((s) => new Set(s));
  return списки[0].filter((id) => прочие.every((s) => s.has(id)));
}

// Терм-образец в графе: роль — это узел, { op, args } — УЖЕ существующий терм.
// Новых термов вывод не строит: рассуждаем о том, что в условии есть.
function найтиТерм(graph, образец, привязка) {
  if (typeof образец === 'string') {
    const id = привязка.get(образец);
    return id === undefined ? null : id;
  }
  const args = [];
  for (const a of образец.args ?? []) {
    const id = найтиТерм(graph, a, привязка);
    if (id === null) return null;
    args.push(id);
  }
  return graph.find(образец.op, args);
}

function атомВГрафе(graph, atom, привязка) {
  if (atom.rel) {
    const args = [];
    for (const a of atom.args) {
      const id = найтиТерм(graph, a, привязка);
      if (id === null) return null;
      args.push(id);
    }
    return { rel: atom.rel, args, значение: atom.значение !== false };
  }
  const t = найтиТерм(graph, atom.t, привязка);
  if (t === null) return null;
  return { p: atom.p, t, значение: atom.значение !== false };
}

function* сопоставления(graph, scene, привязка = new Map(), i = 0) {
  if (i === scene.length) {
    yield привязка;
    return;
  }
  const роль = scene[i];
  for (const id of кандидаты(graph, роль, привязка)) {
    привязка.set(роль.name, id);
    yield* сопоставления(graph, scene, привязка, i + 1);
    привязка.delete(роль.name);
  }
}

