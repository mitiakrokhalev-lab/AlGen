// --- достройка ---------------------------------------------------------------
//
// Доказательство часто требует терма, которого в условии нет: «эпиморфный
// образ абелевой группы абелев» не выводится, пока в графе нет im φ. Поэтому
// перед выводом граф ДОСТРАИВАЕТСЯ каноническими конструкциями (теми, что
// помечены в данных как `авто`, — ядро, образ, центр, коммутант, фактор по
// известно-нормальной подгруппе).
//
// Глубина достройки — настройка человека, а не потолок из кода: на странице
// это ползунок, в CLI флаг. Один круг уже покрывает школу курса, два дают
// Aut(Aut(G)) и растут быстро.

function* наборы(graph, c, из, мир, i = 0, args = []) {
  const slots = c.in ?? [];
  if (i === slots.length) {
    yield [...args];
    return;
  }
  const slot = slots[i];
  const привязка = new Map();
  slots.forEach((s, k) => k < i && привязка.set(s.role, args[k]));
  for (const id of из) {
    const n = graph.get(id);
    if (!fits(n.sort, slot.sort, graph.cat.up)) continue;
    let годится = true;
    for (const k of СВЯЗИ) {
      if (slot[k] === undefined) continue;
      let надо;
      try {
        надо = graph.resolve(slot[k], привязка);
      } catch {
        годится = false;
        break;
      }
      if (graph.rel(id, k) !== надо) {
        годится = false;
        break;
      }
    }
    // Достраивать неопределённое нельзя: фактор по подгруппе, нормальность
    // которой неизвестна, — не терм, а ошибка.
    for (const req of slot.requires ?? []) {
      if (мир.знает({ p: req, t: id }) !== true) годится = false;
    }
    if (!годится) continue;
    args[i] = id;
    привязка.set(slot.role, id);
    yield* наборы(graph, c, из, мир, i + 1, args);
    привязка.delete(slot.role);
  }
  args.length = i;
}

export function насытить(graph, мир, круга = 1) {
  const добавлены = [];
  for (let d = 0; d < круга; d++) {
    const снимок = graph.nodes.map((n) => n.id);
    for (const c of graph.cat.cons.values()) {
      if (!c.авто) continue;
      for (const args of наборы(graph, c, снимок, мир)) {
        const было = graph.nodes.length;
        const id = graph.apply(c.id, args);
        if (graph.nodes.length > было) добавлены.push(id);
      }
    }
  }
  return добавлены;
}

// Достроить и вывести, чередуя: новая нормальность открывает новый фактор.
export function рассуждать(graph, посылки = [], опции = {}) {
  const круга = опции.достройка ?? 1;
  let мир = вывести(graph, посылки, опции);
  for (let d = 0; d < круга; d++) {
    const новые = насытить(graph, мир, 1);
    if (!новые.length) break;
    мир = вывести(graph, посылки, опции);
  }
  return мир;
}

// План вывода: все привязки всех правил, разрешённые ОДИН раз. Привязки
// зависят от строения графа, а не от фактов, поэтому перебирать их на каждом
// круге незачем — на этом вывод и стоял 700 мс вместо 8.
const КЭШ_ПЛАНОВ = new Map();

function планВывода(graph) {
  const кэш = graph._план;
  if (кэш && кэш.узлов === graph.nodes.length) return кэш.план;
  // План зависит только от СТРОЕНИЯ графа. При переборе строение повторяется
  // тысячами: посылки меняются, а термы те же. Подпись — список ключей узлов
  // по порядку, поэтому номера узлов в сохранённом плане остаются годными.
  const подпись = `${graph.cat.id}|${graph.nodes.map((n) => n.key).join('|')}`;
  const готовый = КЭШ_ПЛАНОВ.get(подпись);
  if (готовый) {
    graph._план = { узлов: graph.nodes.length, план: готовый };
    return готовый;
  }
  const план = [];
  for (const rule of правила(graph.cat)) {
    for (const привязка of сопоставления(graph, rule.scene)) {
      const вывод = атомВГрафе(graph, rule.then, привязка);
      if (!вывод) continue;
      const посылки = [];
      let годится = true;
      for (const п of rule.if) {
        const atom = атомВГрафе(graph, п, привязка);
        if (!atom) {
          годится = false;
          break;
        }
        посылки.push(atom);
      }
      if (годится) план.push({ id: rule.id, посылки, вывод });
    }
  }
  graph._план = { узлов: graph.nodes.length, план };
  КЭШ_ПЛАНОВ.set(подпись, план);
  return план;
}

// Кэш живёт между запусками поиска; при смене базы его надо сбросить.
export function забытьПланы() {
  КЭШ_ПЛАНОВ.clear();
}

export function вывести(graph, посылки = [], опции = {}) {
  const мир = new Мир(graph);

  // Единичные клаузы раскладываются ОДИН раз: у мира с конкретными объектами
  // их тысячи, а вызовов вывода — на каждую цель.
  for (const n of graph.nodes) {
    for (const [p, v] of Object.entries(n.props ?? {})) мир.положить({ p, t: n.id }, v, 0, 'условие');
    // Навязанные посылки про построенный терм — такие же единичные клаузы.
    for (const [p, v] of Object.entries(n.навязано ?? {})) {
      мир.положить({ p, t: n.id }, v, 0, 'условие');
    }
    const c = graph.cat.cons.get(n.op);
    for (const [p, v] of Object.entries(c?.gives ?? {})) {
      мир.положить({ p, t: n.id }, v, 0, `построение ${c.id}`);
    }
  }
  for (const a of посылки) мир.положить(a, a.значение !== false, 0, 'условие');

  const план = планВывода(graph);
  // Насыщение останавливается само, когда новых фактов нет; `шаги` — страховка
  // от бесконечного круга. Но страховка, срабатывающая МОЛЧА, — это тихий
  // потолок: вывод глубже сорока шагов оборвался бы, и задача уехала бы в
  // пробел как «недоказуемая», хотя доказательство есть. Поэтому обрыв
  // ОТМЕЧАЕТСЯ на мире, как отмечается обрезанная таблица примеров.
  const шаги = опции.шагов ?? 40;
  let сошлось = false;
  for (let раунд = 0; раунд < шаги; раунд++) {
    let новое = false;
    for (const шаг of план) {
      let глубина = 0;
      let годится = true;
      for (const atom of шаг.посылки) {
        if (мир.знает(atom) !== atom.значение) {
          годится = false;
          break;
        }
        глубина = Math.max(глубина, мир.глубина(atom) ?? 0);
      }
      if (!годится) continue;
      if (мир.положить(шаг.вывод, шаг.вывод.значение, глубина + 1, шаг.id)) новое = true;
    }
    if (process.env.NO_A20 !== '1' && вырожденияВФакты(graph, мир)) новое = true;
    if (process.env.NO_A20 !== '1' && изоЧерезКонструкции(graph, мир)) новое = true;
    if (замкнутьПоИзоморфизму(graph, мир)) новое = true;
    if (!новое) { сошлось = true; break; }
  }
  // Не сошлось за отведённые шаги — значит вывод НЕПОЛОН, и молчать об этом
  // нельзя: «база не доказала» и «база не досчитала» — разные вещи.
  if (!сошлось) мир.недосчитано = шаги;
  return мир;
}
