// РАЗРЯД ПРОБЕЛА: «библиотека мала» или «вопрос открыт».
//
// Корзина «пробел» значит ровно одно: база не доказала и не опровергла. Причин
// у этого две, и они ПРОТИВОПОЛОЖНЫ по смыслу:
//
//   * библиотека МАЛА — предъявить ответ нечем. Как задача такой пробел не
//     стоит ничего: ответ есть, просто у нас нет объекта, на котором он виден.
//     Лечится новой записью в библиотеке или вычислимостью конструкции;
//   * библиотека БОГАТА, а база всё равно молчит — цель подтверждена на многих
//     РАЗЛИЧИМЫХ примерах, и ни один не подвёл. Вот это кандидат в настоящий
//     вопрос: так в выдачу попала гипотеза Капланского.
//
// Разряды считались только в tools/мера.mjs, то есть их видел я, а человек,
// запустивший схему, видел «пробелов 2293» — число, по которому нельзя понять
// ничего. Поэтому разбор перенесён в движок: его ставит сам генератор на
// каждую задачу (поле `разряд`), и показывают его все — страница, командная
// строка и мера. Один источник, одно определение.
//
// Разряды, в порядке проверки (первый подошедший и ставится):
//
//   обрезано     — перебор примеров не дошёл до конца библиотеки. Пробел
//                  МНИМЫЙ: свидетель мог лежать за границей предела;
//   без посылок  — условия нет вовсе. Это вопрос про произвольный объект, и
//                  интересен он редко;
//   пусто        — под условие не подошёл НИ ОДИН объект. Либо такого объекта
//                  у нас нет, либо его не бывает (противоречивое условие — и
//                  тогда виновата база, она обязана была отсеять условие);
//   немо         — объекты нашлись, а цель на них не вычисляется. Дыра не в
//                  библиотеке, а в модели;
//   малолюдно    — цель вычислилась, но подтверждений мало;
//   однолико     — подтверждений много, а различимых среди них мало: нашим
//                  языком примеры неразличимы, и подтверждение по сути одно;
//   низкий этаж  — вопрос про ИСХОДНУЮ вершину, а не про построенную. Про
//                  исходный объект всё интересное либо в учебнике, либо в
//                  библиотеке;
//   кандидат     — всё перечисленное пройдено.

// Порог разнообразия. Семь независимых профилей — это уже не совпадение.
// Почему именно семь, а не восемь: у гипотезы Капланского их ровно семь после
// того, как вырожденная строка «R = ℚ, G = C₁» вышла из счёта. Порог 8
// вычёркивал её, то есть мерил не качество вопроса, а наличие фальшивого
// подтверждения. Поднимать порог обратно надо не правкой числа, а библиотекой.
export const ПОРОГ_РАЗНООБРАЗИЯ = 7;

export const РАЗРЯДЫ = [
  'кандидат', 'низкий этаж', 'однолико', 'малолюдно', 'немо', 'пусто', 'без посылок', 'обрезано',
];

// Бедность библиотеки — это четыре разряда из восьми. Остальные бедностью не
// считаются: «обрезано» лечится пределом, «без посылок» и «низкий этаж» — это
// про форму вопроса, а не про библиотеку.
export const БЕДНОСТЬ = new Set(['пусто', 'немо', 'малолюдно', 'однолико']);

// ЭТАЖ ЦЕЛИ. Выбирающие вершины считаются нулевым этажом: `choose-mod(R)` — это
// «возьмите модуль», а не построение, и цель на ней — вопрос про исходный
// объект. Эту тонкость один раз пропустили, и весь раздел модулей обошёл
// проверку этажа: у него все объекты берутся выбирающей конструкцией.
export function этажТерма(cat, g, id) {
  const n = g.get(id);
  if (!n) return 0;
  if (!n.args.length || cat.cons.get(n.op)?.choice) return 0;
  return 1 + Math.max(...n.args.map((a) => этажТерма(cat, g, a)));
}

export function этажЦели(cat, g, цель) {
  const термы = Array.isArray(цель.или)
    ? цель.или.flatMap((ц) => (ц.rel ? ц.args : [ц.t]))
    : (цель.rel ? цель.args : [цель.t]);
  return Math.max(0, ...термы.map((t) => этажТерма(cat, g, t)));
}

// z — уже оформленная задача (см. `оформить` в src/generate.js). Отдельно
// передаётся число ПОСЫЛОК с непустым набором свойств: в самой задаче свойства
// лежат списком пар, и пустые наборы там тоже есть.
export function разрядПробела(cat, g, цель, z) {
  const посылок = (z.свойства ?? []).filter(([, p]) => Object.keys(p ?? {}).length > 0).length;
  if (z.усечено) return 'обрезано';
  if (!посылок) return 'без посылок';
  if ((z.разнообразие ?? 0) < ПОРОГ_РАЗНООБРАЗИЯ) {
    if (!(z.строк ?? 0)) return 'пусто';
    if (!(z.примеров ?? 0)) return 'немо';
    if ((z.верных ?? 0) < ПОРОГ_РАЗНООБРАЗИЯ) return 'малолюдно';
    return 'однолико';
  }
  if (этажЦели(cat, g, цель) < 1) return 'низкий этаж';
  return 'кандидат';
}

// Человеческое объяснение разряда — то, что показывается рядом с задачей.
export function почемуРазряд(z) {
  switch (z.разряд) {
    case 'обрезано':
      return 'перебор примеров не дошёл до конца библиотеки — пробел может быть мнимым';
    case 'без посылок':
      return 'условия нет: вопрос про произвольный объект';
    case 'пусто':
      return 'ни один объект библиотеки не подошёл под условие — либо его нет у нас, либо условие противоречиво';
    case 'немо':
      return `объекты нашлись (${z.строк}), но цель на них не вычисляется — дыра в модели, не в библиотеке`;
    case 'малолюдно':
      return `подтверждений всего ${z.верных ?? 0} — библиотека не дала материала`;
    case 'однолико':
      return `подтверждений ${z.верных}, а различимых среди них ${z.разнообразие} — примеры неразличимы нашим языком`;
    case 'низкий этаж':
      return 'вопрос про исходную вершину, а не про построенную';
    case 'кандидат':
      return `цель подтверждена на ${z.разнообразие} различимых примерах, и база её не выводит`;
    default:
      return '';
  }
}

// Сводка по списку задач: сколько в каком разряде. Нужна и странице, и мере, и
// командной строке — поэтому здесь, а не в трёх местах.
export function сводкаРазрядов(задачи) {
  const счёт = Object.fromEntries(РАЗРЯДЫ.map((р) => [р, 0]));
  let пробелов = 0;
  for (const z of задачи) {
    if (z.корзина !== 'пробел') continue;
    пробелов++;
    if (z.разряд && счёт[z.разряд] !== undefined) счёт[z.разряд]++;
  }
  const бедность = [...БЕДНОСТЬ].reduce((s, р) => s + счёт[р], 0);
  return { пробелов, счёт, бедность, кандидатов: счёт['кандидат'] };
}
