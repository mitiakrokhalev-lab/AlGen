// Два разных «нет» у вычислителя.
//
// `null` значит МАТЕМАТИЧЕСКОЕ отсутствие: фактор по ненормальной подгруппе не
// существует, композиция несостыкованных морфизмов не существует. Привязка, на
// которой такое встретилось, не пример условия, и её надо выбросить целиком.
//
// `НЕ_СЧИТАЕМ` значит НЕЗНАНИЕ МОДЕЛИ: свободное произведение объявленных
// бесконечных групп существует, но таблицы умножения у него нет; ℤ × A₅
// существует, но в библиотеке не объявлено. Выбрасывать такую привязку нельзя:
// вопрос «верно ли, что G абелева» не становится хуже оттого, что произведение
// посчитать не вышло, — а раньше выбрасывалась вся строка, и таблица примеров
// для схемы «произведение» состояла из 68 строк вместо двух с половиной тысяч.
//
// Разница видна только на бесконечных: у конечных групп считается всё.
export const НЕ_СЧИТАЕМ = Symbol('не считаем');

export const считаемо = (v) => v !== НЕ_СЧИТАЕМ;

// Конъюнкция в ТРЁХ значениях: «не знаю» съедает «да», но не съедает «нет».
// Нужна везде, где свойство целого считается по частям, — у произведения
// групп и у произведения колец. Жила в обоих файлах отдельной копией под
// одним и тем же именем, и склейка страницы на этом спотыкалась.
export const иТри = (a, b) => {
  if (a === false || b === false) return false;
  if (a === undefined || b === undefined) return undefined;
  return a && b;
};

// Группа из каталога, обёрнутая так, как её ждёт модель групп: посчитанная
// конечная — значением «группа», объявленная бесконечная — значением «имя».
// Нужна всякой кросс-категорной конструкции, выдающей группу: R^× и R⁺ из
// колец, Gal(L/K), K^× и K⁺ из полей. Жила двумя копиями под одним именем, и
// склейка страницы на этом спотыкалась.
export const групповоеЗначение = (G) => {
  if (!G) return НЕ_СЧИТАЕМ;
  return G.бесконечная ? { вид: 'имя', зап: G } : { вид: 'группа', G };
};
