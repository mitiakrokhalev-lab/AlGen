// Мост между схемой и моделью полей.
//
// Устроен как кольцевой: считать здесь нечего — расширения полей требуют
// символьной арифметики, а всё интересное в теме бесконечно. Поэтому поля и
// расширения ОБЪЯВЛЕНЫ в data/fld-lib.json, а tools/check-fld.mjs гоняет по
// ним всю базу.
//
// Значения двух видов:
//
//   { вид: 'полеЗ',  зап }     объявленное поле
//   { вид: 'расшир', зап }     объявленное расширение (зап._дом, зап._код)
//
// Числовой слой НЕ свой: степень расширения выдаётся обычным групповым
// значением { вид: 'число', n }, и свойства у него спрашивает та же модель,
// что у порядка группы и индекса подгруппы. Переписывать «чётно», «просто» и
// «делит» второй раз незачем — арифметика от категории не зависит.
//
// Группа Галуа выдаётся значением ГРУППОВЫМ: Gal(ℚ(∛2, ζ₃)/ℚ) — это S₃ из
// каталога групп, и отвечает про неё модель групп.

import { НЕ_СЧИТАЕМ, групповоеЗначение } from './значение.js';

export const ПОЛЕВОЕ = new Set(['полеЗ', 'расшир']);

const полеЗн = (зап) => (зап ? { вид: 'полеЗ', зап } : НЕ_СЧИТАЕМ);
const расширЗн = (зап) => (зап ? { вид: 'расшир', зап } : НЕ_СЧИТАЕМ);

// --- сборка библиотеки ----------------------------------------------------------

export function собратьПоля(данные, каталогГрупп = []) {
  const поля = данные.поля ?? [];
  const расширения = данные.расширения ?? [];
  const беды = [];
  const поПолю = new Map(поля.map((K) => [K.id, K]));
  const поГруппе = new Map();
  for (const G of каталогГрупп) {
    if (G?.id && !поГруппе.has(G.id)) поГруппе.set(G.id, G);
  }

  const полеПо = (id, где) => {
    if (id === undefined) return null;
    const K = поПолю.get(id);
    if (!K) беды.push(`${где}: нет поля «${id}»`);
    return K ?? null;
  };
  const группаПо = (id, где) => {
    if (id === undefined) return null;
    const G = поГруппе.get(id);
    if (!G) беды.push(`${где}: нет группы «${id}» в каталоге`);
    return G ?? null;
  };

  for (const K of поля) {
    const где = `поле ${K.имя}`;
    K._простое = полеПо(K.простое, где);
    K._замыкание = полеПо(K.замыкание, где);
    K._рациональные = полеПо(K.рациональные, где);
    K._мультипликативная = группаПо(K.мультипликативная, где);
    K._аддитивная = группаПо(K.аддитивная, где);
    // Простое подполе бывает только ℚ или 𝔽_p — и в записи это обязано
    // совпасть с характеристикой, иначе объявление само себе противоречит.
    const уПростого = K._простое?.props?.['char-zero'];
    if (уПростого !== undefined && K.props?.['char-zero'] !== undefined
      && уПростого !== K.props['char-zero']) {
      беды.push(`${где}: характеристика не сходится с простым подполем ${K._простое.имя}`);
    }
  }

  // Индекс расширений ПО КОНЦАМ: нужен БАШНЕ. Составное расширение K ⊆ L через
  // M — это то самое вложение K ⊆ L, если оно объявлено; вложение между двумя
  // данными полями у нас одно, и искать его надо по паре (дом, код).
  for (const K of поля) K._расширения = new Map();

  for (const S of расширения) {
    const где = `расширение ${S.имя}`;
    S._дом = полеПо(S.дом, где);
    S._код = полеПо(S.код, где);
    if (S._дом && S._код && !S._дом._расширения.has(S._код.id)) {
      S._дом._расширения.set(S._код.id, S);
    }
    S._галуа = группаПо(S.галуа, где);
    if (S.степень !== undefined && S.props?.['finite-ext'] === false) {
      беды.push(`${где}: степень объявлена, а расширение объявлено бесконечным`);
    }
    if (S.степень === undefined && S.props?.['finite-ext'] === true) {
      беды.push(`${где}: расширение конечно, а степень не указана`);
    }
    if (S.props?.['trivial-ext'] === true && S._дом !== S._код) {
      беды.push(`${где}: тривиальное расширение обязано идти из поля в него же`);
    }
  }

  return { поля, расширения, беды };
}

// --- свойства ------------------------------------------------------------------

export function свойстваЗначенияПоля(v) {
  if (!v) return {};
  if (v.вид === 'полеЗ' || v.вид === 'расшир') return { ...(v.зап.props ?? {}) };
  return {};
}

// --- вычисление узла -------------------------------------------------------------

export function вычислитьУзелПоля(graph, id, значения) {
  const n = graph.get(id);
  const арг = (i) => значения.get(n.args[i]);
  const зап = (v, вид) => (v?.вид === вид ? v.зап : null);
  const K = (i) => зап(арг(i), 'полеЗ');
  const S = (i) => зап(арг(i), 'расшир');

  switch (n.op) {
    case 'choose-field': case 'choose-ext':
      return значения.get(id) ?? null;

    case 'deg': {
      const s = S(2);
      if (!s) return НЕ_СЧИТАЕМ;
      // Бесконечная степень — законное ЗНАЧЕНИЕ, а не отсутствие значения:
      // [ℝ : ℚ] бесконечна, и сказать это надо, а не промолчать.
      if (s.степень !== undefined) return { вид: 'число', n: s.степень };
      if (s.props?.['finite-ext'] === false) return { вид: 'число', n: Infinity };
      return НЕ_СЧИТАЕМ;
    }
    // БАШНЯ: составное расширение K ⊆ L через M. Вычислять его нечем — у нас
    // нет арифметики вложений, — но и выдумывать не надо: если расширение
    // K ⊆ L в библиотеке ОБЪЯВЛЕНО, оно и есть ответ, потому что вложение
    // между двумя данными полями у нас одно. Если не объявлено, терм честно
    // невычислим, и это говорится вслух, а не подменяется пустотой.
    case 'compose-ext': {
      const низ = K(0);
      const верх = K(2);
      const σ = S(3);
      const τ = S(4);
      if (!низ || !верх || !σ || !τ) return НЕ_СЧИТАЕМ;
      // Башня обязана стыковаться: конец нижнего — начало верхнего.
      if (σ._код !== τ._дом) return НЕ_СЧИТАЕМ;
      if (σ._дом !== низ || τ._код !== верх) return НЕ_СЧИТАЕМ;
      // Тождественные звенья: K ⊆ K ⊆ L даёт само верхнее, и наоборот.
      if (σ.props?.['trivial-ext'] === true) return расширЗн(τ);
      if (τ.props?.['trivial-ext'] === true) return расширЗн(σ);
      return расширЗн(низ._расширения?.get(верх.id) ?? null);
    }
    case 'gal': return групповоеЗначение(S(2)?._галуа);
    case 'mul': return групповоеЗначение(K(0)?._мультипликативная);
    case 'add': return групповоеЗначение(K(0)?._аддитивная);

    case 'prime-sub': return полеЗн(K(0)?._простое);
    case 'alg-closure': {
      const k = K(0);
      if (!k) return НЕ_СЧИТАЕМ;
      return полеЗн(k.props?.['alg-closed'] === true ? k : k._замыкание);
    }
    case 'rational': return полеЗн(K(0)?._рациональные);

    default:
      return НЕ_СЧИТАЕМ;
  }
}

// --- кандидаты ------------------------------------------------------------------

export function кандидатыПоля(graph, n, значения, каталог) {
  const арг = (i) => значения.get(n.args[i]);
  switch (n.op) {
    case 'choose-field':
      return каталог.поля.map(полеЗн);
    case 'choose-ext': {
      const K = арг(0);
      const L = арг(1);
      if (K?.вид !== 'полеЗ' || L?.вид !== 'полеЗ') return [];
      return каталог.расширения
        .filter((S) => S._дом === K.зап && S._код === L.зап)
        .map(расширЗн);
    }
    default:
      return [];
  }
}

// --- отношения ------------------------------------------------------------------

export function отношениеПоля(rel, a, b) {
  if (rel !== 'iso') return undefined;
  if (a?.вид !== 'полеЗ' || b?.вид !== 'полеЗ') return undefined;
  if (a.зап === b.зап) return true;
  // Совпадение всех объявленных свойств изоморфизма не доказывает: ℚ(√2) и
  // ℚ(∛2) по нашим свойствам неразличимы, а изоморфны не бывают. Честный
  // ответ — «не знаю», и только отличие хоть в одном свойстве даёт «нет».
  for (const p of Object.keys(a.зап.props ?? {})) {
    const x = a.зап.props[p];
    const y = b.зап.props?.[p];
    if (x !== undefined && y !== undefined && x !== y) return false;
  }
  return undefined;
}

// --- описание -------------------------------------------------------------------

export function описаниеПоля(v, имя) {
  if (v?.вид === 'полеЗ') return `${имя} = ${v.зап.имя}`;
  if (v?.вид === 'расшир') return `${имя} — ${v.зап.имя}`;
  return имя;
}
