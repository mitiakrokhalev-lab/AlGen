// ПОЛУПРЯМОЕ ПРОИЗВЕДЕНИЕ и ДЕЙСТВИЕ — вычислимо.
//
// Зачем. Конструкции `semidirect` и `choose-act` стояли в списке
// `НЕ_В_МОДЕЛИ`, то есть модель про них отвечала «не считаю». Это одна из
// причин немоты: любая цель про N ⋊ Q не вычислялась ни на одном примере.
//
// Но дело не только в немоте, и даже не столько. Главная причина бедности
// библиотеки групп — «малолюдно» и «однолико»: подходящих примеров мало или
// они неразличимы нашим языком. Лечится это новыми объектами, а полупрямое
// произведение — самый дешёвый способ их получить: из тех же сорока пяти
// групп получаются десятки новых, и получаются ВЫЧИСЛЕНИЕМ, а не объявлением,
// то есть без риска соврать в записи.
//
// Что считается:
//
//   * ДЕЙСТВИЕ Q на N — это гомоморфизм Q → Aut(N). И автоморфизмы как
//     отображения, и перебор гомоморфизмов в модели уже есть, так что
//     действия просто перечисляются;
//   * N ⋊ Q — таблица умножения на парах (n, q):
//     (n₁, q₁)(n₂, q₂) = (n₁ · φ(q₁)(n₂), q₁q₂),
//     где φ — действие. Единица — (0, 0), и это согласуется с соглашением
//     модели «единица всегда 0».
//
// Проверка, что получилась ГРУППА, делается не на доверии: ассоциативность
// полупрямого произведения равносильна тому, что φ — гомоморфизм, а это уже
// проверено перебором гомоморфизмов. Тест на ассоциативность всё равно есть —
// он ловит ошибку в индексации пар, а не в математике.

import { группа, умножить, автоморфизмыКакОтображения, гомоморфизмы } from './group.js';

// Действие — это гомоморфизм Q → Aut(N), но в виде, удобном для умножения:
// массив длины |Q|, где элемент q даёт ПЕРЕСТАНОВКУ множества N.
export function действия(N, Q, предел = 64) {
  const авт = автоморфизмыКакОтображения(N);
  if (авт.length === 1) {
    // Единственный автоморфизм — тождественный: действие одно, и полупрямое
    // произведение совпадает с прямым. Выдаём его, а не пустоту: «действий
    // нет» и «действие только тривиальное» — разные утверждения.
    return [Q === null ? [] : Array.from({ length: Q.n }, () => авт[0])];
  }
  const A = автГруппа(N);
  const список = [];
  for (const ψ of гомоморфизмы(Q, A.группа)) {
    if (список.length >= предел) break;
    // ψ: Q → Aut(N) в номерах элементов Aut(N); переводим в перестановки.
    список.push(ψ.map((i) => A.какОтображения[i]));
  }
  return список;
}

// Aut(N) как ГРУППА вместе с соответствием «номер элемента → перестановка».
// Соответствие нужно потому, что `изПерестановок` нумерует элементы в своём
// порядке, и без явной таблицы номер автоморфизма ничего не значит.
function автГруппа(N) {
  return N._автГруппа ??= (() => {
    const авт = автоморфизмыКакОтображения(N);
    const ключ = (p) => p.join(',');
    const номер = new Map();
    const элементы = [];
    const ед = Array.from({ length: N.n }, (_, i) => i);
    const состав = (p, q) => p.map((_, i) => p[q[i]]);
    // Замыкание по композиции в том же порядке, в каком его делает
    // `изПерестановок`: тогда номера совпадают с номерами в её таблице.
    номер.set(ключ(ед), 0);
    элементы.push(ед);
    for (let i = 0; i < элементы.length; i++) {
      for (const г of авт) {
        const пр = состав(элементы[i], г);
        const k = ключ(пр);
        if (!номер.has(k)) {
          номер.set(k, элементы.length);
          элементы.push(пр);
        }
      }
    }
    const n = элементы.length;
    const mul = new Int32Array(n * n);
    for (let a = 0; a < n; a++) {
      for (let b = 0; b < n; b++) {
        mul[a * n + b] = номер.get(ключ(состав(элементы[a], элементы[b])));
      }
    }
    return { группа: группа(n, mul, `Aut(${N.имя ?? '?'})`), какОтображения: элементы };
  })();
}

// N ⋊_φ Q. Пара (n, q) кодируется номером n * |Q| + q, поэтому (0, 0) = 0 —
// соглашение модели о единице соблюдено.
export function полупрямое(N, Q, φ, имя = null) {
  const n = N.n * Q.n;
  const mul = new Int32Array(n * n);
  for (let n1 = 0; n1 < N.n; n1++) {
    for (let q1 = 0; q1 < Q.n; q1++) {
      const π = φ[q1];
      const a = n1 * Q.n + q1;
      for (let n2 = 0; n2 < N.n; n2++) {
        const сдвиг = π[n2];
        for (let q2 = 0; q2 < Q.n; q2++) {
          mul[a * n + (n2 * Q.n + q2)] =
            умножить(N, n1, сдвиг) * Q.n + умножить(Q, q1, q2);
        }
      }
    }
  }
  return группа(n, mul, имя ?? `${N.имя ?? '?'} ⋊ ${Q.имя ?? '?'}`);
}

// Действие ТРИВИАЛЬНО, если каждый элемент Q действует тождественно: тогда
// полупрямое произведение — это прямое, и новой группы не получится.
export function тривиальноДействие(φ) {
  return φ.every((π) => π.every((v, i) => v === i));
}
