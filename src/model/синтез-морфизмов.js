// Синтез КАНОНИЧЕСКИХ МОРФИЗМОВ КОЛЕЦ.
//
// Объявленных гомоморфизмов было 24, и это главная причина бедности схем
// «алгебра» и «гомоморфизм»: пустота 2618 и 1992 пробела — условия на морфизм,
// под которые не подошёл ни один из двадцати четырёх. Писать их дальше рукой
// бессмысленно, потому что канонические морфизмы ничего нового не содержат: они
// определяются самим кольцом, и свойства у них ВЫНУЖДЕННЫЕ, а не объявленные.
//
// Какие и почему:
//
//   * ТОЖДЕСТВЕННЫЙ R → R: инъективен, сюръективен, изоморфизм; ядро нулевое,
//     образ — всё кольцо. Конечномерен (R над собой — модуль с одним
//     образующим) и централен ровно тогда, когда R коммутативно (иначе образ,
//     то есть всё R, в центре не лежит);
//   * ПРОЕКЦИЯ R → R/I по каждому объявленному идеалу: сюръективна, ядро I,
//     инъективна ровно при нулевом I. Конечномерность: R/I порождено над R
//     одним элементом, значит да;
//   * НУЛЕВОЙ R → 0: сюръективен (в нулевом кольце всё совпадает), ядро — всё
//     кольцо, изоморфизм ровно при нулевом R. Это тот же случай проекции, но по
//     единичному идеалу, и выписывается он только там, где единичный идеал
//     объявлен;
//   * ВЛОЖЕНИЕ R → R[x]: инъективно, не сюръективно (x не в образе), НЕ
//     конечномерно — свободный модуль бесконечного ранга. Ради этого свойства
//     синтез и затевался: конечномерность была объявлена у считанных морфизмов,
//     и условия с ней почти не имели примеров;
//   * ВЛОЖЕНИЕ R → M₂(R) скалярными матрицами: инъективно, не сюръективно,
//     КОНЕЧНОМЕРНО (M₂(R) — свободный модуль ранга 4) и ЦЕНТРАЛЬНО при
//     коммутативном R, потому что скалярные матрицы и есть центр M₂(R).
//
// Ядро и образ ставятся ссылками на объявленные идеалы и кольца — иначе
// `ker f` и `im f` остались бы невычислимыми, и половина пользы пропала бы.

const идеалСо = (R, p) => (R.идеалы ?? []).find((i) => i.props?.[p] === true) ?? null;

export function синтезироватьМорфизмыКолец(кольца, морфизмы) {
  const было = new Set(морфизмы.map((f) => `${f.дом}→${f.код}`));
  const поId = new Map(кольца.map((R) => [R.id, R]));
  const out = [];
  const добавить = (зап) => {
    const ключ = `${зап.дом}→${зап.код}`;
    // Рука главнее синтеза: объявленный морфизм между той же парой колец
    // остаётся, а синтезированный не пишется. Расхождение поймала бы сверка.
    if (было.has(ключ)) return;
    было.add(ключ);
    out.push(зап);
  };

  for (const R of кольца) {
    const p = R.props ?? {};
    if (p['trivial-ring'] === true) continue;
    const ноль = идеалСо(R, 'zero-ideal');
    const всё = идеалСо(R, 'whole-ideal');
    const комм = p.comm === true;

    // Тождественный.
    if (ноль) {
      добавить({
        id: `id:${R.id}`,
        имя: `id_${R.имя}`,
        синтез: true,
        дом: R.id,
        код: R.id,
        props: {
          'injective-ring': true,
          'surjective-ring': true,
          'iso-ring': true,
          'finite-dim': true,
          ...(комм ? { 'central-mor': true } : { 'central-mor': false }),
        },
        ядро: ноль.id,
        образ: R.id,
        почему: 'Тождественный морфизм: ядро нулевое, образ — всё кольцо. Централен ровно при коммутативном кольце, потому что образ есть всё кольцо.',
      });
    }

    // Проекции по объявленным идеалам.
    for (const I of R.идеалы ?? []) {
      if (!I.фактор) continue;
      const цель = поId.get(I.фактор);
      if (!цель) continue;
      const нулевой = I.props?.['zero-ideal'] === true;
      const единичный = I.props?.['whole-ideal'] === true;
      // Тождественный уже выписан выше, второй раз его не надо.
      if (нулевой) continue;
      добавить({
        id: `proj:${I.id}`,
        имя: `π: ${R.имя} ↠ ${цель.имя}`,
        синтез: true,
        дом: R.id,
        код: цель.id,
        props: {
          'surjective-ring': true,
          'injective-ring': false,
          'iso-ring': false,
          // R/I порождено над R одним элементом — единицей фактора.
          'finite-dim': true,
          ...(комм ? { 'central-mor': true } : {}),
        },
        ядро: I.id,
        образ: цель.id,
        почему: единичный
          ? 'Нулевой морфизм: ядро — всё кольцо, образ — нулевое кольцо.'
          : 'Каноническая проекция на фактор: сюръективна, ядро — сам идеал.',
      });
    }

    // Вложение в кольцо многочленов.
    const поли = R.поли ? поId.get(R.поли) : null;
    if (поли && ноль) {
      добавить({
        id: `in-poly:${R.id}`,
        имя: `${R.имя} ↪ ${поли.имя}`,
        синтез: true,
        дом: R.id,
        код: поли.id,
        props: {
          'injective-ring': true,
          'surjective-ring': false,
          'iso-ring': false,
          // Свободный модуль БЕСКОНЕЧНОГО ранга: 1, x, x², …
          'finite-dim': false,
          ...(комм ? { 'central-mor': true } : {}),
        },
        ядро: ноль.id,
        образ: R.id,
        почему: 'Вложение констант: инъективно, x в образе не лежит, и как модуль R[x] свободен бесконечного ранга — значит алгебра НЕ конечномерна.',
      });
    }

    // Вложение скалярными матрицами.
    const матрицы = R.матрицы ? поId.get(R.матрицы) : null;
    if (матрицы && ноль) {
      добавить({
        id: `in-mat:${R.id}`,
        имя: `${R.имя} ↪ ${матрицы.имя}`,
        синтез: true,
        дом: R.id,
        код: матрицы.id,
        props: {
          'injective-ring': true,
          'surjective-ring': false,
          'iso-ring': false,
          // Свободный модуль ранга 4.
          'finite-dim': true,
          // Скалярные матрицы и ЕСТЬ центр M₂(R) при коммутативном R.
          ...(комм ? { 'central-mor': true } : {}),
        },
        ядро: ноль.id,
        образ: R.id,
        почему: 'Вложение скалярными матрицами: инъективно, конечномерно (ранг 4), и при коммутативном основании образ есть в точности центр M₂(R).',
      });
    }
    void всё;
  }
  return out;
}
