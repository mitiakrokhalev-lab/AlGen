// Синтез КОЛЬЦА МНОГОЧЛЕНОВ и КОЛЬЦА МАТРИЦ.
//
// Та же мысль, что у произведений: свойства этих двух конструкций ВЫЧИСЛЯЮТСЯ
// по основанию известными теоремами, а не объявляются рукой. Пока они
// объявлялись, `poly` и `mat2` были посчитаны у считанных колец, и всё
// остальное уходило в немоту: на схеме «многочлены» 1553 немых пробела из
// 2126, на схеме «матрицы» — 2263 из 3229. Это не незнание математики, а дыра
// перевода.
//
// Теоремы, по которым считается R[x] над КОММУТАТИВНЫМ основанием (над
// некоммутативным верна лишь часть, и для него свой список — ниже):
//
//   * коммутативность, приведённость, тривиальность — наследуются;
//   * ОБЛАСТЬ: R[x] область ⇔ R область (старший коэффициент произведения —
//     произведение старших);
//   * НЁТЕРОВОСТЬ: теорема Гильберта о базисе, R[x] нётерово ⇔ R нётерово;
//   * ФАКТОРИАЛЬНОСТЬ: теорема Гаусса, R[x] факториально ⇔ R факториально;
//   * ГЛАВНЫЕ ИДЕАЛЫ: R[x] — кольцо главных идеалов ⇔ R поле. Это ровно то
//     место, где многочлены «теряют» свойство: ℤ[x] уже не PID;
//   * ПОЛЕМ, ТЕЛОМ, ЛОКАЛЬНЫМ, АРТИНОВЫМ, ПРОСТЫМ, КОНЕЧНЫМ R[x] не бывает
//     ни при каком ненулевом R: x необратим, идеалов (x − a) много, цепочка
//     (x) ⊃ (x²) ⊃ … не стабилизируется, элементов бесконечно много.
//
// И по которым считается M₂(R):
//
//   * НЁТЕРОВОСТЬ и АРТИНОВОСТЬ наследуются (M₂(R) — конечно порождённый
//     модуль над R), КОНЕЧНОСТЬ и ТРИВИАЛЬНОСТЬ тоже;
//   * ПРОСТОТА наследуется: двусторонние идеалы M₂(R) — это в точности M₂(I);
//   * КОММУТАТИВНОСТИ, ОБЛАСТИ, ПРИВЕДЁННОСТИ, ПОЛЯ, ТЕЛА, PID, UFD,
//     ЛОКАЛЬНОСТИ не бывает ни при каком ненулевом R: e₁₂e₁₂ = 0 даёт и
//     делитель нуля, и нильпотент, а e₁₁ — идемпотент, которого в локальном
//     кольце быть не может;
//   * ЦЕНТР: Z(M₂(R)) = Z(R), то есть скалярные матрицы с центральными
//     элементами. Отсюда у M₂(R) над коммутативным R центр есть сама R — и
//     это закрывает 91 немую цель схемы «матрицы».
//
// Записи помечены `синтез: true`, и в БИБЛИОТЕКУ идут не все: как у
// произведений, берётся по одному представителю на новый набор свойств.
// Остальные остаются связанными, чтобы терм был вычислим.

const НАСЛЕДУЕТСЯ_ПОЛИ = ['comm', 'reduced', 'trivial-ring', 'domain', 'no-zero-div', 'noeth-ring', 'ufd'];
const ЛОЖНО_У_ПОЛИ = ['field', 'division', 'local', 'artin-ring', 'simple-ring', 'finite-ring'];

const НАСЛЕДУЕТСЯ_МАТ = ['noeth-ring', 'artin-ring', 'finite-ring', 'trivial-ring', 'simple-ring'];
const ЛОЖНО_У_МАТ = ['comm', 'domain', 'no-zero-div', 'reduced', 'field', 'division', 'pid', 'ufd', 'local'];

const ключСвойств = (props) => Object.keys(props).sort().map((k) => `${k}:${props[k]}`).join('|');

function свойстваМногочленов(R) {
  const p = R.props ?? {};
  const out = {};
  for (const имя of НАСЛЕДУЕТСЯ_ПОЛИ) {
    if (p[имя] !== undefined) out[имя] = p[имя];
  }
  for (const имя of ЛОЖНО_У_ПОЛИ) out[имя] = false;
  // Кольцо главных идеалов — ровно над полем, и это единственное свойство
  // списка, которое не наследуется и не ложно всегда.
  if (p.field !== undefined) out.pid = p.field;
  return out;
}

// Над НЕКОММУТАТИВНЫМ основанием верна лишь часть списка, и записывается
// ровно она. Отказываться вовсе было дороже: без R[x] над некоммутативным R
// вопросы «R без делителей нуля ⇒ R[x] область целостности?» и «R с делителями
// нуля ⇒ R[x] коммутативно?» подтверждались на одних коммутативных примерах,
// хотя оба ЛОЖНЫ именно из-за некоммутативности.
//
// Что верно и записано:
//   * коммутативность и тривиальность наследуются (R некоммутативно ⇒ R[x]
//     тоже: сами коэффициенты не перестановочны);
//   * ОТСУТСТВИЕ ДЕЛИТЕЛЕЙ НУЛЯ наследуется — довод про старший коэффициент
//     произведения работает в любом кольце без делителей нуля;
//   * НЁТЕРОВОСТЬ наследуется: теорема Гильберта о базисе верна и для
//     левонётеровых некоммутативных колец;
//   * ОБЛАСТЬЮ R[x] не бывает, раз он некоммутативен; полем, телом, артиновым
//     (цепочка (x) ⊃ (x²) ⊃ …), простым ((x) — собственный ненулевой
//     двусторонний идеал) и конечным — тоже.
// Что ПРОПУЩЕНО нарочно: локальность, приведённость, факториальность и
// главность идеалов. Первые две для некоммутативного случая я не знаю, вторые
// две там и не определены стандартно.
const НАСЛЕДУЕТСЯ_ПОЛИ_НК = ['comm', 'trivial-ring', 'no-zero-div', 'noeth-ring'];
const ЛОЖНО_У_ПОЛИ_НК = ['domain', 'field', 'division', 'artin-ring', 'simple-ring', 'finite-ring'];

function свойстваМногочленовНК(R) {
  const p = R.props ?? {};
  const out = {};
  for (const имя of НАСЛЕДУЕТСЯ_ПОЛИ_НК) {
    if (p[имя] !== undefined) out[имя] = p[имя];
  }
  for (const имя of ЛОЖНО_У_ПОЛИ_НК) out[имя] = false;
  return out;
}

function свойстваМатриц(R) {
  const p = R.props ?? {};
  const out = {};
  for (const имя of НАСЛЕДУЕТСЯ_МАТ) {
    if (p[имя] !== undefined) out[имя] = p[имя];
  }
  for (const имя of ЛОЖНО_У_МАТ) out[имя] = false;
  return out;
}

// Нулевой и единичный идеалы — единственные, про которые можно сказать точно,
// не зная строения основания. Фактор по нулевому — само кольцо, по единичному —
// нулевое; остальные идеалы синтез не выдумывает.
function крайниеИдеалы(id, имя, props) {
  const ноль = {
    id: `${id}.0`,
    имя: '0',
    props: {
      'zero-ideal': true,
      'whole-ideal': false,
      proper: props['trivial-ring'] === true ? false : true,
      principal: true,
      'fin-gen-ideal': true,
      'nilpotent-ideal': true,
    },
    фактор: id,
  };
  // Нулевой идеал радикален ровно в приведённом кольце, и прост ровно в
  // области: это не осторожность, а определения, прочитанные через фактор.
  if (props.reduced !== undefined) ноль.props['radical-ideal'] = props.reduced;
  if (props.domain !== undefined) ноль.props.prime = props.domain;
  if (props.field !== undefined) ноль.props['maximal-ideal'] = props.field;
  const всё = {
    id: `${id}.1`,
    имя,
    props: {
      'zero-ideal': props['trivial-ring'] === true,
      'whole-ideal': true,
      proper: false,
      principal: true,
      'fin-gen-ideal': true,
      'nilpotent-ideal': props['trivial-ring'] === true,
      'radical-ideal': true,
      prime: false,
      'maximal-ideal': false,
    },
    фактор: 'Zero',
  };
  return [ноль, всё];
}

// Один проход синтеза: по каждому годному кольцу — одна запись.
function проход({ кольца, было, суффикс, имя, свойства, годен, центр }) {
  const все = [];
  const вКаталог = [];
  const таблица = new Map();
  for (const R of кольца) {
    if (R.синтез) continue;              // синтез над синтезом не строим
    if (!годен(R)) continue;
    const id = `${суффикс}:${R.id}`;
    const props = свойства(R);
    const подпись = имя(R);
    const зап = {
      id,
      имя: подпись,
      синтез: true,
      props,
      идеалы: крайниеИдеалы(id, подпись, props),
      заметка: `Синтезировано из ${R.имя}: свойства посчитаны по теоремам, не объявлены.`,
    };
    const ц = центр ? центр(R) : null;
    if (ц) зап.центр = ц;
    все.push(зап);
    таблица.set(R.id, зап);
    const ключ = ключСвойств(props);
    if (!было.has(ключ)) {
      было.add(ключ);
      вКаталог.push(зап);
    }
  }
  return { все, вКаталог, таблица };
}

export function синтезироватьМногочленыИМатрицы(кольца) {
  const было = new Set(кольца.map((R) => ключСвойств(R.props ?? {})));
  // Уже объявленные вручную не перезаписываем: рука главнее синтеза, а
  // расхождение между ними поймает tools/check-ring.mjs.
  const естьПоли = new Set(кольца.filter((R) => R.поли).map((R) => R.id));
  const естьМат = new Set(кольца.filter((R) => R.матрицы).map((R) => R.id));

  const поли = проход({
    кольца,
    было,
    суффикс: 'poly',
    имя: (R) => `${R.имя}[x]`,
    // Над коммутативным основанием верен весь список теорем, над
    // некоммутативным — только часть, и берётся ровно она.
    свойства: (R) => (R.props?.comm === true
      ? свойстваМногочленов(R)
      : свойстваМногочленовНК(R)),
    годен: (R) => R.props?.['trivial-ring'] !== true && !естьПоли.has(R.id),
    // Центр коммутативного кольца — он сам, и у R[x] тоже. У некоммутативного
    // Z(R[x]) = Z(R)[x], и этого терма у нас нет — значит не объявляем.
    центр: (R) => (R.props?.comm === true ? `poly:${R.id}` : null),
  });

  const мат = проход({
    кольца,
    было,
    суффикс: 'mat2',
    имя: (R) => `M₂(${R.имя})`,
    свойства: свойстваМатриц,
    годен: (R) => R.props?.['trivial-ring'] !== true && !естьМат.has(R.id),
    // Z(M₂(R)) = Z(R): скалярные матрицы с центральными элементами. Для
    // коммутативного R это сама R.
    центр: (R) => (R.props?.comm === true ? R.id : (R.центр ?? null)),
  });

  return {
    все: [...поли.все, ...мат.все],
    вКаталог: [...поли.вКаталог, ...мат.вКаталог],
    поли: поли.таблица,
    матрицы: мат.таблица,
  };
}
