// Мост между схемой и моделью колец.
//
// Здесь, в отличие от групп и конечных пространств, НЕ ВЫЧИСЛЯЕТСЯ ничего:
// каждое кольцо, каждый его идеал и каждый гомоморфизм ОБЪЯВЛЕНЫ в
// data/ring-lib.json, а tools/check-ring.mjs гоняет по объявлениям всю базу и
// требует, чтобы ни одно правило не было нарушено. Причина простая: колец
// малого порядка почти нет, а всё, на чём что-то опровергается, бесконечно.
//
// Значения трёх видов:
//
//   { вид: 'ркольцо',    зап }         объявленное кольцо
//   { вид: 'идеал',      зап }         объявленный идеал (зап._влад — кольцо)
//   { вид: 'ркольцмор',  зап }         объявленный гомоморфизм
//
// Конструкции units и add выдают значение ГРУППОВОЕ — ссылку в каталог групп.
// Это и есть кросс-категорный мост: дальше про R^× спрашивают обычными
// свойствами групп, и отвечает на них модель групп, а не эта.

import { НЕ_СЧИТАЕМ, групповоеЗначение } from './значение.js';

export const КОЛЬЦЕВОЕ = new Set(['ркольцо', 'идеал', 'ркольцмор']);

const кольцоЗн = (зап) => (зап ? { вид: 'ркольцо', зап } : НЕ_СЧИТАЕМ);
const идеалЗн = (зап) => (зап ? { вид: 'идеал', зап } : НЕ_СЧИТАЕМ);
const морЗн = (зап) => (зап ? { вид: 'ркольцмор', зап } : НЕ_СЧИТАЕМ);

// --- сборка библиотеки ----------------------------------------------------------

// Ссылки разрешаются ОДИН раз и хранятся значениями, а не идентификаторами:
// иначе каждый вызов заново ищет по каталогу, а хуже того — легко перепутать
// запись со значением. Поля с подчёркиванием — уже разрешённые.
export function собратьКольца(данные, каталогГрупп = []) {
  const кольца = данные.кольца ?? [];
  const беды = [];
  const поКольцу = new Map(кольца.map((r) => [r.id, r]));
  const поИдеалу = new Map();
  const поГруппе = new Map();
  for (const G of каталогГрупп) {
    if (G?.id && !поГруппе.has(G.id)) поГруппе.set(G.id, G);
  }

  for (const r of кольца) {
    r.кольцо = true;
    for (const i of r.идеалы ?? []) {
      i._влад = r;
      if (поИдеалу.has(i.id)) беды.push(`идеал «${i.id}» объявлен дважды`);
      поИдеалу.set(i.id, i);
    }
  }

  const кольцоПо = (id, где) => {
    if (id === undefined) return null;
    const r = поКольцу.get(id);
    if (!r) беды.push(`${где}: нет кольца «${id}»`);
    return r ?? null;
  };
  const идеалПо = (id, где, влад) => {
    if (id === undefined) return null;
    const i = поИдеалу.get(id);
    if (!i) { беды.push(`${где}: нет идеала «${id}»`); return null; }
    if (влад && i._влад !== влад) беды.push(`${где}: идеал «${id}» живёт в ${i._влад.имя}, а не в ${влад.имя}`);
    return i;
  };
  // Группа берётся ЗНАЧЕНИЕМ каталога: конечная — посчитанная запись, объявленная
  // бесконечная — запись с props. Оборачивает их вызывающий, здесь только поиск.
  const группаПо = (id, где) => {
    if (id === undefined) return null;
    const G = поГруппе.get(id);
    if (!G) беды.push(`${где}: нет группы «${id}» в каталоге`);
    return G ?? null;
  };

  for (const r of кольца) {
    const где = `кольцо ${r.имя}`;
    r._поли = кольцоПо(r.поли, где);
    r._матрицы = кольцоПо(r.матрицы, где);
    r._частных = кольцоПо(r.частных, где);
    r._центр = кольцоПо(r.центр, где);
    r._нильрадикал = идеалПо(r.нильрадикал, где, r);
    r._джекобсон = идеалПо(r.джекобсон, где, r);
    r._обратимые = группаПо(r.обратимые, где);
    r._аддитивная = группаПо(r.аддитивная, где);
    for (const i of r.идеалы ?? []) {
      i._фактор = кольцоПо(i.фактор, `идеал ${i.имя} в ${r.имя}`);
      i._радикал = идеалПо(i.радикал, `идеал ${i.имя} в ${r.имя}`, r);
    }
    if (r.частных !== undefined && r.props?.domain !== true) {
      беды.push(`${где}: поле частных объявлено, а кольцо не область целостности`);
    }
  }

  const произведения = new Map();
  for (const п of данные.произведения ?? []) {
    const A = кольцоПо(п.слева, 'произведение');
    const B = кольцоПо(п.справа, 'произведение');
    const C = кольцоПо(п.равно, 'произведение');
    if (A && B && C) произведения.set(`${A.id}|${B.id}`, C);
  }

  const морфизмы = данные.морфизмы ?? [];
  for (const f of морфизмы) {
    const где = `гомоморфизм ${f.имя}`;
    f._дом = кольцоПо(f.дом, где);
    f._код = кольцоПо(f.код, где);
    f._ядро = идеалПо(f.ядро, где, f._дом);
    f._образ = кольцоПо(f.образ, где);
  }

  // Групповые кольца: ключ «кольцо|группа». Как и произведения, таблица
  // висит на самой записи — у вычисления узла свободных переменных нет.
  const групповые = new Map();
  for (const г of данные.групповые ?? []) {
    const A = кольцоПо(г.кольцо, 'групповое кольцо');
    const C = кольцоПо(г.равно, 'групповое кольцо');
    if (A && C) групповые.set(`${A.id}|${г.группа}`, C);
  }
  const локализации = new Map();
  for (const л of данные.локализации ?? []) {
    const A = кольцоПо(л.кольцо, 'локализация');
    const C = кольцоПо(л.равно, 'локализация');
    if (A && C) локализации.set(`${A.id}|${л.идеал}`, C);
  }
  for (const r of кольца) r._библ = { произведения, групповые, локализации };
  return { кольца, морфизмы, произведения, беды };
}

// --- свойства ------------------------------------------------------------------

export function свойстваЗначенияКольц(v) {
  if (!v) return {};
  if (v.вид === 'идеал') return свойстваИдеала(v.зап);
  if (v.вид === 'ркольцо' || v.вид === 'ркольцмор') return { ...(v.зап.props ?? {}) };
  return {};
}

// Свойства идеала: объявленные плюс ТРИ, которые читаются по его ФАКТОРУ.
// В коммутативном кольце идеал прост ⟺ R/I область, максимален ⟺ R/I поле,
// радикален ⟺ R/I приведено. Факторы в библиотеке объявлены почти у всех
// идеалов, а сами эти три свойства — почти ни у кого: `prime` не вычислялся на
// 108 парах схемы «идеал», `maximal-ideal` на 47, `radical-ideal` на 40, и вся
// эта немота была ровно дырой перевода, а не незнанием.
//
// База знает те же равносильности правилами, но в ТАБЛИЦУ примеров правила не
// ходят: таблица хранит только то, что посчитала модель. Поэтому переводить
// приходится здесь.
//
// Объявленное НЕ перезаписывается: если в записи что-то стоит, оно главнее, а
// расхождение между записью и фактором поймает tools/check-ring.mjs.
function свойстваИдеала(зап) {
  const свои = { ...(зап.props ?? {}) };
  const R = зап._влад;
  if (!R || R.props?.comm !== true) return свои;
  const фактор = зап._фактор;
  if (!фактор) return свои;
  const ф = фактор.props ?? {};
  const добавить = (имя, значение) => {
    if (свои[имя] === undefined && значение !== undefined) свои[имя] = значение;
  };
  добавить('prime', ф.domain);
  добавить('maximal-ideal', ф.field);
  добавить('radical-ideal', ф.reduced);
  return свои;
}

// --- вычисление узла -------------------------------------------------------------

// Идеал кольца, у которого стоит нужная пометка. Нужен там, где конструкция
// обязана дать конкретный объект: нулевой и единичный идеалы.
const идеалСо = (R, p) => (R?.идеалы ?? []).find((i) => i.props?.[p] === true) ?? null;

export function вычислитьУзелКольц(graph, id, значения) {
  const n = graph.get(id);
  const арг = (i) => значения.get(n.args[i]);
  const зап = (v, вид) => (v?.вид === вид ? v.зап : null);
  const R = (i) => зап(арг(i), 'ркольцо');
  const I = (i) => зап(арг(i), 'идеал');

  switch (n.op) {
    case 'choose-ring': case 'choose-ideal': case 'choose-ring-mor': case 'choose-group':
      return значения.get(id) ?? null;

    case 'zero-ideal-of': return идеалЗн(идеалСо(R(0), 'zero-ideal'));
    case 'whole-ideal-of': return идеалЗн(идеалСо(R(0), 'whole-ideal'));

    case 'quotient-ring': return кольцоЗн(I(1)?._фактор);
    case 'ker-ring': return идеалЗн(зап(арг(0), 'ркольцмор')?._ядро);
    case 'im-ring': return кольцоЗн(зап(арг(0), 'ркольцмор')?._образ);

    case 'nilrad': return идеалЗн(R(0)?._нильрадикал);
    case 'jacobson': return идеалЗн(R(0)?._джекобсон);
    case 'radical-of': return идеалЗн(I(1)?._радикал);

    case 'center-ring': {
      const r = R(0);
      if (!r) return НЕ_СЧИТАЕМ;
      return кольцоЗн(r.props?.comm === true ? r : r._центр);
    }
    case 'localize': {
      const r = R(0);
      const i = I(1);
      if (!r || !i) return НЕ_СЧИТАЕМ;
      // Локализация в нулевом идеале области — это поле частных, и считать
      // её отдельной записью незачем: вырождение уже сказано в базе.
      if (i.props?.['zero-ideal'] === true) return кольцоЗн(r.props?.field === true ? r : r._частных);
      // ЕДИНИЧНЫЙ идеал не прост, локализации в нём не бывает. Это не незнание
      // модели, а отсутствие объекта, и говорить надо `null`, а не «не знаю»:
      // иначе каждая такая пара идёт в пробел, хотя задачи там нет вовсе.
      if (i.props?.['whole-ideal'] === true) return null;
      // ТОЖДЕСТВО: в ЛОКАЛЬНОМ кольце локализация по его максимальному идеалу —
      // само кольцо. Локальных колец в библиотеке девятнадцать, и объявлять для
      // каждого по записи бессмысленно, когда это теорема.
      if (r.props?.local === true && i.props?.['maximal-ideal'] === true) return кольцоЗн(r);
      return кольцоЗн(r._библ.локализации.get(`${r.id}|${i.id}`));
    }
    case 'poly': return кольцоЗн(R(0)?._поли);
    case 'mat2': return кольцоЗн(R(0)?._матрицы);
    case 'frac': {
      const r = R(0);
      if (!r) return НЕ_СЧИТАЕМ;
      return кольцоЗн(r.props?.field === true ? r : r._частных);
    }
    case 'prod-ring': {
      const a = R(0);
      const b = R(1);
      if (!a || !b) return НЕ_СЧИТАЕМ;
      // Таблица произведений висит на самой записи: свободных переменных у
      // вычисления узла нет, а кольцо-аргумент есть всегда.
      const т = a._библ.произведения;
      return кольцоЗн(т.get(`${a.id}|${b.id}`) ?? т.get(`${b.id}|${a.id}`));
    }
    // Групповое кольцо берёт вторым аргументом объект ДРУГОЙ категории, а
    // возвращается в свою. Значение группы приходит из каталога групп — тем же
    // видом, каким его отдаёт групповая модель.
    case 'group-ring': {
      const a = R(0);
      const G = группаЗаписи(арг(1));
      if (!a || !G) return НЕ_СЧИТАЕМ;
      // ТОЖДЕСТВО R[1] ≅ R. Объявлять его по записи на каждое кольцо
      // бессмысленно, а польза от него не косметическая: едва оно есть, любое
      // НЕкоммутативное кольцо библиотеки опровергает «G циклическая ⇒ R[G]
      // коммутативно» (C₁ циклична), а любое НЕнётерово — «G конечна ⇒ R[G]
      // нётерово». Без тождества оба вопроса стояли открытыми: в таблице
      // групповых колец не было ни одной записи с некоммутативным R.
      if (тривиальнаяГруппа(G)) return кольцоЗн(a);
      return кольцоЗн(a._библ.групповые.get(`${a.id}|${G.id}`));
    }

    // Кросс-категорные: значение групповое, и дальше его читает модель групп.
    case 'units': return групповоеЗначение(R(0)?._обратимые);
    case 'add': return групповоеЗначение(R(0)?._аддитивная);

    // Идеальная арифметика считается только там, где ответ не зависит от
    // конкретного кольца: с нулём и с единицей. Всё остальное честно
    // невычислимо — выдумывать идеал I + J, которого в объявлении нет, нельзя.
    case 'sum-ideal': {
      const a = I(0);
      const b = I(1);
      if (!a || !b) return НЕ_СЧИТАЕМ;
      if (b.props?.['zero-ideal']) return идеалЗн(a);
      if (a.props?.['zero-ideal']) return идеалЗн(b);
      if (a.props?.['whole-ideal'] || b.props?.['whole-ideal']) return идеалЗн(идеалСо(a._влад, 'whole-ideal'));
      if (a === b) return идеалЗн(a);
      return НЕ_СЧИТАЕМ;
    }
    case 'meet-ideal': {
      const a = I(0);
      const b = I(1);
      if (!a || !b) return НЕ_СЧИТАЕМ;
      if (a.props?.['zero-ideal'] || b.props?.['zero-ideal']) return идеалЗн(идеалСо(a._влад, 'zero-ideal'));
      if (b.props?.['whole-ideal']) return идеалЗн(a);
      if (a.props?.['whole-ideal']) return идеалЗн(b);
      if (a === b) return идеалЗн(a);
      return НЕ_СЧИТАЕМ;
    }
    case 'prod-ideal': {
      const a = I(0);
      const b = I(1);
      if (!a || !b) return НЕ_СЧИТАЕМ;
      if (a.props?.['zero-ideal'] || b.props?.['zero-ideal']) return идеалЗн(идеалСо(a._влад, 'zero-ideal'));
      if (b.props?.['whole-ideal']) return идеалЗн(a);
      if (a.props?.['whole-ideal']) return идеалЗн(b);
      // I · I меньше I почти всегда — и «почти» здесь не годится.
      return НЕ_СЧИТАЕМ;
    }
    default:
      return НЕ_СЧИТАЕМ;
  }
}

// --- кандидаты ------------------------------------------------------------------

// Групповое значение приходит из каталога групп в двух видах: посчитанная
// конечная группа и объявленная бесконечная. Запись у них разная, а нужен от
// неё один только id — по нему ищется групповое кольцо.
// Тривиальность читается и у посчитанной группы, и у объявленной: в таблице
// групповых колец C₁ стоит посчитанной, а в схеме на эту вершину может лечь и
// объявленная запись с `trivial: true`.
const тривиальнаяГруппа = (G) => (G ? (G.n === 1 || G.props?.trivial === true) : false);

const группаЗаписи = (v) => {
  if (v?.вид === 'группа') return v.G;
  if (v?.вид === 'имя') return v.зап;
  return null;
};

export function кандидатыКольц(graph, n, значения, каталог) {
  const арг = (i) => значения.get(n.args[i]);
  switch (n.op) {
    case 'choose-ring':
      return каталог.кольца.map(кольцоЗн);
    case 'choose-group':
      // В каталоге групп лежат не только группы: там же семейства и
      // направленные системы. Групповое кольцо строится по ГРУППЕ, и обернуть
      // семейство значением «группа» значит уронить модель групп на первом же
      // запросе свойств.
      return (каталог.группы ?? [])
        .filter((G) => !G.семейство && !G.система)
        .map(групповоеЗначение);
    case 'choose-ideal': {
      const R = арг(0);
      if (R?.вид !== 'ркольцо') return [];
      return (R.зап.идеалы ?? []).map(идеалЗн);
    }
    case 'choose-ring-mor': {
      const R = арг(0);
      const S = арг(1);
      if (R?.вид !== 'ркольцо' || S?.вид !== 'ркольцо') return [];
      return каталог.морфизмы
        .filter((f) => f._дом === R.зап && f._код === S.зап)
        .map(морЗн);
    }
    default:
      return [];
  }
}

// --- отношения ------------------------------------------------------------------

export function отношениеКольц(rel, a, b) {
  if (rel === 'iso') {
    if (a?.вид !== 'ркольцо' || b?.вид !== 'ркольцо') return undefined;
    if (a.зап === b.зап) return true;
    // Различить кольца можно только свойством, которое у обоих объявлено.
    // Совпадение всех объявленных свойств изоморфизма НЕ доказывает: ℤ/4ℤ и
    // 𝔽₂[x]/(x²) так и не различаются, и честный ответ тут «не знаю».
    for (const p of Object.keys(a.зап.props ?? {})) {
      const x = a.зап.props[p];
      const y = b.зап.props?.[p];
      if (x !== undefined && y !== undefined && x !== y) return false;
    }
    return undefined;
  }
  if (rel === 'le') {
    if (a?.вид !== 'идеал' || b?.вид !== 'идеал') return undefined;
    if (a.зап._влад !== b.зап._влад) return undefined;
    if (a.зап === b.зап) return true;
    const pa = a.зап.props ?? {};
    const pb = b.зап.props ?? {};
    if (pa['zero-ideal'] === true) return true;
    if (pb['whole-ideal'] === true) return true;
    if (pa['whole-ideal'] === true && pb.proper === true) return false;
    if (pb['zero-ideal'] === true && pa['zero-ideal'] === false) return false;
    return undefined;
  }
  return undefined;
}

// --- описание -------------------------------------------------------------------

export function описаниеКольц(v, имя) {
  if (v?.вид === 'ркольцо') return `${имя} = ${v.зап.имя}`;
  if (v?.вид === 'идеал') return `${имя} = ${v.зап.имя} ⊴ ${v.зап._влад.имя}`;
  if (v?.вид === 'ркольцмор') return `${имя} — ${v.зап.имя}`;
  return имя;
}
