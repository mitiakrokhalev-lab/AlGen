// Бесконечные группы: объявленная частичная модель.
//
// Конечную группу мы ВЫЧИСЛЯЕМ, бесконечную — только ОБЪЯВЛЯЕМ: у неё записаны
// свойства, представительные подгруппы, факторы по ним и результаты
// канонических конструкций. Всё, чего в записи нет, честно считается
// невычислимым, и строка примера просто не строится.
//
// Ради этого и сделано: конечная модель слепа к «конечна», «периодична»,
// «конечно порождена», «финитно аппроксимируема» — у всех её групп эти
// свойства одинаковы. ℤ, ℚ, ℚ/ℤ, F₂ и D∞ эту слепоту снимают.
//
// Поскольку всё здесь написано рукой, оно ОБЯЗАНО проверяться правилами базы:
// tools/check-infinite.mjs прогоняет по этим записям тот же набор теорем, что
// tools/compute-groups.mjs прогоняет по вычисленным группам.

import {
  синтезироватьСвободное, запомнитьТривиальную,
} from './синтез-свободных.js';

export const ЗНАЧЕНИЕ_КОНЕЧНОЙ = (G) => ({ вид: 'группа', G });

// Связать записи в готовые к употреблению значения: ссылки на объекты
// заменяются на сами значения, чтобы вычислитель никуда не ходил за словарём.
export function связать(записи, конечные, семейства = [], системы = [], свободные = []) {
  const поИмени = new Map();
  for (const G of конечные) поИмени.set(G.id ?? G.имя, ЗНАЧЕНИЕ_КОНЕЧНОЙ(G));
  for (const з of записи) поИмени.set(з.id, { вид: 'имя', зап: з });
  // Тривиальная группа нужна синтезу свободных произведений: центр A ∗ B
  // тривиален, и чтобы вопросы про него считались, нужно её ЗНАЧЕНИЕ.
  запомнитьТривиальную([...поИмени.values()].find((v) => v.вид === 'группа' && v.G.n === 1) ?? null);

  const беды = [];
  const найти = (id, где) => {
    const v = поИмени.get(id);
    if (!v) беды.push(`${где}: нет объекта «${id}»`);
    return v ?? null;
  };

  for (const з of записи) {
    // Все записи этого файла — БЕСКОНЕЧНЫЕ объекты, и помечать это в данных
    // руками незачем: забытая пометка превращает запись в «посчитанную
    // группу», и модель падает на первой же попытке прочитать её таблицу
    // умножения. Ставим здесь, один раз.
    з.бесконечная = true;
    з._сам = поИмени.get(з.id);
    for (const п of з.подгруппы ?? []) {
      п._владелец = з;
      п._объект = найти(п.объект, `${з.id}/${п.id}`);
    }
    з._поПодгруппе = new Map((з.подгруппы ?? []).map((п) => [п.id, п]));
    з._факторы = new Map(
      Object.entries(з.факторы ?? {}).map(([k, v]) => {
        if (!з._поПодгруппе.has(k)) беды.push(`${з.id}: фактор по неизвестной подгруппе «${k}»`);
        return [k, найти(v, `${з.id}/фактор/${k}`)];
      }),
    );
    з._произведения = new Map(
      Object.entries(з.произведения ?? {}).map(([k, v]) => [k, найти(v, `${з.id}/произведение/${k}`)]),
    );
    // Представительные ЭЛЕМЕНТЫ: у каждого записаны свойства, порождённая им
    // подгруппа и централизатор — ссылками на уже объявленные подгруппы.
    з._элементы = з.элементы ?? [];
    for (const э of з._элементы) {
      for (const [поле, id] of [['порождает', э.порождает], ['централизатор', э.централизатор]]) {
        if (id && !з._поПодгруппе.has(id)) беды.push(`${з.id}/элемент ${э.id}: нет подгруппы «${id}» (${поле})`);
      }
    }
    з._конструкции = {};
    for (const [op, id] of Object.entries(з.конструкции ?? {})) {
      if (op === 'ab' || op === 'aut') {
        з._конструкции[op] = найти(id, `${з.id}/${op}`);
      } else {
        const п = з._поПодгруппе.get(id);
        if (!п) беды.push(`${з.id}/${op}: нет подгруппы «${id}»`);
        else з._конструкции[op] = { вид: 'именПод', зап: п, влад: з };
      }
    }
  }

  // Объявленные морфизмы разрешаются последними: им нужны и подгруппы
  // источника (для ядра), и подгруппы цели (для образа).
  for (const з of записи) {
    з._морфизмы = [];
    for (const м of з.морфизмы ?? []) {
      const код = найти(м.в, `${з.id}/морфизм/${м.в}`);
      if (!код) continue;
      const ядро = разобратьПодгруппу(м.ядро, з._сам, поИмени, беды, `${з.id}/${м.в}/ядро`);
      const образ = разобратьПодгруппу(м.образ, код, поИмени, беды, `${з.id}/${м.в}/образ`);
      з._морфизмы.push({
        вид: 'именМорфизм', имя: м.имя ?? '', дом: з._сам, код, ядро, образ,
        props: { ...(м.props ?? {}) },
      });
    }
  }
  // Бесконечные семейства: у них объявлены произведение и прямая сумма как
  // ПОДГРУППА этого произведения. Без такого семейства модель слепа к
  // разнице ⊕ и ∏ — у конечных семейств они совпадают.
  // Свободные произведения: объявленная таблица. Ключ — пара id, и пишется он
  // в обе стороны: A ∗ B ≅ B ∗ A, объявлять дважды незачем.
  ТАБЛИЦА_СВОБОДНЫХ = new Map();
  for (const з of свободные) {
    const л = найти(з.слева, `свободные/${з.слева} ∗ ${з.справа}`);
    const п = найти(з.справа, `свободные/${з.слева} ∗ ${з.справа}`);
    const р = найти(з.равно, `свободные/${з.слева} ∗ ${з.справа}/равно`);
    if (!л || !п || !р) continue;
    ТАБЛИЦА_СВОБОДНЫХ.set(`${з.слева}|${з.справа}`, р);
    ТАБЛИЦА_СВОБОДНЫХ.set(`${з.справа}|${з.слева}`, р);
  }

  for (const с of семейства) {
    const П = найти(с.произведение, `${с.id}/произведение`);
    с._произведение = П;
    с._сумма = null;
    if (П?.вид === 'имя') {
      const п = П.зап._поПодгруппе.get(с.сумма);
      if (!п) беды.push(`${с.id}: у ${с.произведение} нет подгруппы «${с.сумма}»`);
      else с._сумма = подзначение(п);
    }
  }

  // Направленные системы записываются как семейства: свойства ЧЛЕНОВ и
  // результаты двух пределов. Отсутствие предела — это «не знаем», а не
  // «не существует»: обратный предел есть всегда, просто он не объявлен.
  for (const с of системы) {
    с._копредел = с.копредел ? найти(с.копредел, `${с.id}/копредел`) : null;
    с._предел = с.предел ? найти(с.предел, `${с.id}/предел`) : null;
  }

  return { поИмени, беды };
}

// Ссылка на подгруппу: «всё», «тривиальный» или id объявленной подгруппы.
function разобратьПодгруппу(ссылка, объект, поИмени, беды, где) {
  if (ссылка === undefined || ссылка === null) return null;
  if (ссылка === 'всё') return всяПодгруппа(объект);
  if (ссылка === 'тривиальный') return тривиальнаяПодгруппа(объект);
  if (объект?.вид !== 'имя') {
    беды.push(`${где}: ссылка «${ссылка}» указывает на подгруппу неименованного объекта`);
    return null;
  }
  const п = объект.зап._поПодгруппе.get(ссылка);
  if (!п) {
    беды.push(`${где}: нет подгруппы «${ссылка}»`);
    return null;
  }
  return подзначение(п);
}

// Вся группа и единичная подгруппа — для обоих сортов объектов. У конечной
// это просто список номеров, у объявленной — та подгруппа, что помечена
// «whole» или изоморфна тривиальной группе.
export function всяПодгруппа(v) {
  if (v?.вид === 'группа') {
    return { вид: 'подгруппа', объемлющая: v.G, H: Array.from({ length: v.G.n }, (_, i) => i) };
  }
  if (v?.вид !== 'имя') return null;
  const п = найтиПодгруппу(v.зап, (x) => x.props?.whole === true);
  return п ? подзначение(п) : null;
}

export function тривиальнаяПодгруппа(v) {
  if (v?.вид === 'группа') return { вид: 'подгруппа', объемлющая: v.G, H: [0] };
  if (v?.вид !== 'имя') return null;
  const п = найтиПодгруппу(v.зап, (x) => x._объект?.вид === 'группа' && x._объект.G.n === 1);
  return п ? подзначение(п) : null;
}

export const подзначение = (п) => ({ вид: 'именПод', зап: п, влад: п._владелец });

export function подгруппыИменованной(з) {
  return (з.подгруппы ?? []).map(подзначение);
}

// Свойства именованного значения: у подгруппы сперва свойства того объекта,
// которому она изоморфна, потом свойства самого ВЛОЖЕНИЯ.
export function свойстваИменованного(v, свойстваЗначения) {
  if (v.вид === 'имя') return v.зап.props ?? {};
  if (v.вид === 'именПод') {
    const объектные = v.зап._объект ? свойстваЗначения(v.зап._объект) : {};
    const свои = v.зап.props ?? {};
    // Объявленная подгруппа — тоже ПОДМНОЖЕСТВО (Grp.sub ≤ Grp.subset), и
    // свойства подмножества у неё обязаны быть. Для подгруппы они тривиальны:
    // подгруппой она является по сорту, а «совпадает со всем» — это её же
    // `whole`. Пока этого не было, `set-whole(Z(G))` и `set-whole([G, G])` не
    // вычислялись ни на одном объявленном объекте.
    const подмножественные = { subgroup: true };
    if (свои.whole !== undefined) подмножественные['set-whole'] = свои.whole;
    return { ...объектные, ...свои, ...подмножественные };
  }
  if (v.вид === 'именМорфизм') {
    // Инъективность и сюръективность не записываются дважды: они ЕСТЬ
    // тривиальность ядра и полнота образа. Записанное в props уточняет их,
    // но противоречить не может — это проверяет tools/check-infinite.mjs.
    const изЯдра = v.ядро ? свойстваЗначения(v.ядро).trivial : undefined;
    const изОбраза = v.образ ? свойстваЗначения(v.образ).whole : undefined;
    const injective = v.props.injective ?? изЯдра;
    const surjective = v.props.surjective ?? изОбраза;
    // Нулевой морфизм — это морфизм с ТРИВИАЛЬНЫМ ОБРАЗОМ, и выводить это
    // надо так же, как инъективность из ядра. Пока не выводилось, у всякого
    // объявленного морфизма «нетривиален» было неизвестно, и каждая задача со
    // словами «f нетривиален» оставалась вовсе без примеров.
    const нулевой = v.props['zero-mor'] ?? (v.образ ? свойстваЗначения(v.образ).trivial : undefined);
    return {
      ...v.props,
      ...(injective === undefined ? {} : { injective }),
      ...(surjective === undefined ? {} : { surjective }),
      ...(нулевой === undefined ? {} : { 'zero-mor': нулевой }),
      ...(injective === undefined || surjective === undefined
        ? {} : { iso: injective && surjective }),
    };
  }
  return {};
}

// Морфизмы, которые есть между любыми двумя объектами и потому не
// записываются: нулевой и тождественный.
export function встроенныеМорфизмы(X, Y, вся, трив) {
  const out = [];
  const нулевой = {
    вид: 'именМорфизм', имя: 'тривиальный', дом: X, код: Y,
    ядро: вся(X), образ: трив(Y), props: { 'zero-mor': true },
  };
  out.push(нулевой);
  if (X === Y || (X?.вид === 'имя' && Y?.вид === 'имя' && X.зап === Y.зап)) {
    out.push({
      вид: 'именМорфизм', имя: 'тождественный', дом: X, код: Y,
      ядро: трив(X), образ: вся(Y), props: { iso: true, injective: true, surjective: true },
    });
  }
  return out;
}

// Вложения ниоткуда не берутся: если у объявленной группы есть подгруппа,
// изоморфная X, то есть и вложение X в неё. Записывать это отдельно значило бы
// держать одно и то же в двух местах — и рано или поздно разойтись.
export function вложенияПодгрупп(X, Y, трив) {
  if (Y?.вид !== 'имя') return [];
  const кого = X?.вид === 'имя' ? X.зап : X?.G;
  if (!кого) return [];
  const out = [];
  for (const п of Y.зап.подгруппы ?? []) {
    if (п.props?.whole === true) continue; // это тождественное, оно уже есть
    const об = п._объект;
    if ((об?.вид === 'имя' ? об.зап : об?.G) !== кого) continue;
    out.push({
      вид: 'именМорфизм', имя: `вложение ${п.имя}`, дом: X, код: Y,
      ядро: трив(X), образ: подзначение(п),
      props: { injective: true, surjective: false },
    });
  }
  return out;
}

export function объявленныеМорфизмы(X, Y) {
  if (X?.вид !== 'имя') return [];
  const целевой = Y?.вид === 'имя' ? Y.зап : Y?.G;
  return (X.зап._морфизмы ?? []).filter((м) => {
    const к = м.код?.вид === 'имя' ? м.код.зап : м.код?.G;
    return к === целевой;
  });
}

// Именованная подгруппа, взятая как самостоятельный объект.
export function какОбъект(v) {
  if (!v) return null;
  if (v.вид === 'именПод') return v.зап._объект;
  return v;
}

export function найтиПодгруппу(з, что) {
  return (з.подгруппы ?? []).find(что) ?? null;
}

// --- свободное произведение ---------------------------------------------------
//
// Вычислить его нельзя: A ∗ B бесконечно, едва оба сомножителя нетривиальны.
// Но «нельзя вычислить» не значит «нечего сказать», и сказать есть две вещи:
//
//   * ТОЖДЕСТВО 1 ∗ B ≅ B. Оно не объявление, а теорема, и держится само;
//   * ТАБЛИЦА классических значений (C₂ ∗ C₂ ≅ D∞, C₂ ∗ C₃ ≅ PSL₂(ℤ), ℤ ∗ ℤ ≅ F₂).
//
// Ради тождества всё и сделано. Пока свободное произведение было целиком
// невычислимо, условие «A абелева, B неразрешима» не опровергалось НИЧЕМ: база
// про Z(A ∗ B) молчала, модель молчала, и каждое такое условие уходило в
// пробел. А опровержение лежало на поверхности: A = 1, B = A₅ × ℤ, тогда
// A ∗ B = B и центр у него — ℤ, то есть нетривиален.
//
// Таблица хранится в модуле, а не в записи: у C₂ ∗ C₂ ОБА сомножителя —
// посчитанные конечные группы, ни у одного из них записи нет вовсе, и повесить
// таблицу было бы некуда.

let ТАБЛИЦА_СВОБОДНЫХ = new Map();

const идОбъекта = (v) => {
  if (!v) return null;
  if (v.вид === 'имя') return v.зап.id ?? null;
  if (v.вид === 'группа') return v.G.id ?? null;
  return null;    // подгруппа-как-группа своего id не имеет — и объявить её нечем
};

const тривиален = (v) => {
  if (!v) return false;
  if (v.вид === 'имя') return v.зап.props?.trivial === true;
  if (v.вид === 'группа') return v.G.n === 1;
  return false;
};

// undefined значит «модель не знает» — вызывающая сторона превращает это в
// НЕ_СЧИТАЕМ. Отдельного вида значения здесь не надо: named.js нарочно ничего
// не импортирует, и часовой невычислимости живёт не тут.
export function свободноеПроизведение(X, Y, свойстваЗначения = null) {
  if (!X || !Y) return undefined;
  if (тривиален(X)) return Y;
  if (тривиален(Y)) return X;
  const a = идОбъекта(X);
  const b = идОбъекта(Y);
  if (!a || !b) return undefined;
  // Объявленная таблица ГЛАВНЕЕ синтеза: там, где A ∗ B опознано как знакомый
  // объект (C₂ ∗ C₂ = D∞, ℤ ∗ ℤ = F₂), у него есть и подгруппы, и факторы, и
  // имя, а у синтезированной записи только свойства.
  const объявлено = ТАБЛИЦА_СВОБОДНЫХ.get(`${a}|${b}`);
  if (объявлено) return объявлено;
  // Иначе свойства СЧИТАЮТСЯ по теоремам. Без функции свойств синтез
  // невозможен — вызывающий обязан её передать (см. src/model/instance.js).
  if (!свойстваЗначения) return undefined;
  return синтезироватьСвободное(X, Y, a, b, свойстваЗначения);
}
