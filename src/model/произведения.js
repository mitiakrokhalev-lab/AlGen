// Синтез произведений «объявленная бесконечная × вычисленная конечная».
//
// Почему это нужно. Решая выданные генератором задачи руками, почти каждый раз
// приходишь к контрпримеру вида X × F: неразрешимая с нетривиальным центром —
// это A₅ × ℤ, периодическая не финитно аппроксимируемая — ℤ(2^∞) × V₄,
// непериодическая с конечным центром — C₂ × F₂. Объявлять каждую такую группу
// рукой можно, но это ручная работа на каждую новую дыру, а свойства прямого
// произведения выводятся из сомножителей МЕХАНИЧЕСКИ.
//
// Что синтез НЕ делает: он не выдумывает знание. Свойство произведения берётся
// только там, где оно честно следует из свойств сомножителей (и с тремя
// значениями: «не знаю» у сомножителя даёт «не знаю» у произведения, если
// второй не решает дело сам). Подгрупп объявляется четыре — 0, X × 1, 1 × F и
// вся, — потому что именно они дают факторы X и F и различают «конечного
// индекса» от «бесконечного».
//
// Отбор по СИГНАТУРЕ: произведение попадает в библиотеку, только если его
// набор свойств не встречался ни у одной уже имеющейся группы. Иначе
// библиотека выросла бы в разы, а различать примеры стало бы нечем: перебор
// тратил бы время на сто копий одного и того же.

import { иТри } from './значение.js';
import { свойстваГруппы } from './group.js';

// Трёхзначное «и»: ложь у одного решает дело, «не знаю» заражает остальное.

// Свойства X × F по свойствам сомножителей. F КОНЕЧНА и НЕТРИВИАЛЬНА, X
// бесконечна — на этом держится половина строк.
export function свойстваПроизведения(pX, pF) {
  const out = {
    trivial: false,
    finite: false,
    // Циклическая группа без кручения бесконечна и бескручена; добавив
    // нетривиальный конечный множитель, цикличность теряем всегда.
    cyclic: false,
    // Свободные группы без кручения, а F его вносит.
    free: false,
    // X × 1 — собственная нетривиальная нормальная подгруппа. По той же
    // причине произведение двух нетривиальных РАЗЛОЖИМО — это определение.
    simple: false,
    indecomposable: false,
    // У конечного нетривиального множителя кручение есть и делимости нет, но
    // писать это прямо нельзя: второй множитель бывает и бесконечным, и тогда
    // решает обычная конъюнкция (ℤ × ℚ без кручения, хоть и не делима).
    'torsion-free': иТри(pX['torsion-free'], pF['torsion-free']),
    divisible: иТри(pX.divisible, pF.divisible),
    abelian: иТри(pX.abelian, pF.abelian),
    solvable: иТри(pX.solvable, pF.solvable),
    nilpotent: иТри(pX.nilpotent, pF.nilpotent),
    perfect: иТри(pX.perfect, pF.perfect),
    centerless: иТри(pX.centerless, pF.centerless),
    // У конечного множителя все три верны по определению — это проставлено
    // при нормализации его свойств, поэтому здесь снова обычная конъюнкция.
    periodic: иТри(pX.periodic, pF.periodic),
    'residually-finite': иТри(pX['residually-finite'], pF['residually-finite']),
    'fin-gen': иТри(pX['fin-gen'], pF['fin-gen']),
  };
  for (const k of Object.keys(out)) if (out[k] === undefined) delete out[k];
  return out;
}

// Утверждается ТОЛЬКО то, что следует из строения произведения. Отсутствующее
// свойство значит «не знаю», и это важнее, чем кажется: осторожное
// «characteristic: false» у подгруппы ℤ × 1 в ℤ × S₃ оказалось ложью — эта
// подгруппа там ЦЕНТР, а центр характеристичен всегда. Поймал не тест, а
// сыщик противоречий базы с моделью прямо во время поиска.
const вложение = (доп) => {
  const out = { normal: true, whole: false, 'finite-index': false, ...доп };
  for (const k of Object.keys(out)) if (out[k] === undefined) delete out[k];
  return out;
};

// Одна запись. Второй сомножитель бывает и посчитанной конечной группой, и
// объявленной бесконечной: ℤ × ⊕C₂ нужна не реже, чем ℤ × S₃.
// Возвращает null, если сомножители негодны.
export function синтезПроизведения(X, F) {
  if (!X?.бесконечная) return null;
  const конечный = Boolean(F?.mul);
  if (!конечный && !F?.бесконечная) return null;
  if (конечный && F.n === 1) return null;
  if (!конечный && F.props?.trivial === true) return null;
  const pX = X.props ?? {};
  // У конечной группы периодичность, финитная аппроксимируемость и конечная
  // порождённость верны всегда, но в посчитанных свойствах их может не быть —
  // проставляем явно, иначе конъюнкция выдаст «не знаю» на ровном месте.
  const pF = конечный
    ? { periodic: true, 'residually-finite': true, 'fin-gen': true, ...свойстваГруппы(F) }
    : (F.props ?? {});
  const props = свойстваПроизведения(pX, pF);
  const id = `${X.id}x${F.id}`;
  const имя = `${X.имя} × ${F.имя ?? F.id}`;

  const подгруппы = [
    { id: '0', имя: '1', объект: 'C1', props: вложение({ characteristic: true, central: true }) },
    {
      id: 'бесконечный', имя: `${X.имя} × 1`, объект: X.id,
      // Индекс равен |F| — и при конечном множителе он известен ЧИСЛОМ, а не
      // только своей конечностью. Это и отличает сомножители друг от друга.
      ...(конечный ? { индекс: F.n } : {}),
      props: вложение({ central: pX.abelian === true, 'finite-index': конечный }),
    },
    {
      id: 'конечный', имя: `1 × ${F.имя ?? F.id}`, объект: F.id,
      props: вложение({ central: pF.abelian === true ? true : undefined }),
    },
    {
      id: 'все', имя, объект: id,
      props: вложение({
        characteristic: true, whole: true, 'finite-index': true,
        central: props.abelian === true,
      }),
    },
  ];

  // Центр и коммутант объявляются ТОЛЬКО там, где они совпадают с одной из
  // четырёх подгрупп. Z(X × F) = Z(X) × Z(F), и если, скажем, X абелева, а F
  // нет, центр равен X × Z(F) — такой подгруппы у нас нет, и врать не будем.
  const конструкции = {};
  const абF = pF.abelian === true;
  const безЦF = pF.centerless === true;
  if (pX.abelian === true && абF) конструкции.center = 'все';
  else if (pX.centerless === true && безЦF) конструкции.center = '0';
  else if (pX.abelian === true && безЦF) конструкции.center = 'бесконечный';
  else if (pX.centerless === true && абF) конструкции.center = 'конечный';

  const совF = pF.perfect === true;
  if (pX.abelian === true && абF) конструкции.commutator = '0';
  else if (pX.perfect === true && совF) конструкции.commutator = 'все';
  else if (pX.abelian === true && совF) конструкции.commutator = 'конечный';
  else if (pX.perfect === true && абF) конструкции.commutator = 'бесконечный';

  // Кручение спрашивают только у абелевой. T(X × Y) = T(X) × T(Y), и обе
  // половины надо смотреть: при конечном множителе «без кручения у X» давало
  // 1 × F, но у ℤ × ℚ⁺ второй множитель тоже без кручения, и кручение там
  // НУЛЕВОЕ. Сверка с базой поймала ровно это.
  if (props.abelian === true) {
    const безX = pX['torsion-free'] === true;
    const безY = pF['torsion-free'] === true;
    const перX = pX.periodic === true;
    const перY = pF.periodic === true;
    if (безX && безY) конструкции.torsion = '0';
    else if (безX && перY) конструкции.torsion = 'конечный';
    else if (перX && безY) конструкции.torsion = 'бесконечный';
    else if (перX && перY) конструкции.torsion = 'все';
  }
  // Центр, коммутант и подмодуль кручения характеристичны по определению, и
  // если одна из четырёх подгрупп оказалась одной из них — это надо сказать,
  // иначе база и модель разойдутся на ровном месте.
  const поId = new Map(подгруппы.map((п) => [п.id, п]));
  for (const op of ['center', 'commutator', 'torsion']) {
    const п = поId.get(конструкции[op]);
    if (!п) continue;
    п.props.characteristic = true;
    if (op === 'center') п.props.central = true;
  }
  // Индекс подгруппы X × 1 равен |F|; конечен он только у конечного
  // множителя, и максимальна она ровно тогда, когда F проста.
  const беск = поId.get('бесконечный');
  if (pF.simple === true) беск.props.maximal = true;
  if (!конечный) delete беск.props['finite-index'];

  return {
    id,
    имя,
    бесконечная: true,
    синтез: { из: X.id, на: F.id },
    заметка: `Синтезировано: свойства выведены из ${X.имя} и ${F.имя ?? F.id} по правилам прямого произведения.`,
    props,
    подгруппы,
    конструкции,
    факторы: { 0: id, бесконечный: F.id, конечный: X.id, все: 'C1' },
  };
}

// Сигнатура — упорядоченный список известных свойств. Две группы с одинаковой
// сигнатурой различаются для перебора только подгруппами, а подгрупп у
// синтезированной всего четыре, поэтому второй экземпляр не окупается.
//
// Это ЭВРИСТИКА, а не теорема, и ошибается она в одну сторону — в сторону
// потери. Совпадение свойств не значит совпадения строения: у ℚ⁺ и ℝ⁺ наборы
// свойств одинаковы, а факторы разные (ℚ/ℤ и U). Значит синтезированное
// произведение иногда отбрасывается, хотя его факторы были бы новыми. Когда
// такая потеря станет видна по пробелам, сигнатуру надо будет расширить
// свойствами факторов — но не раньше: библиотека вдвое дороже перебору.
export function сигнатура(props) {
  return Object.keys(props).sort().map((k) => `${k}=${props[k]}`).join(',');
}

// Сетка X × F с отбором по сигнатуре. Множители — представители, а не все
// конечные группы подряд: важна не величина, а сочетание свойств.
export const МНОЖИТЕЛИ = ['C2', 'C3', 'V4', 'S3', 'D4', 'Q8', 'A5'];

// Две РАЗНЫЕ роли, и путать их нельзя.
//
//   `все` — записи, которые надо связать: по ним становится вычислим ТЕРМ
//   prod(X, Y). Их много, и это не беда: перебор их не перебирает.
//
//   `вКаталог` — записи, которые предлагаются вершинам схемы как примеры. Их
//   должно быть мало, иначе перебор захлебнётся.
//
// Раньше это было одно и то же, и получалось так: произведение ⊕C₂ × C₂ имеет
// те же свойства, что ⊕C₂, поэтому отбрасывалось — а вместе с ним пропадала и
// вычислимость терма, и задача «A не циклична, в A есть кручение, B циклична:
// верно ли, что A × B конечна» оставалась без ответа, хотя ответ очевиден.
export function синтезироватьПроизведения(записи, конечные, множители = МНОЖИТЕЛИ) {
  const поId = new Map(конечные.map((G) => [G.id ?? G.имя, G]));
  const занято = new Set([
    ...конечные.map((G) => сигнатура(свойстваГруппы(G))),
    ...записи.map((з) => сигнатура(з.props ?? {})),
  ]);
  const исходные = записи.filter((з) => з.бесконечная && !з.синтез);
  const все = [];
  const вКаталог = [];
  const добавить = (X, F, ключ) => {
    const з = синтезПроизведения(X, F);
    if (!з) return;
    все.push(з);
    // Терм prod(X, F) вычислим независимо от того, взяли ли запись в каталог.
    X.произведения = { ...(X.произведения ?? {}), [ключ]: з.id };
    const s = сигнатура(з.props);
    if (занято.has(s)) return;
    занято.add(s);
    вКаталог.push(з);
  };

  for (const X of исходные) {
    for (const fid of множители) {
      const F = поId.get(fid);
      if (F) добавить(X, F, fid);
    }
  }
  // Бесконечная на бесконечную: ℤ × ⊕C₂ и ℤ × ℤ(2^∞) нужны ровно так же.
  // Пара берётся один раз, но записывается обоим сомножителям — произведение
  // коммутативно, и искать его будут с любой стороны.
  for (let i = 0; i < исходные.length; i++) {
    for (let j = i; j < исходные.length; j++) {
      const X = исходные[i];
      const Y = исходные[j];
      const было = все.length;
      добавить(X, Y, Y.id);
      if (все.length > было && i !== j) {
        Y.произведения = { ...(Y.произведения ?? {}), [X.id]: все[все.length - 1].id };
      }
    }
  }
  return { все, вКаталог };
}
