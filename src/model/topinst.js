// Мост между схемой и моделью топологии.
//
// Устроен так же, как мост групп: конечные пространства ВЫЧИСЛЯЮТСЯ (они же
// предпорядки, см. top.js), бесконечные ОБЪЯВЛЯЮТСЯ. Значения пяти видов:
//
//   { вид: 'простр',    X }                      посчитанное конечное
//   { вид: 'подпростр', объемлющее, A, }         A — номера точек
//   { вид: 'топотоб',   дом, код, φ }            непрерывное отображение
//   { вид: 'имяпростр', зап }                    объявленное бесконечное
//   { вид: 'имяподпр',  зап, влад }              объявленное подпростр

import {
  пространствоП, всеПространства, подпростр, произведениеП, суммаП, стянутьП,
  замыканиеП, внутренностьП, отображенияП, гомеоморфны, ключПространства,
  свойстваПространства, свойстваПодпространства, свойстваОтображения,
} from './top.js';
import { НЕ_СЧИТАЕМ } from './значение.js';

export const ТОПОЛОГИЧЕСКОЕ = new Set([
  'простр', 'подпростр', 'топотоб', 'имяпростр', 'имяподпр',
]);

const топОбёртка = (X) => ({ вид: 'простр', X });
const топПодзн = (объемлющее, A) => ({ вид: 'подпростр', объемлющее, A: [...A].sort((a, b) => a - b) });

export const какПространство = (v) => {
  if (!v) return null;
  if (v.вид === 'простр') return v.X;
  if (v.вид === 'подпростр') {
    v._как ??= подпростр(v.объемлющее, v.A);
    return v._как;
  }
  if (v.вид === 'имяподпр') {
    const о = v.зап._объект;
    return о?.вид === 'простр' ? о.X : null;
  }
  return null;
};

const топЗапись = (v) => {
  if (v?.вид === 'имяпростр') return v.зап;
  if (v?.вид === 'имяподпр') {
    const о = v.зап._объект;
    return о?.вид === 'имяпростр' ? о.зап : null;
  }
  return null;
};

// --- библиотека -----------------------------------------------------------------

// Конечные пространства перечисляются целиком, объявленные подклеиваются.
// Имена конечным даются по числу точек и номеру — они безличны по существу,
// и притворяться, что у 33 пространств на четырёх точках есть имена, незачем.
export function собратьБиблиотеку(записи, доТочек = 4) {
  const конечные = [];
  for (let n = 1; n <= доТочек; n++) {
    всеПространства(n).forEach((X, i) => {
      X.id = n === 1 ? 'точка' : `T${n}.${i}`;
      X.имя = n === 1 ? 'точка' : `${n}-точечное №${i + 1}`;
      конечные.push(X);
    });
  }
  // «пара» — двухточечное ДИСКРЕТНОЕ; на него ссылаются объявления.
  const пара = конечные.find((X) => X.n === 2 && свойстваПространства(X).discrete);
  if (пара) { пара.id = 'пара'; пара.имя = 'две точки (дискретно)'; }

  const поИмени = new Map();
  for (const X of конечные) поИмени.set(X.id, топОбёртка(X));
  for (const з of записи) поИмени.set(з.id, { вид: 'имяпростр', зап: з });

  const беды = [];
  const найти = (id, где) => {
    const v = поИмени.get(id);
    if (!v) беды.push(`${где}: нет пространства «${id}»`);
    return v ?? null;
  };
  for (const з of записи) {
    з.бесконечное = true;
    for (const п of з.подпространства ?? []) {
      п._владелец = з;
      п._объект = найти(п.объект, `${з.id}/${п.id}`);
    }
    з._поПод = new Map((з.подпространства ?? []).map((п) => [п.id, п]));
    з._факторы = new Map(Object.entries(з.факторы ?? {}).map(([k, v]) => {
      if (!з._поПод.has(k)) беды.push(`${з.id}: фактор по неизвестному подпространству «${k}»`);
      return [k, найти(v, `${з.id}/фактор/${k}`)];
    }));
    з._произведения = new Map(Object.entries(з.произведения ?? {})
      .map(([k, v]) => [k, найти(v, `${з.id}/произведение/${k}`)]));
    // Ровно одно подпространство обязано быть всем пространством.
    const целые = (з.подпространства ?? []).filter((п) => п.props?.whole === true);
    if (целые.length !== 1) беды.push(`${з.id}: подпространств со свойством «всё» должно быть ровно одно`);
  }
  return { конечные, записи, беды };
}

export const всёПодпространствоП = (v) => {
  if (v?.вид === 'простр') return топПодзн(v.X, [...Array(v.X.n).keys()]);
  if (v?.вид !== 'имяпростр') return null;
  const п = (v.зап.подпространства ?? []).find((x) => x.props?.whole === true);
  return п ? { вид: 'имяподпр', зап: п, влад: v.зап } : null;
};

// --- свойства -------------------------------------------------------------------

export function свойстваЗначенияТоп(v) {
  if (!v) return {};
  if (v.вид === 'простр') return свойстваПространства(v.X);
  if (v.вид === 'подпростр') return свойстваПодпространства(v.объемлющее, v.A);
  if (v.вид === 'топотоб') {
    return v.имен ? { ...v.имен.props } : свойстваОтображения(v.дом, v.код, v.φ);
  }
  if (v.вид === 'имяпростр') return v.зап.props ?? {};
  if (v.вид === 'имяподпр') {
    // Свойства ОБЪЕКТА берутся у того, чему подпространство гомеоморфно;
    // свойства ВЛОЖЕНИЯ (открыто, замкнуто, плотно, всё) — у самой записи.
    const о = v.зап._объект;
    const объектные = о ? свойстваЗначенияТоп(о) : {};
    return { ...объектные, ...(v.зап.props ?? {}) };
  }
  return {};
}

export function отношениеТоп(rel, a, b) {
  if (rel === 'homeomorphic') {
    const A = какПространство(a);
    const B = какПространство(b);
    if (A && B) return гомеоморфны(A, B);
    const за = топЗапись(a);
    const зб = топЗапись(b);
    if (за && зб) return за.id === зб.id ? true : расходятся(за.props, зб.props);
    if ((A && зб) || (за && B)) return false;
    return undefined;
  }
  if (rel === 'le') {
    if (a?.вид === 'подпростр' && b?.вид === 'подпростр') {
      const в = new Set(b.A);
      return a.A.every((x) => в.has(x));
    }
    return undefined;
  }
  return undefined;
}

// Два объявленных пространства заведомо не гомеоморфны, если расходится хоть
// одно записанное свойство. Совпадение свойств не значит гомеоморфности —
// тогда честный ответ «не знаю».
function расходятся(a, b) {
  for (const k of Object.keys(a ?? {})) {
    if (b?.[k] !== undefined && b[k] !== a[k]) return false;
  }
  return undefined;
}

// --- вычисление конструкций ------------------------------------------------------

export function вычислитьУзелТоп(graph, id, значения, предел = 64) {
  const n = graph.get(id);
  const арг = (i) => значения.get(n.args[i]);
  const P = (v) => какПространство(v);

  switch (n.op) {
    case 'choose-space': case 'choose-sub': case 'choose-map':
      return значения.get(id) ?? null;

    case 'whole-sub': {
      const X = арг(0);
      return всёПодпространствоП(X) ?? НЕ_СЧИТАЕМ;
    }
    case 'closure': {
      const X = арг(0);
      const A = арг(1);
      // У ОБЪЯВЛЕННОГО подпространства замыкание известно в двух случаях, и
      // оба уже записаны в данных: плотное замыкается во всё, замкнутое — в
      // себя. Без этого «cl A» на бесконечных пространствах не считалось
      // вовсе, и вопросы про замыкание проверялись на одних конечных.
      if (A?.вид === 'имяподпр') {
        const p = свойстваЗначенияТоп(A);
        if (p.closed === true) return A;
        if (p.dense === true) return всёПодпространствоП(X) ?? НЕ_СЧИТАЕМ;
        return НЕ_СЧИТАЕМ;
      }
      const x = P(X);
      if (!x || A?.вид !== 'подпростр') return НЕ_СЧИТАЕМ;
      return топПодзн(x, замыканиеП(x, A.A));
    }
    case 'interior': {
      const X = арг(0);
      const A = арг(1);
      // Двойственно: открытое совпадает со своей внутренностью.
      if (A?.вид === 'имяподпр') {
        return свойстваЗначенияТоп(A).open === true ? A : НЕ_СЧИТАЕМ;
      }
      const x = P(X);
      if (!x || A?.вид !== 'подпростр') return НЕ_СЧИТАЕМ;
      return топПодзн(x, внутренностьП(x, A.A));
    }
    case 'prod-top': {
      const X = арг(0);
      const Y = арг(1);
      const объявлено = объявленноеПроизведение(X, Y);
      if (объявлено) return объявлено;
      const x = P(X);
      const y = P(Y);
      // Считаем настоящий предпорядок, только когда обе части конечны;
      // иначе выводим свойства из свойств сомножителей.
      if (x && y && x.n * y.n <= предел) return топОбёртка(произведениеП(x, y));
      return топПроизведение(X, Y);
    }
    case 'sum-top': {
      const X = арг(0);
      const Y = арг(1);
      const x = P(X);
      const y = P(Y);
      if (x && y && x.n + y.n <= предел) return топОбёртка(суммаП(x, y));
      return топСумма(X, Y);
    }
    case 'collapse': {
      const X = арг(0);
      const A = арг(1);
      // Стягивание ОДНОЙ точки ничего не меняет, объявлять такой фактор не
      // надо. Без этой строчки вопрос «A компактно (а в библиотеке это точка):
      // что скажете про X/A» оставался без ответа на объявленных пространствах.
      if (свойстваЗначенияТоп(A).point === true) return X;
      if (X?.вид === 'имяпростр' && A?.вид === 'имяподпр' && A.влад === X.зап) {
        return X.зап._факторы.get(A.зап.id) ?? НЕ_СЧИТАЕМ;
      }
      const x = P(X);
      if (!x || A?.вид !== 'подпростр') return НЕ_СЧИТАЕМ;
      return топОбёртка(стянутьП(x, A.A));
    }
    case 'im-top': {
      const f = арг(0);
      if (f?.вид !== 'топотоб') return НЕ_СЧИТАЕМ;
      if (f.имен) return f.имен.образ ?? НЕ_СЧИТАЕМ;
      return топПодзн(f.код, [...new Set(f.φ)]);
    }
    default:
      return НЕ_СЧИТАЕМ;
  }
}

function объявленноеПроизведение(X, Y) {
  const за = X?.вид === 'имяпростр' ? X.зап : null;
  const зб = Y?.вид === 'имяпростр' ? Y.зап : null;
  if (за && зб) return за._произведения.get(зб.id) ?? зб._произведения.get(за.id) ?? null;
  return null;
}

// --- синтез суммы и произведения -------------------------------------------------
//
// Если хоть один сомножитель объявлен, считать нечего — но и молчать не за что:
// свойства произведения и дизъюнктной суммы выводятся из сомножителей
// МЕХАНИЧЕСКИ. Как и у групп, знание не выдумывается: «не знаю» у сомножителя
// даёт «не знаю» у результата, если второй не решает дело сам.

const иТоп = (a, b) => {
  if (a === false || b === false) return false;
  if (a === undefined || b === undefined) return undefined;
  return a && b;
};

// Всё, что ниже, — КОНЪЮНКЦИИ, и в обе стороны. Каждый сомножитель вкладывается
// в произведениеП как подпростр и получается из него непрерывной открытоПй
// проекцией, поэтому свойство верно у произведения тогда и только тогда, когда
// верно у обоих. Единственное исключение — НОРМАЛЬНОСТЬ: плоскость Зоргенфрея
// не нормальна при нормальных сомножителях, и про T₄ синтез молчит.
const ПО_ОБОИМ_ПРОИЗВ = [
  'point', 'finite', 'countable', 'T0', 'T1', 'T2', 'T3',
  'connected', 'path-connected', 'totally-disconnected',
  'compact', 'locally-compact', 'discrete', 'indiscrete',
  'metrizable', 'first-countable', 'second-countable', 'separable',
];

export function свойстваПроизведенияТоп(a, b) {
  const out = {};
  for (const p of ПО_ОБОИМ_ПРОИЗВ) {
    const v = иТоп(a[p], b[p]);
    if (v !== undefined) out[p] = v;
  }
  return out;
}

// У суммы конъюнктивны те же свойства плюс нормальность (дизъюнктная суммаП
// нормальных нормальна), а связноПсть, линейная связноПсть, одноточечность и
// антидискретность у суммы двух НЕПУСТЫХ ложны всегда: каждая часть открыта и
// замкнута, значит целое распадается.
const ПО_ОБОИМ_СУММА = [
  'finite', 'countable', 'T0', 'T1', 'T2', 'T3', 'T4',
  'totally-disconnected', 'compact', 'locally-compact', 'discrete',
  'metrizable', 'first-countable', 'second-countable', 'separable',
];

export function свойстваСуммыТоп(a, b) {
  const out = { point: false, connected: false, 'path-connected': false, indiscrete: false };
  for (const p of ПО_ОБОИМ_СУММА) {
    const v = иТоп(a[p], b[p]);
    if (v !== undefined) out[p] = v;
  }
  return out;
}

const КЭШ_СИНТЕЗА = new Map();

// Собрать значение-пространствоП из выведенных свойств. ПодпространствоП у него
// одно — всё оно само: объявлять точку или множители нечем, а врать нельзя.
function топСинтезировать(id, имя, props) {
  if (КЭШ_СИНТЕЗА.has(id)) return КЭШ_СИНТЕЗА.get(id);
  const зап = { id, имя, бесконечное: true, синтез: true, props, подпространства: [] };
  const v = { вид: 'имяпростр', зап };
  const всё = {
    id: 'всё', имя, объект: id, _владелец: зап, _объект: v,
    props: { open: true, closed: true, dense: true, whole: true },
  };
  зап.подпространства.push(всё);
  зап._поПод = new Map([['всё', всё]]);
  зап._факторы = new Map();
  зап._произведения = new Map();
  КЭШ_СИНТЕЗА.set(id, v);
  return v;
}

const имяЗначения = (v) => (v?.вид === 'имяпростр' ? v.зап.имя : v?.X?.имя ?? `${v?.X?.n}-точечное`);
const идЗначения = (v) => (v?.вид === 'имяпростр' ? v.зап.id : v?.X?.id ?? `T${v?.X?.n}`);

function топПроизведение(X, Y) {
  const a = свойстваЗначенияТоп(X);
  const b = свойстваЗначенияТоп(Y);
  if (!Object.keys(a).length || !Object.keys(b).length) return НЕ_СЧИТАЕМ;
  return топСинтезировать(
    `${идЗначения(X)}x${идЗначения(Y)}`,
    `${имяЗначения(X)} × ${имяЗначения(Y)}`,
    свойстваПроизведенияТоп(a, b),
  );
}

function топСумма(X, Y) {
  const a = свойстваЗначенияТоп(X);
  const b = свойстваЗначенияТоп(Y);
  if (!Object.keys(a).length || !Object.keys(b).length) return НЕ_СЧИТАЕМ;
  return топСинтезировать(
    `${идЗначения(X)}+${идЗначения(Y)}`,
    `${имяЗначения(X)} ⊔ ${имяЗначения(Y)}`,
    свойстваСуммыТоп(a, b),
  );
}

// --- кандидаты ------------------------------------------------------------------

export function кандидатыТоп(graph, n, значения, каталог, предел = 16) {
  const арг = (i) => значения.get(n.args[i]);
  switch (n.op) {
    case 'choose-space': {
      // Порядок здесь решает больше, чем кажется. На схеме с двумя
      // пространствами перебор лексикографический: пока не кончатся значения
      // Y, X не сдвинется, — поэтому предел на число примеров обрезает всё на
      // первых двух-трёх значениях X. Чередование тут не спасает: оно
      // действует только во внутреннем цикле.
      //
      // Значит вперёд надо ставить САМОЕ ИНФОРМАТИВНОЕ. У групп это мелкие
      // конечные: контрпример обычно мелкий. У топологии наоборот — у конечных
      // пространств половина свойств вырождена, а 33 четырёхточечных отличаются
      // друг от друга мелочами. Поэтому: сперва пространства до трёх точек
      // (Серпинский и прочая классика), затем ВСЕ объявленные, и лишь потом
      // четырёхточечные.
      const годные = каталог.filter((x) => x.бесконечное || x.n <= предел);
      const мелкие = годные.filter((x) => !x.бесконечное && x.n <= 3).map(топОбёртка);
      const крупные = годные.filter((x) => !x.бесконечное && x.n > 3).map(топОбёртка);
      const объявленные = годные.filter((x) => x.бесконечное)
        .map((x) => ({ вид: 'имяпростр', зап: x }));
      return [...мелкие, ...объявленные, ...крупные];
    }
    case 'choose-sub': {
      const X = арг(0);
      if (X?.вид === 'имяпростр') {
        return (X.зап.подпространства ?? []).map((п) => ({ вид: 'имяподпр', зап: п, влад: X.зап }));
      }
      const x = какПространство(X);
      if (!x) return [];
      return всеПодмножества(x.n).map((A) => топПодзн(x, A));
    }
    case 'choose-map': {
      const X = арг(0);
      const Y = арг(1);
      const x = какПространство(X);
      const y = какПространство(Y);
      if (x && y) return отображенияП(x, y).map((φ) => ({ вид: 'топотоб', дом: x, код: y, φ }));
      // Если хоть одно пространство объявлено, перебирать нечего — но три вида
      // отображений есть ВСЕГДА и определяются самими объявлениями: постоянное,
      // вложение объявленного подпространства и проекция на объявленный фактор.
      // Пока их не было, всякая строка схемы с морфизмом имела КОНЕЧНЫЙ образ,
      // и вопрос «верно ли, что im f конечен» подтверждался тысячами примеров.
      return именованныеОтображения(X, Y);
    }
    default:
      return [];
  }
}

// Отображения, выводимые из объявлений. Ничего не выдумывается: каждое
// существует по построению, и у каждого известен образ.
function именованныеОтображения(X, Y) {
  const зX = X?.вид === 'имяпростр' ? X.зап : null;
  const зY = Y?.вид === 'имяпростр' ? Y.зап : null;
  const out = [];
  const подзначение = (зап, влад) => ({ вид: 'имяподпр', зап, влад });

  // Постоянное: образ — точка, если она у цели объявлена.
  const точкаY = зY ? (зY.подпространства ?? []).find((п) => п._объект?.вид === 'простр'
    && п._объект.X.n === 1) : null;
  if (точкаY) {
    out.push({
      вид: 'топотоб',
      имен: {
        имя: 'постоянное', образ: подзначение(точкаY, зY),
        props: { constant: true, injective: false, surjective: false, homeo: false },
      },
    });
  }
  // Тождественное.
  if (зX && зX === зY) {
    const всё = всёПодпространствоП(Y);
    if (всё) {
      out.push({
        вид: 'топотоб',
        имен: {
          имя: 'тождественное', образ: всё,
          props: { homeo: true, injective: true, surjective: true, constant: false },
        },
      });
    }
  }
  // Вложение: у цели объявлено подпространство, гомеоморфное области.
  if (зY) {
    for (const п of зY.подпространства ?? []) {
      if (п.props?.whole === true) continue;
      const совпало = зX ? п._объект?.зап === зX
        : п._объект?.вид === 'простр' && X?.вид === 'простр' && п._объект.X === X.X;
      if (!совпало) continue;
      out.push({
        вид: 'топотоб',
        имен: {
          имя: `вложение ${п.имя}`, образ: подзначение(п, зY),
          props: { injective: true, surjective: false, homeo: false },
        },
      });
    }
  }
  // Проекция на фактор: у области объявлен фактор, гомеоморфный цели.
  if (зX) {
    for (const [idПод, значение] of зX._факторы ?? []) {
      const тот = зY ? значение?.зап === зY
        : значение?.вид === 'простр' && Y?.вид === 'простр' && значение.X === Y.X;
      if (!тот) continue;
      const всё = всёПодпространствоП(Y);
      if (!всё) continue;
      out.push({
        вид: 'топотоб',
        имен: {
          имя: `проекция на фактор по ${зX._поПод.get(idПод)?.имя ?? idПод}`,
          образ: всё,
          props: { surjective: true, injective: false, homeo: false },
        },
      });
    }
  }
  return out;
}

// Подмножества точек. Их 2^n, и при n ≤ 4 это шестнадцать — перечислять
// целиком дешевле, чем выдумывать, какие из них «интересны».
function всеПодмножества(n) {
  const out = [];
  for (let m = 1; m < (1 << n); m++) {
    const A = [];
    for (let i = 0; i < n; i++) if (m & (1 << i)) A.push(i);
    out.push(A);
  }
  return out;
}

export function описаниеТоп(v, имя) {
  if (!v) return null;
  if (v.вид === 'имяпростр') return `${имя} = ${v.зап.имя}`;
  if (v.вид === 'имяподпр') return `${имя} = ${v.зап.имя}`;
  if (v.вид === 'простр') return `${имя} = ${v.X.имя ?? `${v.X.n}-точечное`}`;
  if (v.вид === 'подпростр') {
    return `${имя} — подпростр из ${v.A.length} точек`;
  }
  if (v.вид === 'топотоб') {
    if (v.имен) return `${имя} — ${v.имен.имя}`;
    const об = new Set(v.φ).size;
    return `${имя} — ${об === 1 ? 'постоянное' : `с образом из ${об} точек`}`;
  }
  return null;
}

