// Синтез ПОЛЯ РАЦИОНАЛЬНЫХ ФУНКЦИЙ и АЛГЕБРАИЧЕСКОГО ЗАМЫКАНИЯ.
//
// Та же мысль, что у колец: свойства обеих конструкций ВЫЧИСЛЯЮТСЯ по
// основанию, а не объявляются. Пока объявлялись, `rational` и `alg-closure`
// были посчитаны у считанных полей: на схеме «функции» 19 немых целей из 19, на
// «замыкании» — 20 из 22. А главная беда раздела полей даже не немота, а
// ПУСТОТА: 1461 пробел из 4075 — это «ни один объект библиотеки не подошёл под
// условие», и лечится она только новыми объектами. Синтез их и даёт.
//
// Теоремы, по которым считается K(x):
//
//   * ХАРАКТЕРИСТИКА наследуется: K(x) содержит K, образ единицы тот же;
//   * КОНЕЧНЫМ не бывает — одночленов xⁿ уже бесконечно много;
//   * АЛГЕБРАИЧЕСКИ ЗАМКНУТЫМ не бывает: у t² − x нет корня в K(x);
//   * СОВЕРШЕНСТВО теряется в характеристике p: у x нет корня степени p, и
//     K(x) совершенно РОВНО при характеристике нуль. Это главная причина
//     заводить такие поля: во всей прежней библиотеке несовершенных полей было
//     четыре, и все над 𝔽₂;
//   * ПРОСТЫМ не бывает: простое поле — это 𝔽_p или ℚ, а K(x) содержит K(x)
//     строго больше своего простого подполя.
//
// И по которым считается K̄:
//
//   * ХАРАКТЕРИСТИКА наследуется;
//   * АЛГЕБРАИЧЕСКИ ЗАМКНУТО по построению, значит и СОВЕРШЕННО;
//   * КОНЕЧНЫМ не бывает: конечное поле не замкнуто (многочлен ∏(t − a) + 1
//     корней не имеет);
//   * ПРОСТЫМ не бывает ни при каком K, кроме уже замкнутого, — а для
//     замкнутого синтез и не нужен, модель отдаёт само K.
//
// Расширения K ⊆ K(x) и K ⊆ K̄ объявляются заодно: без них новое поле в схемах
// про расширения не участвует, и половина пользы пропадает.

const ключСвойств = (props) => Object.keys(props).sort().map((k) => `${k}:${props[k]}`).join('|');

function свойстваРациональных(K) {
  const p = K.props ?? {};
  const out = {
    'finite-field': false,
    'alg-closed': false,
    'prime-field': false,
  };
  if (p['char-zero'] !== undefined) {
    out['char-zero'] = p['char-zero'];
    // Совершенно ровно в характеристике нуль: в характеристике p у x нет
    // корня степени p, и поле несовершенно.
    out['perfect-field'] = p['char-zero'];
  }
  return out;
}

function свойстваЗамыкания(K) {
  const p = K.props ?? {};
  const out = {
    'finite-field': false,
    'alg-closed': true,
    'perfect-field': true,
    'prime-field': false,
  };
  if (p['char-zero'] !== undefined) out['char-zero'] = p['char-zero'];
  return out;
}

// Расширение K ⊆ K(x): трансцендентное, значит ни алгебраическое, ни
// сепарабельное, ни нормальное (все три определены только для алгебраических —
// см. заметку о сепарабельности в data/fld-lib.json). Простое: порождено одним
// элементом x.
function расширениеВРациональные(K, idПоля) {
  return {
    id: `${K.id}<rat:${K.id}`,
    имя: `${K.имя}(x)/${K.имя}`,
    дом: K.id,
    код: idПоля,
    props: {
      'trivial-ext': false,
      'finite-ext': false,
      algebraic: false,
      separable: false,
      'normal-ext': false,
      galois: false,
      'simple-ext': true,
    },
    почему: 'Трансцендентное расширение, порождённое одним элементом: простое и бесконечное одновременно.',
  };
}

// Расширение K ⊆ K̄: алгебраическое и нормальное всегда, сепарабельное и Галуа
// ровно при совершенном K (иначе есть несепарабельные элементы), простым не
// бывает — бесконечное алгебраическое одним элементом не порождается.
function расширениеВЗамыкание(K, idПоля) {
  const p = K.props ?? {};
  const props = {
    'trivial-ext': false,
    'finite-ext': false,
    algebraic: true,
    'normal-ext': true,
    'simple-ext': false,
  };
  if (p['perfect-field'] !== undefined) {
    props.separable = p['perfect-field'];
    props.galois = p['perfect-field'];
  }
  return {
    id: `${K.id}<alg:${K.id}`,
    имя: `${K.имя}̄/${K.имя}`,
    дом: K.id,
    код: idПоля,
    props,
    почему: 'Алгебраическое замыкание: расширение алгебраично и нормально по построению, сепарабельно ровно при совершенном основании.',
  };
}

export function синтезироватьПоля(поля, расширения) {
  const былоСвойств = new Set(поля.map((K) => ключСвойств(K.props ?? {})));
  const естьРац = new Set(поля.filter((K) => K.рациональные).map((K) => K.id));
  const естьЗам = new Set(поля.filter((K) => K.замыкание).map((K) => K.id));
  const былоРасш = new Set(расширения.map((r) => r.id));
  const новыеПоля = [];
  const новыеРасширения = [];
  const вКаталог = [];
  const рац = new Map();
  const зам = new Map();

  for (const K of поля) {
    if (K.синтез) continue;
    const p = K.props ?? {};
    if (!естьРац.has(K.id)) {
      const id = `rat:${K.id}`;
      const props = свойстваРациональных(K);
      const зап = {
        id,
        имя: `${K.имя}(x)`,
        синтез: true,
        props,
        простое: K.простое ?? null,
        заметка: `Синтезировано из ${K.имя}: свойства посчитаны по теоремам, не объявлены.`,
      };
      if (!зап.простое) delete зап.простое;
      новыеПоля.push(зап);
      рац.set(K.id, зап);
      const р = расширениеВРациональные(K, id);
      if (!былоРасш.has(р.id)) новыеРасширения.push(р);
      const ключ = ключСвойств(props);
      if (!былоСвойств.has(ключ)) {
        былоСвойств.add(ключ);
        вКаталог.push(зап);
      }
    }
    // Замыкание замкнутого — оно само, и модель это знает без записи.
    if (!естьЗам.has(K.id) && p['alg-closed'] !== true) {
      const id = `alg:${K.id}`;
      const props = свойстваЗамыкания(K);
      const зап = {
        id,
        имя: `${K.имя}̄`,
        синтез: true,
        props,
        простое: K.простое ?? null,
        замыкание: id,
        заметка: `Синтезировано из ${K.имя}: алгебраическое замыкание, свойства посчитаны по теоремам.`,
      };
      if (!зап.простое) delete зап.простое;
      новыеПоля.push(зап);
      зам.set(K.id, зап);
      const р = расширениеВЗамыкание(K, id);
      if (!былоРасш.has(р.id)) новыеРасширения.push(р);
      const ключ = ключСвойств(props);
      if (!былоСвойств.has(ключ)) {
        былоСвойств.add(ключ);
        вКаталог.push(зап);
      }
    }
  }
  return { поля: новыеПоля, расширения: новыеРасширения, вКаталог, рациональные: рац, замыкания: зам };
}
