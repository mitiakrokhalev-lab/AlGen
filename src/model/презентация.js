// ЗАДАНИЕ ОБРАЗУЮЩИМИ И СООТНОШЕНИЯМИ (пункт C5 плана, мишень 8.8).
//
// Мишень, из-за которой это написано:
//
//   G = ⟨a, b | a²² = b¹⁵ = e, ab = ba³⟩, H = ⟨a²⟩.
//   Доказать, что H ⊳ G, и найти |G/H|.
//
// До этого задать такую группу было нечем: в библиотеке рецепты были только
// «циклическая», «перестановки», «произведение» и «таблица». Выписать таблицу
// умножения группы порядка 330 руками нельзя, а перестановками её надо сперва
// найти — то есть сделать ровно то, что делает этот файл.
//
// ЧТО ЗДЕСЬ. Перечисление смежных классов Тодда—Коксетера по подгруппе {e}:
// результат — регулярное представление, то есть действие группы на себе, а по
// нему таблица умножения строится сразу. Дальше работает вся прежняя машина:
// подгруппы, нормальность, индекс, центр — всё считается по таблице, и ничего
// нового для мишени 8.8 не нужно.
//
// ПОЧЕМУ ИМЕННО ЭТОТ АЛГОРИТМ. Он единственный общий: по конечному заданию
// решить, конечна ли группа, НЕВОЗМОЖНО (проблема тривиальности неразрешима,
// Новиков 1955), поэтому любой метод обязан иметь предел и обязан говорить
// вслух, когда в него упёрся. Здесь предел — видимая настройка, а обрыв
// возвращается полем `оборвано`, а не превращается в «группа бесконечна».
// Это ровно то же правило, по которому живут обрезанная таблица примеров и
// несошедшийся вывод.
//
// СЛОВО записывается списком пар [образующая, степень]: a²² это [[0, 22]],
// соотношение ab = ba³ переносится в левую часть как a b a⁻³ b⁻¹, то есть
// [[0, 1], [1, 1], [0, -3], [1, -1]]. Переносить руками — честнее, чем
// заводить разбор строк: разбор строк пришлось бы проверять, а проверять его
// нечем, кроме тех же соотношений.

// Столбцы таблицы: для каждой образующей два — она сама и обратная.
// Номер столбца образующей i — 2i, её обратной — 2i + 1, поэтому обратный
// столбец получается переключением младшего бита.
const инв = (g) => g ^ 1;

// Слово → список столбцов. a⁻³ разворачивается в три столбца a⁻¹.
function вСтолбцы(слово) {
  const out = [];
  for (const [i, степень] of слово) {
    const g = степень >= 0 ? 2 * i : 2 * i + 1;
    for (let k = 0; k < Math.abs(степень); k++) out.push(g);
  }
  return out;
}

export function перечислитьКлассы(образующих, соотношения, предел = 5000) {
  const кол = 2 * образующих;
  const слова = соотношения.map(вСтолбцы);
  // Таблица: таб[c][g] — класс, в который переходит c под действием g.
  // −1 значит «ещё не определено».
  const таб = [new Int32Array(кол).fill(-1)];
  // Склейки классов: union-find. Классы НЕ удаляются, а помечаются как
  // слипшиеся с меньшим — иначе пришлось бы переписывать всю таблицу.
  const p = [0];
  const корень = (c) => {
    let x = c;
    while (p[x] !== x) x = p[x];
    // Сжатие пути: без него на больших группах перечисление заметно медленнее.
    while (p[c] !== c) { const n = p[c]; p[c] = x; c = n; }
    return x;
  };
  let живых = 1;

  const завести = (c, g) => {
    if (таб.length >= предел) return -1;
    const d = таб.length;
    таб.push(new Int32Array(кол).fill(-1));
    p.push(d);
    живых++;
    таб[c][g] = d;
    таб[d][инв(g)] = c;
    return d;
  };

  // Очередь склеек: обрабатывается до пустоты, потому что одна склейка
  // вызывает другие (строки сливаются и их записи начинают спорить).
  const очередь = [];
  const склеить = (a, b) => {
    let x = корень(a);
    let y = корень(b);
    if (x === y) return;
    if (x > y) { const t = x; x = y; y = t; }
    p[y] = x;
    живых--;
    очередь.push(y);
  };

  const разобратьСклейки = () => {
    while (очередь.length) {
      const y = очередь.shift();
      const строка = таб[y];
      for (let g = 0; g < кол; g++) {
        const цель = строка[g];
        if (цель < 0) continue;
        // Запись исчезающего класса переносится на его корень.
        const ц = корень(цель);
        const x = корень(y);
        // Обратная запись у цели больше не должна указывать на y.
        if (корень(таб[ц][инв(g)]) === y) таб[ц][инв(g)] = x;
        const было = таб[x][g];
        if (было < 0) {
          таб[x][g] = ц;
          таб[ц][инв(g)] = x;
        } else if (корень(было) !== ц) {
          склеить(было, ц);
        }
      }
    }
  };

  // Протяжка слова по классу: идём по столбцам слова, доопределяя переходы.
  // Если на конце пришли не туда, откуда начали, — склейка.
  const протянуть = (c, слово) => {
    let x = корень(c);
    for (let k = 0; k < слово.length; k++) {
      const g = слово[k];
      let d = таб[x][g];
      if (d < 0) {
        // На последнем шаге нового класса заводить не надо: конец известен.
        if (k === слово.length - 1) {
          const конец = корень(c);
          таб[x][g] = конец;
          таб[конец][инв(g)] = x;
          return true;
        }
        d = завести(x, g);
        if (d < 0) return false;    // упёрлись в предел
      }
      x = корень(d);
    }
    if (x !== корень(c)) {
      склеить(x, корень(c));
      разобратьСклейки();
    }
    return true;
  };

  // Обход HLT: по каждому живому классу протягиваем все соотношения, потом
  // доопределяем недостающие переходы. Порядок именно такой — он держит
  // таблицу маленькой на тех заданиях, что встречаются в учебниках.
  for (let c = 0; c < таб.length; c++) {
    if (корень(c) !== c) continue;
    for (const w of слова) {
      if (!протянуть(c, w)) return { оборвано: таб.length, предел };
      if (корень(c) !== c) break;     // класс слипся — дальше смысла нет
    }
    if (корень(c) !== c) continue;
    for (let g = 0; g < кол; g++) {
      if (таб[c][g] >= 0) continue;
      if (завести(c, g) < 0) return { оборвано: таб.length, предел };
    }
  }
  разобратьСклейки();

  // Таблица замкнулась: собираем живые классы в номера 0..n−1.
  const номер = new Map();
  for (let c = 0; c < таб.length; c++) if (корень(c) === c) номер.set(c, номер.size);
  const n = номер.size;
  const действие = [];
  for (let g = 0; g < кол; g++) {
    const π = new Int32Array(n);
    for (const [c, i] of номер) {
      const d = таб[c][g];
      if (d < 0) return { оборвано: таб.length, предел };
      π[i] = номер.get(корень(d));
    }
    действие.push(π);
  }
  void живых;
  return { n, действие };
}

// Таблица умножения по регулярному представлению. Класс i — это элемент
// группы (перечисление шло по подгруппе {e}), и произведение двух элементов
// получается протяжкой: куда перейдёт класс a под действием слова, ведущего в
// класс b.
//
// Слово в класс b строим один раз на все пары — обходом в ширину от единицы.
export function таблицаПоПрезентации(образующих, соотношения, предел = 5000) {
  const итог = перечислитьКлассы(образующих, соотношения, предел);
  if (итог.оборвано) return итог;
  const { n, действие } = итог;
  const кол = действие.length;

  // Слово (список столбцов) для каждого класса: путь от единицы.
  const слово = new Array(n).fill(null);
  слово[0] = [];
  const очередь = [0];
  while (очередь.length) {
    const c = очередь.shift();
    for (let g = 0; g < кол; g++) {
      const d = действие[g][c];
      if (слово[d] !== null) continue;
      слово[d] = [...слово[c], g];
      очередь.push(d);
    }
  }
  if (слово.some((w) => w === null)) {
    return { оборвано: n, предел, почему: 'представление не транзитивно' };
  }

  const mul = new Int32Array(n * n);
  for (let a = 0; a < n; a++) {
    for (let b = 0; b < n; b++) {
      let x = a;
      for (const g of слово[b]) x = действие[g][x];
      mul[a * n + b] = x;
    }
  }
  // Индексы самих ОБРАЗУЮЩИХ: они понадобятся, чтобы говорить о конкретных
  // элементах («H = ⟨a²⟩» из мишени 8.8). Образующая — это класс, в который
  // единица переходит под её действием.
  const образующие = [];
  for (let i = 0; i < образующих; i++) образующие.push(действие[2 * i][0]);
  return { n, mul, образующие };
}
