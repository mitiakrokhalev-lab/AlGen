// Вычисление графа условия на КОНКРЕТНЫХ группах.
//
// Здесь живёт весь мост между схемой и моделью: каждой конструкции языка
// сопоставлено настоящее вычисление. Если конструкция в конечной модели
// невыразима (свободное произведение, свободная группа, π₁), вычисление
// возвращает null — и это не ошибка, а граница модели, о которой надо
// сообщить, а не умолчать.
//
// Значения трёх видов:
//   { вид: 'группа',    G }
//   { вид: 'подгруппа', объемлющая, H, какГруппа() }   H — номера в объемлющей
//   { вид: 'морфизм',   дом, код, φ }                  φ — образы по номерам дом

