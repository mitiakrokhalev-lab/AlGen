// Значения категории модулей ходят через те же четыре входа, что и групповые.
// Развилка одна и явная: у модульного значения свой вид, у модульной схемы —
// своя категория. Так вторая категория не расползлась по файлу условиями.
const МОДУЛЬНОЕ = new Set(['кольцо', 'модуль', 'подмодуль', 'модморфизм']);

// --- значения -----------------------------------------------------------------

export const какГруппа = (v) => {
  if (!v) return null;
  if (v.вид === 'группа') return v.G;
  if (v.вид === 'подгруппа') {
    v._как ??= подгруппаКакГруппа(v.объемлющая, v.H);
    return v._как.группа;
  }
  return null;
};

const конечноеПодзначение = (объемлющая, H) => ({ вид: 'подгруппа', объемлющая, H: [...H].sort((a, b) => a - b) });
const обёртка = (G) => ({ вид: 'группа', G });

// Перенести номера из подгруппы-как-группы обратно в объемлющую.
const наружу = (v, элементы) => {
  какГруппа(v);
  return элементы.map((x) => v._как.назад[x]);
};

// Элементы значения как ПОДМНОЖЕСТВА объемлющей группы. Подгруппа — тоже
// подмножество (Grp.sub ≤ Grp.subset), и обе формы обязаны читаться одинаково.
const какМножество = (v) => {
  if (v?.вид === 'подмножество') return { G: v.объемлющая, S: v.S };
  if (v?.вид === 'подгруппа') return { G: v.объемлющая, S: v.H };
  return null;
};

const множество = (объемлющая, S) => ({
  вид: 'подмножество', объемлющая, S: [...new Set(S)].sort((a, b) => a - b),
});

// --- вычисление конструкций -------------------------------------------------------

const НЕ_В_МОДЕЛИ = new Set([
  'pushout', 'free', 'units', 'pi1', 'semidirect', 'choose-act',
]);

export function вычислитьУзел(graph, id, значения, предельныйПорядок = Infinity) {
  const n = graph.get(id);
  if (значения.has(id)) return значения.get(id);
  // ИМПОРТИРОВАННАЯ конструкция считается моделью ТОЙ категории, откуда
  // пришла: центр группы Галуа — это центр группы, и считать его обязана
  // модель групп, а не модель полей. Метку `чужое` ставит импорт
  // (см. src/импорт.js), и развилка по разделу для таких узлов пропускается.
  const чужое = graph.cat.cons.get(n.op)?.чужое;
  if (чужое !== 'grp') {
    if (graph.cat.id === 'mod') return вычислитьУзелМод(graph, id, значения, предельныйПорядок);
    if (graph.cat.id === 'top') return вычислитьУзелТоп(graph, id, значения, предельныйПорядок);
    if (graph.cat.id === 'ring') return вычислитьУзелКольц(graph, id, значения);
    if (graph.cat.id === 'fld') return вычислитьУзелПоля(graph, id, значения);
  }
  const c = graph.cat.cons.get(n.op);
  if (!c) return null;
  if (НЕ_В_МОДЕЛИ.has(n.op)) return НЕ_СЧИТАЕМ;

  const арг = n.args.map((a) => значения.get(a));
  // Свободное произведение разбирается РАНЬШЕ общей развилки: у него свой
  // источник значений (тождество 1 ∗ B = B и объявленная таблица), и работать
  // он обязан и когда оба сомножителя — посчитанные конечные группы. Общая
  // ветка «есть именованный» такой случай не ловит, потому что ни одного
  // именованного там нет.
  if (n.op === 'freeprod') {
    if (арг.some((x) => x === НЕ_СЧИТАЕМ || x === undefined)) return НЕ_СЧИТАЕМ;
    if (арг.some((x) => x === null)) return null;
    const [A, B] = n.args.map((a) => какОбъект(значения.get(a)));
    return свободноеПроизведение(A, B, свойства) ?? НЕ_СЧИТАЕМ;
  }
  // Аргумент, которого модель не осилила, делает невычислимым и этот узел —
  // но объект-то существует, поэтому привязку выбрасывать не за что.
  if (арг.some((x) => x === НЕ_СЧИТАЕМ || x === undefined)) return НЕ_СЧИТАЕМ;
  if (арг.some((x) => x === null)) return null;
  const роль = new Map();
  (c.in ?? []).forEach((s, i) => роль.set(s.role, арг[i]));

  const годен = (v) => {
    const G = какГруппа(v);
    // Порог порядка — видимая настройка, а не потолок из кода: слишком
    // большие группы считаются минутами, и человек должен решать сам.
    return !G || G.n <= предельныйПорядок ? v : НЕ_СЧИТАЕМ;
  };
  // Бесконечные группы не вычисляются, а объявляются: у них своя ветка, и всё,
  // чего в объявлении нет, честно невычислимо.
  const естьИменованный = [...роль.values()].some(
    (v) => v && (v.вид === 'имя' || v.вид === 'именПод' || v.вид === 'именМорфизм'
      || v.вид === 'имясемья' || v.вид === 'имясистема'
      || (v.вид === 'элемент' && v.объемлющая === null)),
  );
  if (естьИменованный) return построитьИменованный(n, роль);
  return годен(построить(graph, n, роль, значения, предельныйПорядок));
}

function построитьИменованный(n, роль) {
  const X = какОбъект(роль.get('X'));
  const N = роль.get('N');
  const F = роль.get('F');
  const зап = X && X.вид === 'имя' ? X.зап : null;
  const D = роль.get('D');
  if (D?.вид === 'имясистема') {
    if (n.op === 'colim') return D.зап._копредел ?? НЕ_СЧИТАЕМ;
    if (n.op === 'lim') return D.зап._предел ?? НЕ_СЧИТАЕМ;
    return НЕ_СЧИТАЕМ;
  }
  if (F?.вид === 'имясемья') {
    if (n.op === 'prod-fam') return F.зап._произведение ?? НЕ_СЧИТАЕМ;
    if (n.op === 'sum-fam') return F.зап._сумма ?? НЕ_СЧИТАЕМ;
    return НЕ_СЧИТАЕМ;
  }

  // Числовые величины объявленных объектов: точного значения нет, но
  // КОНЕЧНОСТЬ известна из объявления, а её одной хватает половине правил.
  if (n.op === 'ord' || n.op === 'index' || n.op === 'eltord') {
    return числоОбъявленного(n, роль);
  }
  const x = роль.get('x');
  if (x?.вид === 'элемент' && x.объемлющая === null) {
    const зэ = x.имен?.вид === 'имя' ? x.имен.зап : null;
    if (!зэ) return НЕ_СЧИТАЕМ;
    // ⟨e⟩ — тривиальная подгруппа, C(e) — вся группа: это верно всегда и
    // объявлять не надо. У объявленного представителя и то, и другое взято
    // из его записи.
    const поId = (id) => {
      const п = зэ._поПодгруппе.get(id);
      return п ? именПодзначение(п) : НЕ_СЧИТАЕМ;
    };
    if (n.op === 'gen') {
      if (x.зап) return x.зап.порождает ? поId(x.зап.порождает) : НЕ_СЧИТАЕМ;
      return тривиальнаяПодгруппа(x.имен) ?? НЕ_СЧИТАЕМ;
    }
    if (n.op === 'centralizer-elt') {
      if (x.зап) return x.зап.централизатор ? поId(x.зап.централизатор) : НЕ_СЧИТАЕМ;
      return всяПодгруппа(x.имен) ?? НЕ_СЧИТАЕМ;
    }
    return НЕ_СЧИТАЕМ;
  }

  // Множество элементов конечного порядка у ОБЪЯВЛЕННОЙ группы. Считать
  // нечего, но три случая следуют из записанных свойств: у периодической это
  // вся группа, у группы без кручения — одна единица, у абелевой — объявленная
  // подгруппа кручения. Для остальных (D∞!) ответ берётся из объявления: там
  // это множество подгруппой быть не обязано, и в этом вся соль конструкции.
  if (n.op === 'torsion-set') {
    if (!зап) return НЕ_СЧИТАЕМ;
    const p = зап.props ?? {};
    if (зап.множествоКручения) {
      return { вид: 'имямножество', влад: зап, props: { ...зап.множествоКручения } };
    }
    if (p.periodic === true) {
      return { вид: 'имямножество', влад: зап, props: { subgroup: true, 'set-whole': true } };
    }
    if (p['torsion-free'] === true) {
      return { вид: 'имямножество', влад: зап, props: { subgroup: true, 'set-whole': p.trivial === true } };
    }
    if (p.abelian === true && зап._конструкции?.torsion) {
      const t = зап._конструкции.torsion;
      return { вид: 'имямножество', влад: зап, props: { subgroup: true, 'set-whole': свойства(t).whole === true } };
    }
    return НЕ_СЧИТАЕМ;
  }

  switch (n.op) {
    case 'trivial-sub': {
      if (!зап) return НЕ_СЧИТАЕМ;
      const п = найтиПодгруппу(зап, (x) => x._объект?.вид === 'группа' && x._объект.G.n === 1);
      return п ? именПодзначение(п) : НЕ_СЧИТАЕМ;
    }
    case 'whole-sub': {
      if (!зап) return НЕ_СЧИТАЕМ;
      const п = найтиПодгруппу(зап, (x) => x.props?.whole === true);
      return п ? именПодзначение(п) : НЕ_СЧИТАЕМ;
    }
    case 'center': case 'commutator': case 'torsion': {
      if (!зап) return НЕ_СЧИТАЕМ;
      if (n.op === 'torsion' && свойства(X).abelian !== true) return null;
      return зап._конструкции[n.op] ?? НЕ_СЧИТАЕМ;
    }
    case 'ab': case 'aut':
      return зап?._конструкции[n.op] ?? НЕ_СЧИТАЕМ;
    case 'quotient': {
      if (!зап || !N || N.вид !== 'именПод' || N.влад !== зап) return НЕ_СЧИТАЕМ;
      if (свойства(N).normal !== true) return null;
      return зап._факторы.get(N.зап.id) ?? НЕ_СЧИТАЕМ;
    }
    case 'prod': {
      // ℤ × A₅ существует; его просто нет в объявлениях. Это незнание модели,
      // и из-за него нельзя терять строку целиком: вопросы про сомножители
      // остаются законными.
      const Y = какОбъект(роль.get('Y'));
      // Умножение на единичную группу объявлять незачем: G × 1 = G. Синтез
      // такие пары пропускает, и без этой строчки вопрос «A конечна и
      // свободна (то есть A = 1): что скажете про A × B» оставался без ответа.
      const единичная = (v) => (v?.вид === 'имя'
        ? v.зап.props?.trivial === true
        : v?.G?.n === 1);
      if (единичная(Y)) return X;
      if (единичная(X)) return Y;
      const другой = Y?.вид === 'имя' ? Y.зап.id : Y?.G?.id;
      if (зап && другой) return зап._произведения.get(другой) ?? НЕ_СЧИТАЕМ;
      const свой = X?.вид === 'имя' ? X.зап.id : X?.G?.id;
      if (Y?.вид === 'имя' && свой) return Y.зап._произведения.get(свой) ?? НЕ_СЧИТАЕМ;
      return НЕ_СЧИТАЕМ;
    }

    // Канонические морфизмы объявлять не надо: проекция и вложение целиком
    // определяются уже записанными подгруппами и факторами.
    case 'proj': {
      if (!зап || N?.вид !== 'именПод' || N.влад !== зап) return НЕ_СЧИТАЕМ;
      if (свойства(N).normal !== true) return null; // проекции по ненормальной НЕТ
      const код = зап._факторы.get(N.зап.id);
      if (!код) return НЕ_СЧИТАЕМ;
      return {
        вид: 'именМорфизм', имя: `π_${N.зап.имя}`, дом: X, код,
        ядро: N, образ: всяПодгруппа(код), props: { surjective: true },
      };
    }
    case 'incl': {
      if (!зап || N?.вид !== 'именПод' || N.влад !== зап) return НЕ_СЧИТАЕМ;
      const дом = N.зап._объект;
      if (!дом) return НЕ_СЧИТАЕМ;
      return {
        вид: 'именМорфизм', имя: `ι_${N.зап.имя}`, дом, код: X,
        ядро: тривиальнаяПодгруппа(дом), образ: N, props: { injective: true },
      };
    }
    case 'ker':
      return F?.вид === 'именМорфизм' ? (F.ядро ?? НЕ_СЧИТАЕМ) : НЕ_СЧИТАЕМ;
    case 'im':
      return F?.вид === 'именМорфизм' ? (F.образ ?? НЕ_СЧИТАЕМ) : НЕ_СЧИТАЕМ;

    default:
      // Всё прочее над бесконечной группой в модели не выражено.
      return НЕ_СЧИТАЕМ;
  }
}

// Порядок, индекс и порядок элемента объявленного объекта. Бесконечность
// известна точно, конкретное конечное значение — нет, и врать про него нельзя:
// «подгруппа конечного индекса» не говорит, каков этот индекс.
function числоОбъявленного(n, роль) {
  const бесконечно = { вид: 'число', n: Infinity };
  const неизвестно = { вид: 'число', n: null };
  if (n.op === 'ord') {
    const X = какОбъект(роль.get('X'));
    const p = X ? свойства(X) : {};
    if (p.trivial === true) return { вид: 'число', n: 1 };
    if (p.finite === false) return бесконечно;
    return неизвестно;
  }
  if (n.op === 'index') {
    const N_ = роль.get('N');
    const p = N_ ? свойства(N_) : {};
    // Объявленное ЗНАЧЕНИЕ индекса, если оно есть: «2ℤ в ℤ» — это индекс 2,
    // а не просто «конечный индекс», и задачи про индекс 2 держатся на нём.
    if (N_?.вид === 'именПод' && Number.isInteger(N_.зап?.индекс)) {
      return { вид: 'число', n: N_.зап.индекс };
    }
    // Индекс — это ПОРЯДОК ФАКТОРА, и если фактор объявлен, писать индекс
    // отдельно незачем: (ℤ : 3ℤ) = |ℤ/3ℤ| = |C₃| = 3. Руками он был проставлен
    // у одной подгруппы ℤ из четырёх — и это был не выбор, а недосмотр.
    if (N_?.вид === 'именПод' && N_.влад?._факторы) {
      const ф = N_.влад._факторы.get(N_.зап.id);
      const G = какГруппа(ф);
      if (G) return { вид: 'число', n: G.n };
      if (ф?.вид === 'имя' && ф.зап.props?.finite === false) return бесконечно;
    }
    if (p.whole === true) return { вид: 'число', n: 1 };
    if (p['finite-index'] === false) return бесконечно;
    return неизвестно;
  }
  const x = роль.get('x');
  const p = x ? свойства(x) : {};
  if (p['identity-elt'] === true) return { вид: 'число', n: 1 };
  if (p.involution === true) return { вид: 'число', n: 2 };
  if (p['torsion-elt'] === false) return бесконечно;
  return неизвестно;
}

function построить(graph, n, роль, значения, предельныйПорядок) {
  const X = роль.get('X');
  const N = роль.get('N');
  const M = роль.get('M');
  const F = роль.get('F');
  switch (n.op) {
    case 'terminal':
      return обёртка(циклическая(1, '1'));
    case 'trivial-sub':
      return конечноеПодзначение(какГруппа(X), [0]);
    case 'whole-sub': {
      const G = какГруппа(X);
      return конечноеПодзначение(G, Array.from({ length: G.n }, (_, i) => i));
    }
    case 'quotient': {
      const G = какГруппа(X);
      if (!N || N.вид !== 'подгруппа' || N.объемлющая !== G) return null;
      if (!нормальна(G, N.H)) return null;
      return обёртка(фактор(G, N.H).группа);
    }
    case 'center':
      return конечноеПодзначение(какГруппа(X), центр(какГруппа(X)));
    case 'commutator':
      return конечноеПодзначение(какГруппа(X), коммутант(какГруппа(X)));
    case 'centralizer':
      return конечноеПодзначение(какГруппа(X), централизатор(какГруппа(X), N.H));
    case 'normalizer':
      return конечноеПодзначение(какГруппа(X), нормализатор(какГруппа(X), N.H));
    case 'normal-closure': {
      const G = какГруппа(X);
      const все = [];
      for (let g = 0; g < G.n; g++) {
        for (const h of N.H) все.push(умножить(G, умножить(G, g, h), G.inv[g]));
      }
      return конечноеПодзначение(G, порождённая(G, все));
    }
    case 'meet':
      return конечноеПодзначение(какГруппа(X), пересечение(N.H, M.H));
    case 'join':
      return конечноеПодзначение(какГруппа(X), порождённая(какГруппа(X), [...N.H, ...M.H]));
    case 'as-sub': {
      // K — подгруппа группы N; вернуть её же как подгруппу X.
      const K = роль.get('K');
      if (!K || K.вид !== 'подгруппа') return null;
      return конечноеПодзначение(какГруппа(X), наружу(N, K.H));
    }
    case 'torsion': {
      const G = какГруппа(X);
      // Операция определена только для абелевых; в конечной абелевой это вся группа.
      if (!свойства(X).abelian) return null;
      return конечноеПодзначение(G, Array.from({ length: G.n }, (_, i) => i));
    }
    case 'ab': {
      const G = какГруппа(X);
      return обёртка(фактор(G, коммутант(G)).группа);
    }
    case 'aut':
      return обёртка(группаАвтоморфизмов(какГруппа(X)));
    case 'inn': {
      const G = какГруппа(X);
      const A = группаАвтоморфизмов(G);
      const все = автоморфизмыКакОтображения(G);
      const внутренние = new Set();
      for (let g = 0; g < G.n; g++) {
        const σ = Array.from({ length: G.n }, (_, x) => умножить(G, умножить(G, g, x), G.inv[g]));
        const i = все.findIndex((φ) => φ.every((v, k) => v === σ[k]));
        if (i >= 0) внутренние.add(i);
      }
      // Номера автоморфизмов в A совпадают с порядком их построения только
      // для тривиальной группы автоморфизмов; иначе ищем по действию.
      if (A.n !== все.length) return null;
      return конечноеПодзначение(A, порождённая(A, [...внутренние]));
    }
    case 'prod': {
      const A = какГруппа(X);
      const B = какГруппа(роль.get('Y'));
      // Проверять порядок ДО построения: таблица умножения на 3600 элементов
      // строится тринадцатью миллионами записей, и выбрасывать её потом поздно.
      if (A.n * B.n > предельныйПорядок) return НЕ_СЧИТАЕМ;
      return обёртка(прямоеПроизведение(A, B));
    }
    // --- семейства ---------------------------------------------------------
    //
    // Семейство в модели — список значений. Бесконечных семейств модель не
    // строит: они объявляются, как и бесконечные группы (см. named.js).
    // У ПОСТОЯННОЙ системы оба предела равны самому объекту: и прямой, и
    // обратный предел постоянной диаграммы — это она сама.
    case 'colim': case 'lim': {
      const D = роль.get('D');
      if (D?.вид === 'система') return D.член;
      return null;
    }
    case 'union': {
      const a = какМножество(роль.get('A'));
      const b = какМножество(роль.get('B'));
      if (!a || !b || a.G !== b.G) return НЕ_СЧИТАЕМ;
      return множество(a.G, [...a.S, ...b.S]);
    }
    case 'torsion-set': {
      const G = какГруппа(роль.get('X'));
      if (!G) return НЕ_СЧИТАЕМ;
      // В КОНЕЧНОЙ группе порядок конечен у всякого элемента, поэтому это
      // всё множество. Смысл конструкции проявляется на бесконечных.
      return множество(G, [...Array(G.n).keys()]);
    }
    case 'ord': {
      const G = какГруппа(роль.get('X'));
      return { вид: 'число', n: G ? G.n : null };
    }
    case 'index': {
      const G = какГруппа(роль.get('X'));
      const N_ = роль.get('N');
      if (!G || N_?.вид !== 'подгруппа') return НЕ_СЧИТАЕМ;
      return { вид: 'число', n: G.n / N_.H.length };
    }
    case 'eltord': {
      const x = роль.get('x');
      if (x?.вид !== 'элемент' || x.объемлющая === null) return НЕ_СЧИТАЕМ;
      return { вид: 'число', n: порядокЭлемента(x.объемлющая, x.x) };
    }
    case 'as-elt': {
      const N_ = роль.get('N');
      const x = роль.get('x');
      if (N_?.вид !== 'подгруппа' || x?.вид !== 'элемент' || x.объемлющая === null) return НЕ_СЧИТАЕМ;
      // Номер элемента в подгруппе-как-группе переводится обратно в номер
      // в объемлющей — тем же `наружу`, что и у подгрупп.
      return { вид: 'элемент', объемлющая: N_.объемлющая, x: наружу(N_, [x.x])[0] };
    }
    case 'gen': {
      const x = роль.get('x');
      if (x?.вид !== 'элемент' || x.объемлющая === null) return НЕ_СЧИТАЕМ;
      return конечноеПодзначение(x.объемлющая, порождённая(x.объемлющая, [x.x]));
    }
    case 'centralizer-elt': {
      const x = роль.get('x');
      if (x?.вид !== 'элемент' || x.объемлющая === null) return НЕ_СЧИТАЕМ;
      const G = x.объемлющая;
      const C = [];
      for (let g = 0; g < G.n; g++) {
        if (умножить(G, g, x.x) === умножить(G, x.x, g)) C.push(g);
      }
      return конечноеПодзначение(G, C);
    }
    case 'apply-mor': {
      const F = роль.get('F');
      const x = роль.get('x');
      if (F?.вид !== 'морфизм' || x?.вид !== 'элемент' || x.объемлющая === null) return НЕ_СЧИТАЕМ;
      return { вид: 'элемент', объемлющая: F.код, x: F.φ[x.x] };
    }
    case 'prod-fam': {
      const F = роль.get('F');
      if (F?.вид !== 'семья') return null;
      // У ОДНОЧЛЕННОГО семейства произведение равно самому члену — считать
      // нечего, и объявленный член тут ничему не мешает. Пока этого не было,
      // семейство {ℤ²} роняло всю строку, и вопросы про несчётные и
      // нециклические члены оставались без единого примера.
      if (F.члены.length === 1) return F.члены[0];
      let P = null;
      for (const ч of F.члены) {
        const G = какГруппа(ч);
        // Член, которого модель не считает, делает невычислимым произведение,
        // но само произведение существует: это незнание, а не отсутствие.
        if (!G) return НЕ_СЧИТАЕМ;
        if (!P) P = G;
        else {
          if (P.n * G.n > предельныйПорядок) return НЕ_СЧИТАЕМ;
          P = прямоеПроизведение(P, G);
        }
      }
      return P ? обёртка(P) : null;
    }
    case 'sum-fam': {
      const F = роль.get('F');
      if (F?.вид !== 'семья') return null;
      // У конечного семейства прямая сумма — это всё произведение. Бесконечных
      // семейств в вычислимой части модели нет, поэтому иначе и не бывает.
      const идП = graph.rel(n.id, 'ambient');
      let P = значения.get(идП);
      if (!P) {
        P = вычислитьУзел(graph, идП, значения, предельныйПорядок);
        if (P) значения.set(идП, P);
      }
      if (P === НЕ_СЧИТАЕМ) return НЕ_СЧИТАЕМ;
      // Одночленное семейство: сумма тоже равна члену, и «⊕ совпадает с ∏»
      // у неё верно — это и есть вырожденный, но законный случай.
      if (F.члены.length === 1) return всяПодгруппа(P);
      const G = какГруппа(P);
      if (!G) return НЕ_СЧИТАЕМ;
      return конечноеПодзначение(G, Array.from({ length: G.n }, (_, i) => i));
    }
    case 'meet-fam': case 'join-fam': {
      const Ф = роль.get('Ф');
      const G = какГруппа(X);
      if (Ф?.вид !== 'подсемья' || !G || Ф.объемлющая !== G) return null;
      if (!Ф.члены.length) return null;
      if (n.op === 'meet-fam') {
        let H = Ф.члены[0];
        for (const M2 of Ф.члены.slice(1)) H = пересечение(H, M2);
        return конечноеПодзначение(G, H);
      }
      return конечноеПодзначение(G, порождённая(G, Ф.члены.flat()));
    }

    case 'prod-sub': {
      const A = какГруппа(X);
      const B = какГруппа(роль.get('Y'));
      if (!A || !B || N?.объемлющая !== A || M?.объемлющая !== B) return null;
      // Объемлющая группа — тот САМЫЙ терм A × B, что стоит в графе: сравнение
      // подгрупп идёт по тождеству объекта, а не по строению.
      const идП = graph.rel(n.id, 'ambient');
      let P = значения.get(идП);
      if (!P) {
        P = вычислитьУзел(graph, идП, значения, предельныйПорядок);
        if (P) значения.set(идП, P);
      }
      const G = какГруппа(P);
      if (!G || G.n !== A.n * B.n) return null;
      const H = [];
      for (const a of N.H) for (const b of M.H) H.push(a * B.n + b);
      return конечноеПодзначение(G, H);
    }
    case 'ker':
      return конечноеПодзначение(F.дом, ядро(F.дом, F.φ));
    case 'im':
      return конечноеПодзначение(F.код, образ(F.дом, F.φ));
    case 'image-of':
      return конечноеПодзначение(F.код, порождённая(F.код, N.H.map((x) => F.φ[x])));
    case 'preimage': {
      const вN = new Set(N.H);
      const out = [];
      for (let g = 0; g < F.дом.n; g++) if (вN.has(F.φ[g])) out.push(g);
      return конечноеПодзначение(F.дом, out);
    }
    case 'compose': {
      const G2 = роль.get('G');
      if (F.код !== G2.дом) return null;
      return { вид: 'морфизм', дом: F.дом, код: G2.код, φ: F.φ.map((x) => G2.φ[x]) };
    }
    case 'proj': {
      const G = какГруппа(X);
      if (!нормальна(G, N.H)) return null;
      const ф = фактор(G, N.H);
      // Кодомен проекции — ТОТ САМЫЙ терм G/N, что стоит в графе, а не свежая
      // копия: подгруппы сравниваются по тождеству объемлющего объекта, и с
      // копией «образ M при π» переставал быть подгруппой вершины G/N.
      const идК = graph.rel(n.id, 'cod');
      let K = значения.get(идК);
      if (!K) {
        K = вычислитьУзел(graph, идК, значения, предельныйПорядок);
        if (K) значения.set(идК, K);
      }
      const код = какГруппа(K) ?? ф.группа;
      if (код.n !== ф.группа.n) return null;
      return { вид: 'морфизм', дом: G, код, φ: ф.слой };
    }
    case 'incl': {
      const G = какГруппа(X);
      какГруппа(N);
      return { вид: 'морфизм', дом: N._как.группа, код: G, φ: N._как.назад };
    }
    case 'equalizer': {
      const G2 = роль.get('G');
      const out = [];
      for (let g = 0; g < F.дом.n; g++) if (F.φ[g] === G2.φ[g]) out.push(g);
      return конечноеПодзначение(F.дом, out);
    }
    case 'coequalizer': {
      const G2 = роль.get('G');
      const H = F.код;
      const слова = [];
      for (let g = 0; g < F.дом.n; g++) слова.push(умножить(H, F.φ[g], H.inv[G2.φ[g]]));
      const все = [];
      for (let h = 0; h < H.n; h++) {
        for (const w of слова) все.push(умножить(H, умножить(H, h, w), H.inv[h]));
      }
      const R = порождённая(H, все);
      return обёртка(фактор(H, R).группа);
    }
    case 'pullback': {
      const G2 = роль.get('G');
      const A = F.дом;
      const B = G2.дом;
      const P = прямоеПроизведение(A, B);
      const пары = [];
      for (let a = 0; a < A.n; a++) {
        for (let b = 0; b < B.n; b++) if (F.φ[a] === G2.φ[b]) пары.push(a * B.n + b);
      }
      return конечноеПодзначение(P, пары);
    }
    default:
      return null;
  }
}

// --- свойства значения --------------------------------------------------------------

export function свойства(v) {
  if (!v) return {};
  if (v._props) return v._props;
  if (МОДУЛЬНОЕ.has(v.вид)) {
    v._props = свойстваЗначенияМод(v);
    return v._props;
  }
  if (ТОПОЛОГИЧЕСКОЕ.has(v.вид)) {
    v._props = свойстваЗначенияТоп(v);
    return v._props;
  }
  if (КОЛЬЦЕВОЕ.has(v.вид)) {
    v._props = свойстваЗначенияКольц(v);
    return v._props;
  }
  if (ПОЛЕВОЕ.has(v.вид)) {
    v._props = свойстваЗначенияПоля(v);
    return v._props;
  }
  let out = {};
  if (v.вид === 'имя' || v.вид === 'именПод' || v.вид === 'именМорфизм') {
    out = свойстваИменованного(v, свойства);
    v._props = out;
    return out;
  }
  if (v.вид === 'группа') out = свойстваГруппы(v.G);
  else if (v.вид === 'подгруппа') {
    // Подгруппа — ЭТО подмножество (Grp.sub ≤ Grp.subset), и свойства
    // подмножества у неё обязаны считаться тоже. Без этих двух строк
    // `set-whole` у подгруппы не вычислялся НИКОГДА: на схеме «подгруппа» это
    // было 195 немых пробелов из 534 — больше трети всей её бедности. Для
    // подгруппы оба свойства тривиальны: подгруппой она является по сорту, а
    // «совпадает со всем» — это её же `whole`.
    const под = свойстваПодгруппы(v.объемлющая, v.H);
    out = {
      ...свойстваГруппы(какГруппа(v)),
      ...под,
      subgroup: true,
      'set-whole': под.whole,
    };
  } else if (v.вид === 'морфизм') out = свойстваМорфизма(v.дом, v.код, v.φ);
  else if (v.вид === 'подмножество') out = свойстваМножества(v);
  else if (v.вид === 'имямножество') out = { ...v.props };
  else if (v.вид === 'число') out = свойстваЧисла(v);
  else if (v.вид === 'элемент') out = свойстваЭлемента(v);
  else if (v.вид === 'семья' || v.вид === 'подсемья') out = свойстваСемьи(v);
  else if (v.вид === 'имясемья') out = v.зап.props ?? {};
  else if (v.вид === 'имясистема') out = v.зап.props ?? {};
  else if (v.вид === 'система') out = свойстваСистемы(v);
  v._props = out;
  return out;
}

// Подмножество: подгруппа ли оно и совпадает ли со всей группой. Больше про
// произвольное подмножество сказать нечего — свойства групп к нему не
// применимы, и сорт заведён ровно затем, чтобы их и не спрашивали.
function свойстваМножества(v) {
  const G = v.объемлющая;
  const в = new Uint8Array(G.n);
  for (const x of v.S) в[x] = 1;
  let подгруппа = в[0] === 1;
  if (подгруппа) {
    for (const a of v.S) {
      if (!в[G.inv[a]]) { подгруппа = false; break; }
      for (const b of v.S) {
        if (!в[умножить(G, a, b)]) { подгруппа = false; break; }
      }
      if (!подгруппа) break;
    }
  }
  return { subgroup: подгруппа, 'set-whole': v.S.length === G.n };
}

// Число: натуральное или БЕСКОНЕЧНОСТЬ. Бесконечность — не отсутствие
// значения, а значение: |ℤ| бесконечен, и это надо уметь сказать. Неизвестное
// же значение (n === null) даёт «не знаю» по всем свойствам сразу.
function свойстваЧисла(v) {
  if (v.n === null || v.n === undefined) return {};
  if (!Number.isFinite(v.n)) {
    return { 'num-finite': false, 'num-one': false, 'num-two': false, 'num-prime': false };
  }
  return {
    'num-finite': true,
    'num-one': v.n === 1,
    'num-two': v.n === 2,
    'num-prime': простое(v.n),
    'num-even': v.n % 2 === 0,
  };
}

function простое(n) {
  if (n < 2) return false;
  for (let d = 2; d * d <= n; d++) if (n % d === 0) return false;
  return true;
}

const НОД = (a, b) => (b === 0 ? a : НОД(b, a % b));

// Элемент конечной группы — просто номер. Всё о нём считается точно: порядок,
// централизатор, порождённая подгруппа. У ОБЪЯВЛЕННОЙ группы вычислять нечего,
// но единица есть всегда, и она даёт строки там, где иначе их не было бы вовсе.
function свойстваЭлемента(v) {
  if (v.объемлющая === null) {
    if (v.зап) return { ...v.зап.props };
    // Единица объявленной группы: централена и периодична по определению,
    // порождает только тривиальную подгруппу.
    return {
      'identity-elt': true, 'central-elt': true, 'torsion-elt': true,
      involution: false, generator: свойства(v.имен)?.trivial === true,
    };
  }
  const G = v.объемлющая;
  const порядок = порядокЭлемента(G, v.x);
  const центр = new Set(центр_(G));
  return {
    'identity-elt': v.x === 0,
    'central-elt': центр.has(v.x),
    'torsion-elt': true,
    involution: порядок === 2,
    generator: порядок === G.n,
  };
}

// Постоянная система: все члены — одна и та же группа, все отображения
// тождественны. Свойства членов — её свойства; отображения инъективны и
// сюръективны разом, потому что тождественны.
function свойстваСистемы(v) {
  return {
    ...свойства(v.член),
    'constant-sys': true,
    'injective-sys': true,
    'surjective-sys': true,
  };
}

// Свойство семейства — это «у КАЖДОГО члена». Неизвестное хотя бы у одного
// делает неизвестным и у семейства: «не знаем» не складывается в «да».
function свойстваСемьи(v) {
  const части = v.вид === 'подсемья'
    ? v.члены.map((H) => свойства({ вид: 'подгруппа', объемлющая: v.объемлющая, H }))
    : v.члены.map((x) => свойства(x));
  const out = { 'finite-fam': true };
  if (!части.length) return out;
  for (const p of Object.keys(части[0])) {
    let все = true;
    let неизвестно = false;
    for (const c of части) {
      if (c[p] === undefined) неизвестно = true;
      else if (c[p] !== true) все = false;
    }
    if (!неизвестно) out[p] = все;
    else if (!все) out[p] = false;
  }
  return out;
}

export function отношение(rel, a, b) {
  if (!a || !b) return undefined;
  if (МОДУЛЬНОЕ.has(a.вид) || МОДУЛЬНОЕ.has(b.вид)) return отношениеМод(rel, a, b);
  if (ТОПОЛОГИЧЕСКОЕ.has(a.вид) || ТОПОЛОГИЧЕСКОЕ.has(b.вид)) return отношениеТоп(rel, a, b);
  if (КОЛЬЦЕВОЕ.has(a.вид) || КОЛЬЦЕВОЕ.has(b.вид)) return отношениеКольц(rel, a, b);
  if (ПОЛЕВОЕ.has(a.вид) || ПОЛЕВОЕ.has(b.вид)) return отношениеПоля(rel, a, b);
  if (rel === 'num-eq' || rel === 'num-divides' || rel === 'num-coprime') {
    if (a.вид !== 'число' || b.вид !== 'число') return undefined;
    const p = a.n;
    const q = b.n;
    if (p === null || q === null) return undefined;
    // Две бесконечности не обязаны быть одной мощностью, делимость для них
    // не определена вовсе — честный ответ «не знаю», а не «да».
    if (!Number.isFinite(p) || !Number.isFinite(q)) return undefined;
    if (rel === 'num-eq') return p === q;
    if (rel === 'num-divides') return p !== 0 && q % p === 0;
    return НОД(p, q) === 1;
  }
  if (rel === 'commute' || rel === 'conjugate') {
    if (a.вид !== 'элемент' || b.вид !== 'элемент') return undefined;
    if (a.объемлющая === null || b.объемлющая === null || a.объемлющая !== b.объемлющая) {
      // Две единицы одной объявленной группы — это один элемент.
      return a.объемлющая === null && b.объемлющая === null && a.имен === b.имен
        ? true : undefined;
    }
    const G = a.объемлющая;
    if (rel === 'commute') return умножить(G, a.x, b.x) === умножить(G, b.x, a.x);
    for (let g = 0; g < G.n; g++) {
      if (умножить(G, умножить(G, g, a.x), G.inv[g]) === b.x) return true;
    }
    return false;
  }
  if (rel === 'iso') {
    const A = какОбъект(a);
    const B = какОбъект(b);
    // Две объявленные бесконечные группы: одна и та же запись — изоморфны;
    // разные — «нет» лишь тогда, когда расходится хоть одно записанное
    // свойство. Иначе НЕ ЗНАЕМ, и врать тут нельзя.
    const именA = A?.вид === 'имя';
    const именB = B?.вид === 'имя';
    if (именA && именB) {
      if (A.зап === B.зап) return true;
      const pa = свойства(A);
      const pb = свойства(B);
      for (const k of Object.keys(pa)) {
        if (pb[k] !== undefined && pa[k] !== pb[k]) return false;
      }
      return undefined;
    }
    if (именA !== именB) {
      // Конечная и бесконечная изоморфны быть не могут — если так записано.
      const p = свойства(именA ? A : B).finite;
      return p === false ? false : undefined;
    }
    const G1 = какГруппа(A);
    const G2 = какГруппа(B);
    return G1 && G2 ? изоморфны(G1, G2) : undefined;
  }
  if (rel === 'le' || rel === 'eq-sub') {
    // Две ОБЪЯВЛЕННЫЕ подгруппы одной группы: полного решётчатого описания у
    // нас нет, но три случая известны всегда и стоят дёшево — та же самая
    // подгруппа, тривиальная внутри любой, любая внутри всей. Без них вопрос
    // «C(x) ⩽ ⟨x⟩» на бесконечных группах не получал ни одного примера.
    if (a.вид === 'именПод' && b.вид === 'именПод' && a.влад === b.влад) {
      if (a.зап === b.зап) return true;
      const pa = свойства(a);
      const pb = свойства(b);
      if (rel === 'eq-sub') {
        if (pa.whole === true && pb.whole === true) return true;
        if (pa.trivial === true && pb.trivial === true) return true;
        if (pa.whole === true && pb.whole === false) return false;
        if (pa.trivial === true && pb.trivial === false) return false;
        return undefined;
      }
      if (pb.whole === true) return true;
      if (pa.trivial === true) return true;
      if (pa.whole === true && pb.whole === false) return false;
      if (pb.trivial === true && pa.trivial === false) return false;
      return undefined;
    }
    if (a.вид !== 'подгруппа' || b.вид !== 'подгруппа') return undefined;
    if (a.объемлющая !== b.объемлющая) return undefined;
    if (rel === 'le') return содержит(b.H, a.H);
    return a.H.length === b.H.length && содержит(b.H, a.H);
  }
  return undefined;
}

// --- перечисление привязок -------------------------------------------------------

// Свободные узлы получают значения по порядку: сначала объекты из библиотеки
// (мелкие вперёд — контрпример чаще мелкий), потом подгруппы и морфизмы, уже
// зависящие от выбранного.
// Привязки идут КУБАМИ, а не вложенными циклами, и это не ускорение, а
// исправление выборки. Вложенные циклы при урезанном бюджете двигают только
// ПОСЛЕДНЮЮ вершину: на схеме произведения при бюджете 1500 и каталоге из 125
// объектов первая вершина успевала пройти двенадцать значений, вторая — все
// сто двадцать пять. Выборка выходила перекошенной до бессмыслицы — задача «A
// совершенна, B нетривиальна ⇒ B ≅ A × B» получила 114 подтверждений, и во
// всех 114 A была одна и та же тривиальная группа просто потому, что до
// других совершенных групп перебор не доходил.
//
// Поэтому перебор идёт по УРОВНЯМ: уровень L — это все наборы, где каждый
// индекс не больше L, а хотя бы один равен L. Оборванный на любом месте
// перебор даёт тогда ПОЛНЫЙ куб из L первых объектов по каждой вершине —
// выборка сбалансирована по построению, а не по удаче. Порядок «мелкие
// вперёд» при этом сохраняется: внутри уровня индексы растут, а список
// кандидатов по-прежнему начинается с мелких.
//
// Цена названа: уровень L заново проходит ПРЕФИКСЫ наборов. Чтобы это не
// превратилось в L³ вычислений модели, поддерево, которое уже не может
// дотянуться до L, отсекается на последней вершине — и общая работа остаётся
// порядка размера самого пространства наборов.
export function* привязки(graph, свободные, каталог, предел = Infinity, предельныйПорядок = Infinity) {
  let выдано = 0;
  let максСписка = 0;

  function* шаг(i, значения, L, достигнуто) {
    if (выдано >= предел) return;
    if (i === свободные.length) {
      // Набор уровня L обязан содержать индекс L: иначе он уже выдан раньше.
      if (!достигнуто) return;
      выдано++;
      yield значения;
      return;
    }
    const id = свободные[i];
    const список = кандидатыДляУзла(graph, graph.get(id), значения, каталог, предельныйПорядок);
    if (список.length > максСписка) максСписка = список.length;
    const последняя = i === свободные.length - 1;
    const до = Math.min(L, список.length - 1);
    for (let j = 0; j <= до; j++) {
      if (выдано >= предел) return;
      const станет = достигнуто || j === L;
      // На последней вершине набор без индекса L выдан на прошлых уровнях.
      if (!станет && последняя) continue;
      const след = new Map(значения);
      след.set(id, список[j]);
      // Достроить всё, что стало вычислимым. Если какая-то конструкция на этой
      // привязке не определена (фактор по ненормальной), привязка отпадает.
      if (!достроить(graph, след, свободные.slice(i + 1), предельныйПорядок)) continue;
      yield* шаг(i + 1, след, L, станет);
    }
  }

  for (let L = 0; выдано < предел; L++) {
    const было = выдано;
    yield* шаг(0, new Map(), L, false);
    // Уровень не дал ничего и все списки короче его — перебор исчерпан.
    if (выдано === было && L >= максСписка - 1) break;
  }
}

function достроить(graph, значения, ещёСвободные, предельныйПорядок = Infinity) {
  const надо = new Set(ещёСвободные);
  for (const n of graph.nodes) {
    if (значения.has(n.id) || надо.has(n.id)) continue;
    if (n.op === 'given' || n.op === 'named') continue;
    if (!n.args.every((a) => значения.has(a) || надо.has(a))) continue;
    if (n.args.some((a) => надо.has(a))) continue;
    const v = вычислитьУзел(graph, n.id, значения, предельныйПорядок);
    // Не определено — привязка не годится (фактор по ненормальной не терм).
    // Не посчитано — узел просто остаётся без значения: про него ответят
    // «не знаю», а про остальные вершины схемы ответят как обычно.
    if (v === null) return false;
    if (v === НЕ_СЧИТАЕМ) continue;
    значения.set(n.id, v);
  }
  return true;
}

function кандидатыДляУзла(graph, n, значения, каталог, предельныйПорядок = Infinity) {
  if (graph.cat.id === 'mod') return кандидатыМод(graph, n, значения, каталог, предельныйПорядок);
  if (graph.cat.id === 'top') return кандидатыТоп(graph, n, значения, каталог, предельныйПорядок);
  if (graph.cat.id === 'ring') return кандидатыКольц(graph, n, значения, каталог);
  if (graph.cat.id === 'fld') return кандидатыПоля(graph, n, значения, каталог);
  const c = graph.cat.cons.get(n.op);
  if (n.op === 'choose-diag') {
    // Объявленные системы вперёд: постоянных много и все они вырождены,
    // а интересны как раз объявленные — на них пределы и расходятся.
    const объявленные = каталог.filter((x) => x.система)
      .map((x) => ({ вид: 'имясистема', зап: x }));
    const постоянные = каталог
      .filter((x) => !x.семейство && !x.система && (x.бесконечная || x.n <= предельныйПорядок))
      .map((x) => ({ вид: 'система', член: x.бесконечная ? { вид: 'имя', зап: x } : обёртка(x) }));
    return [...объявленные, ...постоянные];
  }
  if (n.op === 'named') {
    // Именованный объект привязывается к СЕБЕ, а не к чему попало из каталога.
    const кто = каталог.find((x) => x.id === (n.объект ?? n.имя) || x.имя === n.имя);
    if (!кто) return [];
    return [кто.бесконечная ? { вид: 'имя', зап: кто } : обёртка(кто)];
  }
  if (n.op === 'given') {
    if (n.sort !== 'Grp.obj') return [];
    const годные = каталог.filter((x) => x.бесконечная || x.n <= предельныйПорядок);
    // Конечные и бесконечные ЧЕРЕДУЮТСЯ. Если просто дописать бесконечные в
    // конец, предел на число примеров обрежет перебор раньше, чем до них
    // дойдёт очередь, — на схеме с морфизмом так и вышло: из полутора тысяч
    // строк бесконечных было сто.
    const конечные = годные.filter((x) => !x.бесконечная);
    const беск = годные.filter((x) => x.бесконечная);
    const вперемешку = [];
    for (let k = 0; k < Math.max(конечные.length, беск.length); k++) {
      if (k < конечные.length) вперемешку.push(конечные[k]);
      if (k < беск.length) вперемешку.push(беск[k]);
    }
    return вперемешку.map((x) => (x.бесконечная ? { вид: 'имя', зап: x } : обёртка(x)));
    return [];
  }
  if (n.op === 'choose-sub') {
    const X = какОбъект(значения.get(n.args[0]));
    if (X?.вид === 'имя') return подгруппыИменованной(X.зап);
    const G = какГруппа(X);
    if (!G) return [];
    return подгруппы(G).map((H) => конечноеПодзначение(G, H));
  }
  if (n.op === 'choose-mor') {
    const ОБ = какОбъект(значения.get(n.args[0]));
    const ОК = какОбъект(значения.get(n.args[1]));
    // У бесконечных групп все гомоморфизмы не перечислить, поэтому берутся
    // ПРЕДСТАВИТЕЛИ: нулевой, тождественный и объявленные. Для опровержения
    // этого достаточно — контрпример остаётся контрпримером.
    if (ОБ?.вид === 'имя' || ОК?.вид === 'имя') {
      return [
        ...встроенныеМорфизмы(ОБ, ОК, всяПодгруппа, тривиальнаяПодгруппа),
        ...вложенияПодгрупп(ОБ, ОК, тривиальнаяПодгруппа),
        ...объявленныеМорфизмы(ОБ, ОК),
      ];
    }
    const X = какГруппа(ОБ);
    const Y = какГруппа(ОК);
    if (!X || !Y) return [];
    return гомоморфизмы(X, Y).map((φ) => ({ вид: 'морфизм', дом: X, код: Y, φ }));
  }
  if (n.op === 'choose-elt') {
    const X = значения.get(n.args[0]);
    const G = какГруппа(какОбъект(X));
    // У объявленной группы вычислимых элементов нет. Единица есть всегда, а
    // остальные объявляются представителями — без них схема с элементом не
    // видела бы ни одной бесконечной группы, и «x конечного порядка»
    // подтверждалось бы на одних конечных.
    if (!G) {
      const зап = какОбъект(X)?.вид === 'имя' ? какОбъект(X).зап : null;
      if (!зап) return X ? [{ вид: 'элемент', объемлющая: null, имен: X }] : [];
      const out = [{ вид: 'элемент', объемлющая: null, имен: X, единица: true }];
      for (const э of зап._элементы ?? []) {
        out.push({ вид: 'элемент', объемлющая: null, имен: X, зап: э });
      }
      return out;
    }
    return Array.from({ length: G.n }, (_, i) => ({ вид: 'элемент', объемлющая: G, x: i }));
  }
  if (n.op === 'choose-fam') {
    // Одночленные семейства и пары мелких групп. БЕСКОНЕЧНЫЕ семейства (с
    // бесконечным числом членов) объявляются отдельно — вычислить их нельзя.
    //
    // Одночленные строятся и из ОБЪЯВЛЕННЫХ групп тоже. Пока их не было,
    // семейство {ℤ²} не существовало, и вопрос «каждая группа семейства не
    // циклична: верно ли, что конечна» оставался пробелом, хотя опровергается
    // однчленным семейством из ℤ². Одночленное семейство — законная
    // направленность: у него ∏ = ⊕ = сам член.
    const конечные = каталог.filter((x) => !x.бесконечная && !x.семейство && !x.система
      && x.n <= предельныйПорядок);
    // Прежде здесь стояло `конечные.slice(0, 8)` — скрытый потолок, не названный
    // ни настройкой, ни замером: пары строились лишь из восьми МЕЛЬЧАЙШИХ
    // групп каталога (он отсортирован по возрастанию), и семейство {C₉, C₉} не
    // существовало вовсе. Потолок лишний: ограничение и так есть, и оно
    // осмысленное — произведение порядков не больше предела, проверка стоит
    // ниже. Пар при 44 конечных группах 1936, и каждая отсекается этим
    // условием до всякой работы.
    const мелкие = конечные;
    const out = каталог
      .filter((x) => x.семейство)
      .map((зап) => ({ вид: 'имясемья', зап }));
    out.push(...каталог.filter((x) => x.бесконечная)
      .map((зап) => ({ вид: 'семья', члены: [{ вид: 'имя', зап }] })));
    out.push(...конечные.map((G) => ({ вид: 'семья', члены: [обёртка(G)] })));
    for (const A of мелкие) {
      for (const B of мелкие) {
        if (A.n * B.n <= предельныйПорядок) {
          out.push({ вид: 'семья', члены: [обёртка(A), обёртка(B)] });
        }
      }
    }
    return out;
  }
  if (n.op === 'choose-subfam') {
    const G = какГруппа(какОбъект(значения.get(n.args[0])));
    if (!G) return [];
    const все = подгруппы(G);
    const out = все.map((H) => ({ вид: 'подсемья', объемлющая: G, члены: [H] }));
    for (let a = 0; a < все.length; a++) {
      for (let b = a + 1; b < все.length; b++) {
        out.push({ вид: 'подсемья', объемлющая: G, члены: [все[a], все[b]] });
      }
    }
    return out;
  }
  if (n.op === 'choose-elt') return []; // элементный слой ещё не сделан
  if (c?.choice) return [];
  return [];
}

// Опознание построенной группы по каталогу. Сначала отбор по инварианту
// (порядок, набор порядков элементов, абелевость), потом НАСТОЯЩАЯ проверка
// изоморфизма: инвариант совпадает и у неизоморфных групп, а писать в
// контрпримере неверное имя — хуже, чем не писать никакого.
let указательКаталога = null;

const инвариант = (G) => `${G.n}|${[...порядкиГруппы(G)].sort((a, b) => a - b).join(',')}`;

function порядкиГруппы(G) {
  const out = [];
  for (let a = 0; a < G.n; a++) {
    let x = a;
    let k = 1;
    while (x !== 0) {
      x = умножить(G, x, a);
      k++;
    }
    out.push(k);
  }
  return out;
}

export function опознать(G, каталог) {
  // Имя у записи спрашивается ПЕРВЫМ, до всякого каталога: группа, пришедшая
  // из кросс-категорной конструкции (Gal(L/K), R^×), уже названа, а каталог
  // раздела в этот момент не групповой — он полевой или кольцевой, и искать в
  // нём бесполезно. Без этого контрпример читался как «G — порядка 2» вместо
  // «G = C₂».
  if (G.имя) return G.имя;
  if (!каталог || !каталог.length) return null;
  if (!указательКаталога || указательКаталога.каталог !== каталог) {
    const карта = new Map();
    for (const K of каталог.filter((x) => x.mul)) {
      const k = инвариант(K);
      if (!карта.has(k)) карта.set(k, []);
      карта.get(k).push(K);
    }
    указательКаталога = { каталог, карта };
  }
  for (const K of указательКаталога.карта.get(инвариант(G)) ?? []) {
    if (изоморфны(G, K)) return K.имя;
  }
  return null;
}

const описаниеЧлена = (v, каталог) => (v.вид === 'имя'
  ? v.зап.имя
  : опознать(v.G, каталог) ?? `группы порядка ${v.G.n}`);

export function описаниеПривязки(graph, значения, имена, каталог = null) {
  const куски = [];
  for (const [имя, id] of имена) {
    const v = значения.get(id);
    if (!v) continue;
    if (ТОПОЛОГИЧЕСКОЕ.has(v.вид)) {
      куски.push(описаниеТоп(v, имя));
    } else if (МОДУЛЬНОЕ.has(v.вид)) {
      куски.push(описаниеМод(v, имя));
    } else if (КОЛЬЦЕВОЕ.has(v.вид)) {
      куски.push(описаниеКольц(v, имя));
    } else if (ПОЛЕВОЕ.has(v.вид)) {
      куски.push(описаниеПоля(v, имя));
    } else if (v.вид === 'имя') {
      куски.push(`${имя} = ${v.зап.имя}`);
    } else if (v.вид === 'именПод') {
      куски.push(`${имя} = ${v.зап.имя}${v.зап._объект ? '' : ''}`);
    } else if (v.вид === 'группа') {
      const опознано = опознать(v.G, каталог);
      куски.push(`${имя} ${опознано ? `= ${опознано}` : `— порядка ${v.G.n}`}`);
    } else if (v.вид === 'подгруппа') {
      const опознано = опознать(какГруппа(v), каталог);
      куски.push(`${имя} — подгруппа порядка ${v.H.length}${опознано ? ` (${опознано})` : ''}`);
    } else if (v.вид === 'имясистема') {
      куски.push(`${имя} = ${v.зап.имя}`);
    } else if (v.вид === 'система') {
      куски.push(`${имя} — постоянная система из ${описаниеЧлена(v.член, каталог)}`);
    } else if (v.вид === 'имямножество') {
      куски.push(`${имя} — множество кручения ${v.влад.имя}`);
    } else if (v.вид === 'число') {
      куски.push(`${имя} = ${v.n === null ? '?' : (Number.isFinite(v.n) ? v.n : '∞')}`);
    } else if (v.вид === 'элемент') {
      куски.push(v.объемлющая === null
        ? `${имя} — ${v.зап ? v.зап.имя : 'единица'}`
        : `${имя} — элемент порядка ${порядокЭлемента(v.объемлющая, v.x)}`);
    } else if (v.вид === 'имясемья') {
      куски.push(`${имя} = ${v.зап.имя}`);
    } else if (v.вид === 'семья') {
      // Член бывает и ОБЪЯВЛЕННЫМ — у него нет таблицы умножения, зато есть имя.
      куски.push(`${имя} = (${v.члены.map((x) => (x.вид === 'имя'
        ? x.зап.имя
        : опознать(какГруппа(x), каталог) ?? `порядка ${какГруппа(x)?.n}`)).join(', ')})`);
    } else if (v.вид === 'подсемья') {
      куски.push(`${имя} — ${v.члены.length} подгрупп(ы) порядков ${v.члены.map((H) => H.length).join(', ')}`);
    } else if (v.вид === 'именМорфизм') {
      куски.push(`${имя} — ${v.имя || 'гомоморфизм'}`);
    } else if (v.вид === 'морфизм') {
      const образов = new Set(v.φ).size;
      const вид = образов === 1 ? 'тривиальный'
        : образов === v.дом.n ? 'вложение' : `с образом порядка ${образов}`;
      куски.push(`${имя} — ${вид}`);
    }
  }
  return куски.join(', ');
}
