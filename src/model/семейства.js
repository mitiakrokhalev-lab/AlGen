// Параметризованные семейства групп: Cₙ, Dₙ, Sₙ, Aₙ, (ℤ/p)ᵏ.
//
// Зачем это отдельно от каталога. В библиотеке 34 конечные группы поимённо, и
// добавить к ним сотню членов семейств нельзя: таблица примеров каждого раздела
// вырастет вчетверо, а новых НАБОРОВ СВОЙСТВ почти не появится — C₁₇ и C₁₉
// неразличимы ни одним нашим свойством. Семейство ценно другим: по нему
// задаётся вопрос, которого в языке свойств нет вовсе, —
//
//     ПРИ КАКИХ n верно, что Aut(Cₙ) циклична?
//
// Ответ здесь не «да/нет», а МНОЖЕСТВО ЗНАЧЕНИЙ ПАРАМЕТРА, и считается он
// честно: модель строит Cₙ для каждого n и смотрит. Поэтому семейства живут
// своим каталогом и своим инструментом (tools/семейства.mjs), а разделы
// работают на прежней библиотеке.
//
// Рецепты строятся программно: диэдральная и симметрическая группы задаются
// перестановками, и выписывать их рукой для каждого n бессмысленно.

import { поРецепту } from './catalogue.js';

const цикл = (n) => {
  // Перестановка-цикл (0 1 … n−1) как массив образов.
  const p = [];
  for (let i = 0; i < n; i++) p.push((i + 1) % n);
  return p;
};

const отражение = (n) => {
  // i ↦ (n − i) mod n: отражение правильного n-угольника.
  const p = [];
  for (let i = 0; i < n; i++) p.push((n - i) % n);
  return p;
};

const транспозиция = (n, a, b) => {
  const p = [];
  for (let i = 0; i < n; i++) p.push(i === a ? b : (i === b ? a : i));
  return p;
};

const цикл3 = (n, a, b, c) => {
  const p = [];
  for (let i = 0; i < n; i++) p.push(i === a ? b : (i === b ? c : (i === c ? a : i)));
  return p;
};

// Описание семейства: как из параметра получить рецепт, имя и порядок.
// «порядок» нужен заранее, чтобы не строить то, что заведомо велико.
export const СЕМЕЙСТВА = {
  C: {
    имя: 'циклические',
    подпись: (n) => `C${нижний(n)}`,
    порядок: (n) => n,
    годен: (n) => n >= 1,
    рецепт: (n) => ({ вид: 'циклическая', порядок: n }),
  },
  D: {
    имя: 'диэдральные',
    подпись: (n) => `D${нижний(n)}`,
    порядок: (n) => 2 * n,
    // D₁ и D₂ в разных книгах значат разное; начинаем с треугольника.
    годен: (n) => n >= 3,
    рецепт: (n) => ({ вид: 'перестановки', генераторы: [цикл(n), отражение(n)] }),
  },
  S: {
    имя: 'симметрические',
    подпись: (n) => `S${нижний(n)}`,
    порядок: (n) => факториал(n),
    годен: (n) => n >= 1,
    рецепт: (n) => (n === 1
      ? { вид: 'циклическая', порядок: 1 }
      : { вид: 'перестановки', генераторы: [транспозиция(n, 0, 1), цикл(n)] }),
  },
  A: {
    имя: 'знакопеременные',
    подпись: (n) => `A${нижний(n)}`,
    порядок: (n) => (n <= 1 ? 1 : факториал(n) / 2),
    годен: (n) => n >= 3,
    // Знакопеременная порождается тройными циклами: (0 1 2) и длинный цикл по
    // чётности n. Для чётного n цикл (0 1 … n−1) нечётен, поэтому берётся цикл
    // по n−1 точке.
    рецепт: (n) => ({
      вид: 'перестановки',
      генераторы: n % 2 === 1
        ? [цикл3(n, 0, 1, 2), цикл(n)]
        : [цикл3(n, 0, 1, 2), сдвинутыйЦикл(n)],
    }),
  },
};

function сдвинутыйЦикл(n) {
  // (1 2 … n−1): цикл по всем точкам, кроме нулевой.
  const p = [0];
  for (let i = 1; i < n; i++) p.push(i + 1 === n ? 1 : i + 1);
  return p;
}

function факториал(n) {
  let out = 1;
  for (let i = 2; i <= n; i++) out *= i;
  return out;
}

const НИЖНИЕ = '₀₁₂₃₄₅₆₇₈₉';
function нижний(n) {
  return String(n).split('').map((c) => НИЖНИЕ[Number(c)]).join('');
}

// Члены семейства как ПОСЧИТАННЫЕ группы. Порог порядка — видимая настройка:
// S₇ это 5040 элементов, и перечислять его подгруппы минуты.
export function членыСемейства(ключ, { от = 1, до = 40, предельныйПорядок = 200 } = {}) {
  const сем = СЕМЕЙСТВА[ключ];
  if (!сем) throw new Error(`нет семейства «${ключ}»`);
  const out = [];
  for (let n = от; n <= до; n++) {
    if (!сем.годен(n)) continue;
    if (сем.порядок(n) > предельныйПорядок) continue;
    const имя = сем.подпись(n);
    const G = поРецепту(сем.рецепт(n), имя, []);
    G.id = `${ключ}${n}@сем`;
    G.имя = имя;
    G.параметр = n;
    out.push(G);
  }
  return out;
}
