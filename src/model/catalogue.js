// Библиотека конкретных групп.
//
// В данных лежат РЕЦЕПТЫ (образующие перестановки, порядок циклической,
// произведение двух других), а не таблицы умножения: таблица A₅ — это 3600
// чисел, и хранить её незачем, когда она строится за миллисекунду. Свойства в
// данных тоже есть, но не как источник истины, а как сверка: они посчитаны
// заранее, и при загрузке модель обязана выдать ровно их.

import {
  изПерестановок, циклическая, прямоеПроизведение, группа, свойстваГруппы,
} from './group.js';
import { таблицаПоПрезентации } from './презентация.js';

const построенные = new Map();

export function поРецепту(рецепт, имя, библиотека) {
  switch (рецепт.вид) {
    case 'перестановки':
      return изПерестановок(рецепт.генераторы, имя);
    case 'циклическая':
      return циклическая(рецепт.порядок, имя);
    case 'произведение': {
      const A = группаПоИмени(рецепт.левый, библиотека);
      const B = группаПоИмени(рецепт.правый, библиотека);
      return прямоеПроизведение(A, B, имя);
    }
    case 'таблица':
      return группа(рецепт.порядок, Int32Array.from(рецепт.mul), имя);
    // ОБРАЗУЮЩИЕ И СООТНОШЕНИЯ. Таблица строится перечислением смежных
    // классов (см. src/model/презентация.js). Предел перечисления — часть
    // рецепта, а не потолок из кода: по конечному заданию решить, конечна ли
    // группа, невозможно, и упёрлись мы в предел или группа правда
    // бесконечна — разные вещи, поэтому обрыв говорится вслух.
    case 'презентация': {
      const r = таблицаПоПрезентации(
        рецепт.образующих, рецепт.соотношения, рецепт.предел ?? 5000,
      );
      if (r.оборвано) {
        throw new Error(
          `${имя}: перечисление смежных классов оборвано на ${r.оборвано} классах`
          + ` (предел ${r.предел})${r.почему ? `, ${r.почему}` : ''}`,
        );
      }
      const G = группа(r.n, r.mul, имя);
      G.образующие = r.образующие;
      return G;
    }
    default:
      throw new Error(`не знаю рецепт «${рецепт.вид}»`);
  }
}

export function группаПоИмени(id, библиотека) {
  if (построенные.has(id)) return построенные.get(id);
  const запись = библиотека.find((x) => x.id === id);
  if (!запись) throw new Error(`нет группы «${id}» в библиотеке`);
  const G = поРецепту(запись.рецепт, запись.имя, библиотека);
  G.id = id;
  построенные.set(id, G);
  return G;
}

export function забытьПостроенные() {
  построенные.clear();
}

// Кватернионы Q₈ — единственная группа, которую проще задать таблицей: как
// перестановки она задаётся регулярным представлением, а это восемь массивов
// по восемь чисел, где ошибиться легче, чем в правилах i·j = k.
export function кватернионы() {
  // Элемент — пара (знак, единица), единицы: 0 = 1, 1 = i, 2 = j, 3 = k.
  const код = (знак, ед) => ед * 2 + (знак < 0 ? 1 : 0);
  const мнимые = [
    // [результат, знак] для i·j и т.д.; строка — левый, столбец — правый.
    [[0, +1], [1, +1], [2, +1], [3, +1]],
    [[1, +1], [0, -1], [3, +1], [2, -1]],
    [[2, +1], [3, -1], [0, -1], [1, +1]],
    [[3, +1], [2, +1], [1, -1], [0, -1]],
  ];
  const n = 8;
  const mul = new Int32Array(n * n);
  for (let e1 = 0; e1 < 4; e1++) {
    for (let s1 of [+1, -1]) {
      for (let e2 = 0; e2 < 4; e2++) {
        for (let s2 of [+1, -1]) {
          const [e, s] = мнимые[e1][e2];
          mul[код(s1, e1) * n + код(s2, e2)] = код(s1 * s2 * s, e);
        }
      }
    }
  }
  return группа(n, mul, 'Q₈');
}

// Проверка: свойства, посчитанные моделью, обязаны совпасть с записанными.
// Расхождение значит, что данные и код разошлись, — и молча это пропускать
// нельзя, потому что дальше на них опирается опровержение задач.
export function сверить(библиотека) {
  const беды = [];
  for (const запись of библиотека) {
    const G = группаПоИмени(запись.id, библиотека);
    if (G.n !== запись.порядок) {
      беды.push(`${запись.id}: порядок ${G.n}, а записан ${запись.порядок}`);
      continue;
    }
    const посчитано = свойстваГруппы(G);
    for (const [p, v] of Object.entries(запись.props ?? {})) {
      if (посчитано[p] !== v) {
        беды.push(`${запись.id}: свойство ${p} — модель говорит ${посчитано[p]}, записано ${v}`);
      }
    }
  }
  return беды;
}
