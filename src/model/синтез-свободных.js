// Синтез СВОБОДНОГО ПРОИЗВЕДЕНИЯ по теоремам.
//
// Зачем. До этого A ∗ B вычислялось ТОЛЬКО по объявленной таблице
// (`ТАБЛИЦА_СВОБОДНЫХ`), и для всякой другой пары модель отвечала
// «НЕ_СЧИТАЕМ». Цена замерена: на схеме «свободное произведение и его центр»
// из 1161 пробела 670 (57.7 %) — разряда «немо», то есть объекты под условие
// нашлись, а цель на них не вычислилась ни разу. Это не бедность библиотеки
// групп: это дыра в модели, и новыми группами она не лечится.
//
// Писать таблицу руками бессмысленно: пар в библиотеке больше ста двадцати на
// сто двадцать, а свойства A ∗ B ВЫЧИСЛЯЮТСЯ по A и B — тот же приём, что уже
// дал синтез колец и полей. Теоремы, по которым считается каждое свойство:
//
//   * ТРИВИАЛЬНОСТЬ, КОНЕЧНОСТЬ, АБЕЛЕВОСТЬ, ЦИКЛИЧНОСТЬ — все ложны при
//     нетривиальных множителях: A ∗ B содержит A и B как подгруппы, и
//     элементы разных множителей не перестановочны;
//   * ЦЕНТР ТРИВИАЛЕН (`centerless`) — классика: централизатор нетривиального
//     элемента лежит в сопряжённом множителе или циклический, и пересечение
//     всех таких централизаторов тривиально;
//   * НЕРАЗЛОЖИМОСТЬ — следствие того же утверждения о централизаторах
//     (разбор см. в правиле «свободное произведение нетривиальных
//     неразложимо» в data/grp.json);
//   * ПРОСТОТА ложна: ядро отображения A ∗ B → A × B нетривиально и
//     собственно;
//   * БЕЗ КРУЧЕНИЯ ⟺ оба множителя без кручения (теорема Куроша о подгруппах:
//     всякая конечная подгруппа сопряжена с подгруппой множителя);
//   * ПЕРИОДИЧНОСТЬ ложна: при нетривиальных множителях в A ∗ B есть элемент
//     бесконечного порядка (произведение ab двух нетривиальных элементов
//     разных множителей — бесконечного порядка);
//   * СВОБОДА ⟺ оба множителя свободны (теорема Куроша: свободное
//     произведение свободных свободно; обратно — подгруппа свободной
//     свободна);
//   * КОНЕЧНАЯ ПОРОЖДЁННОСТЬ ⟺ оба множителя конечно порождены (теорема
//     Грушко: ранг свободного произведения равен сумме рангов);
//   * ФИНИТНАЯ АППРОКСИМИРУЕМОСТЬ ⟺ оба множителя финитно аппроксимируемы
//     (теорема Грюнберга);
//   * СОВЕРШЕНСТВО ⟺ оба множителя совершенны: абелианизация свободного
//     произведения есть прямое произведение абелианизаций;
//   * РАЗРЕШИМОСТЬ — ровно у C₂ ∗ C₂ = D∞, и только у неё: во всех остальных
//     случаях A ∗ B содержит свободную подгруппу ранга 2. Поэтому значение
//     ставится лишь тогда, когда про ОБА множителя известно, второго они
//     порядка или нет; иначе свойство остаётся несчитанным — и это честнее,
//     чем угадать;
//   * НИЛЬПОТЕНТНОСТЬ ложна всегда: D∞ не нильпотентна, остальные содержат
//     свободную подгруппу;
//   * ДЕЛИМОСТЬ ложна: в A ∗ B у элемента a из множителя нет корня.
//
// Чего синтез НЕ делает. Он не выдумывает подгрупп, факторов и произведений:
// у синтезированной записи они пусты, и вопросы про них останутся
// несчитанными. Единственная конструкция, которую он отдаёт, — ЦЕНТР, и
// отдаёт потому, что знает его точно: он тривиален.

// Значение тривиальной группы и запись её как подгруппы: нужны, чтобы центр
// синтезированного произведения был настоящим значением, а не «не считаем».
// Ставится при связывании библиотеки — там, где тривиальная группа заведомо
// есть.
let ТРИВИАЛЬНОЕ = null;

export function запомнитьТривиальную(значение) {
  ТРИВИАЛЬНОЕ = значение ?? null;
}

// Порядок множителя, если он известен: нужен ровно для разрешимости (D∞).
const порядок = (v) => {
  if (v?.вид === 'группа') return v.G.n;
  if (v?.вид === 'имя') return v.зап.порядок ?? (v.зап.props?.finite === false ? Infinity : null);
  if (v?.вид === 'подгруппа') return v.H.length;
  return null;
};

const И = (a, b) => (a === undefined || b === undefined ? undefined : a && b);

export function свойстваСвободного(pA, pB, nA, nB) {
  const out = {
    trivial: false,
    finite: false,
    abelian: false,
    cyclic: false,
    simple: false,
    nilpotent: false,
    divisible: false,
    periodic: false,
    centerless: true,
    indecomposable: true,
  };
  // Свойства, наследуемые «в обе стороны»: верны у произведения ровно тогда,
  // когда верны у обоих множителей. Если про один из множителей свойство
  // неизвестно, оно остаётся неизвестным и у произведения — выдумывать нечего.
  for (const p of ['torsion-free', 'free', 'fin-gen', 'residually-finite', 'perfect']) {
    const v = И(pA[p], pB[p]);
    if (v !== undefined) out[p] = v;
  }
  // Разрешимость: только D∞ = C₂ ∗ C₂.
  if (nA !== null && nB !== null && nA !== undefined && nB !== undefined) {
    out.solvable = nA === 2 && nB === 2;
  }
  return out;
}

// Кэш по паре идентификаторов: пар в библиотеке тысячи, и строить запись
// заново на каждую привязку незачем. Хэш-консинг графа термов опирается на то,
// что одно и то же значение приходит одним объектом.
const КЭШ = new Map();

export function синтезироватьСвободное(X, Y, идA, идB, свойстваЗначения) {
  const ключ = `${идA}|${идB}`;
  const было = КЭШ.get(ключ);
  if (было) return было;

  const pA = свойстваЗначения(X) ?? {};
  const pB = свойстваЗначения(Y) ?? {};
  const props = свойстваСвободного(pA, pB, порядок(X), порядок(Y));
  const имяA = X?.зап?.имя ?? X?.G?.имя ?? идA;
  const имяB = Y?.зап?.имя ?? Y?.G?.имя ?? идB;

  const зап = {
    id: `freeprod:${идA}|${идB}`,
    имя: `${имяA} ∗ ${имяB}`,
    синтез: true,
    бесконечная: true,
    props,
    подгруппы: [],
    _поПодгруппе: new Map(),
    _факторы: new Map(),
    _произведения: new Map(),
    _элементы: [],
    _конструкции: {},
    заметка: 'Синтезировано: свойства свободного произведения посчитаны по теоремам Куроша, Грушко и Грюнберга, а не объявлены.',
  };
  const значение = { вид: 'имя', зап };
  зап._сам = значение;

  // ЦЕНТР. Он тривиален, и это единственная конструкция, которую синтез
  // отдаёт. Записывается как объявленная подгруппа, изоморфная тривиальной
  // группе: тогда вопросы «Z(A ∗ B) тривиален/неразложим/конечен» становятся
  // вычислимыми, а их было больше всего.
  if (ТРИВИАЛЬНОЕ) {
    const центр = {
      id: 'center',
      имя: '1',
      объект: ТРИВИАЛЬНОЕ.G?.id ?? ТРИВИАЛЬНОЕ.зап?.id ?? 'C1',
      props: { normal: true, characteristic: true, central: true, whole: false },
      _владелец: зап,
      _объект: ТРИВИАЛЬНОЕ,
    };
    зап.подгруппы.push(центр);
    зап._поПодгруппе.set('center', центр);
    зап._конструкции.center = { вид: 'именПод', зап: центр, влад: зап };
  }

  КЭШ.set(ключ, значение);
  return значение;
}

export function забытьСинтезированныеСвободные() {
  КЭШ.clear();
}
