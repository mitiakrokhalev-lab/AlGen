export function свойстваКольца(v) {
  return { ...v.props };
}

// Свободен ли A над ℤ/nℤ: A ≅ (ℤ/n)^k. Проверка через счёт элементов,
// убиваемых каждым делителем n: у свободного их ровно m^k.
function свободенНадZn(G, n) {
  const k = Math.round(Math.log(G.n) / Math.log(n));
  if (n ** k !== G.n) return false;
  for (let m = 1; m <= n; m++) {
    if (n % m !== 0) continue;
    let счёт = 0;
    for (let x = 0; x < G.n; x++) if (кратное(G, x, m) === 0) счёт++;
    if (счёт !== m ** k) return false;
  }
  return true;
}

// Существует ли такой модуль вообще: кольцо обязано убивать группу.
function модульНад(R, v, G, з) {
  if (R.экспонента === 0) return true;
  if (G) return убивает(R, G);
  const e = з?.модуль?.экспонента;
  return Number.isInteger(e) && e > 0 && R.экспонента % e === 0;
}

export function свойстваМодуля(v) {
  if (v._св) return v._св;
  // Объявленный модуль над объявленным кольцом: считать нечего, всё в записи.
  if (v.имен) {
    v._св = { ...v.имен.props };
    return v._св;
  }
  const R = v.R;
  const G = конечная(v);
  const гр = групповые(v);
  const з = запись(v);
  const out = {};

  // Пары «кольцо и группа» бывают несуществующие: C₃ не модуль над ℤ/2ℤ. При
  // переборе такие не строятся, но счёт слепых пятен идёт по ВСЕМ парам, и
  // отвечать про несуществующий объект нельзя — ответ был бы выдуманным.
  if (!модульНад(R, v, G, з)) {
    v._св = out;
    return out;
  }

  const поле = R.props.field === true;
  const область = R.props.domain === true;

  if (G) {
    out.finite = true;
    out.trivial = G.n === 1;
    out.cyclic = гр.cyclic ?? цикличнаКонечная(G);
    out['fin-gen'] = true;
    out.noetherian = true;
    out.artinian = true;
    out.simple = подгруппы(G).length === 2;
    out.free = R.экспонента === 0 ? G.n === 1 : свободенНадZn(G, R.экспонента);
    // НЕРАЗЛОЖИМОСТЬ и ПОЛУПРОСТОТА. Два свойства, заведённые против
    // «одноликости»: прежними десятью ℤ/4 и ℤ/2 × ℤ/2 не различались вовсе.
    //
    // Конечная абелева группа неразложима ровно тогда, когда она циклическая
    // ПОРЯДКА СТЕПЕНИ ПРОСТОГО: разложение в произведение циклических
    // примарных единственно, и слагаемых в нём больше одного, едва порядок не
    // примарный. Нулевой модуль неразложимым не считается.
    out.indecomposable = G.n > 1 && степеньПростого(G.n) && цикличнаКонечная(G);
    // Полупростота: над ℤ простые модули — это ℤ/p, значит модуль полупрост
    // ровно при экспоненте, СВОБОДНОЙ ОТ КВАДРАТОВ. Над кольцом ненулевой
    // экспоненты простые — те же ℤ/p при p, делящем экспоненту, и условие то
    // же. Нулевой модуль полупрост как пустая сумма.
    out.semisimple = безКвадратов(экспонентаГруппы(G));
  } else if (з) {
    out.finite = з.props.finite === true;
    out.trivial = з.props.trivial === true;
    out.cyclic = з.props.cyclic;
    out['fin-gen'] = з.props['fin-gen'];
    // Над всеми нашими кольцами (ℤ и конечные) нётеровость модуля — это в
    // точности конечная порождённость: сами кольца нётеровы.
    out.noetherian = з.props['fin-gen'];
    out.artinian = з.модуль?.artinian;
    out.simple = з.props.finite === true ? undefined : false;
    // Свободность зависит от КОЛЬЦА, а пометка в записи отвечает про ℤ: ⊕C₂
    // не свободна как ℤ-модуль и свободна как 𝔽₂-пространство. Над полем
    // считать нечего — базис есть у всякого пространства; у конечных модулей
    // свободность по-прежнему вычисляется, и сверка с правилом остаётся
    // настоящей проверкой.
    out.free = поле ? true : з.модуль?.free;
    // У объявленного модуля неразложимость берётся из записи его ГРУППЫ: это
    // одно и то же свойство, подмодули абелевой группы — её подгруппы.
    if (з.props?.indecomposable !== undefined) out.indecomposable = з.props.indecomposable;
    // Полупростота объявленного: сказать наверняка можно про модуль БЕЗ
    // КРУЧЕНИЯ — у него нет ни одного простого подмодуля, значит не полупрост
    // (кроме нулевого). Остальное не выдумываем.
    if (з.props?.['torsion-free'] === true && з.props?.trivial !== true) out.semisimple = false;
  }

  // Кручение и делимость осмысленны над ОБЛАСТЬЮ: иначе «необратимый элемент»
  // и «делитель нуля» перестают быть разными вещами, и свойство вырождается в
  // тождественно истинное. Лучше молчать, чем отвечать вырожденной правдой.
  if (поле) {
    // Над полем ненулевые элементы обратимы: кручения нет и делимость даром.
    // А вот свободность здесь НЕ подставляется, хотя над полем она и так
    // верна: пусть её считает та же проверка, что над ℤ/4ℤ, — тогда правило
    // «над полем всякий модуль свободен» останется независимой сверкой.
    out['torsion-free'] = true;
    out.divisible = true;
  } else if (область) {
    out['torsion-free'] = G ? G.n === 1 : гр['torsion-free'];
    out.divisible = G ? G.n === 1 : гр.divisible;
  }

  // ГОМОЛОГИЧЕСКИЕ СВОЙСТВА. Считаются ТОЛЬКО там, где они вынуждены теоремой,
  // а не там, где их хотелось бы знать: правило, которое сверять нечем, — это
  // не правило, а обещание. Без этого места все одиннадцать новых правил о
  // Ext, Tor и проективности лежали в базе непроверенными: сверка честно
  // сообщала «посылки сошлись 0 раз».
  //
  //   * над ПОЛЕМ всё проективно, инъективно и плоско — у всякого
  //     пространства есть базис и всякое вложение расщепляется;
  //   * над ПОЛУПРОСТЫМ кольцом (у нас это ℤ/nℤ со свободной от квадратов n)
  //     всякий модуль полупрост, а полупростой — прямое слагаемое свободного,
  //     то есть проективен; инъективность и плоскость оттуда же;
  //   * над ОБЛАСТЬЮ ГЛАВНЫХ ИДЕАЛОВ три теоремы дают три равенства:
  //     проективный = свободный (Капланский), плоский = без кручения,
  //     инъективный = делимый. Все три — настоящие теоремы, и именно поэтому
  //     сверка здесь не пустая: правило «свободен ⇒ проективен» проверяется
  //     на том, что модель посчитала свободность САМОСТОЯТЕЛЬНО.
  //
  // Над ℤ/4ℤ (не область и не полупростое) не говорится ничего: проективный
  // там не равен свободному, и выдумывать нечего.
  const полупростоеКольцо = R.экспонента > 0 && безКвадратов(R.экспонента);
  if (поле || полупростоеКольцо) {
    out.projective = true;
    out['injective-mod'] = true;
    out.flat = true;
  } else if (R.props.pid === true) {
    if (out.free !== undefined) out.projective = out.free;
    if (out['torsion-free'] !== undefined) out.flat = out['torsion-free'];
    if (out.divisible !== undefined) out['injective-mod'] = out.divisible;
  }

  if (v.вид === 'подмодуль' && v.объемл) {
    const M = конечная(v.объемл);
    // «Весь» и «максимален» — свойства ВЛОЖЕНИЯ: у объявленной подгруппы они
    // записаны при ней, а не при объекте, которому она изоморфна.
    const вл = вложениеЗаписи(v);
    if (вл.whole !== undefined) out.whole = вл.whole;
    if (вл.maximal !== undefined) out.maximal = вл.maximal;
    if (M && G) out.whole = G.n === M.n;
    if (M && G) {
      const H = v.A.вид === 'подгруппа' ? v.A.H : null;
      if (H) {
        out.maximal = свойстваМодуля(модуль(R, { вид: 'группа', G: фактор(M, H).группа })).simple === true;
        out.summand = прямоеСлагаемое(M, H);
      }
    }
  }

  v._св = out;
  return out;
}

// Число простых множителей с кратностью: Ω(12) = 3, потому что 12 = 2·2·3.
// Для конечного модуля над ℤ это и есть длина композиционного ряда — все
// композиционные факторы суть ℤ/p.
function длинаПоПорядку(n) {
  let m = n;
  let k = 0;
  for (let p = 2; p * p <= m; p++) {
    while (m % p === 0) { m /= p; k++; }
  }
  if (m > 1) k++;
  return k;
}

// Экспонента конечной абелевой группы — НОК порядков элементов.
function экспонентаГруппы(G) {
  let e = 1;
  for (let x = 0; x < G.n; x++) {
    const o = порядокЭлемента(G, x);
    e = (e / НОДчисел(e, o)) * o;
  }
  return e;
}

const НОДчисел = (a, b) => (b === 0 ? a : НОДчисел(b, a % b));

const безКвадратов = (n) => {
  if (n <= 1) return true;
  for (let d = 2; d * d <= n; d++) if (n % (d * d) === 0) return false;
  return true;
};

const степеньПростого = (n) => {
  if (n < 2) return false;
  for (let p = 2; p <= n; p++) {
    if (n % p !== 0) continue;
    let m = n;
    while (m % p === 0) m /= p;
    return m === 1;
  }
  return false;
};

function цикличнаКонечная(G) {
  for (let x = 0; x < G.n; x++) if (порядокЭлемента(G, x) === G.n) return true;
  return G.n === 1;
}

// P — прямое слагаемое M, если найдётся Q с P ∩ Q = 0 и |P|·|Q| = |M|.
function прямоеСлагаемое(M, H) {
  const надо = M.n / H.length;
  if (!Number.isInteger(надо)) return false;
  for (const K of подгруппы(M)) {
    if (K.length !== надо) continue;
    if (пересечение(H, K).length === 1) return true;
  }
  return false;
}

// Полнота и тривиальность ВЛОЖЕНИЯ — для значений модели групп: посчитанная
// подгруппа знает свой размер, объявленная — свои пометки.
function полноеВложение(v) {
  if (!v) return undefined;
  if (v.вид === 'подгруппа') return v.H.length === v.объемлющая.n;
  if (v.вид === 'именПод') return v.зап.props?.whole;
  return undefined;
}

function тривиальноеВложение(v) {
  if (!v) return undefined;
  if (v.вид === 'подгруппа') return v.H.length === 1;
  if (v.вид === 'именПод') {
    const о = v.зап._объект;
    if (о?.вид === 'группа') return о.G.n === 1;
    if (о?.вид === 'имя') return о.зап.props?.trivial === true;
  }
  return undefined;
}

export function свойстваМорфизмаМод(v) {
  if (v.имен) {
    // Инъективность, сюръективность и нулевость — это тривиальность ядра и
    // полнота образа, и считать их надо прямо здесь. Делегировать модели
    // групп нельзя: она спросила бы свойства у МОДУЛЬНОГО опросчика, а тот про
    // групповые значения ничего не знает и молча возвращал пустоту — оттого у
    // морфизма «именованный модуль → конечный» сюръективность была неизвестна,
    // и всякое условие со словами «f не сюръективен» теряло эти строки.
    const p = v.имен.props ?? {};
    const инъ = p.injective ?? тривиальноеВложение(v.имен.ядро);
    const сюр = p.surjective ?? полноеВложение(v.имен.образ);
    const нул = p['zero-mor'] ?? тривиальноеВложение(v.имен.образ);
    const out = {};
    if (инъ !== undefined) out.injective = инъ;
    if (сюр !== undefined) out.surjective = сюр;
    if (нул !== undefined) out['zero-mor'] = нул;
    if (инъ !== undefined && сюр !== undefined) out['iso-mor'] = инъ && сюр;
    return out;
  }
  const { дом, код, φ } = v;
  const яд = ядро(дом, φ);
  const об = образ(дом, φ);
  return {
    injective: яд.length === 1,
    surjective: об.length === код.n,
    'iso-mor': яд.length === 1 && об.length === код.n,
    'zero-mor': об.length === 1,
  };
}

export function свойстваЗначенияМод(v) {
  if (!v) return {};
  if (v.вид === 'кольцо') return свойстваКольца(v);
  if (v.вид === 'модуль' || v.вид === 'подмодуль') return свойстваМодуля(v);
  if (v.вид === 'модморфизм') return свойстваМорфизмаМод(v);
  return {};
}

export function отношениеМод(rel, a, b) {
  if (rel === 'iso') {
    const A = конечная(a);
    const B = конечная(b);
    if (A && B) return изоморфны(A, B);
    const за = запись(a);
    const зб = запись(b);
    if (за && зб) return за.id === зб.id;
    if ((A && зб) || (за && B)) return false;
    return undefined;
  }
  if (rel === 'le') {
    if (a.A?.вид === 'подгруппа' && b.A?.вид === 'подгруппа') {
      const H = new Set(b.A.H);
      return a.A.H.every((x) => H.has(x));
    }
    return undefined;
  }
  return undefined;
}

