// Модель модулей над кольцом.
//
// Главное решение здесь одно, и оно даёт всю модель почти даром: КАЖДОЕ кольцо
// этой модели — ℤ или ℤ/nℤ, то есть действует через ℤ. А значит:
//
//   * R-модуль — это абелева группа (с условием nA = 0 для R = ℤ/nℤ);
//   * ПОДмодуль — это в точности подгруппа (действие целочисленное, стабильность
//     даром), и перечислять подмодули не нужно: они уже перечислены;
//   * гомоморфизм модулей — это в точности гомоморфизм групп.
//
// Поэтому вся арифметика берётся из уже написанной и уже проверенной модели
// групп, а здесь остаётся ровно то, что у модулей СВОЁ, — свойства. И они
// расходятся по-настоящему: ℤ² свободна как ℤ-модуль и не свободна как группа,
// а «прост» у модуля значит не то же, что «проста» у группы.
//
// Цена решения: колец без делителей нуля тут всего ℤ и поля ℤ/p, поэтому
// правило, верное над ℤ и ложное над каким-нибудь k[x,y], модель не поймает.
// Это записано в README как известная дыра, а не забыто.

