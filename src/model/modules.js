export function вычислитьУзелМод(graph, id, значения, предел = Infinity) {
  const n = graph.get(id);
  const арг = (i) => значения.get(n.args[i]) ?? null;
  const G = (v) => конечная(v);

  switch (n.op) {
    case 'choose-ring': case 'choose-mod': case 'choose-submod': case 'choose-mod-mor':
      return значения.get(id) ?? null;

    case 'whole-mod': {
      const M = арг(0);
      const g = G(M);
      if (!g) return НЕ_СЧИТАЕМ;
      return подзн(M.R, M, [...Array(g.n).keys()]);
    }
    case 'zero-sub': {
      const M = арг(0);
      const g = G(M);
      if (!g) return НЕ_СЧИТАЕМ;
      return подзн(M.R, M, [0]);
    }
    case 'quotient-mod': {
      const M = арг(0);
      const P = арг(1);
      const g = G(M);
      if (g && P?.A?.вид === 'подгруппа') {
        return модуль(M.R, { вид: 'группа', G: фактор(g, P.A.H).группа });
      }
      // ОБЪЯВЛЕННЫЙ модуль по ОБЪЯВЛЕННОМУ подмодулю: фактор берётся из той же
      // таблицы `факторы`, по которой считается `quotient` в разделе групп.
      // Без этого M/T(M) не вычислялся ни на одном бесконечном модуле — а это
      // главный терм всей схемы «кручение».
      if (!M || !P) return НЕ_СЧИТАЕМ;
      const гр = факторОбъявленного(M.A, P.A);
      return гр ? модуль(M.R, гр) : НЕ_СЧИТАЕМ;
    }
    case 'sum-mod': {
      const M = арг(0);
      const N = арг(1);
      const a = G(M);
      const b = G(N);
      if (a && b && a.n * b.n <= предел) {
        return модуль(M.R, { вид: 'группа', G: прямоеПроизведение(a, b) });
      }
      // ОБЪЯВЛЕННЫЕ модули. M ⊕ N как абелева группа — это M × N, а таблица
      // произведений объявленных групп в библиотеке уже есть: та же, по
      // которой считается `prod` в разделе групп. Пока этого хода не было,
      // `sum-mod` над бесконечными модулями не вычислялся никогда — 74 немые
      // цели на схеме «сумма», то есть вся её бедность.
      if (!M || !N || M.R !== N.R) return НЕ_СЧИТАЕМ;
      const гр = суммаОбъявленных(M.A, N.A);
      return гр ? модуль(M.R, гр) : НЕ_СЧИТАЕМ;
    }
    case 'ker-mod': {
      const f = арг(0);
      if (!f) return НЕ_СЧИТАЕМ;
      if (f.имен) {
        if (f.имен.ядро) return подмодуль(f.R, f.имен.ядро, f.модДом);
        // Ядро СЛЕДУЕТ из свойств морфизма, и записывать его тогда незачем: у
        // инъективного оно тривиально, у нулевого — вся область определения.
        // Пока этого не было, ker f у объявленного морфизма не вычислялся,
        // даже когда в записи стояло «инъективен».
        const п = f.имен.props ?? {};
        if (п.injective === true) {
          const под = тривиальнаяПодгруппа(f.модДом?.A);
          if (под) return подмодуль(f.R, под, f.модДом);
        }
        if (п['zero-mor'] === true) {
          const под = всяПодгруппа(f.модДом?.A);
          if (под) return подмодуль(f.R, под, f.модДом);
        }
        return НЕ_СЧИТАЕМ;
      }
      return подзн(f.R, f.модДом, ядро(f.дом, f.φ));
    }
    case 'im-mod': {
      const f = арг(0);
      if (!f) return НЕ_СЧИТАЕМ;
      if (f.имен) {
        if (f.имен.образ) return подмодуль(f.R, f.имен.образ, f.модКод);
        // То же с образом: у сюръективного он весь, у нулевого тривиален.
        const п = f.имен.props ?? {};
        if (п.surjective === true) {
          const под = всяПодгруппа(f.модКод?.A);
          if (под) return подмодуль(f.R, под, f.модКод);
        }
        if (п['zero-mor'] === true) {
          const под = тривиальнаяПодгруппа(f.модКод?.A);
          if (под) return подмодуль(f.R, под, f.модКод);
        }
        return НЕ_СЧИТАЕМ;
      }
      return подзн(f.R, f.модКод, образ(f.дом, f.φ));
    }
    case 'len': {
      const M = арг(1);
      if (!M) return НЕ_СЧИТАЕМ;
      // ДЛИНА — число членов композиционного ряда. Считать её через ПОРЯДОК
      // группы можно ровно там, где композиционные факторы суть ℤ/p: длина
      // равна числу простых множителей порядка С КРАТНОСТЬЮ, ℓ(C₁₂) = 3, ибо
      // 12 = 2·2·3. Это и есть то, чем C₄, C₈ и C₁₆ различаются, а прежними
      // двенадцатью свойствами не различались вовсе.
      //
      // Над кольцом, у которого простые модули БЕСКОНЕЧНЫ, формула неверна, и
      // сверка это поймала: ℚ² над M₂(ℚ) ПРОСТ, то есть длины 1, а по порядку
      // группы выходила бесконечность. Поэтому у объявленного модуля над
      // объявленным кольцом берётся только то, что сказано в записи, а
      // остальное честно невычислимо.
      if (M.имен) {
        const p = M.имен.props ?? {};
        if (p.trivial === true) return { вид: 'число', n: 0 };
        if (p.simple === true) return { вид: 'число', n: 1 };
        return НЕ_СЧИТАЕМ;
      }
      const g = G(M);
      if (g) return { вид: 'число', n: длинаПоПорядку(g.n) };
      // Бесконечный модуль над ℤ композиционного ряда не имеет: простые
      // ℤ-модули конечны, значит бесконечный не набрать конечным рядом. Это
      // ЗНАЧЕНИЕ, а не отсутствие значения, — как |ℤ| у групп.
      const св = свойстваМодуля(M);
      if (св.finite === false) return { вид: 'число', n: Infinity };
      return НЕ_СЧИТАЕМ;
    }
    case 'tors': {
      const M = арг(1);
      const g = G(M);
      // Кручение считается по НЕОБРАТИМЫМ элементам кольца, а не по целым
      // числам: над ℤ/pℤ ненулевые скаляры обратимы, и T(M) = 0, хотя как
      // абелева группа M целиком периодическая. Сверка с базой поймала ровно
      // это: «без кручения ⇒ T(M) = 0» ломалось на каждом модуле над полем.
      if (g) return подзн(M.R, M, M.R.экспонента === 0 ? кручение(g) : [0]);
      // ОБЪЯВЛЕННЫЙ модуль: своей таблицы умножения у него нет, но кручение
      // его группы либо записано, либо СЛЕДУЕТ из записанных свойств —
      // у периодической это вся группа, у группы без кручения одна единица.
      if (!M) return НЕ_СЧИТАЕМ;
      const под = кручениеОбъявленного(M);
      return под ? подмодуль(M.R, под, M) : НЕ_СЧИТАЕМ;
    }
    case 'hom-mod': {
      const M = арг(1);
      const N = арг(2);
      const a = G(M);
      const b = G(N);
      if (!a || !b) return НЕ_СЧИТАЕМ;
      const H = модульГомоморфизмов(a, b, предел);
      return H ? модуль(M.R, { вид: 'группа', G: H }) : null;
    }
    default:
      return НЕ_СЧИТАЕМ;
  }
}

// Нулевой модуль нейтрален: M ⊕ 0 = M. Это тождество, а не объявление, и
// держится оно само — объявлять произведение с тривиальной группой незачем.
const тривиальноеЗн = (v) => (v?.вид === 'имя'
  ? v.зап.props?.trivial === true
  : v?.G?.n === 1);

const идЗн = (v) => (v?.вид === 'имя' ? (v.зап.id ?? null) : (v?.G?.id ?? null));

// Сумма объявленных модулей через таблицу произведений их ГРУПП. Ключ ищется в
// обе стороны: M × N ≅ N × M, и объявлять дважды незачем.
function суммаОбъявленных(a, b) {
  if (!a || !b) return null;
  if (тривиальноеЗн(b)) return a;
  if (тривиальноеЗн(a)) return b;
  const ia = идЗн(a);
  const ib = идЗн(b);
  if (a.вид === 'имя' && ib) {
    const r = a.зап._произведения?.get(ib);
    if (r) return r;
  }
  if (b.вид === 'имя' && ia) {
    const r = b.зап._произведения?.get(ia);
    if (r) return r;
  }
  return null;
}

// Фактор объявленного модуля по объявленному подмодулю. Два случая считаются
// сами и записывать их не надо: по нулевому подмодулю фактор — сам модуль, по
// всему — нулевой. Остальное берётся из объявленной таблицы факторов.
function факторОбъявленного(A, P) {
  if (A?.вид !== 'имя' || P?.вид !== 'именПод' || P.влад !== A.зап) return null;
  const p = P.зап.props ?? {};
  if (p['zero-ideal'] === true) return null;      // чужой сорт: не наш случай
  const объект = P.зап._объект;
  if (объект?.вид === 'группа' && объект.G.n === 1) return A;   // M/0 = M
  if (p.whole === true) return тривиальныйОбъект(A);            // M/M = 0
  return A.зап._факторы?.get(P.зап.id) ?? null;
}

// Нулевой модуль как ОБЪЕКТ (а не подмодуль): у объявленной группы он берётся
// из её же тривиальной подгруппы.
function тривиальныйОбъект(A) {
  const п = тривиальнаяПодгруппа(A);
  return п?.вид === 'именПод' ? п.зап._объект : null;
}

// Кручение объявленного модуля. Над кольцом с ненулевой экспонентой ненулевые
// скаляры обратимы, и кручение тривиально по определению; над ℤ оно берётся из
// записи, а два случая следуют из свойств и записывать их не надо.
function кручениеОбъявленного(M) {
  const A = M.A;
  if (A?.вид !== 'имя') return null;
  if (M.R.экспонента !== 0) return тривиальнаяПодгруппа(A);
  const p = A.зап.props ?? {};
  if (p['torsion-free'] === true) return тривиальнаяПодгруппа(A);
  if (p.periodic === true) return всяПодгруппа(A);
  return A.зап._конструкции?.torsion ?? null;
}

// Hom(M, N) как модуль: элементы — гомоморфизмы, сложение поточечное.
//
// Таблица умножения строится честно, и её размер — КВАДРАТ числа
// гомоморфизмов: при 256 это 65 536 клеток, что считается мгновенно, а при
// 4096 — шестнадцать миллионов, и это уже минуты. Поэтому предел есть, но он
// назван и обоснован ценой, а не взят с потолка: прежде стояло 64 без всякого
// довода, и Hom(C₈, C₈) ещё проходил, а Hom(C₂⁴, C₂⁴) — уже нет, хотя его
// таблица всего 65 536 клеток.
const ПРЕДЕЛ_ГОМОМОРФИЗМОВ = 256;

function модульГомоморфизмов(A, B, предел) {
  const список = гомоморфизмы(A, B);
  if (список.length > Math.min(предел, ПРЕДЕЛ_ГОМОМОРФИЗМОВ)) return null;
  const индекс = new Map(список.map((φ, i) => [φ.join(','), i]));
  const mul = [];
  for (let i = 0; i < список.length; i++) {
    const строка = [];
    for (let j = 0; j < список.length; j++) {
      const сумма = список[i].map((y, x) => умножить(B, y, список[j][x]));
      const k = индекс.get(сумма.join(','));
      if (k === undefined) return null;
      строка.push(k);
    }
    mul.push(строка);
  }
  return группа(список.length, mul, `Hom(${A.имя ?? '?'}, ${B.имя ?? '?'})`);
}

// --- кандидаты -----------------------------------------------------------------

export function кандидатыМод(graph, n, значения, каталог, предел = Infinity) {
  const арг = (i) => значения.get(n.args[i]) ?? null;
  switch (n.op) {
    case 'choose-ring':
      return каталог.кольца;
    case 'choose-mod': {
      const R = арг(0);
      if (!R) return [];
      // У объявленного кольца модели нет: модули перечислены при нём самом.
      // Вычислимых модулей над ним не бывает вовсе — ℤ через него не
      // действует, — поэтому перечень и есть вся библиотека.
      if (R.объявлено) {
        return (R.модули ?? []).map((м) => ({ вид: 'модуль', R, имен: м }));
      }
      const годные = каталог.модули.filter((x) => подходит(R, x, предел));
      return годные.map((x) => модуль(R, x));
    }
    case 'choose-submod': {
      const M = арг(0);
      const g = конечная(M);
      if (g) return подгруппы(g).map((H) => подзн(M.R, M, H));
      const з = M?.A?.вид === 'имя' ? M.A.зап : null;
      if (!з) return [];
      return (з.подгруппы ?? []).map((п) => подмодуль(M.R, { вид: 'именПод', зап: п, влад: п._владелец }, M));
    }
    case 'choose-mod-mor': {
      const M = арг(0);
      const N = арг(1);
      const a = конечная(M);
      const b = конечная(N);
      if (a && b) {
        return гомоморфизмы(a, b).map((φ) => ({
          вид: 'модморфизм', R: M.R, дом: a, код: b, φ, модДом: M, модКод: N,
        }));
      }
      // Если хоть один модуль объявленный, гомоморфизмы берутся из модели
      // ГРУПП — и это не натяжка: кольцо действует через ℤ, поэтому всякий
      // гомоморфизм абелевых групп автоматически R-линеен. Пока этой ветки не
      // было, схема с морфизмом не видела ни одного бесконечного модуля, и
      // вопрос «ker f конечно порождён» подтверждался тремя тысячами конечных
      // примеров подряд.
      return именованныеМорфизмы(M, N);
    }
    default:
      return [];
  }
}

// Гомоморфизмы, когда хоть один модуль объявленный. Берутся из модели групп
// тремя путями — встроенные (нулевой, тождественный), вложения по объявленным
// подгруппам и объявленные рукой, — и заворачиваются в модульное значение,
// чтобы ядро и образ считались как подмодули.
function именованныеМорфизмы(M, N) {
  const X = M?.A ?? null;
  const Y = N?.A ?? null;
  if (!X || !Y) return [];
  const out = [
    ...встроенныеМорфизмы(X, Y, всяПодгруппа, тривиальнаяПодгруппа),
    ...вложенияПодгрупп(X, Y, тривиальнаяПодгруппа),
    ...объявленныеМорфизмы(X, Y),
  ];
  return out.map((м) => ({ вид: 'модморфизм', R: M.R, имен: м, модДом: M, модКод: N }));
}

// Абелева группа служит модулем над R, если её убивает экспонента R.
function подходит(R, A, предел) {
  const G = конечная(A);
  if (G) {
    if (G.n > предел) return false;
    return убивает(R, G);
  }
  // Объявленная бесконечная. Над ℤ модулем служит любая абелева группа; над
  // ℤ/nℤ — та, у которой объявлена экспонента, делящая n. Без этого ⊕C₂ не
  // считалась векторным пространством над 𝔽₂, и «бесконечномерных» примеров у
  // раздела не было вовсе: все модули над полем выходили конечными.
  if (R.экспонента === 0) return true;
  const e = A?.зап?.модуль?.экспонента;
  return Number.isInteger(e) && e > 0 && R.экспонента % e === 0;
}

export function описаниеМод(v, имя) {
  if (!v) return null;
  if (v.вид === 'кольцо') return `${имя} = ${v.имя}`;
  if (v.вид === 'модуль' || v.вид === 'подмодуль') {
    // Объявленный модуль над объявленным кольцом называется своим именем:
    // порядка у него нет, и «порядка undefined» — не описание, а мусор.
    if (v.имен) return `${имя} = ${v.имен.имя}`;
    const з = запись(v);
    if (з) return `${имя} = ${v.A.зап?.имя ?? з.имя}`;
    const G = конечная(v);
    const где = v.вид === 'подмодуль' ? 'подмодуль порядка' : 'порядка';
    return `${имя} — ${где} ${G?.n}`;
  }
  if (v.вид === 'модморфизм') {
    if (v.имен) return `${имя} — ${v.имен.имя}`;
    const об = new Set(v.φ).size;
    return `${имя} — ${об === 1 ? 'нулевой' : об === v.дом.n ? 'вложение' : `с образом порядка ${об}`}`;
  }
  return null;
}

