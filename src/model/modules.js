// --- кольца -------------------------------------------------------------------

export function кольца(путь) {
  return JSON.parse(readFileSync(путь, 'utf8')).кольца.map((к) => ({ ...к, вид: 'кольцо' }));
}

// Экспонента 0 значит ℤ: модулем над ним служит любая абелева группа.
const убивает = (к, G) => к.экспонента === 0
  || [...Array(G.n).keys()].every((x) => кратное(G, x, к.экспонента) === 0);

function кратное(G, x, m) {
  let y = 0;
  for (let i = 0; i < m; i++) y = умножить(G, y, x);
  return y;
}

// --- значения -----------------------------------------------------------------
//
// Модуль хранит кольцо и АБЕЛЕВУ ГРУППУ под ним — в том же виде, в каком её
// знает модель групп: посчитанная таблица или объявленная запись.

export const модуль = (R, A) => ({ вид: 'модуль', R, A });
export const подмодуль = (R, A, объемл) => ({ вид: 'подмодуль', R, A, объемл });

export const конечная = (v) => {
  if (!v) return null;
  const A = v.A ?? v;
  if (A.вид === 'группа') return A.G;
  if (A.вид === 'подгруппа') {
    A._как ??= подгруппаКакГруппа(A.объемлющая, A.H);
    return A._как.группа;
  }
  // Объявленная подгруппа бесконечной группы бывает КОНЕЧНОЙ: кручение ℚ/ℤ
  // внутри ℂ* — это C_n с посчитанной таблицей. Такой подмодуль считается
  // целиком, и отдавать его в «ничего не знаем» было бы потерей примеров.
  //
  // Поле `_объект` — это ЗНАЧЕНИЕ ({вид:'группа'} или {вид:'имя'}), а не
  // запись. Пока здесь стояло `A.зап._объект.mul`, условие не срабатывало
  // никогда, и у всякого именованного подмодуля терялись свойства объекта:
  // ядро нулевого морфизма из ℤ не знало даже, что оно конечно порождено.
  if (A.вид === 'именПод' && A.зап?._объект?.вид === 'группа') return A.зап._объект.G;
  return null;
};

// Объявленная запись со СВОЙСТВАМИ. У посчитанной конечной группы их нет —
// она проходит другим путём, через `конечная`.
const запись = (v) => {
  const A = v?.A ?? v;
  if (A?.вид === 'имя') return A.зап?.props ? A.зап : null;
  if (A?.вид === 'именПод') {
    const о = A.зап?._объект;
    if (о?.вид === 'имя') return о.зап;
    return null;
  }
  return null;
};

// Свойства ВЛОЖЕНИЯ у объявленной подгруппы (нормальна, вся, конечного
// индекса) живут в самой записи подгруппы и к объекту отношения не имеют.
const вложениеЗаписи = (v) => {
  const A = v?.A ?? v;
  return A?.вид === 'именПод' ? (A.зап?.props ?? {}) : {};
};

const групповые = (v) => {
  const з = запись(v);
  if (з) return з.props ?? {};
  const G = конечная(v);
  return G ? { finite: true } : {};
};

