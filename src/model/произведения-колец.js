// Синтез произведений колец.
//
// Библиотека колец объявлена рукой, и рукой её дальше не нарастить: тридцать
// записей дают на схеме «кольцо и идеал» восемьдесят четыре строки примеров, а
// на схеме из одного кольца — тридцать. На таком числе почти всякая тройка
// посылок отсекает всё, и раздел состоит из пробелов, которые значат не
// «трудно», а «проверить было негде».
//
// Произведение из этого положения выводит потому, что его свойства
// ВЫЧИСЛЯЮТСЯ по сомножителям, а не объявляются:
//
//   * коммутативность, нётеровость, артиновость, приведённость, конечность —
//     покомпонентно, то есть конъюнкция;
//   * область, поле, тело, локальность, простота — ЛОЖНЫ у произведения двух
//     ненулевых, и это не осторожность, а теорема: (1,0)·(0,1) = 0, а R × 0 и
//     0 × S — два разных максимальных... точнее, два разных собственных
//     ненулевых двусторонних идеала.
//
// Идеалы произведения — это в точности I × J, и четыре из них известны всегда:
// нулевой, единичный и два канонических, R × 0 и 0 × S. Их свойства тоже
// считаются: R × 0 прост ровно тогда, когда S — область (фактор по нему есть
// S), и максимален ровно тогда, когда S — поле.
//
// В БИБЛИОТЕКУ идут не все: как и у групп, берётся по одному представителю на
// новый набор свойств, а остальные остаются связанными — чтобы терм R × S был
// вычислим, даже если примером это кольцо не предлагается.

import { иТри } from './значение.js';

const КОНЪЮНКТИВНЫЕ = ['comm', 'noeth-ring', 'artin-ring', 'reduced', 'finite-ring'];
const ЛОЖНЫЕ = ['domain', 'field', 'division', 'pid', 'ufd', 'local', 'simple-ring', 'trivial-ring'];


function свойстваПроизведенияКолец(R, S) {
  const props = {};
  for (const p of КОНЪЮНКТИВНЫЕ) {
    const v = иТри(R.props?.[p], S.props?.[p]);
    if (v !== undefined) props[p] = v;
  }
  for (const p of ЛОЖНЫЕ) props[p] = false;
  return props;
}

// Канонический идеал R × 0. Фактор по нему — ВТОРОЙ сомножитель: то, что в
// идеале уцелело, в факторе убивается, и наоборот. Отсюда единственный
// параметр, от которого всё зависит, и он называется фактором, а не как-нибудь
// ещё: перепутать «что внутри» и «что снаружи» здесь легче всего, и сверщик
// поймал ровно эту путаницу на 252 произведениях.
//
//   прост        ⇔ фактор — область целостности;
//   максимален   ⇔ фактор — поле;
//   радикален    ⇔ фактор приведён, ибо √(R × 0) = R × N(S).
function каноническийИдеал(id, имя, оставшийся) {
  const props = {
    'zero-ideal': false,
    'whole-ideal': false,
    proper: true,
    // Порождается идемпотентом (1, 0) — один элемент, значит главный.
    principal: true,
    'fin-gen-ideal': true,
    // Идемпотентный ненулевой идеал нильпотентным не бывает: I² = I ≠ 0.
    'nilpotent-ideal': false,
  };
  if (оставшийся.props?.domain !== undefined) props.prime = оставшийся.props.domain;
  if (оставшийся.props?.field !== undefined) props['maximal-ideal'] = оставшийся.props.field;
  if (оставшийся.props?.reduced !== undefined) props['radical-ideal'] = оставшийся.props.reduced;
  return { id, имя, props, фактор: оставшийся.id, радикал: props['radical-ideal'] === true ? id : undefined };
}

function идеалыПроизведения(id, R, S, props) {
  const ноль = {
    id: `${id}.0`,
    имя: '0',
    props: {
      'zero-ideal': true,
      'whole-ideal': false,
      proper: true,
      principal: true,
      'fin-gen-ideal': true,
      'nilpotent-ideal': true,
      prime: false,
      'maximal-ideal': false,
      ...(props.reduced !== undefined ? { 'radical-ideal': props.reduced } : {}),
    },
    фактор: id,
  };
  if (props.reduced === true) ноль.радикал = ноль.id;
  const всё = {
    id: `${id}.1`,
    имя: `${R.имя} × ${S.имя}`,
    props: {
      'zero-ideal': false,
      'whole-ideal': true,
      proper: false,
      principal: true,
      'fin-gen-ideal': true,
      'nilpotent-ideal': false,
      prime: false,
      'maximal-ideal': false,
      'radical-ideal': true,
    },
    фактор: 'Zero',
    радикал: `${id}.1`,
  };
  return [
    ноль,
    каноническийИдеал(`${id}.L`, `${R.имя} × 0`, S),
    каноническийИдеал(`${id}.R`, `0 × ${S.имя}`, R),
    всё,
  ];
}

// Набор свойств сравнивается по ФИКСИРОВАННОМУ списку, а не по тем ключам,
// какие в записи случились: у объявленного кольца проставлены все тринадцать, у
// синтезированного — только посчитанные, и сравнение по ключам объявило бы
// новым всякое произведение подряд. Неизвестное — это третье значение, и
// различать его от «нет» здесь обязательно.
const ВСЕ_СВОЙСТВА = [...КОНЪЮНКТИВНЫЕ, ...ЛОЖНЫЕ];
const ключСвойств = (props) => ВСЕ_СВОЙСТВА.map((k) => `${k}=${props[k] ?? '?'}`).join(',');

export function синтезироватьПроизведенияКолец(кольца) {
  // Нулевой сомножитель произведение вырождает: R × 0 ≅ R, и такая запись —
  // это та же R под другим именем. Вырождение уже записано правилом, второй
  // раз его сюда тащить незачем.
  const годные = кольца.filter((R) => R.props?.['trivial-ring'] !== true && !R.синтез);
  const было = new Set(кольца.map((R) => ключСвойств(R.props ?? {})));
  const все = [];
  const вКаталог = [];
  const таблица = new Map();
  const идеалПо = new Map();
  for (const R of кольца) for (const i of R.идеалы ?? []) идеалПо.set(i.id, i);
  const нулевой = (X, поле) => идеалПо.get(X[поле])?.props?.['zero-ideal'] === true;

  for (const R of годные) {
    for (const S of годные) {
      // Произведение коммутативно как КОЛЬЦО, но не как терм: R × S и S × R
      // изоморфны, и второй порядок ничего нового не даёт. У групп было иначе
      // только потому, что там подгруппа N × M порядок сомножителей видит.
      if (S.id < R.id) continue;
      const id = `prod:${R.id}|${S.id}`;
      const props = свойстваПроизведенияКолец(R, S);
      const зап = {
        id,
        имя: `${R.имя} × ${S.имя}`,
        синтез: true,
        props,
        идеалы: идеалыПроизведения(id, R, S, props),
        заметка: `Синтезировано из ${R.имя} и ${S.имя}: свойства посчитаны по сомножителям, не объявлены.`,
      };
      // Нильрадикал и радикал Джекобсона известны ровно там, где они нулевые у
      // обоих сомножителей: N(R × S) = N(R) × N(S), J(R × S) = J(R) × J(S).
      // Смотрим на СЫРЫЕ ссылки, а не на разрешённые: синтез идёт до сборки
      // библиотеки, иначе синтезированные записи в неё не попадут.
      if (нулевой(R, 'нильрадикал') && нулевой(S, 'нильрадикал')) зап.нильрадикал = `${id}.0`;
      if (нулевой(R, 'джекобсон') && нулевой(S, 'джекобсон')) зап.джекобсон = `${id}.0`;
      все.push(зап);
      таблица.set(`${R.id}|${S.id}`, зап);
      таблица.set(`${S.id}|${R.id}`, зап);
      const ключ = ключСвойств(props);
      if (!было.has(ключ)) {
        было.add(ключ);
        вКаталог.push(зап);
      }
    }
  }
  return { все, вКаталог, таблица };
}
