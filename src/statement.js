// Печать задачи словами.
//
// Задача — это граф условия, набор посылок и цель. Отсюда получается текст
// вида «Пусть G — группа, N ⩽ G. Известно, что N нормальна, G/N периодична.
// Верно ли, что G периодична?»
//
// Две вещи, за которые здесь отвечает именно печать, а не движок:
//   * отрицание УНИВЕРСАЛЬНОГО терма ставится перед «всякая», а не после:
//     «не всякая подгруппа G делима», а не «всякая подгруппа G не делима».
//     Движок выводит ¬∀, и текст обязан утверждать ¬∀;
//   * у каждого участника сцены должно быть введение, иначе в условии
//     возникает буква из ниоткуда.

import { nameParticipants, render } from './term.js';

// Свойство на сорте с шаблоном `каждый` читается ПОЧЛЕННО — но не всякое.
// «Абелева» живёт и на объекте, и на системе, значит на системе это «у каждого
// члена». А «все отображения системы инъективны» живёт ТОЛЬКО на системе: это
// свойство самой системы, и подставлять в него «каждая группа системы 𝒟» —
// значит получить «все отображения системы каждая группа системы 𝒟
// инъективны». Различие простое: почленно читается то, что объявлено ещё и на
// сорте БЕЗ шаблона.
function почленноеСвойство(cat, sort, p) {
  if (!cat.sorts.get(sort)?.каждый || !p) return false;
  const где = Array.isArray(p.sort) ? p.sort : [p.sort];
  return где.some((s) => !cat.sorts.get(s)?.каждый);
}

export function атомТекст(graph, atom, names) {
  // Дизъюнкция печатается словом «или» и без скобок: «A тривиальна или
  // B тривиальна» — ровно так это и читается вслух.
  if (Array.isArray(atom.или)) {
    return atom.или.map((a) => атомТекст(graph, a, names)).join(' или ');
  }
  const p0 = atom.rel ? null : graph.cat.props.get(atom.p);
  const терм = (id) => {
    const sort = graph.get(id).sort;
    const шаблон = graph.cat.sorts.get(sort)?.каждый;
    const s = render(graph, id, names);
    const надо = atom.rel ? Boolean(шаблон) : почленноеСвойство(graph.cat, sort, p0);
    return надо ? шаблон.replace('%s', s) : s;
  };
  if (atom.rel) {
    const r = graph.cat.rels.get(atom.rel);
    if (!r) throw new Error(`нет отношения ${atom.rel}`);
    const s = (r.формула ?? '%1 ~ %2')
      .replace('%1', терм(atom.args[0]))
      .replace('%2', терм(atom.args[1]));
    if (atom.значение !== false) return s;
    return r.отрицание
      ? r.отрицание.replace('%1', терм(atom.args[0])).replace('%2', терм(atom.args[1]))
      : `неверно, что ${s}`;
  }
  const p = graph.cat.props.get(atom.p);
  if (!p) throw new Error(`нет свойства ${atom.p}`);
  // %a — объемлющий объект. Без него «[N, N] нормальна» не говорит, В ЧЁМ
  // нормальна, а это ровно разница между задачей 5.9 и её тривиальной частью.
  const подставить = (шаблон) => {
    const по = (rel) => {
      const t = graph.rel(atom.t, rel);
      return t === null || t === undefined ? '?' : терм(t);
    };
    return шаблон
      .replace('%s', терм(atom.t))
      .replace('%a', () => по('ambient'))
      .replace('%b', () => по('base'));
  };
  // У свойства бывает ОТДЕЛЬНАЯ почленная форма. Она нужна тем свойствам, чья
  // обычная фраза начинается не с подлежащего: подстановка «каждая группа
  // системы 𝒟» в «в %s извлекается корень любой степени» даёт нечитаемое «в
  // каждая группа системы 𝒟 извлекается корень». Русский падеж — не мелочь:
  // условие читает человек, и сломанная фраза стоит ему доверия ко всей выдаче.
  const почленно = почленноеСвойство(graph.cat, graph.get(atom.t)?.sort, p);
  const фраза = (почленно && p.почленная) || p.фраза || `%s: ${p.id}`;
  const отрицание = (почленно && p['почленное-отрицание']) || p.отрицание;
  const s = подставить(фраза);
  if (atom.значение === false) {
    // Всеобщность у нас выражена ВВЕДЕНИЕМ («Пусть N ⩽ G»), а не самим термом,
    // поэтому отрицание — это отрицание свойства. Оговорка нужна, потому что
    // в прошлом проекте термы бывали универсальными («всякая подгруппа G»), и
    // там отрицание обязано было вставать ПЕРЕД «всякая»: ¬∀, а не ∀¬.
    return отрицание ? подставить(отрицание) : `неверно, что ${s}`;
  }
  return s;
}

function введение(graph, id, names) {
  const n = graph.get(id);
  const sort = graph.cat.sorts.get(n.sort);
  const шаблон = sort?.введение ?? `%s — ${sort?.имя ?? n.sort}`;
  const имя = names.get(id) ?? render(graph, id, names);
  const под = (rel) => {
    const t = graph.rel(id, rel);
    return t === null || t === undefined ? '?' : render(graph, t, names);
  };
  return шаблон
    .replace('%s', имя)
    .replace('%a', () => под('ambient'))
    .replace('%d', () => под('dom'))
    .replace('%c', () => под('cod'))
    // %b — кольцо, над которым живёт объект. В двусортной категории без него
    // введение «M — модуль» не сказало бы главного: над ЧЕМ модуль.
    .replace('%b', () => под('base'));
}

export function задачаТекст(graph, { участники, посылки = [], цель }) {
  // Цели может не быть вовсе: у вопроса «вычислите» спрашивают величину
  // терма, а не истинность утверждения, и условие собирается тем же кодом.
  const атомы = цель ? [...посылки, цель] : [...посылки];
  const узлыАтома = (a) => (Array.isArray(a.или)
    ? a.или.flatMap(узлыАтома)
    : (a.rel ? a.args : [a.t]));
  const корни = [...участники, ...атомы.flatMap(узлыАтома)];
  const names = nameParticipants(graph, корни);

  // Вершины под «существует» не вводятся как данные: они и есть то, что надо
  // предъявить, поэтому уезжают внутрь вопроса вместе со своими свойствами.
  const есть = участники.filter((id) => graph.get(id).quant === 'exists');
  const все = участники.filter((id) => graph.get(id).quant !== 'exists');
  const свойстваУзла = (id) =>
    Object.entries(graph.get(id).props ?? {})
      .map(([prop, значение]) => атомТекст(graph, { p: prop, t: id, значение }, names));

  const сцена = все.map((id) => введение(graph, id, names));
  const факты = [...все.flatMap(свойстваУзла), ...посылки.map((a) => атомТекст(graph, a, names))];

  const части = [];
  if (сцена.length) части.push(`Пусть ${сцена.join(', ')}.`);
  if (факты.length) части.push(`Известно, что ${факты.join(', ')}.`);

  if (!цель) return { текст: части.join(' '), names };
  if (есть.length) {
    const кто = есть.map((id) => введение(graph, id, names)).join(' и ');
    const условия = [...есть.flatMap(свойстваУзла), атомТекст(graph, цель, names)];
    части.push(`Верно ли, что существует ${кто}, для которой ${условия.join(' и ')}?`
      + ' Докажите или опровергните.');
  } else {
    части.push(`Верно ли, что ${атомТекст(graph, цель, names)}? Докажите или опровергните.`);
  }
  return { текст: части.join(' '), names };
}
