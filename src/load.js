const here = dirname(fileURLToPath(import.meta.url));
export const DATA = join(here, '..', 'data');

export function category(id) {
  const raw = JSON.parse(readFileSync(join(DATA, `${id}.json`), 'utf8'));
  const cat = requireClean(loadCategory(raw));
  // ИМПОРТ ЧУЖОЙ КАТЕГОРИИ (пункт C1). Раздел объявляет, какие сорта он берёт
  // из другого раздела, и получает оттуда свойства, конструкции и правила —
  // вместо того, чтобы копировать по шесть свойств руками. Подробно — в
  // src/импорт.js.
  for (const з of raw.импорт ?? []) {
    const чужая = requireClean(loadCategory(
      JSON.parse(readFileSync(join(DATA, `${з.раздел}.json`), 'utf8')),
    ));
    импортироватьСорта(cat, чужая, з.сорта ?? []);
  }
  // Правила проверяются на язык ПОСЛЕ импорта: свои правила раздела вправе
  // говорить о импортированных свойствах («группа Галуа циклична»), и до
  // импорта язык ещё не полон. Правило, сославшееся на несуществующее
  // свойство, не срабатывает никогда и делает это молча — поэтому проверка и
  // появилась (см. `проверитьЯзыкПравил` в src/schema.js).
  const беды = проверитьЯзыкПравил(cat);
  if (беды.length) {
    throw new Error([`категория ${id}: правила говорят на языке, которого нет:`, ...беды].join('\n  '));
  }
  return cat;
}

// Библиотека конкретных групп, собранная по рецептам. Мелкие вперёд:
// контрпример почти всегда мелкий, и искать его надо с них.
export function каталогГрупп(опции = {}) {
  const { бесконечные = true, полный = false } = опции;
  const raw = JSON.parse(readFileSync(join(DATA, 'groups.json'), 'utf8'));
  const конечные = [...raw.группы]
    .sort((a, b) => a.порядок - b.порядок)
    .map((z) => группаПоИмени(z.id, raw.группы));
  if (!бесконечные) return конечные;
  const записи = JSON.parse(readFileSync(join(DATA, 'infinite.json'), 'utf8')).объекты;
  const сем = JSON.parse(readFileSync(join(DATA, 'infinite.json'), 'utf8')).семейства ?? [];
  const сист = JSON.parse(readFileSync(join(DATA, 'infinite.json'), 'utf8')).системы ?? [];
  // Произведения синтезируются ДО связывания: дальше они живут как обычные
  // записи, и связыватель проверяет их наравне со всеми. В БИБЛИОТЕКУ идут не
  // все — только те, чей набор свойств нов; остальные нужны лишь затем, чтобы
  // терм prod(X, Y) стал вычислимым.
  let вКаталог = [];
  if (опции.произведения !== false) {
    const син = синтезироватьПроизведения(записи, конечные);
    записи.push(...син.все);
    вКаталог = син.вКаталог;
  }
  const своб = JSON.parse(readFileSync(join(DATA, 'infinite.json'), 'utf8')).свободные ?? [];
  const { беды } = связать(записи, конечные, сем, сист, своб);
  if (беды.length) throw new Error('data/infinite.json:' + String.fromCharCode(10) + '  ' + беды.join(String.fromCharCode(10) + '  '));
  // Бесконечные идут ПОСЛЕ конечных: контрпример чаще мелкий и конечный,
  // и искать его надо с них. Синтезированные произведения, не прошедшие отбор,
  // в библиотеку не попадают — они остались связаны и вычислимы, но примерами
  // не предлагаются.
  const объявленные = записи.filter((з) => !з.синтез);
  // `полный` нужен сверщику: произведения, не взятые в библиотеку, всё равно
  // участвуют в вычислениях как значения термов, и правила обязаны быть
  // проверены и на них — иначе проверяется не то, что работает.
  if (полный) return [...конечные, ...записи, ...сем, ...сист];
  return [...конечные, ...объявленные, ...вКаталог, ...сем, ...сист];
}

// Каталог для категории модулей. Модули — это абелевы группы уже собранного
// каталога: ни одной новой таблицы умножения строить не надо, потому что
// каждое наше кольцо действует через ℤ.
export function каталогМодулей(опции = {}) {
  const группы = каталогГрупп(опции);
  // Модуль над ℤ — это АБЕЛЕВА группа, и проверять это надо вычислением, а не
  // наличием пометки: у посчитанных групп пометок нет вовсе, и фильтр по ним
  // молча пропускал в библиотеку модулей S₃ и A₅.
  const годится = (x) => {
    if (x.семейство || x.система) return false;
    return x.бесконечная ? x.props?.abelian === true : абелева(x);
  };
  const модули = группы.filter(годится)
    .map((x) => (x.бесконечная ? { вид: 'имя', зап: x } : { вид: 'группа', G: x }));
  return { кольца: кольца(join(DATA, 'rings.json')), модули, группы };
}

// Библиотека топологии: конечные пространства перечисляются целиком (они же
// предпорядки), бесконечные объявляются. Порядок тот же, что у групп, —
// мелкие вперёд: контрпример чаще всего мелкий.
export function каталогПространств({ доТочек = 4 } = {}) {
  const записи = JSON.parse(readFileSync(join(DATA, 'top-infinite.json'), 'utf8')).объекты;
  // Перенесённое из старого Генератора лежит отдельным файлом: так видно,
  // что объявлено рукой, а что пришло извне и проверено сверкой.
  const извне = join(DATA, 'top-pibase.json');
  if (existsSync(извне)) записи.push(...JSON.parse(readFileSync(извне, 'utf8')).объекты);
  const { конечные, беды } = собратьБиблиотеку(записи, доТочек);
  if (беды.length) throw new Error('data/top-infinite.json:' + String.fromCharCode(10) + '  ' + беды.join(String.fromCharCode(10) + '  '));
  return [...конечные, ...записи];
}

// Библиотека колец. Ничего не вычисляется: каждое кольцо, его идеалы и
// гомоморфизмы объявлены рукой, а сверщик tools/check-ring.mjs гоняет по ним
// всю базу. Каталог групп нужен ради кросс-категорных ссылок: R^× и R⁺ — это
// настоящие группы из группового каталога, а не отдельные записи.
export function каталогКолец(опции = {}) {
  const данные = JSON.parse(readFileSync(join(DATA, 'ring-lib.json'), 'utf8'));
  const группы = опции.группы ?? каталогГрупп();
  // Произведения синтезируются ДО связывания: дальше они живут обычными
  // записями, и связыватель проверяет их наравне со всеми.
  const син = опции.произведения === false
    ? { все: [], вКаталог: [], таблица: new Map() }
    : синтезироватьПроизведенияКолец(данные.кольца);
  const объявленные = [...данные.кольца];
  данные.кольца.push(...син.все);
  // Многочлены и матрицы синтезируются ПОСЛЕ произведений и до связывания: над
  // произведением R[x] и M₂(R) так же осмысленны, как над объявленным кольцом,
  // и теоремы для них те же. Ссылку `поли`/`матрицы` синтез проставляет сам —
  // иначе запись есть, а терм `poly(R)` по-прежнему невычислим.
  const син2 = опции.произведения === false
    ? { все: [], вКаталог: [], поли: new Map(), матрицы: new Map() }
    : синтезироватьМногочленыИМатрицы(данные.кольца);
  for (const [идОснования, зап] of син2.поли) {
    const R = данные.кольца.find((x) => x.id === идОснования);
    if (R && !R.поли) R.поли = зап.id;
  }
  for (const [идОснования, зап] of син2.матрицы) {
    const R = данные.кольца.find((x) => x.id === идОснования);
    if (R && !R.матрицы) R.матрицы = зап.id;
  }
  данные.кольца.push(...син2.все);
  // Канонические морфизмы — последними: им нужны и кольца, и ссылки `поли`,
  // `матрицы`, которые проставил синтез выше. Объявленных гомоморфизмов было
  // 24, и это была главная причина бедности схем «алгебра» и «гомоморфизм»:
  // условия на морфизм не находили ни одного примера.
  //
  // Синтез идёт ТОЛЬКО по кольцам каталога, а не по всем 2300. Причина
  // измерена: по всем выходит 9053 морфизма, из которых в примеры попадают 191
  // (кандидаты `choose-ring-mor` отбираются по обоим концам, а концы должны
  // быть в каталоге), зато сверка колец перестаёт укладываться в двадцать
  // минут — правила про морфизмы прогоняются по каждому.
  if (опции.произведения !== false) {
    const вКаталоге = [...объявленные, ...син.вКаталог, ...син2.вКаталог];
    данные.морфизмы = [...(данные.морфизмы ?? []),
      ...синтезироватьМорфизмыКолец(вКаталоге, данные.морфизмы ?? [])];
  }
  const б = собратьКольца(данные, группы);
  if (б.беды.length) throw new Error('data/ring-lib.json:' + String.fromCharCode(10) + '  ' + б.беды.join(String.fromCharCode(10) + '  '));
  for (const [ключ, зап] of син.таблица) б.произведения.set(ключ, зап);
  //  нужен сверщику: произведения, не взятые в библиотеку, всё равно
  // участвуют в вычислениях как значения термов, и правила обязаны быть
  // проверены и на них — иначе проверяется не то, что работает.
  if (!опции.полный) б.кольца = [...объявленные, ...син.вКаталог, ...син2.вКаталог];
  // Каталог ГРУПП кладётся в кольцевой каталог целиком: без него перебор не
  // сможет взять группу для группового кольца. Это не дублирование — это тот
  // же список, и кросс-категорная конструкция обязана видеть ровно его.
  б.группы = группы;
  return б;
}

// Библиотека полей и расширений. Ничего не вычисляется; каталог групп нужен
// ради кросс-категорных ссылок — группа Галуа, мультипликативная и
// аддитивная группы берутся оттуда настоящими группами.
export function каталогПолей(опции = {}) {
  const данные = JSON.parse(readFileSync(join(DATA, 'fld-lib.json'), 'utf8'));
  const группы = опции.группы ?? каталогГрупп();
  // Рациональные функции и алгебраическое замыкание синтезируются ДО
  // связывания: их свойства считаются по теоремам, и дальше они живут обычными
  // записями, которые связыватель проверяет наравне со всеми. Ссылки
  // `рациональные`/`замыкание` синтез проставляет сам — иначе запись есть, а
  // терм по-прежнему невычислим.
  const объявленныеПоля = [...данные.поля];
  const син = опции.синтез === false
    ? { поля: [], расширения: [], вКаталог: [], рациональные: new Map(), замыкания: new Map() }
    : синтезироватьПоля(данные.поля, данные.расширения);
  for (const [идОснования, зап] of син.рациональные) {
    const K = данные.поля.find((x) => x.id === идОснования);
    if (K && !K.рациональные) K.рациональные = зап.id;
  }
  for (const [идОснования, зап] of син.замыкания) {
    const K = данные.поля.find((x) => x.id === идОснования);
    if (K && !K.замыкание) K.замыкание = зап.id;
  }
  данные.поля.push(...син.поля);
  данные.расширения.push(...син.расширения);
  const б = собратьПоля(данные, группы);
  if (б.беды.length) throw new Error('data/fld-lib.json:' + String.fromCharCode(10) + '  ' + б.беды.join(String.fromCharCode(10) + '  '));
  return б;
}

// Каталог по идентификатору раздела. Одна развилка на весь проект: раньше
// такая же стояла в bin/gen.mjs и в tools/задачник.mjs, и новый раздел
// приходилось дописывать в три места, а забытое место молча отдавало каталог
// групп.
export function каталогРаздела(раздел, опции = {}) {
  if (раздел === 'mod') return каталогМодулей(опции);
  if (раздел === 'top') return каталогПространств(опции);
  if (раздел === 'ring') return каталогКолец(опции);
  if (раздел === 'fld') return каталогПолей(опции);
  return каталогГрупп(опции);
}
