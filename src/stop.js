// Уступка управления и жетон остановки.
//
// Два стоячих требования, из-за которых этот файл вообще есть:
//   * стадия, начавшая сообщением и замолчавшая на минуту, считается
//     сломанной — молчащая стадия неотличима от повисшей;
//   * никаких выдуманных потолков: обрыв бывает только по кнопке человека или
//     по его же настройке, и о нём объявляется вслух.
//
// Троттлинг по ВРЕМЕНИ, а не по числу шагов: шаги бывают разной цены, и
// «каждые 500 шагов» у дорогой стадии означает те же минуты молчания.

export function жетон() {
  return { стоп: false, причина: null };
}

export function makeYielder({ каждые = 60, тик = null, знак = null } = {}) {
  let последний = Date.now();
  return async function уступить(сообщение) {
    if (знак?.стоп) throw new ОстановленоЧеловеком(знак.причина ?? 'остановлено');
    const теперь = Date.now();
    const пора = теперь - последний >= каждые;
    // Сообщение о прогрессе передаётся всегда, а УСТУПАТЬ управление надо
    // по времени — иначе тысячи сообщений превращаются в тысячи макрозадач.
    // В обычном процессе setTimeout(0) почти бесплатен, но под `node --test`
    // он стоит миллисекунды, и перебор, считающийся 26 секунд, не заканчивался
    // за семь минут. Троттлинг по времени — это то, что и было задумано:
    // сообщение не повод отдавать кадр.
    if (тик && сообщение !== undefined) тик(сообщение);
    if (пора) {
      последний = теперь;
      await новыйКадр();
    }
  };
}

export class ОстановленоЧеловеком extends Error {}

function новыйКадр() {
  // setTimeout(0) в браузере отдаёт кадр отрисовке, в Node — просто макрозадачу.
  return new Promise((готово) => setTimeout(готово, 0));
}
