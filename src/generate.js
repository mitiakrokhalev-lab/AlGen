// СЛЕДОВАНИЯ МЕЖДУ ЛИТЕРАЛАМИ УСЛОВИЯ, посчитанные ОДИН РАЗ на схему.
//
// Зачем. Условие «A некоммутативно И не область» это то же условие, записанное
// длиннее: некоммутативное кольцо областью не бывает. У одного условия таких
// записей столько, сколько у него выводимых следствий, и каждая шла отдельной
// задачей. Замер: в разделе колец ТРЕТЬ бедности (1781 пробел из 5184 на схеме
// «алгебра») — ровно это. В группах меньше, но тоже есть: «G циклична и N не
// характеристична» давало 34 пустых пробела, хотя в циклической группе ВСЯКАЯ
// подгруппа характеристична.
//
// Почему считается здесь, а не на каждом условии. Проверять «выводится ли эта
// посылка из остальных» на каждом условии — значит пересобирать сцену на каждую
// посылку каждого условия: свойства записаны В УЗЛАХ графа, и вывод без
// посылки всё равно их видит, так что дешёвой проверки нет. Я это попробовал, и
// для перебора оказалось неподъёмно. А следование между ДВУМЯ литералами от
// условия не зависит вовсе — оно свойство БАЗЫ и СХЕМЫ, и считать его надо раз
// на схему: по одному выводу на литерал.
//
// Литералы берутся ПО ВСЕЙ СЦЕНЕ, а не внутри одной вершины, и это
// существенно: «G циклична» говорит про G, а следствие — про подгруппу N,
// и внутривершинная таблица такую пару не видит. Первая редакция этой
// проверки была именно внутривершинной и пропускала ровно такие случаи.
//
// Отсекается ПАРА, а не цепочка: условие из трёх посылок, где третья выводится
// лишь из двух первых вместе, здесь не ловится. Это честный предел дешёвой
// проверки; остаток считает `мера --лишние`.
function следованияСхемы(cat, схема, пулы) {
  const табл = new Set();
  for (const { имя, пул } of пулы) {
    for (const p of пул) {
      for (const знак of [true, false]) {
        let g;
        let имена;
        try {
          ({ g, имена } = построитьСхему(cat, схема, new Map([[имя, { [p]: знак }]])));
        } catch {
          continue;
        }
        const мир = вывести(g, []);
        if (мир.противоречие) continue;
        for (const { имя: имя2, пул: пул2 } of пулы) {
          const узел = имена.get(имя2);
          if (узел === undefined) continue;
          for (const q of пул2) {
            if (имя === имя2 && q === p) continue;
            const v = мир.знает({ p: q, t: узел });
            if (v === undefined) continue;
            табл.add(`${имя}|${p}:${знак}=>${имя2}|${q}:${v}`);
          }
        }
      }
    }
  }
  return табл;
}

// Есть ли в условии литерал, следующий из другого литерала этого же условия.
// Условие приходит картой «имя вершины → свойства».
function естьСледствие(табл, свойства) {
  const литералы = [];
  for (const [имя, props] of свойства) {
    for (const [p, v] of Object.entries(props)) литералы.push([имя, p, v]);
  }
  if (литералы.length < 2) return false;
  for (const [и1, p, з1] of литералы) {
    for (const [и2, q, з2] of литералы) {
      if (и1 === и2 && p === q) continue;
      if (табл.has(`${и1}|${p}:${з1}=>${и2}|${q}:${з2}`)) return true;
    }
  }
  return false;
}

// Подмножества пула размера не больше k. Границу задаёт человек; своих
// потолков здесь нет.
function подмножества(пул, k) {
  const out = [[]];
  const идти = (начало, набор) => {
    if (набор.length >= k) return;
    for (let i = начало; i < пул.length; i++) {
      набор.push(пул[i]);
      out.push([...набор]);
      идти(i + 1, набор);
      набор.pop();
    }
  };
  идти(0, []);
  return out;
}

function произведение(списки) {
  let out = [[]];
  for (const список of списки) {
    const next = [];
    for (const префикс of out) for (const x of список) next.push([...префикс, x]);
    out = next;
  }
  return out;
}

const ключАтома = (g, a) => {
  if (Array.isArray(a.или)) {
    return `или(${a.или.map((x) => ключАтома(g, x)).sort().join(",")})`;
  }
  return a.rel ? `${a.rel}#${g.get(a.args[0]).key}#${g.get(a.args[1]).key}` : `${a.p}@${g.get(a.t).key}`;
};

// Дизъюнктивные цели собираются из атомов с ОДНИМ И ТЕМ ЖЕ предикатом:
// «A тривиальна или B тривиальна», «F ⊆ H или H ⊆ F». Это не ограничение
// выразительности ради выразительности, а наблюдение: именно такой вид у
// дизъюнкций в задачнике, а перебор всех пар атомов возвёл бы число целей
// в квадрат.
function дизъюнкции(атомы, имяПоУзлу) {
  const поПредикату = new Map();
  for (const a of атомы) {
    const k = a.rel ?? a.p;
    if (!поПредикату.has(k)) поПредикату.set(k, []);
    поПредикату.get(k).push(a);
  }
  const out = [];
  for (const список of поПредикату.values()) {
    for (let i = 0; i < список.length; i++) {
      for (let j = i + 1; j < список.length; j++) {
        out.push({ или: [список[i], список[j]] });
      }
    }
  }
  return out;
}

// Знание базы о дизъюнкции: верна, если верна хоть одна часть; ложна, если
// ложны обе. Хорновский вывод дизъюнкций не доказывает, и это честно: он
// отвечает только когда одна из частей выводится целиком.
function знаетЦель(мир, цель) {
  if (!Array.isArray(цель.или)) return мир.знает(цель);
  const v = цель.или.map((a) => мир.знает(a));
  if (v.some((x) => x === true)) return true;
  if (v.every((x) => x === false)) return false;
  return undefined;
}

// Ответ базы на цель со словом «существует» — это СВИДЕТЕЛЬ, а не вывод.
// Импликациями существование не доказывается: «всякая тривиальная подгруппа
// абелева» ничего не говорит о том, есть ли тривиальная подгруппа. Зато если
// подставить вместо искомой вершины готовый терм — единичную подгруппу, центр,
// коммутант, ядро — и база подтвердит про него и посылки, и цель, то предъявлен
// именно свидетель. Так это и делается на бумаге.
function свидетельИзБазы(g, мир, узелЕ, цель, гипотезыЕ) {
  const сорт = g.get(узелЕ).sort;
  const связи = ['ambient', 'dom', 'cod', 'base'].map((k) => [k, g.rel(узелЕ, k)]);
  for (const кандидат of g.nodes) {
    if (кандидат.id === узелЕ) continue;
    if (кандидат.sort !== сорт) continue;
    if (g.cat.cons.get(кандидат.op)?.choice) continue; // другой выбор — не свидетель
    if (связи.some(([k, v]) => v !== null && g.rel(кандидат.id, k) !== v)) continue;

    const кэш = new Map();
    const подставить = (atom) => {
      if (atom.rel) {
        const args = atom.args.map((t) => подставитьТерм(g, t, узелЕ, кандидат.id, кэш));
        return args.some((x) => x === null) ? null : { ...atom, args };
      }
      const t = подставитьТерм(g, atom.t, узелЕ, кандидат.id, кэш);
      return t === null ? null : { ...atom, t };
    };

    let годится = true;
    for (const п of гипотезыЕ) {
      const a = подставить(п);
      if (!a || мир.знает(a) !== (п.значение !== false)) {
        годится = false;
        break;
      }
    }
    if (!годится) continue;
    const ц = подставить(цель);
    if (ц && мир.знает(ц) === (цель.значение !== false)) {
      return { узел: кандидат.id, глубина: мир.глубина(ц) ?? 0 };
    }
  }
  return null;
}

// Перестроить терм, заменив одну вершину другой. Если по дороге встретился
// ЧУЖОЙ выбирающий узел, подстановка отменяется: пересобрав его, мы получили
// бы другую подгруппу, а не ту же самую.
function подставитьТерм(g, id, из, в, кэш) {
  if (id === из) return в;
  if (кэш.has(id)) return кэш.get(id);
  const n = g.get(id);
  if (!n.args.length) return id;
  const args = n.args.map((a) => подставитьТерм(g, a, из, в, кэш));
  if (args.some((a) => a === null)) return null;
  if (args.every((a, i) => a === n.args[i])) return id;
  if (g.cat.cons.get(n.op)?.choice) return null;
  let out = null;
  try {
    out = g.apply(n.op, args);
  } catch {
    out = null;
  }
  кэш.set(id, out);
  return out;
}

// Про какие вершины спрашиваем. Пустой список значит «про все»: человек
// выбирает итоговый объект сам, и это первое, что он хочет сузить, когда схема
// перестаёт быть игрушечной.
function спрашиваем(атом, имяПоУзлу, цели) {
  if (!цели || !цели.length) return true;
  const узлы = атом.rel ? атом.args : [атом.t];
  return узлы.every((id) => цели.includes(имяПоУзлу.get(id)));
}

