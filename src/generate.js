function перемешать(массив, зерно) {
  const out = [...массив];
  let s = зерно >>> 0 || 1;
  const сл = () => ((s = (s * 1664525 + 1013904223) >>> 0) / 4294967296);
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(сл() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}
