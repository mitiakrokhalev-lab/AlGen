// ИМПОРТ ЧУЖОЙ КАТЕГОРИИ В СХЕМУ.
//
// Задача (пункт C1 плана). «Группа Галуа расширения K ⊆ L» сказать можно:
// конструкция `gal` возвращает `Grp.obj`, и кросс-категорность для этого и
// закладывалась. А «центр группы Галуа» сказать нельзя — чужой сорт в каждом
// разделе ЛИСТ: свойства на нём есть, конструкций из него нет, и цепочка
// обрывается на первом же шаге в чужую категорию.
//
// Как было до этого. В `data/fld.json` руками выписаны шесть групповых
// свойств — абелева, циклична, конечна, тривиальна, разрешима, проста. Это и
// есть та самая копия, про которую план говорит «не копировать по шесть
// свойств в каждый файл»: копия не только дублирует, она ещё и МОЛЧА
// отстаёт — в группах свойств шестнадцать, и десять из них в полях сказать
// нельзя, хотя группа Галуа ими обладает.
//
// Как теперь. Раздел объявляет в данных:
//
//   "импорт": [{ "раздел": "grp", "сорта": ["Grp.obj"] }]
//
// и получает ОТТУДА всё, что целиком живёт на импортированных сортах:
// свойства, конструкции и ПРАВИЛА. Правило берётся только тогда, когда все
// его сорта импортированы и все его свойства известны — иначе оно говорит о
// том, чего в этом разделе нет, и втаскивать его значило бы втащить половину
// чужой категории молча.
//
// Что НЕ импортируется и почему:
//
//   * конструкции БЕЗ ВХОДОВ, то есть выбирающие чужой объект на пустом месте
//     (`choose-group`). «Возьмите группу со свойствами» в разделе полей
//     означало бы, что перебор начинает перебирать и группы, а мы пришли сюда
//     за полями. Группа в схеме полей появляется только как РЕЗУЛЬТАТ: группа
//     Галуа, мультипликативная, аддитивная. А вот выбирающая конструкция С
//     ВХОДОМ импортируется: «возьмите подгруппу группы Галуа» новых объектов в
//     перебор не вносит, и без неё соответствие Галуа не выразить;
//   * конструкции, у которых хоть один вход или выход вне импортированных
//     сортов. Фактор по подгруппе требует `Grp.sub`, и импортировать его
//     значило бы импортировать весь подобъектный слой;
//   * отношения. `iso` групп перенесла бы свойства, но её входы — тот же
//     `Grp.obj`, и работать она будет, если её импортировать явно; пока
//     незачем, и лишнего не берём.
//
// Важное про МОДЕЛЬ. Импортированная конструкция вычисляется моделью ТОЙ
// категории, откуда пришла: центр группы Галуа считает модель групп, а не
// модель полей. Чтобы это было видно в коде, импортированные конструкции
// помечаются полем `чужое` с идентификатором родной категории, и
// `вычислитьУзел` по этой метке и отправляет узел в нужную модель.

const сортаАтома = (cat, a) => {
  const имена = [];
  if (a.p) имена.push(a.p);
  return имена;
};

// Все сорта, упомянутые в сцене правила.
function сортаСцены(scene) {
  const out = [];
  for (const v of Object.values(scene ?? {})) {
    out.push(typeof v === 'string' ? v : v.sort);
  }
  return out;
}

export function импортироватьСорта(cat, чужая, сорта) {
  const нужные = new Set(сорта);
  const добавлено = { свойства: 0, конструкции: 0, правила: 0, отношения: 0 };

  // 1. СВОЙСТВА. Берутся все, объявленные на импортированном сорте. Если
  // такое свойство в разделе уже есть (руками скопировано), оставляем своё:
  // в нём может быть другая формулировка фразы, и менять её импорт не должен.
  for (const p of чужая.props.values()) {
    const свои = String(p.sort).split(',').map((x) => x.trim());
    if (!свои.some((s) => нужные.has(s))) continue;
    if (cat.props.has(p.id)) continue;
    cat.props.set(p.id, { ...p, импортировано: чужая.id });
    добавлено.свойства++;
  }

  // 2. КОНСТРУКЦИИ, целиком живущие на импортированных сортах.
  for (const c of чужая.cons.values()) {
    if (cat.cons.has(c.id)) continue;
    const входы = (c.in ?? []).map((s) => s.sort);
    const выход = typeof c.out === 'string' ? c.out : c.out?.sort;
    // Конструкция БЕЗ входов вводила бы в перебор чужой свободный объект:
    // «возьмите группу со свойствами» в разделе полей означало бы, что
    // перебор начинает перебирать группы, а мы пришли за полями. Группа
    // здесь появляется только как РЕЗУЛЬТАТ: группа Галуа, мультипликативная,
    // аддитивная.
    //
    // А вот выбирающая конструкция С ВХОДОМ — дело другое, и первая редакция
    // этого места ошибочно отсекала и её: «возьмите подгруппу H группы Галуа»
    // никаких новых объектов в перебор не вносит, подгруппа берётся у уже
    // построенной группы — ровно как идеал у кольца. Без неё соответствие
    // Галуа не выразить вовсе: его левая половина начинается со слов «пусть
    // H — подгруппа группы Галуа».
    if (!входы.length) continue;
    if (!входы.every((s) => нужные.has(s)) || !нужные.has(выход)) continue;
    cat.cons.set(c.id, { ...c, чужое: чужая.id });
    добавлено.конструкции++;
  }

  // 3. ПРАВИЛА. Только те, что целиком выражаются в импортированном языке.
  const известно = (a) => {
    if (a.rel) return cat.rels.has(a.rel);
    return cat.props.has(a.p);
  };
  for (const r of чужая.rules ?? []) {
    const сорта2 = сортаСцены(r.scene);
    if (!сорта2.length || !сорта2.every((s) => нужные.has(s))) continue;
    const атомы = [...(r.if ?? []), r.then];
    if (!атомы.every(известно)) continue;
    // Правило вправе говорить о ТЕРМЕ (`{op: 'center', args: ['X']}`), и тогда
    // его конструкция тоже обязана быть импортирована — иначе правило
    // сослалось бы на операцию, которой в разделе нет.
    const термОк = атомы.every((a) => {
      const термы = a.rel ? a.args : [a.t];
      return термы.every((t) => typeof t === 'string' || !t?.op || cat.cons.has(t.op));
    });
    if (!термОк) continue;
    if ((cat.rules ?? []).some((x) => x.id === r.id)) continue;
    cat.rules.push({ ...r, импортировано: чужая.id });
    добавлено.правила++;
  }
  // Кэш разобранных правил мог быть построен до импорта.
  delete cat._правила;
  delete cat._переносимые;
  void сортаАтома;
  return добавлено;
}
