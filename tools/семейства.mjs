// Вопросы о ПАРАМЕТРЕ: «при каких n верно, что …».
//
//   node tools/семейства.mjs                        — все семейства, все схемы
//   node tools/семейства.mjs --семейство C          — только циклические
//   node tools/семейства.mjs --схема автоморфизмы   — только одна схема
//   node tools/семейства.mjs --до 60                — докуда идти по параметру
//
// Чем это отличается от перебора по корзинам. Там вопрос — «верно ли», и ответ
// один на всё условие. Здесь вопрос — «ПРИ КАКИХ n», и ответ есть МНОЖЕСТВО
// значений параметра. Такого вопроса в языке свойств нет вовсе: свойство либо
// верно у объекта, либо нет, а «верно при n = 1, 2, 4 и при n = pᵏ» — это
// утверждение о семействе, а не об объекте.
//
// Отвечает на него не база, а МОДЕЛЬ: Cₙ строится для каждого n и
// проверяется. Поэтому ответ всегда с оговоркой «среди проверенных n», и
// оговорка эта честная — закономерность, увиденная до n = 60, теоремой не
// становится. Зато она ровно того рода, который человек потом доказывает: «при
// каких n группа Aut(Cₙ) циклична» — настоящий вопрос с настоящим ответом.
//
// Схемы берутся только те, где СВОБОДНА ОДНА вершина — сам объект. Будь в схеме
// ещё и подгруппа, на каждое n пришлось бы много привязок, и «при каких n»
// распалось бы на «при каких n и какой подгруппе»: другой вопрос, другая форма.

import { category } from '../src/load.js';
import { таблицаПримеров, ключПоИмени, НЕИЗВЕСТНО } from '../src/witness.js';
import { СЕМЕЙСТВА, членыСемейства } from '../src/model/семейства.js';
import { ПОРАЗДЕЛАМ } from '../src/схемы.js';
import { построитьСхему } from '../src/scene.js';
import { задачаТекст } from '../src/statement.js';

const арг = (имя, по) => {
  const i = process.argv.indexOf(`--${имя}`);
  return i >= 0 ? process.argv[i + 1] : по;
};
const толькоСем = арг('семейство', null);
const толькоСхема = арг('схема', null);
const до = Number(арг('до', 40));
const предельныйПорядок = Number(арг('порядок', 130));

const cat = category('grp');

// Схема годится, если свободна ровно одна вершина и она — объект.
function годнаяСхема(схема) {
  const свободные = схема.узлы.filter((n) => n.op === 'given' || n.op === 'named'
    || cat.cons.get(n.op)?.choice);
  return свободные.length === 1 && свободные[0].op === 'given';
}

const простое = (n) => {
  if (n < 2) return false;
  for (let d = 2; d * d <= n; d++) if (n % d === 0) return false;
  return true;
};
const степеньПростого = (n) => {
  if (n < 2) return false;
  for (let p = 2; p <= n; p++) {
    if (n % p !== 0) continue;
    let m = n;
    while (m % p === 0) m /= p;
    return m === 1;
  }
  return false;
};

// Как назвать множество значений параметра. Узнаём только те закономерности,
// которые ЧЕЛОВЕК потом может проверить: чётность, простота, степень простого,
// явный список. Если ни одна не подошла — печатаем список как он есть и не
// притворяемся, что нашли закон.
function описать(верные, определённые) {
  const мн = new Set(верные);
  const все = определённые;
  const совпало = (пред) => все.every((n) => мн.has(n) === пред(n));
  if (совпало((n) => n % 2 === 0)) return 'ровно при чётных n';
  if (совпало((n) => n % 2 === 1)) return 'ровно при нечётных n';
  if (совпало(простое)) return 'ровно при простых n';
  if (совпало((n) => !простое(n))) return 'ровно при составных n (и при n = 1)';
  if (совпало(степеньПростого)) return 'ровно при n — степени простого';
  // Классический вид: n = 1, 2, 4, pᵏ, 2pᵏ при нечётном простом p. Именно так
  // описываются n, при которых у ℤ/n есть первообразный корень, — и ответ на
  // «при каких n группа Aut(Cₙ) циклична» выглядит ровно этим множеством.
  // Без имени он печатается списком, и закономерность в нём не видна.
  const первообразный = (n) => {
    if (n === 1 || n === 2 || n === 4) return true;
    let m = n;
    if (m % 2 === 0) m /= 2;
    if (m % 2 === 0) return false;   // делится на 4 и больше четырёх
    return степеньПростого(m) && m > 1;
  };
  if (совпало(первообразный)) return 'ровно при n = 1, 2, 4, pᵏ, 2pᵏ (p — нечётное простое)';
  const порог = все.find((n) => мн.has(n) && все.filter((m) => m >= n).every((m) => мн.has(m)));
  if (порог !== undefined && верные.length && верные[0] === порог) return `ровно при n ⩾ ${порог}`;
  if (верные.length <= 8) return `при n ∈ {${верные.join(', ')}}`;
  const нет = все.filter((n) => !мн.has(n));
  if (нет.length <= 8) return `при всех n, кроме ${нет.join(', ')}`;
  return `при n ∈ {${верные.slice(0, 10).join(', ')}, …}`;
}

const находки = [];
// Склейка по множеству значений — главный отбор этого инструмента: без неё
// один факт о тривиальном центре выдаётся шестью разными словами.
const склеено = new Set();
const повторАтома = new Set();

for (const [ключ, сем] of Object.entries(СЕМЕЙСТВА)) {
  if (толькоСем && ключ !== толькоСем) continue;
  const члены = членыСемейства(ключ, { от: 1, до, предельныйПорядок });
  if (члены.length < 4) continue;

  for (const [имяСхемы, схема] of Object.entries(ПОРАЗДЕЛАМ.grp)) {
    if (толькоСхема && имяСхемы !== толькоСхема) continue;
    if (!годнаяСхема(схема)) continue;

    // Для каждого n — своя таблица из одной строки: каталог из одной группы.
    const поАтому = new Map();
    const параметры = [];
    for (const G of члены) {
      let т;
      try {
        т = await таблицаПримеров({ cat, схема, каталог: [G], предел: 4, предельныйПорядок });
      } catch {
        continue;
      }
      if (!т.строки.length) continue;
      параметры.push(G.параметр);
      const r = т.строки[0];
      т.атомы.forEach((a, i) => {
        const ключА = ключПоИмени(a, т.имяПоУзлу);
        if (т.постоянные.has(ключА)) return; // слепое свойство — проверять было нечем
        if (!поАтому.has(ключА)) поАтому.set(ключА, { атом: a, значения: new Map() });
        поАтому.get(ключА).значения.set(G.параметр, r.биты[i]);
      });
    }
    if (параметры.length < 4) continue;

    const { g, имена } = построитьСхему(cat, схема);
    const имяПоУзлу = new Map([...имена].map(([имя, id]) => [id, имя]));
    const участники = схема.узлы.filter((n) => n.op === 'given').map((n) => имена.get(n.имя));

    for (const { атом, значения } of поАтому.values()) {
      const определённые = [...значения.entries()].filter(([, b]) => b !== НЕИЗВЕСТНО).map(([n]) => n);
      if (определённые.length < 4) continue;
      const верные = определённые.filter((n) => значения.get(n) === 1);
      // Всегда верно или всегда ложно — это обычное утверждение, и его место в
      // переборе по корзинам, а не здесь.
      if (!верные.length || верные.length === определённые.length) continue;
      const текст = задачаТекст(g, { участники, посылки: [], цель: атом }).текст
        .replace(/Верно ли, что (.*)\? Докажите или опровергните\./u, 'При каких n верно, что $1?');
      // СКЛЕЙКА. Про тривиальную группу верно всё сразу, и «Z(G) тривиальна»,
      // «Z(G) свободна», «Z(G) без кручения» дают одно и то же множество n —
      // это один факт, пересказанный шесть раз. Поэтому атомы с одинаковым
      // множеством значений на ОДНОЙ вершине склеиваются. Склеиваются и
      // ДОПОЛНИТЕЛЬНЫЕ множества: «Z(G) тривиальна при нечётных» и «Z(G)
      // проста при чётных» — тоже один факт.
      // Склейка идёт по КЛЮЧУ ТЕРМА, а не по имени вершины: у абелевой группы
      // Z(G) и есть G, вырождение их отождествило, и «G проста» с «Z(G)
      // проста» — буквально одно утверждение.
      const вершина = (атом.rel ? атом.args : [атом.t]).map((id) => g.get(id).key).join(',');
      const свой = верные.join('.');
      const чужой = определённые.filter((n) => !верные.includes(n)).join('.');
      const ключСклейки = `${вершина}|${свой < чужой ? свой : чужой}`;
      if (склеено.has(ключСклейки)) continue;
      склеено.add(ключСклейки);
      // И тот же атом на разных схемах — тоже повтор: «G проста» одинаково
      // звучит в схеме «объект», «центр» и «автоморфизмы».
      // Общий повтор ловится БЕЗ вершины: если одно и то же свойство верно
      // ровно при тех же n, это один вопрос для читателя, даже если в одной
      // схеме он про G, а в другой про Z(G). На сорока значениях параметра
      // случайное совпадение множеств неправдоподобно.
      const ключАтома = `${атом.rel ?? атом.p}|${свой}`;
      if (повторАтома.has(ключАтома)) continue;
      повторАтома.add(ключАтома);
      находки.push({
        семейство: сем.имя,
        подпись: сем.подпись,
        схема: имяСхемы,
        текст,
        ответ: описать(верные, определённые),
        проверено: `${Math.min(...определённые)}…${Math.max(...определённые)}`,
        сколько: определённые.length,
      });
    }
  }
}

// Закономерность, названная словом («ровно при чётных n»), интереснее списка:
// её можно пытаться доказать. Поэтому сперва они.
const названо = (x) => (x.ответ.startsWith('ровно') ? 0 : 1);
находки.sort((a, b) => названо(a) - названо(b) || b.сколько - a.сколько);

console.log(`вопросов о параметре: ${находки.length}`);
for (const x of находки.slice(0, Number(арг('сколько', 40)))) {
  console.log(`\n[${x.семейство}, схема «${x.схема}»] ${x.текст}`);
  console.log(`    ${x.ответ}  (проверено n = ${x.проверено}, ${x.сколько} значений)`);
}
