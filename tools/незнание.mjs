// Сколько модель НЕ ЗНАЕТ — по клеткам таблицы примеров.
//
//   node tools/незнание.mjs                 — по всем разделам
//   node tools/незнание.mjs --раздел ring   — по одному
//   node tools/незнание.mjs --подробно      — с разбивкой по вершинам схемы
//
// Зачем отдельно от меры. «Бедность библиотеки» в мере — это НЕ «модель не знает
// объекта». Бедность считается на КОНКРЕТНОМ наборе посылок: подходящих
// примеров мало или они неразличимы нашим языком. А незнание — другое и
// измеряется иначе: берём таблицу «привязка × атом» и считаем долю клеток, где
// стоит НЕИЗВЕСТНО. Клетка пуста по одной из двух причин:
//
//   * терм НЕВЫЧИСЛИМ на этой привязке — `free`, `pushout`, `semidirect`,
//     `pi1` не выражены в модели вовсе, а у объявленной бесконечной группы
//     вычислимо только то, что записано рукой;
//   * свойство не определено математически — у ненормальной подгруппы нет
//     фактора, и это не пробел знания, а отсутствие объекта.
//
// Разделить их таблица не умеет (в ней и то, и другое — НЕИЗВЕСТНО), поэтому
// печатается разбивка по ВЕРШИНАМ: вершина, чёрная почти целиком, — это первый
// случай, и лечится он вычислимостью конструкции.

import { category, каталогРаздела } from '../src/load.js';
import { таблицаПримеров, ключПоИмени, НЕИЗВЕСТНО } from '../src/witness.js';
import { ПОРАЗДЕЛАМ } from '../src/схемы.js';

const арг = (имя, по) => {
  const i = process.argv.indexOf(`--${имя}`);
  return i >= 0 ? process.argv[i + 1] : по;
};
const толькоРаздел = арг('раздел', null);
const толькоСхема = арг('схема', null);
const подробно = process.argv.includes('--подробно');

// Предел порядка ПО СХЕМЕ. Цена предела — не построение таблицы умножения (её
// размер проверяется заранее), а перечисление ПОДГРУПП результата: свойство
// «проста» требует всех подгрупп, и для группы порядка 144 это минуты. Поэтому
// у схем, где результат — произведение двух свободных вершин, предел свой.
// Число примеров ПО СХЕМЕ. На схеме морфизмов таблица при пределе порядка 200
// перестаёт влезать в 20 000 строк, и все её пробелы становятся «обрезано» —
// то есть мнимыми. Шестьдесят тысяч строк она занимает целиком, считается за
// три минуты, и 956 мнимых пробелов превращаются в 529 бедных и 390 кандидатов.
// Число примеров ПО СХЕМЕ. Пусто, и это итог, а не недоделка.
//
// Здесь стояли три бюджета — `grp/морфизм` 60 000, `ring/групповое` 40 000,
// `mod/гомоморфизм` 60 000, — и каждый был поставлен после того, как рост
// библиотеки переполнял таблицу и все пробелы схемы становились мнимыми. После
// склейки строк в РАЗЛИЧНЫЕ ПРОФИЛИ (см. src/witness.js) они стали не нужны:
// замерено, что при бюджете раздела все три схемы считаются без обрезания
// вовсе — `ring/групповое` за 23 с, `grp/морфизм` за 31 с, `mod/гомоморфизм`
// за 80 с. А бюджет 60 000 при этом СТАЛ ВРЕДЕН: раздел групп на нём падал по
// памяти, и его схемы после морфизмов не считались.
//
// Правило на будущее: бюджет сверх раздельного — признак того, что таблица
// хранит лишнее, а не того, что схема трудная.
const ПРИМЕРОВ_СХЕМЫ = {};


const ПОРЯДОК_СХЕМЫ = {
  'grp/произведение': 24,
  'grp/пределы': 24,
};

const БЮДЖЕТ = {
  grp: { примеров: 20000, порядок: 200 },
  mod: { примеров: 20000, порядок: 200 },
  top: { примеров: 8000, порядок: 4 },
  ring: { примеров: 8000, порядок: 200 },
  fld: { примеров: 20000, порядок: 200 },
};

let всегоКлеток = 0;
let всегоПусто = 0;

for (const раздел of (толькоРаздел ? [толькоРаздел] : Object.keys(БЮДЖЕТ))) {
  const cat = category(раздел);
  const каталог = каталогРаздела(раздел);
  for (const [имяСхемы, схема] of Object.entries(ПОРАЗДЕЛАМ[раздел] ?? {})) {
    if (толькоСхема && имяСхемы !== толькоСхема) continue;
    let т;
    try {
      т = await таблицаПримеров({
        cat, схема, каталог,
        предел: ПРИМЕРОВ_СХЕМЫ[`${раздел}/${имяСхемы}`] ?? БЮДЖЕТ[раздел].примеров,
        предельныйПорядок: ПОРЯДОК_СХЕМЫ[`${раздел}/${имяСхемы}`] ?? БЮДЖЕТ[раздел].порядок,
      });
    } catch (e) {
      console.error(`  ${раздел}/${имяСхемы}: не прошло — ${e.message}`);
      continue;
    }
    const клеток = т.строки.length * т.атомы.length;
    let пусто = 0;
    // По вершине: у атома-свойства вершина одна, у отношения — две, и пустая
    // клетка отношения виновата обеими. Записываем на каждую.
    const поВершине = new Map();
    const имяАтома = т.атомы.map((a) => ключПоИмени(a, т.имяПоУзлу));
    // Атом таблицы назван УЗЛАМИ графа (`t` у свойства, `args` у отношения), а
    // человеку нужны имена вершин схемы — их даёт `имяПоУзлу`.
    const вершиныАтома = т.атомы.map((a) => (a.rel ? a.args : [a.t])
      .map((id) => т.имяПоУзлу.get(id) ?? String(id)));
    for (const r of т.строки) {
      r.биты.forEach((b, i) => {
        const нет = b === НЕИЗВЕСТНО;
        if (нет) пусто++;
        for (const в of вершиныАтома[i]) {
          let s = поВершине.get(в);
          if (!s) поВершине.set(в, (s = { клеток: 0, пусто: 0 }));
          s.клеток++;
          if (нет) s.пусто++;
        }
      });
    }
    всегоКлеток += клеток;
    всегоПусто += пусто;
    const доля = клеток ? (100 * пусто / клеток).toFixed(1) : '—';
    console.log(`${раздел}/${имяСхемы}: строк ${т.строки.length}, атомов ${т.атомы.length}, `
      + `НЕИЗВЕСТНО ${пусто} из ${клеток} = ${доля}%`);
    if (подробно) {
      const список = [...поВершине.entries()]
        .map(([в, s]) => [в, s.клеток ? 100 * s.пусто / s.клеток : 0])
        .sort((a, b) => b[1] - a[1]);
      for (const [в, д] of список) console.log(`    ${в}: ${д.toFixed(1)}%`);
    }
    // Самый чёрный атом схемы — это и есть подсказка, что чинить.
    const чернее = имяАтома
      .map((имя, i) => [имя, т.строки.filter((r) => r.биты[i] === НЕИЗВЕСТНО).length])
      .sort((a, b) => b[1] - a[1])[0];
    if (чернее && чернее[1] > 0 && !подробно) {
      console.log(`    чернее всех: ${чернее[0]} — пусто на ${чернее[1]} строках из ${т.строки.length}`);
    }
  }
}

console.log('');
console.log(`ИТОГО клеток ${всегоКлеток}, НЕИЗВЕСТНО ${всегоПусто} = `
  + `${(100 * всегоПусто / Math.max(1, всегоКлеток)).toFixed(1)}%`);
console.log('');
console.log('Это доля клеток таблицы, а НЕ доля объектов, которых нет в библиотеке.');
console.log('Пустая клетка значит либо «терм не вычислился», либо «объекта нет»');
console.log('(фактора по ненормальной подгруппе не существует) — таблица их не различает.');
