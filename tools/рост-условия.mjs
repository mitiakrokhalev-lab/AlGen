// Что происходит при РОСТЕ УСЛОВИЯ.
//
//   node tools/рост-условия.mjs --раздел grp --схема центр
//   node tools/рост-условия.mjs --раздел ring --схема фактор --до 4
//
// Граница `объект` — это сколько свойств разрешено навесить на одну исходную
// вершину. Почти вся работа до сих пор шла при границе 2, и это надо проверить
// отдельно: условие из четырёх требований — другая задача, и портиться при его
// росте может многое.
//
// Что проверяется на каждой границе:
//
//   * ДОГОВОР О КОРЗИНАХ: сумма по корзинам равна числу пар «посылки × цель».
//     Договор не косметический — на нём стоит вся мера: если пара потерялась,
//     значит какой-то случай молча не разобран;
//   * ПРОТИВОРЕЧИЯ базы и модели: база доказала, а пример опроверг. При росте
//     условия в вывод втягивается больше правил, и несогласованность, которой
//     при двух посылках не видно, вылезает при четырёх;
//   * доля ПУСТЫХ условий: чем больше требований, тем меньше объектов им
//     удовлетворяет, и пустота обязана расти. Вопрос не в том, растёт ли она, а
//     в том, не превращается ли выдача в одну пустоту;
//   * доля ВЫРОЖДЕННЫХ и ПРОТИВОРЕЧИВЫХ условий, отсеянных ДО разбора: их
//     считает сам перебор, и по ним видно, успевает ли база за ростом условия;
//   * РАЗЛИЧНЫЕ ВОПРОСЫ среди кандидатов. Это главная проверка: если кандидатов
//     при росте условия становится в тридцать раз больше, а различных вопросов
//     столько же, значит рост условия не даёт ничего, кроме украшений, и
//     большие условия надо не искать, а отсеивать;
//   * время и память.

import { category, каталогРаздела } from '../src/load.js';
import { генерировать } from '../src/generate.js';
import { построитьСхему, ключВопроса } from '../src/scene.js';
import { ПОРАЗДЕЛАМ } from '../src/схемы.js';
import { кэшПримеров } from '../src/кэш-примеров.js';

// Таблица примеров берётся с диска, если данные и код модели не менялись.
// Флаг `--без-кэша` — для случая, когда надо замерить честную постройку.
const КЭШ = process.argv.includes('--без-кэша') ? null : кэшПримеров();

const арг = (имя, по) => {
  const i = process.argv.indexOf(`--${имя}`);
  return i >= 0 ? process.argv[i + 1] : по;
};
const раздел = арг('раздел', 'grp');
const имяСхемы = арг('схема', null);
const от = Number(арг('от', 1));
const до = Number(арг('до', 4));
const примеров = Number(арг('примеров', 8000));
const порядок = Number(арг('порядок', 60));
const хватит = Number(арг('хватит', 20000));



const cat = category(раздел);
const каталог = каталогРаздела(раздел);
const схемы = ПОРАЗДЕЛАМ[раздел] ?? {};
const выбранные = имяСхемы ? { [имяСхемы]: схемы[имяСхемы] } : схемы;
if (имяСхемы && !схемы[имяСхемы]) throw new Error(`нет схемы «${имяСхемы}» в разделе ${раздел}`);



const посылки = (z) => (z.свойства ?? []).filter(([, p]) => Object.keys(p).length > 0);

for (const [имя, схема] of Object.entries(выбранные)) {
  console.log(`\n=== ${раздел}/${имя}`);
  let сцена;
  try {
    сцена = построитьСхему(cat, схема);
  } catch (e) {
    console.error(`  сцена не построилась: ${e.message}`);
    continue;
  }
  for (let граница = от; граница <= до; граница++) {
    const t0 = Date.now();
    let итог;
    try {
      итог = await генерировать({
        кэш: КЭШ,
        cat,
        схема,
        границы: {
          объект: граница, подобъект: граница, морфизм: граница, элемент: граница,
          кольцо: граница, число: граница, подмножество: граница, группа: граница,
        },
        каталог,
        примеров,
        предельныйПорядок: порядок,
        хватит,
      });
    } catch (e) {
      console.log(`  граница ${граница}: НЕ ПРОШЛО — ${e.message}`);
      continue;
    }
    const пробелы = итог.найдено.filter((z) => z.корзина === 'пробел');
    let пусто = 0;
    let немо = 0;
    let кандидаты = 0;
    const разные = new Set();
    // Разряд ставит генератор (src/мера-пробела.js); здесь он только читается.
    for (const z of пробелы) {
      if (z.разряд === 'пусто') пусто++;
      else if (z.разряд === 'немо') немо++;
      else if (z.разряд === 'кандидат') {
        кандидаты++;
        разные.add(ключВопроса(сцена.g, сцена.имена, z.цель));
      }
    }
    // Отсеянное ДО разбора: вырожденные и противоречивые условия. Это и есть
    // мера того, успевает ли база за ростом условия.
    const досрочно = Object.entries(итог.счёт)
      .filter(([к]) => !['пробел', 'выводится', 'опровергается', 'опровергается примером'].includes(к))
      .reduce((s, [, v]) => s + v, 0);
    const секунд = ((Date.now() - t0) / 1000).toFixed(1);
    const память = (process.memoryUsage().heapUsed / 1048576).toFixed(0);
    console.log(`  граница ${граница}: пар ${итог.пар}, найдено ${итог.найдено.length}`
      + `, отсеяно до разбора ${досрочно} (${(100 * досрочно / Math.max(1, итог.пар)).toFixed(1)}%)`
      + `, пробелов ${пробелы.length}, пусто ${пусто}, немо ${немо}`
      + `, КАНДИДАТОВ ${кандидаты} (РАЗНЫХ ${разные.size})`
      + ` | баланс ${итог.баланс ? 'сошёлся' : 'НЕ СОШЁЛСЯ'}`
      + `, противоречий ${итог.противоречия.length}`
      + `${итог.оборвано ? ', ОБОРВАНО' : ''}`
      + ` | ${секунд} с, ${память} МБ`);
    if (!итог.баланс) {
      const сумма = Object.values(итог.счёт).reduce((a, b) => a + b, 0);
      console.log(`      ДОГОВОР НАРУШЕН: сумма по корзинам ${сумма}, пар ${итог.пар}`);
      console.log(`      ${JSON.stringify(итог.счёт)}`);
    }
    for (const п of итог.противоречия.slice(0, 3)) {
      console.log(`      ПРОТИВОРЕЧИЕ: ${п.цель} по правилу «${п.правило}»; пример: ${п.пример}`);
    }
  }
}
