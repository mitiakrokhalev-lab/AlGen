// Проверка объявленных колец правилами базы.
//
//   node tools/check-ring.mjs
//
// Кольца в AlGen не вычисляются — все они написаны рукой, и ошибиться в них
// можно где угодно. Защита та же, что у бесконечных групп: прогнать по
// библиотеке ВСЕ правила базы, написанные раньше и независимо, и потребовать,
// чтобы ни одно не оказалось ложным. Правило и запись — два независимых
// источника, и расхождение значит, что один из них врёт; какой именно, решает
// человек, но молча разойтись они не могут.
//
// Плюс проверки самой записи: у кольца ровно один нулевой и ровно один
// единичный идеал, фактор по единичному — нулевое кольцо, и так далее.

import { category, каталогКолец } from '../src/load.js';
import { TermGraph } from '../src/term.js';
import { правила } from '../src/deduce.js';
import { вычислитьУзел, свойства, отношение } from '../src/model/instance.js';
import { НЕ_СЧИТАЕМ, групповоеЗначение } from '../src/model/значение.js';

const cat = category('ring');
// Сверяется ПОЛНЫЙ набор: синтезированные произведения, не взятые в
// библиотеку примеров, всё равно бывают значением терма R × S, и правила
// обязаны быть верны и на них.
const библиотека = каталогКолец({ полный: true });
const { кольца, морфизмы } = библиотека;
// Группы для кросс-категорных правил — те же, что видит перебор.
const группы = (библиотека.группы ?? []).filter((G) => !G.семейство && !G.система);
const беды = [];

const кольцоЗн = (зап) => ({ вид: 'ркольцо', зап });
const идеалЗн = (зап) => ({ вид: 'идеал', зап });
const морЗн = (зап) => ({ вид: 'ркольцмор', зап });

// --- проверки самой записи -----------------------------------------------------

for (const r of кольца) {
  const ид = r.идеалы ?? [];
  if (!ид.length) { беды.push(`${r.имя}: не объявлено ни одного идеала`); continue; }
  const нулевые = ид.filter((i) => i.props?.['zero-ideal'] === true);
  const целые = ид.filter((i) => i.props?.['whole-ideal'] === true);
  if (нулевые.length !== 1) беды.push(`${r.имя}: нулевых идеалов должно быть ровно один, а их ${нулевые.length}`);
  if (целые.length !== 1) беды.push(`${r.имя}: единичных идеалов должно быть ровно один, а их ${целые.length}`);
  for (const i of ид) {
    const p = i.props ?? {};
    if (p['whole-ideal'] === true && p.proper === true) беды.push(`${r.имя}/${i.имя}: разом весь и собственный`);
    if (p['whole-ideal'] === true && i.фактор !== 'Zero') беды.push(`${r.имя}/${i.имя}: фактор по единичному идеалу обязан быть нулевым кольцом`);
    if (p['zero-ideal'] === true && i.фактор !== undefined && i.фактор !== r.id && r.id !== 'Zero') {
      беды.push(`${r.имя}/${i.имя}: фактор по нулевому идеалу обязан быть самим кольцом, а объявлен ${i.фактор}`);
    }
  }
  // Свойства кольца и свойства фактора по нулевому идеалу — одно и то же
  // кольцо, и расходиться они не могут.
  if (r.props?.field === true && r.props?.comm !== true) беды.push(`${r.имя}: поле обязано быть коммутативным`);
  if (r.props?.domain === true && r.props?.comm !== true) беды.push(`${r.имя}: область обязана быть коммутативной`);
}

for (const f of морфизмы) {
  const где = `${f.имя}`;
  const ядро = f._ядро?.props ?? {};
  if (f.props?.['injective-ring'] === true && ядро['zero-ideal'] !== true) {
    беды.push(`${где}: инъективен, а ядро объявлено не нулевым`);
  }
  if (f.props?.['injective-ring'] === false && ядро['zero-ideal'] === true) {
    беды.push(`${где}: не инъективен, а ядро нулевое`);
  }
  if (f.props?.['surjective-ring'] === true && f._образ !== f._код) {
    беды.push(`${где}: сюръективен, а образ объявлен не кодоменом`);
  }
  if (f._ядро && f._ядро._фактор && f._образ && f._ядро._фактор !== f._образ) {
    беды.push(`${где}: теорема о гомоморфизме нарушена — R/ker = ${f._ядро._фактор.имя}, а образ ${f._образ.имя}`);
  }
}

// --- сцена правила --------------------------------------------------------------

// Роли сцены раскладываются по сортам: кольца строятся первыми, потому что от
// них зависят идеалы (ambient) и морфизмы (dom, cod).
function собратьСцену(rule) {
  const g = new TermGraph(cat);
  const узлы = new Map();
  const роли = { кольца: [], идеалы: [], морфизмы: [], группы: [] };
  // Сцена нормализованного правила — СПИСОК ролей с именем внутри, а не
  // объект «имя → сорт»: так её отдаёт deduce.js после раскрытия
  // «переносит»-правил и контрапозиций.
  const записи = (rule.scene ?? []).map((о) => [о.name, о]);
  // Сцена с ГРУППОЙ сверяется наравне с прочими: правила про групповое
  // кольцо иначе остались бы непроверенными, а это ровно те правила, где
  // ошибиться легче всего — они связывают две категории.
  if (записи.some(([, о]) => !String(о.sort).startsWith('Ring.') && о.sort !== 'Grp.obj')) return null;

  for (const [имя, о] of записи) {
    if (о.sort === 'Ring.obj') { узлы.set(имя, g.apply('choose-ring', [])); роли.кольца.push(имя); }
    else if (о.sort === 'Grp.obj') { узлы.set(имя, g.apply('choose-group', [])); роли.группы.push(имя); }
  }
  for (const [имя, о] of записи) {
    if (о.sort === 'Ring.ideal') {
      const A = узлы.get(о.ambient);
      if (A === undefined) return null;
      узлы.set(имя, g.apply('choose-ideal', [A]));
      роли.идеалы.push({ имя, ambient: о.ambient });
    } else if (о.sort === 'Ring.mor') {
      const D = узлы.get(о.dom);
      const C = узлы.get(о.cod);
      if (D === undefined || C === undefined) return null;
      узлы.set(имя, g.apply('choose-ring-mor', [D, C]));
      роли.морфизмы.push({ имя, dom: о.dom, cod: о.cod });
    }
  }

  const построить = (образец) => {
    if (typeof образец === 'string') return узлы.get(образец) ?? null;
    const args = (образец.args ?? []).map(построить);
    if (args.some((x) => x === null)) return null;
    try {
      return g.apply(образец.op, args);
    } catch {
      return null;
    }
  };
  const атомы = [...(rule.if ?? []), rule.then].map((a) => ({
    ...a,
    узлы: a.rel ? a.args.map(построить) : [построить(a.t)],
  }));
  if (атомы.some((a) => a.узлы.some((x) => x === null || x === undefined))) return null;
  return { g, узлы, атомы, роли };
}

function значенияАтома(значения, a) {
  if (a.rel) return отношение(a.rel, значения.get(a.узлы[0]), значения.get(a.узлы[1]));
  const v = значения.get(a.узлы[0]);
  return v && v !== НЕ_СЧИТАЕМ ? свойства(v)[a.p] : undefined;
}

// Все наборы значений для ролей сцены. Колец тридцать, идеалов у каждого
// два-пять, морфизмов между данной парой обычно ноль или один — перебор
// целиком посилен, и обрезать его незачем.
function* наборы(роли) {
  const выбор = new Map();
  function* поКольцам(k) {
    if (k === роли.кольца.length) { yield* поГруппам(0); return; }
    for (const r of кольца) { выбор.set(роли.кольца[k], r); yield* поКольцам(k + 1); }
  }
  function* поГруппам(k) {
    if (k === роли.группы.length) { yield* поИдеалам(0); return; }
    for (const G of группы) { выбор.set(роли.группы[k], G); yield* поГруппам(k + 1); }
  }
  function* поИдеалам(k) {
    if (k === роли.идеалы.length) { yield* поМорфизмам(0); return; }
    const { имя, ambient } = роли.идеалы[k];
    for (const i of выбор.get(ambient).идеалы ?? []) { выбор.set(имя, i); yield* поИдеалам(k + 1); }
  }
  function* поМорфизмам(k) {
    if (k === роли.морфизмы.length) { yield new Map(выбор); return; }
    const { имя, dom, cod } = роли.морфизмы[k];
    for (const f of морфизмы) {
      if (f._дом !== выбор.get(dom) || f._код !== выбор.get(cod)) continue;
      выбор.set(имя, f);
      yield* поМорфизмам(k + 1);
    }
  }
  yield* поКольцам(0);
}

// --- прогон --------------------------------------------------------------------

let проверено = 0;
let сработало = 0;
const пропущено = [];

// ПРОГРЕСС ПО ПРАВИЛАМ. Сверка идёт минутами, а прежде она молчала до самого
// конца — и когда библиотека выросла, стало невозможно отличить «считает» от
// «зависла». Правило печатается ДО перебора, а его цена — после: по этим двум
// строкам сразу видно, какое правило дорогое и почему.
const всегоПравил = правила(cat).length;
let номер = 0;
const t0 = Date.now();
// Возврат каретки держим в переменной: строка идёт в одну и ту же линию
// терминала, и перевода строки тут быть не должно.
const ВК = String.fromCharCode(13);
const стереть = () => process.stderr.write(ВК + ' '.repeat(80) + ВК);

for (const rule of правила(cat)) {
  номер++;
  const сцена = собратьСцену(rule);
  if (!сцена) { пропущено.push(rule.id); continue; }
  process.stderr.write(`${ВК}[${номер}/${всегоПравил}] ${rule.id.slice(0, 60)}`.padEnd(80));
  const тНачало = Date.now();
  let наборовПравила = 0;
  const { g, узлы, атомы, роли } = сцена;
  const вид = new Map();
  for (const имя of роли.кольца) вид.set(имя, кольцоЗн);
  for (const имя of роли.группы) вид.set(имя, групповоеЗначение);
  for (const { имя } of роли.идеалы) вид.set(имя, идеалЗн);
  for (const { имя } of роли.морфизмы) вид.set(имя, морЗн);

  for (const набор of наборы(роли)) {
    наборовПравила++;
    const значения = new Map();
    for (const [имя, зап] of набор) значения.set(узлы.get(имя), вид.get(имя)(зап));
    let целиком = true;
    for (const n of g.nodes) {
      if (значения.has(n.id)) continue;
      const v = вычислитьУзел(g, n.id, значения);
      if (v === null || v === НЕ_СЧИТАЕМ) { целиком = false; break; }
      значения.set(n.id, v);
    }
    if (!целиком) continue;
    const посылки = атомы.slice(0, -1);
    const вывод = атомы[атомы.length - 1];
    if (!посылки.every((a) => значенияАтома(значения, a) === (a.значение !== false))) continue;
    проверено++;
    const v = значенияАтома(значения, вывод);
    if (v === undefined) continue;
    сработало++;
    if (v !== (вывод.значение !== false)) {
      const где = [...набор].map(([имя, зап]) => `${имя} = ${зап.имя}`).join(', ');
      беды.push(`правило «${rule.id}» ложно при ${где}`);
    }
  }
  const сек = (Date.now() - тНачало) / 1000;
  // Печатаем только дорогие правила: иначе двести строк шума, в которых
  // дорогое правило не найти.
  if (сек >= 2) {
    стереть();
    console.log(`  дорого: ${сек.toFixed(1)} с, наборов ${наборовПравила} — правило «${rule.id}»`);
  }
}
стереть();
console.log(`перебор правил занял ${((Date.now() - t0) / 1000).toFixed(1)} с`);

console.log(`колец: ${кольца.length}, идеалов: ${кольца.reduce((s, r) => s + (r.идеалы ?? []).length, 0)}, гомоморфизмов: ${морфизмы.length}`);
console.log(`посылки сошлись ${проверено} раз, вывод был проверяем ${сработало} раз`);
if (пропущено.length) console.log(`правил вне библиотеки колец (числа, группы): ${пропущено.length}`);

const уникальные = [...new Set(беды)];
if (уникальные.length) {
  console.log(`\nрасхождений: ${уникальные.length}`);
  for (const b of уникальные.slice(0, 60)) console.log(`  ${b}`);
  process.exitCode = 1;
} else {
  console.log('\nрасхождений нет: объявленные кольца не противоречат ни одному правилу базы');
}
