// --- взаимная проверка с базой правил --------------------------------------------

const cat = category('grp');

// Правило вида «если свойства объекта, то свойство объекта» проверяется на
// каждой группе; правило про подгруппу — на каждой паре «группа, подгруппа».
function проверитьПравила() {
  const беды = [];
  const сцены = {
    объект: (G) => [{ X: { вид: 'группа', G } }],
    подгруппа: (G) =>
      подгруппы(G).map((H) => ({ X: { вид: 'группа', G }, N: { вид: 'подгруппа', G, H } })),
  };

  const значение = (привязка, атом) => {
    const цель = разобратьТерм(привязка, атом.t ?? null);
    if (!цель) return undefined;
    return цель.props[atomИмя(атом)];
  };
  const atomИмя = (атом) => атом.p;

  const разобратьТерм = (привязка, t) => {
    if (typeof t === 'string') {
      const у = привязка[t];
      if (!у) return null;
      if (у.вид === 'группа') return { props: свойстваГруппы(у.G) };
      if (у.вид === 'подгруппа') {
        const под = подгруппаКакГруппа(у.G, у.H);
        return {
          props: { ...свойстваГруппы(под.группа), ...свойстваПодгруппы(у.G, у.H) },
        };
      }
      return null;
    }
    if (t && t.op) {
      const внутрь = (t.args ?? []).map((a) => привязка[a]).filter(Boolean);
      if (внутрь.length !== (t.args ?? []).length) return null;
      const G = внутрь[0]?.G;
      if (!G) return null;
      if (t.op === 'center') return { props: подгруппаСвойства(G, центр(G)) };
      if (t.op === 'commutator') return { props: подгруппаСвойства(G, коммутант(G)) };
      if (t.op === 'quotient') {
        const N = внутрь[1];
        if (!N || N.вид !== 'подгруппа' || !нормальна(G, N.H)) return null;
        return { props: свойстваГруппы(фактор(G, N.H).группа) };
      }
      if (t.op === 'im' || t.op === 'ker') return null; // морфизмов в этих сценах нет
      return null;
    }
    return null;
  };

  const подгруппаСвойства = (G, H) => ({
    ...свойстваГруппы(подгруппаКакГруппа(G, H).группа),
    ...свойстваПодгруппы(G, H),
  });

  for (const правило of cat.rules) {
    const роли = Object.keys(правило.scene);
    const вид = роли.length === 1 && роли[0] === 'X' ? 'объект'
      : роли.length === 2 && роли.includes('X') && роли.includes('N') ? 'подгруппа' : null;
    if (!вид) continue;
    if ((правило.if ?? []).some((a) => a.rel) || правило.then.rel) continue;

    for (const запись of библиотека) {
      const G = группаПоИмени(запись.id, библиотека);
      for (const привязка of сцены[вид](G)) {
        let посылки = true;
        let неизвестно = false;
        for (const a of правило.if) {
          const v = значение(привязка, a);
          if (v === undefined) неизвестно = true;
          else if (v !== (a.значение !== false)) посылки = false;
        }
        if (!посылки || неизвестно) continue;
        const вывод = значение(привязка, правило.then);
        if (вывод === undefined) continue;
        if (вывод !== (правило.then.значение !== false)) {
          беды.push(
            `правило «${правило.id}» ложно на ${запись.id}` +
            (привязка.N ? ` (подгруппа порядка ${привязка.N.H.length})` : ''),
          );
        }
      }
    }
  }
  return беды;
}

