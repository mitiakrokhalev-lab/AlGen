// Реестр мишеней: проверка договора.
//
//   node tools/targets.mjs            — отчёт по всем
//   node tools/targets.mjs 5.9 6.14   — по названным
//   node tools/targets.mjs --текст    — только тексты задач
//   node tools/targets.mjs --примеры  — что говорит про каждую мишень библиотека
//
// Договор: всё, что в data/targets.json объявлено ВЫРАЗИМЫМ, обязано
// собираться движком — граф строится, атомы проверяются по сортам, условие
// связно, все requires выполнены. Иначе ненулевой код возврата.
//
// Когда появится перебор, договор усилится: «обязано НАХОДИТЬСЯ». Пока он
// проверяет ровно то, что честно проверяемо, и не притворяется большим.

import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { category, DATA, каталогГрупп } from '../src/load.js';
import { таблицаПримеров, отобратьСтроки, разбор, ключПоИмени } from '../src/witness.js';
import { TermGraph } from '../src/term.js';
import { known, undefinedSlots, components } from '../src/facts.js';
import { рассуждать } from '../src/deduce.js';
import { задачаТекст } from '../src/statement.js';
import { fits, свойствоПодходит } from '../src/sorts.js';

const реестр = JSON.parse(readFileSync(join(DATA, 'targets.json'), 'utf8'));
// Мишени живут не только в группах. Реестр начинался как список задач по
// теории групп, и раздел был один — а с появлением мишеней про модули
// (точные последовательности, Ext, Tor) запись «раздел» стала обязательной.
// По умолчанию группы: так записаны все пятьдесят четыре прежние мишени, и
// переписывать их незачем.
const категории = new Map();
const катДля = (раздел = 'grp') => {
  if (!категории.has(раздел)) категории.set(раздел, category(раздел));
  return категории.get(раздел);
};
const cat = катДля('grp');

export function собрать(задача) {
  const g = new TermGraph(катДля(задача.раздел));
  const имена = new Map();
  const узел = (имя) => {
    if (!имена.has(имя)) throw new Error(`узел «${имя}» не объявлен раньше использования`);
    return имена.get(имя);
  };
  for (const n of задача.узлы ?? []) {
    if (имена.has(n.имя)) throw new Error(`узел «${n.имя}» объявлен дважды`);
    if (n.op === 'given' || n.op === 'named') {
      имена.set(n.имя, g.given(n.sort, n.props ?? {}, {
        имя: n.показ ?? n.объект ?? null,
        объект: n.объект ?? null,
        named: n.op === 'named',
      }));
    } else {
      имена.set(n.имя, g.apply(n.op, (n.args ?? []).map(узел), { props: n.props ?? {}, quant: n.quant }));
    }
  }
  const атом = (a) => {
    if (Array.isArray(a.или)) return { ...a, или: a.или.map(атом) };
    return a.rel ? { ...a, args: a.args.map(узел) } : { ...a, t: узел(a.t) };
  };
  return {
    g,
    имена,
    участники: (задача.участники ?? []).map(узел),
    посылки: (задача.посылки ?? []).map(атом),
    цель: атом(задача.цель),
  };
}

// Атом обязан быть осмысленным: свойство живёт на подходящем сорте, у
// отношения совпадают согласующие связи. Иначе «H ⩽ G» тихо превратится в
// сравнение несравнимого.
// Дизъюнктивная цель проверяется по частям: «A или B» законна, когда законны
// обе части.
// Категория берётся У ГРАФА: мишени бывают не только групповые, и жёстко
// взятый `cat` объявлял модульные атомы сломанными («свойство fin-gen живёт на
// Grp.obj, а терм сорта Mod.obj»). Граф свою категорию знает — спрашиваем его.
function проверитьАтом(g, a) {
  const cat = g.cat;
  if (Array.isArray(a.или)) {
    for (const x of a.или) {
      const беда = проверитьАтом(g, x);
      if (беда) return беда;
    }
    return null;
  }
  if (a.rel) {
    const r = cat.rels.get(a.rel);
    if (!r) return `нет отношения ${a.rel}`;
    for (let i = 0; i < 2; i++) {
      const s = g.get(a.args[i]).sort;
      if (!fits(s, r.in[i], cat.up)) return `отношение ${a.rel}: аргумент ${i + 1} сорта ${s}, ждали ${r.in[i]}`;
    }
    if (r.same) {
      const x = g.rel(a.args[0], r.same);
      const y = g.rel(a.args[1], r.same);
      if (x !== y) return `отношение ${a.rel}: не совпадает ${r.same}`;
    }
    return null;
  }
  const p = cat.props.get(a.p);
  if (!p) return `нет свойства ${a.p}`;
  const s = g.get(a.t).sort;
  if (!свойствоПодходит(s, p, cat.up)) {
    return `свойство ${a.p} живёт на ${p.sort}, а терм сорта ${s}`;
  }
  return null;
}

export function проверить(задача) {
  const беды = [];
  let текст = null;
  let разбор = null;
  try {
    разбор = собрать(задача);
  } catch (e) {
    return { беды: [`не собралось: ${e.message}`], текст: null };
  }
  const { g, участники, посылки, цель } = разбор;
  for (const a of [...посылки, цель]) {
    const беда = проверитьАтом(g, a);
    if (беда) беды.push(беда);
  }
  if (!беды.length) {
    try {
      текст = задачаТекст(g, { участники, посылки, цель }).текст;
    } catch (e) {
      беды.push(`не печатается: ${e.message}`);
    }
  }

  const атомы = [...посылки, цель];
  const узлыАтома = (a) => (Array.isArray(a.или)
    ? a.или.flatMap(узлыАтома)
    : (a.rel ? a.args : [a.t]));
  const корни = [...участники, ...атомы.flatMap(узлыАтома)];
  const рёбра = атомы.filter((a) => a.rel).map((a) => a.args);
  const куски = components(g, корни, рёбра);
  if (куски.length > 1) беды.push(`условие распадается на ${куски.length} куска`);

  // Определённость судится ПО ВЫВЕДЕННЫМ фактам — ровно как в переборе.
  // Иначе договор требует от мишени того, чего генератор не требует:
  // нормальность прообраза даёт лемма базы, а не поле gives.
  const мир = рассуждать(g, посылки, { достройка: 1 });
  const спросить = (graph, id, prop) => {
    const v = мир.знает({ p: prop, t: id });
    return v === undefined ? known(graph, id, prop) : v;
  };
  const дыры = undefinedSlots(g, корни, спросить);
  const неопределено = дыры.map((d) => `${d.op}/${d.роль} требует «${d.свойство}» — ${d.статус}`);

  return { беды, текст, неопределено, разбор };
}

// Проверка мишени по библиотеке примеров: что говорит модель про цель при
// посылках задачи. Если задача из задачника ОПРОВЕРГАЕТСЯ конкретной группой,
// ошибка либо в том, как я записал условие, либо в модели, — и в любом случае
// знать об этом надо.
export async function поПримерам(задача, каталог, примеров = 400, предельныйПорядок = 24) {
  const { g, имена, посылки, цель } = собрать(задача);
  const имяПоУзлу = new Map([...имена].map(([имя, id]) => [id, имя]));
  const таблица = await таблицаПримеров({
    cat, схема: { узлы: задача.узлы }, каталог, предел: примеров, предельныйПорядок,
  });
  // Посылки — и наложенные на вершины свойства, и отдельно записанные атомы.
  const условия = [];
  for (const n of задача.узлы) {
    for (const [p, v] of Object.entries(n.props ?? {})) {
      условия.push({ ключ: `${p}@${n.имя}`, значение: v !== false });
    }
  }
  for (const a of посылки) {
    условия.push({ ключ: ключПоИмени(a, имяПоУзлу), значение: a.значение !== false });
  }
  const строки = отобратьСтроки(таблица, условия);
  const ключЦели = ключПоИмени(цель, имяПоУзлу);
  const итог = разбор(таблица, строки, ключЦели, цель.значение === false ? 0 : 1);
  return {
    ...итог,
    ждём: цель.значение !== false,
    слепое: таблица.постоянные.has(ключЦели),
    всегоСтрок: таблица.строки.length,
  };
}

// Договор в виде, годном для теста: список нарушений, пустой — значит цел.
export function нарушенияДоговора() {
  const беды = [];
  for (const задача of реестр.задачи) {
    if (задача.статус !== 'выразима') continue;
    if (!задача.узлы) {
      беды.push(`${задача.id}: объявлена выразимой, но графа нет`);
      continue;
    }
    const итог = проверить(задача);
    const плохо = [...итог.беды, ...(итог.неопределено ?? [])];
    if (плохо.length) беды.push(`${задача.id}: ${плохо.join('; ')}`);
  }
  return беды;
}

export const задачи = реестр.задачи;

