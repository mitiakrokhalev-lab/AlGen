async function отчёт() {
const аргументы = process.argv.slice(2);
const толькоТекст = аргументы.includes('--текст');
const отбор = аргументы.filter((a) => !a.startsWith('--'));

const счёт = new Map();
let провалов = 0;
const провалившиеся = [];

for (const задача of реестр.задачи) {
  счёт.set(задача.статус, (счёт.get(задача.статус) ?? 0) + 1);
  if (отбор.length && !отбор.includes(задача.id)) continue;
  const строгая = задача.статус === 'выразима';
  if (!задача.узлы) {
    if (!толькоТекст) {
      const чего = (задача.нужно ?? [задача.почему ?? '—']).join('; ');
      console.log(`· ${задача.id.padEnd(14)} ${задача.статус.padEnd(10)} ${чего}`);
    }
    if (строгая) {
      провалов++;
      провалившиеся.push(`${задача.id}: объявлена выразимой, но графа нет`);
    }
    continue;
  }

  const итог = проверить(задача);
  const плохо = строгая && (итог.беды.length || itogНеопределено(итог));
  if (плохо) {
    провалов++;
    провалившиеся.push(`${задача.id}: ${[...итог.беды, ...итог.неопределено].join('; ')}`);
  }

  if (толькоТекст) {
    if (итог.текст) console.log(`${задача.id}. ${итог.текст}`);
    continue;
  }
  console.log(`${плохо ? '✗' : '✓'} ${задача.id.padEnd(14)} ${задача.статус}`);
  if (итог.текст) console.log(`    ${итог.текст}`);
  for (const b of итог.беды) console.log(`    БЕДА: ${b}`);
  for (const d of итог.неопределено ?? []) console.log(`    не определено: ${d}`);
  for (const n of задача.нужно ?? []) console.log(`    нужно: ${n}`);
}

if (!толькоТекст) {
  console.log('\nпо статусам: ' + [...счёт].map(([k, v]) => `${k} ${v}`).join(', '));
  console.log(`всего задач в реестре: ${реестр.задачи.length}`);
}
if (провалов) {
  console.error(`\nДОГОВОР НАРУШЕН, задач ${провалов}:`);
  for (const p of провалившиеся) console.error(`  ${p}`);
  process.exit(1);
}
}

function itogНеопределено(итог) {
  return (итог.неопределено ?? []).length > 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (process.argv.includes('--примеры')) await поПримерамВсе();
  else await отчёт();
}

async function поПримерамВсе() {
  const каталог = каталогГрупп();
  let спорных = 0;
  for (const z of реестр.задачи.filter((x) => x.узлы)) {
    let и;
    try { и = await поПримерам(z, каталог); } catch (e) { console.log(`${z.id.padEnd(16)} не проверить: ${e.message}`); continue; }
    const вердикт = !и.подходящих ? 'подходящих примеров нет'
      : и.контрпример ? `ОПРОВЕРГАЕТСЯ: ${и.контрпример.описание}`
      : и.слепое ? `верна на всех ${и.подходящих} — но это слепое пятно модели`
      : `верна на всех ${и.подходящих} подходящих`;
    if (и.контрпример) спорных++;
    console.log(`${z.id.padEnd(16)} ${вердикт}`);
  }
  console.log(`
мишеней, опровергнутых примером: ${спорных}`);
}
