// Сбор хороших задач в ЗАДАЧНИК.md.
//
//   node tools/задачник.mjs                  — пройти по всем разделам и дописать
//   node tools/задачник.mjs --раздел top     — только по одному разделу
//   node tools/задачник.mjs --сколько 60     — сколько задач брать с одной схемы
//
// Что такое «хорошая задача». Корзина сама по себе ответа не даёт: пробел
// бывает и оттого, что подходящих примеров не нашлось вовсе, а опровержение —
// оттого, что утверждение ложно всюду и скучно. Поэтому отбор по признакам:
//
//   * ПРОБЕЛ берётся, только если примеров подходило достаточно много. Тогда
//     «ни база, ни библиотека не отвечают» значит открытый вопрос, а не пустое
//     условие;
//   * ОПРОВЕРЖЕНИЕ берётся, только если контрпример ТОНКИЙ: цель верна почти
//     на всех подходящих примерах. Задача, ложная всюду, решается первым же
//     взглядом;
//   * ВЫВОД берётся при глубине от трёх шагов. Одношаговое следствие — не
//     задача, а определение.
//
// Условия со слепыми пятнами отбрасываются целиком: если посылка или цель
// говорит о свойстве, одинаковом у всей библиотеки, проверить её было нечем.
//
// Корзины и признаков мало: перебор ОБЯЗАН считать все пары «посылки × цель»,
// а читать их человеку незачем. Поэтому ещё пять отборов, и каждый вырос из
// задачи, которая в книге выглядела глупо (подробности при каждой функции):
//
//   посылкиКасаютсяЦели      — посылка не участвует в вопросе никак;
//   естьЛишняяПосылка        — посылка выводится из остальных;
//   естьУкрашение            — без посылки ответ ТОТ ЖЕ, значит она не работает;
//   условиеСхлопывается      — условие сводит объект к вырожденному или противоречиво;
//   свидетельВырожден        — весь ответ в нулевом кольце, и задача на этом одна;
//   выводПереноситСведения   — вывод обязан идти с вершины на вершину, а не
//                              раскручивать определения на одной и той же;
//   самыеКороткие            — одна цель и один свидетель — одна задача;
//   цельСледуетИзМалости    — цель следует из одной лишь малости вершины;
//   ПРЕДЕЛ_НА_ЦЕЛЬ           — не больше двух задач про одну цель на схему;
//   цельВЧужомВходе          — вопрос про чужой ВХОД (группу в разделе колец);
//   ПРЕДЕЛ_НА_УСЛОВИЕ        — и не больше двух с одним и тем же условием.
//
// Файл ПОПОЛНЯЕТСЯ, а не переписывается: задача, попавшая туда однажды,
// остаётся, даже если следующий прогон её не выдал. Повторы отсекаются по
// тексту — он и есть то, что читает человек.

