const посылки = (z) => (z.свойства ?? []).filter(([, props]) => Object.keys(props).length > 0);

function годится(z) {
  if (z.слепое || z.слепыеПосылки) return false;
  // ОБРЕЗАННАЯ таблица делает пробел мнимым. «Верно ли, что im f конечно?» без
  // единой посылки висело открытым вопросом на 8000 примерах ровно потому, что
  // предел строк кончался раньше, чем перебор доходил до бесконечных
  // пространств: свидетель в библиотеке был, но за границей предела. Перебор
  // об этом честно предупреждает пометкой, а отбор её не читал.
  if (z.корзина === 'пробел' && z.усечено) return false;
  if (z.корзина === 'пробел') {
    // Пробел БЕЗ ПОСЫЛОК — не вопрос, а признание, что библиотека мала:
    // «верно ли, что im f нётерово» без единого условия ответа не ждёт.
    if (!посылки(z).length) return false;
    return (z.примеров ?? 0) >= ПОРОГ_ПРИМЕРОВ;
  }
  if (z.корзина === 'опровергается примером') return Boolean(z.тонкий);
  if (z.корзина === 'выводится') {
    // ОДНОЙ работающей посылки выводу мало. «R факториально ⇒ R[x]
    // коммутативно» проходит и глубину (факториально ⇒ область ⇒ коммутативно ⇒
    // многочлены коммутативны), и перенос сведений с вершины на вершину — а
    // содержания в нём нет: это цепочка определений плюс одно «сохраняет».
    // Содержательная теорема СВОДИТ ВМЕСТЕ по меньшей мере два независимых
    // условия: «кольцо главных идеалов И артиново ⇒ R[x] главных идеалов»
    // (оттого что вместе они дают поле).
    //
    // Проверка идёт по атомам, а не по вершинам: два требования на одной
    // вершине — тоже два требования.
    const атомов = посылки(z).reduce((s, [, p]) => s + Object.keys(p).length, 0);
    return атомов >= 2 && (z.глубина ?? 0) >= ПОРОГ_ГЛУБИНЫ;
  }
  return false;
}

// Посылка обязана КАСАТЬСЯ цели: её вершина должна лежать в опоре того, про
// что спрашивают. Без этого в задачник идут условия вида «X не одноточечно,
// Y счётно — верно ли, что Y конечно?», где первая посылка не участвует в
// вопросе никак и только сбивает читателя. Перебор такие пары считать обязан
// (договор о корзинах), а задачник — нет.
function посылкиКасаютсяЦели(cat, схема, z) {
  const { g, имена } = построитьСхему(cat, схема, new Map(z.свойства));
  const узлыЦели = (ц) => {
    if (Array.isArray(ц.или)) return ц.или.flatMap(узлыЦели);
    return ц.rel ? ц.узлы.map((и) => имена.get(и)) : [имена.get(ц.узел)];
  };
  const опора = new Set();
  for (const t of узлыЦели(z.цель)) {
    if (t === undefined) return false;
    for (const x of g.support(t)) опора.add(x);
  }
  return посылки(z).every(([имя]) => опора.has(имена.get(имя)));
}

// Посылка, выводимая из ОСТАЛЬНЫХ, — мусор в условии. «X не одноточечно, X
// бесконечно» читается как два требования, а второе влечёт первое, и человек
// зря ищет, где пригодилось первое. Перебор такие пары обязан считать, а
// задачник — нет.
function естьЛишняяПосылка(cat, схема, z) {
  const свойства = посылки(z);
  const атомы = [];
  for (const [имя, props] of свойства) {
    for (const [p, v] of Object.entries(props)) атомы.push({ имя, p, значение: v });
  }
  if (атомы.length < 2) return false;
  for (let i = 0; i < атомы.length; i++) {
    const без = атомы.filter((_, k) => k !== i);
    const карта = new Map();
    for (const a of без) {
      карта.set(a.имя, { ...(карта.get(a.имя) ?? {}), [a.p]: a.значение });
    }
    let g;
    let имена;
    try {
      ({ g, имена } = построитьСхему(cat, схема, карта));
    } catch {
      continue;
    }
    const мир = рассуждать(g, [...имена.values()]);
    const узел = имена.get(атомы[i].имя);
    if (узел === undefined) continue;
    if (мир.знает({ p: атомы[i].p, t: узел }) === (атомы[i].значение !== false)) return true;
  }
  return false;
}

// Свойства, означающие ВЫРОЖДЕННЫЙ объект, — по одному имени на категорию.
// Список был `trivial` и `point`, то есть только про группы и пространства, и
// потому «R нулевое ⇒ R нётерово?» проходило в книгу как вывод глубины три: в
// нулевом кольце верно всё, и задача там ровно одна.
const ВЫРОЖДАЮЩИЕ = ['trivial', 'point', 'trivial-ring', 'trivial-ext'];

// Условие, СХЛОПЫВАЮЩЕЕ объект, задачей не является. «G конечна, G без
// кручения» значит G = 1, и всё дальнейшее — про единичную группу; «G
// тривиальна, x бесконечного порядка» и вовсе противоречиво. Перебор обязан
// считать и такие пары, но читать их незачем.
//
// Вырожденный объект, на котором опровергается почти что угодно: у колец это
// НУЛЕВОЕ кольцо, где 1 = 0 и нулевой идеал разом является всем кольцом.
// Контрпример из него математически безупречен («нильпотентный идеал не обязан
// быть собственным — возьмите R = 0»), но задача на этом ровно одна, а выдаёт
// перебор её десятками: посылки-то у всех разные, а ответ один и тот же.
//
// У групп и пространств такого исключения нет: единичная группа и точка —
// полноправные контрпримеры, и «G = 1» читается как содержательный ответ.
// Ловится именно КОЛЬЦО, равное нулю, а не идеал: описание идеала выглядит как
// «I = 0 ⊴ ℤ/4ℤ», и нулевой идеал нормального кольца — обычное дело. Поэтому
// после нуля требуется запятая или конец строки: у идеала там стоит «⊴».
const ВЫРОЖДЕННЫЙ_СВИДЕТЕЛЬ = { ring: /(^|,\s*)[^\s,=]+ = 0(,|$)/u };

function свидетельВырожден(раздел, z) {
  const образец = ВЫРОЖДЕННЫЙ_СВИДЕТЕЛЬ[раздел];
  if (!образец || !z.свидетель) return false;
  return образец.test(z.свидетель);
}

// --- посылка обязана РАБОТАТЬ ---------------------------------------------------
//
// Самый частый брак в выдаче — посылка-УКРАШЕНИЕ: она не выводится из остальных
// (значит «лишней» её не назовёшь), касается той же вершины (значит «не
// касается цели» тоже мимо), а ответ без неё тот же. «S коммутативно, S не
// артиново — верно ли, что ker f собственный?»: коммутативность там не при чём
// вовсе, и читатель честно ищет, где она пригодилась.
//
// Проверяется ДАРОМ: перебор обязан был посчитать ту же цель и с меньшим набором
// посылок — договор о корзинах не позволяет ему пропустить ни одну пару. Значит
// достаточно поискать эту пару в его же выдаче.
const ключУсловия = (свойства) => (свойства ?? []).filter(([, p]) => Object.keys(p).length > 0)
  .map(([имя, props]) => `${имя}:${Object.entries(props)
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([p, v]) => (v === false ? `!${p}` : p))
    .join(',')}`)
  .sort()
  .join('&');

const ключЗадачи = (z) => `${ключУсловия(посылки(z))}|${JSON.stringify(z.цель)}`;

// Все наборы посылок, полученные выбрасыванием РОВНО ОДНОГО требования.
function* безОднойПосылки(z) {
  const атомы = [];
  for (const [имя, props] of посылки(z)) {
    for (const [p, v] of Object.entries(props)) атомы.push([имя, p, v]);
  }
  if (атомы.length < 1) return;
  for (let i = 0; i < атомы.length; i++) {
    const карта = new Map();
    атомы.forEach(([имя, p, v], k) => {
      if (k === i) return;
      карта.set(имя, { ...(карта.get(имя) ?? {}), [p]: v });
    });
    yield `${ключУсловия([...карта])}|${JSON.stringify(z.цель)}`;
  }
}

function естьУкрашение(индекс, z) {
  for (const ключ of безОднойПосылки(z)) {
    const у = индекс.get(ключ);
    // Задачи без этой посылки в выдаче нет — судить не о чем.
    if (!у || у.сам === z) continue;
    // Ответ изменился — посылка работает.
    if (у.корзина !== z.корзина) continue;
    // Корзина та же, но контрпример другой — посылка всё-таки участвует.
    if (z.корзина === 'опровергается примером' && у.свидетель !== z.свидетель) continue;
    return true;
  }
  return false;
}

// --- вывод обязан ПЕРЕНОСИТЬ сведения -------------------------------------------
//
// «R — тело ⇒ R факториально», «R — кольцо главных идеалов ⇒ R без
// нильпотентов», «A нормально ⇒ A удовлетворяет T₀» — всё это не задачи, а
// раскрутка определений: посылка и цель сидят на ОДНОЙ вершине, и доказательство
// есть цепочка импликаций про один объект. Глубина вывода этого не различает:
// «поле ⇒ главных идеалов ⇒ факториально» — те же три шага, что у содержательной
// теоремы.
//
// Содержательный вывод ПЕРЕНОСИТ сведения по постройке: дано про G — спрашивают
// про Z(G) или G/N. Тогда читателю есть что делать.
//
// К ОПРОВЕРЖЕНИЯМ это не относится: там вся соль в контрпримере, и «M
// циклический ⇒ M нётеров?» на одной вершине — хорошая задача, потому что
// отвечает на неё ℤ[x₁, x₂, …].
const вершиныЦели = (ц) => {
  if (Array.isArray(ц?.или)) return ц.или.flatMap(вершиныЦели);
  return ц?.rel ? ц.узлы : [ц?.узел];
};

// Вопрос по КЛЮЧАМ ТЕРМОВ: чем задача опознаётся для читателя. Ключ общий с
// tools/мера.mjs — он в src/scene.js, и задвоить его было бы ровно той
// граблей, на которую этот проект уже наступал с заготовками схем.
//
// Сцена сюда передаётся ГОТОВАЯ, одна на схему: от посылок ключ не зависит
// (посылки меняют свойства на узлах, а структуру графа задаёт схема).
function ключВопроса(сцена, z) {
  if (!сцена) return JSON.stringify(z.цель);
  return ключПоТермам(сцена.g, сцена.имена, z.цель);
}

// На схеме ИЗ ОДНОЙ ВЕРШИНЫ переносить нечего по построению, и требовать этого
// значило бы выкинуть весь раздел «один объект» целиком. Там задачу судят
// прочие признаки: глубина, работающие посылки, невырожденность.
function выводПереноситСведения(схема, z) {
  if ((схема.узлы ?? []).length < 2) return true;
  const цель = new Set(вершиныЦели(z.цель));
  return посылки(z).some(([имя]) => !цель.has(имя));
}

// --- «малое ⇒ какое угодно» -----------------------------------------------------
//
// Самая назойливая семья в выдаче: «Y конечно — верно ли, что im f компактно?»,
// «…сепарабельно?», «…локально компактно?», «…первой аксиомы счётности?». Все
// они проходят и признак глубины, и перенос сведений с вершины на вершину — а
// читаются как одна мысль, повторённая десять раз: подпространство конечного
// пространства конечно, а у конечного верно почти всё.
//
// Ловится точно, без списка исключений: если цель выводится ИЗ ОДНОЙ ЛИШЬ
// малости целевой вершины, то задача не про цель, а про малость. Настоящая
// теорема так не ловится: «конечная p-группа имеет нетривиальный центр» из
// одной конечности центра не следует.
const МАЛОСТЬ = ['point', 'trivial', 'finite', 'trivial-ring', 'finite-ring', 'finite-field', 'trivial-ext'];

function цельСледуетИзМалости(cat, схема, z) {
  const { g, имена } = построитьСхему(cat, схема, new Map(z.свойства));
  const мир = рассуждать(g, [...имена.values()]);
  for (const имя of вершиныЦели(z.цель)) {
    const id = имена.get(имя);
    if (id === undefined) continue;
    for (const p of МАЛОСТЬ) {
      if (z.цель.p === p) continue;                    // спрашивают как раз про малость
      if (мир.знает({ p, t: id }) !== true) continue;  // вершина и не мала
      // Ставим ОДНУ эту малость и смотрим, хватит ли её на цель.
      let один;
      try {
        один = построитьСхему(cat, схема, new Map([[имя, { [p]: true }]]));
      } catch {
        continue;
      }
      const м2 = рассуждать(один.g, [...один.имена.values()]);
      const t = один.имена.get(имя);
      if (z.цель.rel) continue;
      if (м2.знает({ p: z.цель.p, t }) === (z.цель.значение !== false)) return true;
    }
  }
  return false;
}

// --- цель в ЧУЖОЙ категории -----------------------------------------------------
//
// Кросс-категорная схема тащит в раздел объект другой категории: групповое
// кольцо берёт группу, поле Галуа отдаёт группу. Спрашивать про ПОСТРОЕННЫЙ
// чужой объект — ровно то, ради чего кросс-категорность и заводилась: «верно
// ли, что Gal(L/K) абелева» — хороший вопрос в разделе полей.
//
// А вот спрашивать про ЧУЖОЙ ВХОД бессмысленно: «Пусть R — кольцо, G — группа.
// Верно ли, что G конечно порождена?» — это задача раздела групп, случайно
// попавшая в раздел колец, и отвечает на неё чужая база, которой здесь нет.
function цельВЧужомВходе(cat, схема, z) {
  const свой = `${{ grp: 'Grp', mod: 'Mod', top: 'Top', ring: 'Ring', fld: 'Fld' }[cat.id]}.`;
  const поИмени = new Map((схема.узлы ?? []).map((n) => [n.имя, n]));
  for (const имя of вершиныЦели(z.цель)) {
    const n = поИмени.get(имя);
    if (!n) continue;
    const c = cat.cons.get(n.op);
    // Свободный узел — тот, что выбирается, а не строится.
    if (!c?.choice) continue;
    const sort = typeof c.out === 'string' ? c.out : c.out?.sort;
    if (sort && !String(sort).startsWith(свой)) return true;
  }
  return false;
}

// Одна цель, один и тот же контрпример — одна задача, сколько бы посылок к ней
// ни приписали. «I конечно порождён?» опровергается кольцом ℤ[x₁, x₂, …] и без
// посылок, и с посылкой «I — не всё кольцо», и с «R не артиново»: посылки
// разные, а решение слово в слово одно. Оставляем САМУЮ КОРОТКУЮ формулировку —
// в ней ничего лишнего, и читателю не приходится гадать, где пригодилось
// условие, которое нигде не пригодилось.
//
// Отбор по выводимости («лишняя посылка») этого не ловит: посылка бывает не
// выводима из остальных и всё-таки не нужна для ответа.
function самыеКороткие(найденные) {
  const лучшие = new Map();
  for (const z of найденные) {
    const ключ = `${JSON.stringify(z.цель)}|${z.свидетель ?? ''}`;
    const было = лучшие.get(ключ);
    const длина = посылки(z).reduce((s, [, p]) => s + Object.keys(p).length, 0);
    if (!было || длина < было.длина) лучшие.set(ключ, { z, длина });
  }
  // Порядок сохраняем исходный: он идёт от простых условий к сложным, и по нему
  // дальше шагает выборка.
  const взять = new Set([...лучшие.values()].map((x) => x.z));
  return найденные.filter((z) => взять.has(z));
}

// Проверяется по ВЫВЕДЕННЫМ фактам: тривиальность, которую никто не требовал,
// но которая следует из посылок, — признак схлопывания.
function условиеСхлопывается(cat, схема, z) {
  let g;
  let имена;
  try {
    ({ g, имена } = построитьСхему(cat, схема, new Map(z.свойства)));
  } catch {
    return true;
  }
  const мир = рассуждать(g, [...имена.values()]);
  if (мир.противоречие) return true;
  const потребовано = new Set();
  for (const [имя, props] of z.свойства ?? []) {
    for (const p of Object.keys(props)) потребовано.add(`${p}@${имя}`);
  }
  for (const [имя, id] of имена) {
    // У ИСХОДНОЙ вершины тривиальность вырождает всю постройку: в A × B с
    // тривиальным A произведение — это B, и схема лишняя. Неважно, потребовали
    // её или вывели. У ПОСТРОЕННОЙ (центр, коммутант) тривиальность — честное
    // условие на исходные данные, и запрещать её нельзя; вырождением она
    // становится, только если её не требовали, а она всё равно следует.
    const исходная = g.get(id).args.length === 0;
    for (const p of ВЫРОЖДАЮЩИЕ) {
      if (!исходная && потребовано.has(`${p}@${имя}`)) continue;
      if (мир.знает({ p, t: id }) === true) return true;
    }
  }
  return false;
}

const ПОМЕТКА = {
  'пробел': 'открытый вопрос: ни база, ни библиотека не отвечают',
  'опровергается примером': 'ложно, но контрпример тонкий',
  'выводится': 'доказуемо из базы',
};

function собратьРаздел(раздел, старые) {
  const cat = category(раздел);
  const каталог = каталогРаздела(раздел);
  const схемы = ПОРАЗДЕЛАМ[раздел] ?? {};
  const out = [];
  return (async () => {
    for (const [имяСхемы, схема] of Object.entries(схемы)) {
      let итог;
      try {
        итог = await генерировать({
        кэш: КЭШ,
          cat, схема, границы: ГРАНИЦЫ, каталог,
          примеров: ПРИМЕРОВ_СХЕМЫ[`${раздел}/${имяСхемы}`] ?? БЮДЖЕТ[раздел].примеров,
          предельныйПорядок: ПОРЯДОК_СХЕМЫ[`${раздел}/${имяСхемы}`] ?? БЮДЖЕТ[раздел].порядок,
          хватит: БЮДЖЕТ[раздел].хватит,
        });
      } catch (e) {
        console.error(`  ${имяСхемы}: не прошло — ${e.message}`);
        continue;
      }
      // Годные берутся НЕ подряд: первые находки отличаются одной посылкой и
      // читаются как одна задача, переписанная десять раз. Шаг по списку даёт
      // разные условия при той же цене.
      // Указатель по всей выдаче схемы: нужен, чтобы спросить «а каков ответ без
      // этой посылки». Строится один раз — перебор уже всё посчитал.
      const индекс = new Map();
      for (const z of итог.найдено) индекс.set(ключЗадачи(z), { корзина: z.корзина, свидетель: z.свидетель, сам: z });

      const годные = самыеКороткие(итог.найдено.filter((z) => годится(z)
        && посылкиКасаютсяЦели(cat, схема, z)
        && !естьЛишняяПосылка(cat, схема, z)
        && !условиеСхлопывается(cat, схема, z)
        && !свидетельВырожден(раздел, z)
        && !цельВЧужомВходе(cat, схема, z)
        && !естьУкрашение(индекс, z)
        && (z.корзина !== 'выводится' || выводПереноситСведения(схема, z))
        && (z.корзина !== 'выводится' || !цельСледуетИзМалости(cat, схема, z))));
      const шаг = Math.max(1, Math.floor(годные.length / сколько));
      const выбор = [];
      // КВОТА НА ЦЕЛЬ. Без неё выдача читается как одна задача, переписанная
      // пять раз: «верно ли, что I главный» подряд с разными посылками. Цель —
      // это то, что читатель запоминает, и повторять её больше двух раз на
      // схему незачем.
      // Сцена схемы — одна на все её задачи: нужна только ключу вопроса.
      let сценаСхемы = null;
      try {
        сценаСхемы = построитьСхему(cat, схема);
      } catch { /* схема без свободных вершин — ключ вернётся по имени цели */ }
      const поЦели = new Map();
      const поУсловию = new Map();
      const поВопросу = new Map();
      const квота = (z) => {
        const ц = JSON.stringify(z.цель);
        const у = ключУсловия(посылки(z));
        const в = ключВопроса(сценаСхемы, z);
        const kц = (поЦели.get(ц) ?? 0) + 1;
        const kу = (поУсловию.get(у) ?? 0) + 1;
        const kв = (поВопросу.get(в) ?? 0) + 1;
        поЦели.set(ц, kц);
        поУсловию.set(у, kу);
        поВопросу.set(в, kв);
        // Одни и те же данные с разными вопросами читаются как одна задача:
        // «Y конечно — верно ли, что im f компактно / сепарабельно / …».
        return kц <= ПРЕДЕЛ_НА_ЦЕЛЬ && kу <= ПРЕДЕЛ_НА_УСЛОВИЕ && kв <= ПРЕДЕЛ_НА_ВОПРОС;
      };
      for (let k = 0; k < годные.length && выбор.length < сколько * 3; k += шаг) {
        if (квота(годные[k])) выбор.push(годные[k]);
      }

      const взятые = [];
      for (const z of выбор) {
        let текст;
        try {
          текст = текстЗадачи(cat, схема, z);
        } catch {
          continue;
        }
        if (старые.has(текст)) continue;
        старые.add(текст);
        взятые.push({
          текст,
          корзина: z.корзина,
          свидетель: z.свидетель ?? null,
          глубина: z.глубина ?? null,
          правило: z.правило ?? null,
          примеров: z.примеров ?? null,
          верных: z.верных ?? null,
          схема: схема.имя ?? имяСхемы,
        });
        if (взятые.length >= сколько) break;
      }
      console.log(`  ${имяСхемы}: взято ${взятые.length}`);
      out.push(...взятые);
    }
    return out;
  })();
}

function запись(z, номер) {
  const хвост = [];
  if (z.корзина === 'выводится') {
    хвост.push(`глубина вывода ${z.глубина}${z.правило ? `, последний шаг — «${z.правило}»` : ''}`);
  }
  if (z.свидетель) хвост.push(`контрпример: ${z.свидетель}`);
  if (z.примеров) хвост.push(`примеров подходит ${z.примеров}, цель верна на ${z.верных}`);
  return [
    `— **${номер}.** ${z.текст}`,
    '',
    `  *${ПОМЕТКА[z.корзина] ?? z.корзина}*${хвост.length ? `; ${хвост.join('; ')}` : ''}`,
    '',
  ].join('\n');
}

