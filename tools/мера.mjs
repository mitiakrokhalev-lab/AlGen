// Мерило пробелов: «математика не знает» или «библиотека мала».
//
//   node tools/мера.mjs                  — по всем разделам
//   node tools/мера.mjs --раздел ring    — по одному
//
// Зачем. «Пробел» — одна корзина, а причин у него две, и они противоположны:
//
//   * библиотека МАЛА — подходящих примеров мало или все они неразличимы нашим
//     же языком. Такой пробел закрывается новой записью в библиотеке, и как
//     ЗАДАЧА он ничего не стоит: ответ есть, его просто нечем предъявить;
//   * библиотека БОГАТА, а ответа всё равно нет — цель подтверждается на многих
//     НЕЗАВИСИМЫХ примерах, а база доказать не может. Вот это кандидат в
//     настоящий вопрос: ровно так в выдачу попала гипотеза Капланского.
//
// Различает их РАЗНООБРАЗИЕ, а не число примеров. Триста подходящих строк
// ничего не значат, если все триста дают один и тот же вектор битов: нашим
// языком они неразличимы, и подтверждение одно. Поэтому считается число
// РАЗЛИЧНЫХ профилей (см. `разнообразие` в src/generate.js).
//
// Второй признак — ЭТАЖНОСТЬ: цель на исходной вершине («верно ли, что G
// проста») и цель на построенной («верно ли, что центр G/N тривиален») — вопросы
// разной глубины. Научный кандидат обязан спрашивать про построенное: про
// исходный объект всё интересное либо в учебнике, либо в библиотеке.

