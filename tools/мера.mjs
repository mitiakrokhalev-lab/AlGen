// Этаж цели: 0 — спрашивают про исходную вершину, 1 и больше — про построенную,
// и число говорит, сколько конструкций между данными и вопросом.
//
// Сцена строится ОДИН РАЗ на схему, а не на каждый набор посылок: посылки
// меняют только свойства на узлах, а структуру графа задаёт схема. Вырождений
// `построитьСхему` не делает вовсе — это работа normalize, и вырожденные
// условия отсеиваются раньше.

const посылки = (z) => (z.свойства ?? []).filter(([, p]) => Object.keys(p).length > 0);

// Есть ли в условии посылка, выводимая из остальных. Сцена пересобирается без
// неё — иначе свойство, записанное в узле, будет видно выводу и проверка
// выродится в тождество.
function естьЛишняяПосылка(cat, схема, z) {
  const атомы = [];
  for (const [имя, props] of посылки(z)) {
    for (const [p, v] of Object.entries(props)) атомы.push({ имя, p, значение: v });
  }
  if (атомы.length < 2) return false;
  for (let i = 0; i < атомы.length; i++) {
    const карта = new Map();
    атомы.forEach((a, k) => {
      if (k === i) return;
      карта.set(a.имя, { ...(карта.get(a.имя) ?? {}), [a.p]: a.значение });
    });
    let g;
    let имена;
    try {
      ({ g, имена } = построитьСхему(cat, схема, карта));
    } catch {
      continue;
    }
    const узел = имена.get(атомы[i].имя);
    if (узел === undefined) continue;
    const мир = рассуждать(g, [...имена.values()]);
    if (мир.знает({ p: атомы[i].p, t: узел }) === (атомы[i].значение !== false)) return true;
  }
  return false;
}

