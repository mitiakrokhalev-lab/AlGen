// Перенос топологических пространств из старого Генератора (данные π-Base).
//
//   node tools/import-pibase.mjs [--записать]
//
// Пользователь с самого начала просил: старые базы использовать МОЖНО, но
// обязательно ПРИСПОСОБИТЬ под новый формат. Здесь ровно это, и приспособление
// не сводится к переименованию:
//
//   * из 260 свойств π-Base у нас есть 16 под теми же именами; остальные
//     отбрасываются — держать свойство, про которое база ничего не знает,
//     значит раздувать перебор без единого нового ответа;
//   * наши T₃ и T₄ включают T₁, а у π-Base «регулярно» и «нормально» стоят
//     отдельно, поэтому они ВЫЧИСЛЯЮТСЯ конъюнкцией, а не переносятся;
//   * пространство берётся, только если оно знает достаточно много наших
//     свойств и если его набор свойств НОВ — иначе библиотека растёт, а
//     различать примеры нечем (тот же отбор по сигнатуре, что у произведений).
//
// И главное: перенесённое ПРОВЕРЯЕТСЯ. После записи надо прогнать
// tools/check-top.mjs — все 396 правил базы поедут по новым пространствам, и
// расхождение будет значить ошибку либо в моих правилах, либо в переносе.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const КОРЕНЬ = join(here, '..');
const ИСТОЧНИК = 'C:/Users/User/Desktop/Генератор/data/topology-pibase.json';

const записать = process.argv.includes('--записать');

const мои = JSON.parse(readFileSync(join(КОРЕНЬ, 'data/top.json'), 'utf8'));
const уже = JSON.parse(readFileSync(join(КОРЕНЬ, 'data/top-infinite.json'), 'utf8'));
let источник;
try {
  источник = JSON.parse(readFileSync(ИСТОЧНИК, 'utf8'));
} catch {
  console.error(`не читается ${ИСТОЧНИК} — старый Генератор не на месте`);
  process.exit(1);
}

const мояПо = мои.properties.filter((p) => p.sort === 'Top.obj').map((p) => p.id);
const ихПо = new Set(источник.properties.map((p) => p.id));
const прямые = мояПо.filter((id) => ихПо.has(id));

// У примеров свойства записаны КОДАМИ π-Base (P000125), а читаемое имя лежит
// в справочнике свойств полем `pibase`. Без этого перевода видно одно свойство
// из двадцати, и весь перенос выглядит пустым.
const поКоду = new Map();
for (const p of источник.properties) {
  if (p.pibase) поКоду.set(p.pibase, p.id);
}

function читаемые(props) {
  const out = {};
  for (const [k, v] of Object.entries(props ?? {})) {
    const имя = поКоду.get(k) ?? k;
    if (out[имя] === undefined) out[имя] = v;
  }
  return out;
}

// Три значения: true, false и «не знаю» (ключа нет).
const и = (a, b) => {
  if (a === false || b === false) return false;
  if (a === undefined || b === undefined) return undefined;
  return true;
};

// Свойства, у которых ИМЯ совпадает, а СМЫСЛ нет. Переносить их нельзя —
// получится не база, а противоречие.
//
// `locally-compact`: источник объявляет пространство «One-point
// compactification of the metric fan» одновременно компактным и НЕ локально
// компактным. При записанном там же определении («у каждой точки есть
// окрестность с компактным замыканием») это невозможно: в компакте такой
// окрестностью служит всё пространство. Значит в данных имелась в виду другая,
// более сильная локальная компактность (база компактных окрестностей), а у нас
// — слабая, и правило «компактно ⇒ локально компактно» в нашей базе верно.
// Сверка поймала расхождение на первом же прогоне; пропускаем свойство.
const ЧУЖИЕ = new Set(['locally-compact']);

function перевести(props) {
  const out = {};
  for (const id of прямые) {
    if (ЧУЖИЕ.has(id)) continue;
    if (props[id] !== undefined) out[id] = props[id];
  }
  // T₃ и T₄ у нас включают T₁ — у π-Base это отдельные свойства.
  const T3 = и(props.regular, props.T1);
  const T4 = и(props.normal, props.T1);
  if (T3 !== undefined) out.T3 = T3;
  if (T4 !== undefined) out.T4 = T4;
  // «Одноточечно» π-Base не знает, но конечное и связное вместе с T₁ дают его.
  return out;
}

const сигнатура = (props) => Object.keys(props).sort().map((k) => `${k}=${props[k]}`).join(',');

const занято = new Set(уже.объекты.map((з) => сигнатура(з.props ?? {})));
const занятыеИмена = new Set(уже.объекты.map((з) => з.id));

// Порог подобран ЗАМЕРОМ, а не на глаз: данные π-Base в старом Генераторе
// разрежены — из наших девятнадцати свойств пространство знает 0…6, чаще
// одно-два. При пороге 8 не проходит ни одно, при 4 — тринадцать.
const ПОРОГ = 4;
const взятые = [];
const счёт = { всего: источник.examples.length, мало: 0, повтор: 0, взято: 0 };

for (const пример of источник.examples) {
  const props = перевести(читаемые(пример.props));
  const известно = Object.keys(props).length;
  if (известно < ПОРОГ) { счёт.мало++; continue; }
  const s = сигнатура(props);
  if (занято.has(s)) { счёт.повтор++; continue; }
  занято.add(s);
  let id = `pb-${пример.id}`;
  while (занятыеИмена.has(id)) id += '_';
  занятыеИмена.add(id);
  взятые.push({
    id,
    имя: пример.name,
    источник: `π-Base ${пример.id}`,
    props,
    подпространства: [
      {
        id: 'точка', имя: 'точка', объект: 'точка',
        // Утверждается ТОЛЬКО известное. «Не замкнута, не открыта, не плотна»
        // выглядело осторожностью, а было ложью: в T₁-пространстве точка
        // замкнута, и сверка поймала это на первом же прогоне. Отсутствие
        // ключа значит «не знаю» — это и есть осторожность.
        props: {
          whole: false,
          ...(props.T1 === true ? { closed: true } : {}),
          ...(props.discrete === true ? { open: true } : {}),
        },
      },
      {
        id: 'всё', имя: пример.name, объект: id,
        props: { open: true, closed: true, dense: true, whole: true },
      },
    ],
  });
  счёт.взято++;
}

console.log(`свойств перенесено напрямую: ${прямые.length} из ${мояПо.length} наших`);
console.log(`  ${прямые.join(', ')}`);
console.log('  T3 и T4 вычислены из «регулярно/нормально» и T₁');
console.log(`пространств в источнике: ${счёт.всего}`);
console.log(`  знают меньше ${ПОРОГ} наших свойств: ${счёт.мало}`);
console.log(`  повторяют уже имеющийся набор свойств: ${счёт.повтор}`);
console.log(`  ВЗЯТО: ${счёт.взято}`);

if (!записать) {
  console.log('\nничего не записано; чтобы записать — флаг --записать');
  console.log('после записи ОБЯЗАТЕЛЬНО: node tools/check-top.mjs');
  process.exit(0);
}

const файл = join(КОРЕНЬ, 'data/top-pibase.json');
writeFileSync(файл, `${JSON.stringify({
  заметка: 'Перенесено из старого Генератора (данные π-Base) утилитой tools/import-pibase.mjs. Свойства, которых нет в нашей базе, отброшены; T₃ и T₄ вычислены конъюнкцией с T₁. Подпространств у этих записей всего два (точка и всё): π-Base их не знает, и выдумывать нельзя.',
  объекты: взятые,
}, null, 2)}\n`);
console.log(`\nзаписано: ${файл}`);
console.log('теперь: node tools/check-top.mjs');
