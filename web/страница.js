function собратьФильтры() {
  const где = $('фильтры');
  где.innerHTML = '';
  const сделать = (ключ, подпись, включено, данные) => {
    const обёртка = document.createElement('div');
    обёртка.className = 'галка';
    обёртка.style.flex = '0 0 auto';
    const i = document.createElement('input');
    i.type = 'checkbox';
    i.id = ключ;
    i.checked = включено;
    if (данные) i.dataset.корзина = данные;
    i.onchange = перерисоватьВыдачу;
    const l = document.createElement('label');
    l.htmlFor = ключ;
    l.textContent = подпись;
    обёртка.append(i, l);
    где.appendChild(обёртка);
  };
  сделать('ф-пробел', 'пробелы', true, 'пробел');
  сделать('ф-выводится', 'выводится из базы', false, 'выводится');
  сделать('ф-примером', 'опровергается примером', true, 'опровергается примером');
  сделать('ф-опровергается', 'опровергается базой', true, 'опровергается');
  сделать('ф-без-посылок', 'вопросы без посылок', false, null);
  // Две галочки про ПРОБЕЛЫ. По умолчанию бедность библиотеки спрятана: это
  // не задачи, а долг перед библиотекой, и показывать их вперемешку с
  // кандидатами в научные значит прятать кандидатов в тысяче пустых условий.
  сделать('ф-кандидаты', 'только кандидаты в научные', false, null);
  сделать('ф-бедность', 'показать бедность библиотеки', false, null);
}

function собратьЗаготовки() {
  const sel = $('заготовка');
  // Список СТРОИТСЯ ЗАНОВО, а не дополняется: при смене раздела старые
  // заготовки в нём оставались, и в кольцах предлагалось «взять заготовку —
  // центр и фактор по центру», которой в этой категории нет вовсе.
  sel.textContent = '';
  for (const [id, з] of Object.entries(ЗАГОТОВКИ)) {
    const o = document.createElement('option');
    o.value = id;
    o.textContent = з.имя;
    sel.appendChild(o);
  }
  sel.value = РАЗДЕЛЫ[раздел].начальная;
  sel.onchange = () => {
    схема = структурноКопировать(ЗАГОТОВКИ[sel.value]);
    обновить();
  };
}

function собратьРазделы() {
  const sel = $('раздел');
  sel.textContent = '';
  for (const [id, з] of Object.entries(РАЗДЕЛЫ)) {
    const o = document.createElement('option');
    o.value = id;
    o.textContent = `${з.cat.имя} — готово`;
    sel.appendChild(o);
  }
  // Коммутативные кольца отдельным разделом не заводятся и не заведутся:
  // коммутативность — это СВОЙСТВО, и «возьмём коммутативное кольцо» уже
  // выражается посылкой. Отдельная категория ради одного свойства раздвоила бы
  // библиотеку и базу пополам.
  for (const [id, имя] of [['alg', 'алгебры над кольцом']]) {
    const x = document.createElement('option');
    x.value = id;
    x.textContent = `${имя} — базы ещё нет`;
    x.disabled = true;
    sel.appendChild(x);
  }
  sel.value = раздел;
  sel.onchange = () => {
    раздел = sel.value;
    const з = РАЗДЕЛЫ[раздел];
    cat = з.cat;
    каталог = з.каталог;
    ЗАГОТОВКИ = з.заготовки;
    схема = структурноКопировать(ЗАГОТОВКИ[з.начальная]);
    собратьЗаготовки();
    собратьФильтры();
    сводкаБазы();
    обновить();
  };
  сводкаБазы();
}

function сводкаБазы() {
  $('строка-кольцо').hidden = !cat.sorts.has('Ring.obj');
  // Числовой сорт есть у групп (порядок, индекс) и у полей (степень), и
  // условий на него вешают отдельной границей — как в командной строке.
  $('строка-число').hidden = ![...cat.sorts.keys()].some((s) => s.endsWith('.num'));
  const библиотека = раздел === 'mod'
    ? `${каталог.кольца.length} колец и ${каталог.модули.length} модулей`
    : раздел === 'fld'
      ? библиотекаПолей.поля.length + ' полей и ' + библиотекаПолей.расширения.length + ' расширений'
      : раздел === 'ring'
      ? `${библиотекаКолец.кольца.length} колец и ${библиотекаКолец.морфизмы.length} гомоморфизмов`
      : раздел === 'top'
      ? `${библиотекаТоп.конечные.length} конечных и ${ДАННЫЕ.пространства.length} объявленных пространств`
      : `${конечныеГруппы.length} конечных и ${каталогГрупп.filter((x) => x.бесконечная).length} бесконечных групп`;
  $('сводка-базы').textContent =
    `в базе: свойств ${cat.props.size}, конструкций ${cat.cons.size}, ` +
    `отношений ${cat.rels.size}, правил ${РАЗДЕЛЫ[раздел].данные.rules.length}; ` +
    `библиотека: ${библиотека}` +
    (бедыСвязи.length ? ` (ОШИБКИ СВЯЗЕЙ: ${бедыСвязи.length})` : '');
}

