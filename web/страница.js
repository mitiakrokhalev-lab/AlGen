async function искать({ случайная = false } = {}) {
  const { ошибка } = перестроить();
  if (ошибка) {
    $('состояние').textContent = 'схема не собирается — поиск не начат';
    return;
  }
  знак = жетон();
  $('искать').disabled = true;
  $('случайная').disabled = true;
  $('стоп').disabled = false;
  $('полоса').style.display = 'block';
  $('полоса').value = 0;
  const t0 = Date.now();

  const хватитПоле = Number($('хватит').value);
  const параметры = {
    cat,
    схема,
    границы: {
      объект: Number($('гр-объект').value),
      подобъект: Number($('гр-подобъект').value),
      морфизм: Number($('гр-морфизм').value),
      кольцо: Number($('гр-кольцо').value),
      число: Number($('гр-число').value),
    },
    достройка: Number($('достройка').value),
    каталог: Number($('примеров').value) > 0 ? каталог : null,
    примеров: Number($('примеров').value),
    предельныйПорядок: Number($('порядок').value),
    цели: схема.узлы.filter((n) => n.цель).map((n) => n.имя),
    хватит: случайная ? 1 : (хватитПоле > 0 ? хватитПоле : null),
    случайно: случайная ? true : $('случайно').checked,
    зерно: случайная ? (Date.now() % 100000) + 1 : Number($('зерно').value),
    знак,
    тик: (с) => {
      if (с.вид === 'примеры') {
        $('состояние').textContent = `строю примеры: просмотрено ${с.сделано}, годных ${с.найдено}`;
      } else if (с.вид === 'примеры-готовы') {
        $('состояние').textContent = `примеров построено: ${с.строк}${с.усечено ? ' (усечено — см. «Примеров на схему»)' : ''}`;
      } else if (с.вид === 'начало') {
        $('состояние').textContent =
          `наборов посылок: ${с.наборов}; свободных вершин: ${с.свободных}`;
        $('полоса').max = с.наборов;
      } else {
        $('полоса').value = с.сделано;
        $('состояние').textContent =
          `просмотрено ${с.сделано} из ${с.всего}; найдено ${с.найдено}`;
      }
    },
  };

  try {
    последняя = await генерировать(параметры);
    показать(последняя, ((Date.now() - t0) / 1000).toFixed(1));
  } catch (e) {
    $('состояние').textContent = `сорвалось: ${e.message}`;
  } finally {
    знак = null;
    $('искать').disabled = false;
    $('случайная').disabled = false;
    $('стоп').disabled = true;
    $('полоса').style.display = 'none';
  }
}

function показать(итог, секунд) {
  const строки = [];
  for (const [k, v] of Object.entries(итог.счёт)) if (v) строки.push(`${k}: <b>${v}</b>`);
  строки.push(`пар всего: <b>${итог.пар}</b>`);
  строки.push(итог.баланс ? 'баланс сошёлся' : '<b>БАЛАНС НЕ СОШЁЛСЯ</b>');
  $('корзины').innerHTML = строки.map((s) => `<span>${s}</span>`).join('');
  показатьРазряды(итог);

  const хвост = итог.оборвано ? `; оборвано: ${итог.оборвано.причина}` : '';
  if (итог.противоречия?.length) {
    строки.push(`<b style="color:var(--опровергается)">база спорит с моделью: ${итог.противоречия.length}</b>`);
  }
  $('состояние').textContent = `готово за ${секунд} с; найдено ${итог.найдено.length}${хвост}`;
  перерисоватьВыдачу();
}

// РАЗБОР ПРОБЕЛОВ по разрядам. Корзина «пробел» значит только «база не
// доказала и не опровергла», а причин у этого две противоположные: библиотека
// мала (ответ есть, предъявить нечем) или вопрос действительно открыт. Пока
// обе показывались одним числом, выдача из двух тысяч пробелов не говорила
// ничего. Разряды считает движок (src/мера-пробела.js), здесь только показ.
const ЧТО_ЗНАЧИТ = {
  'обрезано': 'перебор примеров не дошёл до конца библиотеки — поднимите «примеров на схему»',
  'без посылок': 'условия нет: вопрос про произвольный объект',
  'пусто': 'ни один объект библиотеки не подошёл под условие',
  'немо': 'объекты нашлись, но цель на них не вычисляется — дыра в модели',
  'малолюдно': 'подтверждений слишком мало',
  'однолико': 'подтверждений много, а различимых среди них мало',
  'низкий этаж': 'вопрос про исходную вершину, а не про построенную',
  'кандидат': 'цель подтверждена на многих различимых примерах, и база её не выводит',
};

function показатьРазряды(итог) {
  const где = $('разряды');
  if (!где) return;
  const св = сводкаРазрядов(итог.найдено);
  if (!св.пробелов) { где.innerHTML = ''; return; }
  const доля = (v) => `${(100 * v / св.пробелов).toFixed(1)}%`;
  const ряд = (имя, v, что, класс) => `<div class="${класс ?? ''}" style="display:contents">`
    + `<span class="имя">${экран(имя)}</span><span class="сколько">${v}</span>`
    + `<span class="доля">${доля(v)}</span><span class="что">${экран(что)}</span></div>`;
  const части = [`<div style="display:contents"><span class="имя" style="grid-column:1/-1;color:var(--тусклый)">из чего состоят ${св.пробелов} пробелов:</span></div>`];
  for (const р of РАЗРЯДЫ) {
    if (!св.счёт[р]) continue;
    части.push(ряд(р === 'кандидат' ? 'КАНДИДАТЫ В НАУЧНЫЕ' : р, св.счёт[р], ЧТО_ЗНАЧИТ[р] ?? '', р === 'кандидат' ? 'кандидат' : ''));
  }
  части.push(`<div class="итог" style="display:contents"><span class="имя">бедность библиотеки</span>`
    + `<span class="сколько">${св.бедность}</span><span class="доля">${доля(св.бедность)}</span>`
    + `<span class="что">лечится библиотекой и моделью, а не математикой</span></div>`);
  где.innerHTML = части.join('');
}

function перерисоватьВыдачу() {
  const где = $('выдача');
  где.innerHTML = '';
  if (!последняя) return;
  const показыватьПустые = $('ф-без-посылок')?.checked;
  const корзины = new Set(
    [...document.querySelectorAll('input[data-корзина]')]
      .filter((i) => i.checked)
      .map((i) => i.dataset.корзина),
  );
  // Галочки по РАЗРЯДУ действуют только на пробелы: у остальных корзин разряда
  // нет, и прятать их по нему было бы ложью.
  const кандидатыТолько = $('ф-кандидаты')?.checked;
  const бедностьТоже = $('ф-бедность')?.checked;
  const список = последняя.найдено.filter((z) => {
    // «Только кандидаты» — это кнопка «покажи интересное»: она прячет и
    // остальные корзины тоже. Иначе человек ставит галочку и видит те же три
    // сотни опровержений, среди которых кандидатов по-прежнему не найти.
    if (кандидатыТолько) return z.корзина === 'пробел' && z.разряд === 'кандидат';
    if (!корзины.has(z.корзина)) return false;
    if (!показыватьПустые && !z.посылок) return false;
    // Бедность библиотеки по умолчанию спрятана: это долг перед библиотекой, а
    // не задачи, и вперемешку с остальным она топит всё остальное.
    if (z.корзина === 'пробел' && z.разряд && !бедностьТоже && БЕДНОСТЬ.has(z.разряд)) return false;
    return true;
  });
  if (!список.length) {
    где.innerHTML = '<div class="пусто-выдача">Под эти галочки ничего не попало. ' +
      'Скучное спрятано, а не выброшено — снимите ограничения, чтобы увидеть всё.</div>';
    return;
  }
  for (const z of список.slice(0, 300)) {
    const d = document.createElement('div');
    d.className = `задача ${z.корзина}`;
    const пометки = пометкиЗадачи(z);
    d.innerHTML = `<div class="текст"><span class="ярлык">${экран(z.корзина)}</span>${экран(текстЗадачи(cat, схема, z))}</div>` +
      (пометки.length ? `<div class="пометки">${пометки.map(экран).join(' · ')}</div>` : '');
    где.appendChild(d);
  }
  if (список.length > 300) {
    const d = document.createElement('div');
    d.className = 'пусто-выдача';
    d.textContent = `показаны первые 300 из ${список.length} — это ограничение ОТРИСОВКИ, не поиска`;
    где.appendChild(d);
  }
}

