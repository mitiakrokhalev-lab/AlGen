function добавитьУзел() {
  const op = $('операция').value;
  if (op === 'given') {
    const имя = свободноеИмя('Grp.obj');
    схема.узлы.push({ имя, op: 'given', sort: 'Grp.obj' });
  } else {
    const c = cat.cons.get(op);
    const args = c.in.map((_, i) => $('слоты').querySelector(`select[data-слот="${i}"]`)?.value);
    if (args.some((a) => !a)) {
      $('ошибка-схемы').textContent = 'не выбраны аргументы';
      return;
    }
    const имя = свободноеИмя(c.out.sort);
    схема.узлы.push({ имя, op, args });
  }
  const проба = перестроить();
  if (проба.ошибка) {
    схема.узлы.pop();
    $('ошибка-схемы').textContent = `так нельзя: ${проба.ошибка}`;
    return;
  }
  обновить();
}

// «Дорастить случайно» — это то самое разрешение генератору самому продолжить
// схему: он берёт случайную допустимую конструкцию над уже построенным.
function доростить() {
  const { g, имена } = перестроить();
  if (!g) return;
  const годные = доступныеОперации(g, имена).filter((о) => о.id !== 'given');
  if (!годные.length) return;
  for (let попытка = 0; попытка < 12; попытка++) {
    const оп = годные[Math.floor(Math.random() * годные.length)];
    const c = cat.cons.get(оп.id);
    const args = [];
    let можно = true;
    for (let i = 0; i < c.in.length; i++) {
      const список = годныеВСлот(g, имена, c, i, args);
      if (!список.length) {
        можно = false;
        break;
      }
      args.push(список[Math.floor(Math.random() * список.length)]);
    }
    if (!можно) continue;
    схема.узлы.push({ имя: свободноеИмя(c.out.sort), op: оп.id, args });
    if (перестроить().ошибка) схема.узлы.pop();
    else break;
  }
  обновить();
}

