function нарисовать(g, имена) {
  const svg = $('схема-рисунок');
  // Не innerHTML = '': в разметке лежит <defs> с наконечником стрелки,
  // и стирать его вместе с рисунком нельзя.
  for (const e of [...svg.children]) if (e.tagName !== 'defs') e.remove();
  if (!g) return;
  const порядок = схема.узлы.map((n) => n.имя);
  const слой = new Map();
  for (const n of схема.узлы) {
    слой.set(n.имя, Math.max(0, ...(n.args ?? []).map((a) => (слой.get(a) ?? 0) + 1)));
  }
  const поСлоям = new Map();
  for (const имя of порядок) {
    const s = слой.get(имя);
    if (!поСлоям.has(s)) поСлоям.set(s, []);
    поСлоям.get(s).push(имя);
  }
  const слоёв = Math.max(1, поСлоям.size);
  const Ш = 400, В = 210;
  const шагX = Ш / (слоёв + 0.4);
  const места = new Map();
  for (const [s, список] of поСлоям) {
    const шагY = В / (список.length + 1);
    список.forEach((имя, k) => места.set(имя, { x: 34 + s * шагX, y: шагY * (k + 1) }));
  }

  const нс = 'http://www.w3.org/2000/svg';
  const добавить = (тег, атр, текст) => {
    const e = document.createElementNS(нс, тег);
    for (const [k, v] of Object.entries(атр)) e.setAttribute(k, v);
    if (текст !== undefined) e.textContent = текст;
    svg.appendChild(e);
    return e;
  };
  for (const n of схема.узлы) {
    for (const a of n.args ?? []) {
      const от = места.get(a), до = места.get(n.имя);
      if (от && до) добавить('line', { x1: от.x + 26, y1: от.y, x2: до.x - 26, y2: до.y });
    }
  }
  const names = nameParticipants(g, [...имена.values()]);
  for (const n of схема.узлы) {
    const м = места.get(n.имя);
    const свободный = n.op === 'given' || cat.cons.get(n.op)?.choice;
    добавить('rect', {
      x: м.x - 26, y: м.y - 15, width: 52, height: 30, rx: 6,
      class: свободный ? 'свободный' : '',
    });
    добавить('text', { x: м.x, y: м.y + 1, 'text-anchor': 'middle' },
      n.цель ? `${n.имя} ?` : n.имя);
    const формула = безопасно(() => render(g, имена.get(n.имя), names));
    if (формула && формула !== n.имя) {
      добавить('text', { x: м.x, y: м.y + 25, 'text-anchor': 'middle', class: 'подпись' }, формула);
    }
  }

  // Морфизм — это ВЕРШИНА графа построения, но на рисунке он читается как
  // стрелка между своими концами. Рисуем и то и другое: коробку с именем и
  // пунктирную стрелку dom → cod, иначе схема перестаёт быть похожа на то,
  // что человек держит в голове.
  for (const n of схема.узлы) {
    const id = имена.get(n.имя);
    const sort = g.get(id).sort;
    if (!sort.endsWith('.mor')) continue;
    const дом = g.rel(id, 'dom');
    const код = g.rel(id, 'cod');
    const откуда = найтиМесто(дом, имена, места);
    const куда = найтиМесто(код, имена, места);
    if (!откуда || !куда) continue;
    const выгиб = откуда === куда ? 28 : 16;
    const сx = (откуда.x + куда.x) / 2;
    const сy = Math.min(откуда.y, куда.y) - выгиб;
    добавить('path', {
      class: 'морфизм',
      'marker-end': 'url(#стрелка)',
      d: `M${откуда.x},${откуда.y - 16} Q${сx},${сy} ${куда.x},${куда.y - 16}`,
    });
    добавить('text', { x: сx, y: сy - 2, 'text-anchor': 'middle', class: 'морфизм' }, n.имя);
  }
}

function найтиМесто(id, имена, места) {
  for (const [имя, x] of имена) if (x === id) return места.get(имя) ?? null;
  return null;
}

function безопасно(f) {
  try {
    return f();
  } catch {
    return null;
  }
}

