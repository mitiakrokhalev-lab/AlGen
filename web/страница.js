function обновить() {
  const { g, имена, ошибка } = перестроить();
  $('ошибка-схемы').textContent = ошибка ? `Схема не собирается: ${ошибка}` : '';
  нарисовать(g, имена);

  const tbody = $('список-узлов');
  tbody.innerHTML = '';
  const names = g ? nameParticipants(g, [...имена.values()]) : null;
  схема.узлы.forEach((n, i) => {
    const tr = document.createElement('tr');
    const c = cat.cons.get(n.op);
    const что = n.op === 'given'
      ? (cat.sorts.get(n.sort)?.имя ?? n.sort)
      : `${c?.имя ?? n.op}${(n.args ?? []).length ? ` (${n.args.join(', ')})` : ''}`;
    const формула = g && names ? безопасно(() => render(g, имена.get(n.имя), names)) : null;
    tr.innerHTML = `<td class="имя">${экран(n.имя)}</td>
      <td class="что">${экран(что)}${формула && формула !== n.имя ? ` &nbsp;<i>${экран(формула)}</i>` : ''}</td>`;

    // Квантор. По умолчанию «для всякой»: так читается «пусть N ⩽ G» в
    // обычной математической речи, и так же рассуждает вывод.
    const tdК = document.createElement('td');
    tdК.style.width = '1%';
    if (c?.choice) {
      const s = document.createElement('select');
      s.style.fontSize = '12px';
      s.style.padding = '1px 3px';
      for (const [v, т] of [['forall', 'для всякой'], ['exists', 'существует']]) {
        const o = document.createElement('option');
        o.value = v;
        o.textContent = т;
        s.appendChild(o);
      }
      s.value = n.quant ?? 'forall';
      s.title = 'для всякой — утверждение про любую такую вершину; существует — надо предъявить хотя бы одну';
      s.onchange = () => {
        n.quant = s.value;
        обновить();
      };
      tdК.appendChild(s);
    }
    tr.appendChild(tdК);

    // Про какую вершину спрашиваем. Ни одной отмеченной — спрашиваем про все.
    const tdЦ = document.createElement('td');
    tdЦ.style.width = '1%';
    const ч = document.createElement('input');
    ч.type = 'checkbox';
    ч.checked = Boolean(n.цель);
    ч.title = 'спрашивать про эту вершину';
    ч.onchange = () => {
      n.цель = ч.checked;
      обновить();
    };
    tdЦ.appendChild(ч);
    tr.appendChild(tdЦ);

    const td = document.createElement('td');
    td.style.width = '1%';
    const кн = document.createElement('button');
    кн.textContent = 'убрать';
    кн.disabled = схема.узлы.some((m) => (m.args ?? []).includes(n.имя));
    кн.title = кн.disabled ? 'на эту вершину ссылаются другие' : 'убрать вершину';
    кн.onclick = () => {
      схема.узлы.splice(i, 1);
      обновить();
    };
    td.appendChild(кн);
    tr.appendChild(td);
    tbody.appendChild(tr);
  });
  const отмечено = схема.узлы.filter((n) => n.цель).map((n) => n.имя);
  $('про-что').textContent = отмечено.length
    ? `спрашиваем про: ${отмечено.join(', ')}`
    : 'спрашиваем про все вершины — отметьте галочкой, чтобы сузить';

  заполнитьОперации(g, имена);
}

function экран(s) {
  return String(s).replace(/[&<>]/gu, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;' }[c]));
}

function заполнитьОперации(g, имена) {
  const sel = $('операция');
  const было = sel.value;
  sel.innerHTML = '';
  if (!g) {
    $('слоты').innerHTML = '';
    return;
  }
  for (const оп of доступныеОперации(g, имена)) {
    const o = document.createElement('option');
    o.value = оп.id;
    o.textContent = оп.имя;
    sel.appendChild(o);
  }
  if ([...sel.options].some((o) => o.value === было)) sel.value = было;
  заполнитьСлоты(g, имена);
}

function заполнитьСлоты(g, имена) {
  const где = $('слоты');
  где.innerHTML = '';
  const op = $('операция').value;
  if (op === 'given' || !op) return;
  const c = cat.cons.get(op);
  const выбрано = [];
  c.in.forEach((slot, i) => {
    const обёртка = document.createElement('div');
    обёртка.style.marginTop = '7px';
    const l = document.createElement('label');
    l.textContent = `${slot.role} — ${cat.sorts.get(slot.sort)?.имя ?? slot.sort}` +
      (slot.requires?.length ? ` (нужно: ${slot.requires.join(', ')})` : '');
    const s = document.createElement('select');
    s.dataset.слот = String(i);
    обёртка.append(l, s);
    где.appendChild(обёртка);
    выбрано.push(null);
  });
  const пересчитать = () => {
    c.in.forEach((slot, i) => {
      const s = где.querySelector(`select[data-слот="${i}"]`);
      const было = s.value;
      const годные = годныеВСлот(g, имена, c, i, выбрано);
      s.innerHTML = '';
      for (const имя of годные) {
        const o = document.createElement('option');
        o.value = имя;
        o.textContent = имя;
        s.appendChild(o);
      }
      if (годные.includes(было)) s.value = было;
      выбрано[i] = s.value || null;
      s.onchange = () => {
        выбрано[i] = s.value;
        пересчитать();
      };
    });
  };
  пересчитать();
}

