function свободноеИмя(sort) {
  const пул = cat.sorts.get(sort)?.буквы ?? ['t'];
  const занято = new Set(схема.узлы.map((n) => n.имя));
  for (const б of пул) if (!занято.has(б)) return б;
  for (let i = 2; ; i++) {
    const имя = `${пул[пул.length - 1]}${i}`;
    if (!занято.has(имя)) return имя;
  }
}

// Кандидаты в слот: сорт подходит и согласование (ambient/dom/cod) выполнено
// относительно уже выбранных аргументов. Это то же условие, что проверяет
// движок, — здесь оно просто показано заранее, чтобы не предлагать негодное.
function годныеВСлот(g, имена, c, i, выбрано) {
  const slot = c.in[i];
  const привязка = new Map();
  c.in.forEach((s, k) => k < i && выбрано[k] && привязка.set(s.role, имена.get(выбрано[k])));
  const out = [];
  for (const [имя, id] of имена) {
    const n = g.get(id);
    if (!fits(n.sort, slot.sort, cat.up)) continue;
    let годится = true;
    for (const k of ['ambient', 'dom', 'cod', 'base']) {
      if (slot[k] === undefined) continue;
      try {
        if (g.rel(id, k) !== g.resolve(slot[k], привязка)) годится = false;
      } catch {
        годится = false;
      }
    }
    if (годится) out.push(имя);
  }
  return out;
}

function доступныеОперации(g, имена) {
  // Имя берётся у КАТЕГОРИИ, а не вписано: в разделе колец «пусть дана
  // группа» — просто неправда, а в топологии речь о пространстве.
  const главный = cat.sorts.get(ГЛАВНЫЙ_СОРТ[cat.id]);
  const список = [{ id: 'given', имя: `пусть дан объект: ${главный?.имя ?? 'объект'}` }];
  for (const c of cat.cons.values()) {
    if (!c.in.length) continue;
    const выбрано = [];
    let можно = true;
    for (let i = 0; i < c.in.length; i++) {
      const годные = годныеВСлот(g, имена, c, i, выбрано);
      if (!годные.length) {
        можно = false;
        break;
      }
      выбрано.push(годные[0]);
    }
    if (можно) список.push({ id: c.id, имя: c.имя ?? c.id });
  }
  return список;
}

